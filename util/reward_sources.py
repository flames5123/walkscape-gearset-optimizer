"""Reverse index: item display name -> achievement / AP-track / faction
reputation reward sources.

Consumed by the /api/item-sources endpoint (ui/app.py) so the frontend
"sources" section can show which achievement, Achievement-Points milestone, or
faction-reputation tier grants an item that otherwise has no drop/recipe/shop
source (these items previously rendered "No sources found").

Source dict shapes (mirrors the other /api/item-sources entries — each carries
a stable ``id`` so ``add_source`` de-dupes correctly):

  achievement_reward: {type, id (achievement id), name, difficulty, description, quantity}
  ap_reward:          {type, id ("ap_<points>"), points, quantity}
  faction_reward:     {type, id ("faction_<name>_<rep>"), faction, reputation, tier_title, quantity}
"""
import re
from typing import Dict, List, Optional


def _build_item_id_name_index() -> Dict[str, str]:
    """Map lowercased autogenerated attribute name -> item display name.

    Reward payloads reference items by id (e.g. 'cooking_chest', 'pathfinder'),
    which equals the lowercased class-attribute name of the corresponding
    Material / Item / Consumable / Container entry (e.g. Container.COOKING_CHEST,
    Item.PATHFINDER). Scanning those classes builds the id -> display-name map.
    """
    idx: Dict[str, str] = {}

    def scan(cls) -> None:
        if cls is None:
            return
        for attr in dir(cls):
            if attr.startswith("_"):
                continue
            obj = getattr(cls, attr, None)
            name = getattr(obj, "name", None)
            if isinstance(name, str) and name:
                idx.setdefault(attr.lower(), name)

    try:
        from util.autogenerated.materials import Material
        scan(Material)
    except Exception:
        pass
    try:
        from util.autogenerated.equipment import Item
        scan(Item)
    except Exception:
        pass
    try:
        from util.autogenerated.consumables import Consumable
        scan(Consumable)
    except Exception:
        pass
    try:
        from util.autogenerated.containers import Container
        scan(Container)
    except Exception:
        pass
    return idx


def _display_name(item_id: Optional[str], idx: Dict[str, str]) -> Optional[str]:
    if not item_id:
        return None
    hit = idx.get(str(item_id).lower())
    if hit:
        return hit
    # Fall back to a humanized form so a newly-added reward item is still
    # surfaced (better than dropping it) until the catalog scan picks it up.
    pretty = str(item_id).replace("_", " ").replace("-", " ").strip().title()
    return pretty or None


def build_reward_source_index() -> Dict[str, List[dict]]:
    """Return {lowercased item name: [reward source dict, ...]}."""
    out: Dict[str, List[dict]] = {}
    idx = _build_item_id_name_index()

    def add(name: Optional[str], source: dict) -> None:
        if not name:
            return
        out.setdefault(name.lower().strip(), []).append(source)

    # --- Achievements -> item rewards ---
    try:
        from util.autogenerated.achievements import ACHIEVEMENTS
    except Exception:
        ACHIEVEMENTS = {}
    try:
        from util.autogenerated.achievement_descriptions import ACHIEVEMENT_DESCRIPTIONS
    except Exception:
        ACHIEVEMENT_DESCRIPTIONS = {}

    for aid, ach in ACHIEVEMENTS.items():
        rewards = ach.get("itemRewards") or []
        if not rewards:
            continue
        difficulty = (ach.get("difficulty") or "normal").lower()
        desc = ACHIEVEMENT_DESCRIPTIONS.get(aid, {}) or {}
        reqs = desc.get("requirements") or []
        desc_text = " • ".join(r for r in reqs if r)
        for ir in rewards:
            name = _display_name(ir.get("id"), idx)
            if not name:
                continue
            add(name, {
                "type": "achievement_reward",
                "id": aid,
                "name": ach.get("name") or aid,
                "difficulty": difficulty,
                "description": desc_text,
                "quantity": ir.get("quantity"),
            })

    # --- Achievement-Points track -> item rewards ---
    try:
        from util.autogenerated.rewards import REWARDS
    except Exception:
        REWARDS = {}
    for rid, reward in REWARDS.items():
        if reward.get("type") != "achievementPoints":
            continue
        m = re.search(r"(\d+)\s*$", str(rid))
        points = int(m.group(1)) if m else None
        for ir in reward.get("rewardItems") or []:
            name = _display_name(ir.get("id"), idx)
            if not name:
                continue
            add(name, {
                "type": "ap_reward",
                "id": f"ap_{points}" if points is not None else str(rid),
                "points": points,
                "quantity": ir.get("quantity"),
            })

    # --- Faction reputation tracks -> tier reward items ---
    try:
        from util.autogenerated.faction_rewards import ALL_FACTION_TRACKS
    except Exception:
        ALL_FACTION_TRACKS = {}
    for track in ALL_FACTION_TRACKS.values():
        faction = track.faction_name
        for tier in track.tiers:
            for rw in tier.rewards:
                name = rw.item_name
                if not name:
                    continue
                add(name, {
                    "type": "faction_reward",
                    "id": f"faction_{faction}_{tier.reputation_required}",
                    "faction": faction,
                    "reputation": tier.reputation_required,
                    "tier_title": tier.title,
                    "quantity": rw.quantity,
                })

    return out
