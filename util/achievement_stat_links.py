"""
Links between achievements and custom stats, for the Achievement Tracker.

Single source of truth for the achievement <-> custom-stat sync logic. Two
relationships:

  EQUIVALENCES (bidirectional mirror): an achievement and a custom stat that
      are the exact same thing. Toggling either side flips the other, so
      completing the achievement flips the custom stat the optimizer already
      reads -- no optimizer changes needed.

  PARENT_CHILD (one-way auto-check): when the parent custom stat (an
      "explore every location in <region>" gate) is satisfied, the child
      achievement is implied complete and is auto-checked. Checking the child
      does NOT complete the parent, and a child may be checked independently
      (a manually-checked child is left alone if the parent is later cleared).

Region membership was derived from util/autogenerated/locations.py:
  Barbantok -> jarvonia, Noiseless Pass -> gdte, Myriadian Arc -> wrentmark,
  Darktide Trench -> syrenthia. GDTE has 17 locations and Jarvonia 21, matching
  the "Wetlands Explorer [17]" / "Arctic Explorer [21]" requirement targets.

Keep custom-stat ids in sync with util/custom_stats_catalog.py.
"""

# achievement_id  <->  custom_stat_id   (bidirectional mirror)
EQUIVALENCES = {
    'wetlands_explorer': 'explored_realm_gdte',
    'arctic_explorer': 'explored_realm_jarvonia',
}

# child achievement_id  ->  parent custom_stat_id   (one-way: parent done => child auto-checked)
#
# we_need_to_go_deeper: the "Essence of the swamp" is required to explore the
# GDTE bog, so a fully-explored GDTE implies you obtained it. (It is ALSO
# auto-checkable on its own via item ownership of "Essence of the swamp" --
# that lives on the parsed requirement's auto_source, not here.)
PARENT_CHILD = {
    'barbarian_village': 'explored_realm_jarvonia',
    'you_shall_not_pass!': 'explored_realm_gdte',
    'not_in_al_kharid_anymore': 'explored_realm_wrentmark',
    'trench_explorer': 'explored_realm_syrenthia',
    'we_need_to_go_deeper': 'explored_realm_gdte',
}


def custom_stat_for_achievement(achievement_id):
    """Return the equivalent custom-stat id for a mirrored achievement, or None."""
    return EQUIVALENCES.get(achievement_id)


def achievement_for_custom_stat(custom_stat_id):
    """Reverse of EQUIVALENCES: custom-stat id -> mirrored achievement id, or None."""
    for aid, sid in EQUIVALENCES.items():
        if sid == custom_stat_id:
            return aid
    return None


def parent_custom_stat_for_child(achievement_id):
    """Return the parent custom-stat id whose completion auto-checks this child."""
    return PARENT_CHILD.get(achievement_id)


def children_of_custom_stat(custom_stat_id):
    """All child achievement ids auto-checked when the given custom stat is done."""
    return [aid for aid, sid in PARENT_CHILD.items() if sid == custom_stat_id]
