#!/usr/bin/env python3
"""Shared pet species -> catalog resolution.

``PETS_BY_NAME`` is keyed by the pet's DISPLAY NAME — title-case with spaces,
e.g. ``'Golden Frog'``, ``'Pet Rock'``. Game exports and the UI, however, carry
the SPECIES id, which is snake_case: ``'golden_frog'``, ``'pet_rock'``.

Historically call sites resolved a species with a bare ``str.capitalize()``:

    PETS_BY_NAME.get(species.capitalize())   # 'golden_frog' -> 'Golden_frog'  ✗

``capitalize()`` only upper-cases the first letter and leaves the underscore, so
it matches ONLY single-word species (``'camel'`` -> ``'Camel'`` ✓) and silently
misses every multi-word pet. The Golden Frog and Pet Rock were therefore dropped
from the optimizer pet pool, never scored, never shown in the "applicable stats"
pet popup, and their abilities never surfaced (bug 83a55d82).

Resolve through here so every call site handles multi-word species — and rare
variants — identically.
"""


def pet_display_name(species) -> str:
    """Canonical ``PETS_BY_NAME`` key for a raw species id or name.

    ``'golden_frog'`` -> ``'Golden Frog'``, ``'Golden_frog'`` -> ``'Golden Frog'``,
    ``'pet_rock'`` -> ``'Pet Rock'``, ``'camel'`` -> ``'Camel'``,
    ``'Golden Frog'`` -> ``'Golden Frog'`` (idempotent).
    """
    return str(species or '').replace('_', ' ').strip().title()


def resolve_pet_levels(species):
    """Resolve a raw species id OR display name to its ``PetLevels`` object.

    Returns ``None`` when the species can't be resolved. Handles snake_case
    ids, legacy ``capitalize()`` strings, plain display names, and rare export
    names (rare-variant species that live in ``PETS_BY_RARE_EXPORT_NAME``).
    """
    if not species:
        return None
    from util.autogenerated.pets import PETS_BY_NAME, PETS_BY_RARE_EXPORT_NAME
    s = str(species).strip()
    return (
        PETS_BY_NAME.get(pet_display_name(s))
        or PETS_BY_NAME.get(s)
        or PETS_BY_NAME.get(s.capitalize())
        or PETS_BY_RARE_EXPORT_NAME.get(s.lower().replace(' ', '_'))
        or PETS_BY_RARE_EXPORT_NAME.get(s.lower())
    )


# Skill CATEGORY membership — mirrors ``SkillInstance.matches_skill`` in
# util/walkscape_constants.py. Pets group their stats/abilities under either a
# concrete skill ('trinketry', 'hunting') OR a category ('artisan', 'gathering',
# 'utility'). Duplicated here (rather than imported) so this module stays
# dependency-free and safe to import from the autogenerated pets catalog.
_ARTISAN_SKILLS = {'carpentry', 'cooking', 'crafting', 'smithing', 'trinketry', 'tailoring'}
_GATHERING_SKILLS = {'fishing', 'foraging', 'mining', 'woodcutting', 'hunting'}
_UTILITY_SKILLS = {'agility'}


def stat_key_matches_skill(stat_key, skill) -> bool:
    """Does an ability_stats / stat skill KEY apply to a concrete SKILL?

    Matches an exact skill-name key AND the three category keys the game groups
    pets under (artisan / gathering / utility). ``'global'`` is deliberately NOT
    matched here: a global ability is not tied to any skill, and the ability-pet
    selector must not force-equip a global-ability pet for every skill.
    """
    if not stat_key or not skill:
        return False
    k = str(stat_key).lower()
    s = str(skill).lower()
    if k == s:
        return True
    if k == 'artisan':
        return s in _ARTISAN_SKILLS
    if k == 'gathering':
        return s in _GATHERING_SKILLS
    if k == 'utility':
        return s in _UTILITY_SKILLS
    return False


def ability_stats_apply_to_skill(ability_stats, skill_type) -> bool:
    """True if any non-``global`` key in an ``ability_stats`` dict applies to
    ``skill_type`` (exact skill name or its category, e.g. ``'artisan'`` for
    ``'crafting'``)."""
    if not ability_stats or not skill_type:
        return False
    return any(stat_key_matches_skill(k, skill_type) for k in ability_stats)
