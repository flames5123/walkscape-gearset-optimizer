        # Special cases to match existing conventions
        display = display.replace('Diving Gear', 'Diving gear')
        display = display.replace('Advanced Diving Gear', 'Advanced diving gear')
        display = display.replace('Expert Diving Gear', 'Expert diving gear')
        display = display.replace('Light Source', 'Light source')
        display = display.replace('Achievement Reward', 'Achievement reward')
        display = display.replace('Hunting Bow', 'Hunting bow')
        display = display.replace('Hunting Trap', 'Hunting trap')
        display = display.replace('Hunting Net', 'Hunting net')
        display = display.replace('Fishing Net', 'Fishing net')
