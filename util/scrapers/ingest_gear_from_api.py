def _resolve_special_table(item_name):
    """Map a 'roll_special_table' stat to its ItemFindingCategory by item name.

    The API doesn't say WHICH special table the item rolls, so infer from the
    item name: Adventurers' guild items roll the AGT table; spectral/ectoplasm
    gear rolls the ectoplasm table. Defaults to ectoplasm (the original hardcode)
    for unknown items, which should be reviewed.
    """
    n = (item_name or '').lower()
    if 'guild' in n or 'adventurer' in n:
        return 'ItemFindingCategory.ADVENTURERS_GUILD_TOKENS'
    if 'spectral' in n or 'ectoplasm' in n:
        return 'ItemFindingCategory.ECTOPLASM'
    print(f"  ⚠ roll_special_table on '{item_name}' — unknown table, defaulting to ECTOPLASM; review")
    return 'ItemFindingCategory.ECTOPLASM'


def parse_attrs(attrs, item_name=''):
    """Parse itemAttrs into nested stats dict {skill: {location: {stat: value}}}.

    Attrs gated behind a CollectibleOwned requirement are SKIPPED here — they are
    conditional (not always-on) and are handled by parse_collectible_gated_attrs().
    """
    stats = {}
    for attr in (attrs or []):
        # Skip collectible-gated attrs — routed to gated_stats['total_collectibles'].
        if _collectible_threshold(attr.get('requirements') or []) is not None:
            continue
        # Skip set-bonus attrs — routed to gated_stats['set_pieces'] (conditional,
        # not always-on). Without this the '... if wearing N set items' tiers get
        # summed into base stats (e.g. Treasure hunter bandolier +40% always-on).
        if _set_bonus_gate(attr.get('requirements') or []) is not None:
            continue
        attr_stats = attr.get('stats') or []
        reqs = attr.get('requirements') or []

        # Determine skill from requirements
        skill = 'global'
        location = 'global'
        for req in reqs:
            req_type = req.get('type', '')
            req_data = req.get('requirement', {})
            if req_type == 'mainSkill':
                skill = req_data.get('skill', 'global')
            elif req_type == 'mainSkillType':
                # Skill type like "gathering", "artisan" — maps to composite skill
                skill = req_data.get('type', 'global')
            elif req_type == 'location':
                location = req_data.get('location', 'global')
            elif req_type == 'locationHasKeywords':
                kws = req_data.get('keywords', [])
                if kws:
                    location = kws[0]  # e.g. 'underwater', 'spectral'
            elif req_type == 'realm':
                location = req_data.get('realm', 'global')

        for s in attr_stats:
            stat_name = s.get('stat', '')
            value = s.get('value', 0)
            is_percent = s.get('isPercent', True)
            is_negative = s.get('isNegative', False)

            # Map stat name
            if stat_name == 'steps_required':
                mapped = 'steps_percent' if is_percent else 'steps_add'
            elif stat_name == 'bonus_experience':
                mapped = 'bonus_xp_percent' if is_percent else 'bonus_xp_add'
            elif stat_name == 'roll_special_table':
                # The special table rolled is item-specific and NOT in the stat
                # payload — resolve it from the item name (e.g. Adventurers' guild
                # buckler -> AGT; Spectral gear -> ectoplasm).
                mapped = _resolve_special_table(item_name)
            else:
                mapped = STAT_MAP.get(stat_name)

            # Unknown/new stat types (e.g. the 3 new unused stats in this API
            # revision) aren't in STAT_MAP → skip silently rather than crash.
            if not mapped:
                continue

            # Convert: API stores as decimal (0.05 = 5%), we store as percentage (5.0)
            if is_percent and mapped not in ('steps_add', 'bonus_xp_add', 'quality_outcome', 'inventory_space'):
                stored_value = round(value * 100, 4)
            else:
                stored_value = value

            if is_negative:
                stored_value = -abs(stored_value)

            if skill not in stats:
                stats[skill] = {}
            if location not in stats[skill]:
                stats[skill][location] = {}
            # Accumulate (some items have multiple attrs for same stat)
            existing = stats[skill][location].get(mapped, 0)
            stats[skill][location][mapped] = round(existing + stored_value, 4)

    return stats


def parse_requirements(reqs):
    """Parse requirements list into our format."""
    result = []
    for req in (reqs or []):
        req_type = req.get('type', '')
        req_data = req.get('requirement', {})
        if req_type == 'skillLevel':
            result.append({
                'type': 'skill',
                'skill': req_data.get('skill', '').title(),
                'level': req_data.get('level', 1)
            })
        elif req_type == 'totalSkillLevel':
            result.append({
                'type': 'total_skill_level',
                'value': req_data.get('levels', 0)
            })
        elif req_type == 'reputation':
            result.append({
                'type': 'reputation',
                'faction': req_data.get('faction', ''),
                'amount': req_data.get('amount', 0)
            })
    return result


def get_existing_names():
    """Get set of item names already in equipment.py."""
    content = EQUIP_FILE.read_text()
    names = set()
    for m in re.finditer(r'name="([^"]+)"', content):
        names.add(m.group(1).lower())
    for m in re.finditer(r"name='([^']+)'", content):
        names.add(m.group(1).lower())
    return names


def format_stats(stats):
    """Format stats dict as Python literal."""
    if not stats:
        return '{}'
    lines = ['{']
    for skill, locs in stats.items():
        lines.append(f"            '{skill}': {{")
        for loc, stat_map in locs.items():
            stat_str = ', '.join(f"'{k}': {v}" for k, v in stat_map.items())
            lines.append(f"                '{loc}': {{{stat_str}}},")
        lines.append('            },')
    lines.append('        }')
    return '\n        '.join(lines)


def generate_item_instance(item):
    """Generate ItemInstance code for a non-crafted item."""
    name = item['name']
    enum_name = name_to_enum(name)
    uuid = item.get('id', f'item-{enum_name.lower()}')
    slot = item.get('gearType', 'tool')
    keywords = clean_keywords(item.get('keywords', []))
    rarity = item.get('quality', 'common')
    value = extract_item_value(item)
    reqs = parse_requirements(item.get('requirements', []))
    stats = parse_attrs(item.get('itemAttrs', []), name)
    gated = parse_collectible_gated_attrs(item.get('itemAttrs', []), name)
    gated.update(parse_set_bonus_attrs(item.get('itemAttrs', [])))

    kw_str = repr(keywords)
    req_str = repr(reqs) if reqs else '[]'
    stats_str = format_stats(stats)
    gated_str = repr(gated) if gated else '{}'

    return f'''
    {enum_name} = ItemInstance(
        name="{name}",
        uuid="item-{uuid}",
        stats={stats_str},
        slot="{slot}",
        keywords={kw_str},
        value={value},
        rarity='{rarity}',
        location_reqs=[],
        gated_stats={gated_str},
        requirements={req_str}
    )
'''


def generate_crafted_item(item):
    """Generate CraftedItem code for a crafted item."""
    name = item['name']
    enum_name = name_to_enum(name)
    uuid = item.get('id', f'item-{enum_name.lower()}')
    slot = item.get('gearType', 'tool')
    keywords = clean_keywords(item.get('keywords', []))
    value = extract_item_value(item)
    reqs = parse_requirements(item.get('requirements', []))

    # Base stats (common quality)
    base_stats = parse_attrs(item.get('itemAttrs', []), name)

    # Quality stats — API gives additions per quality, but CraftedItem.update() replaces
    # entire skill keys. So we need to compute CUMULATIVE stats (base + additions) for each quality.
    quality_stats = {}
    quality_values = {}
    for qa in (item.get('itemQualityAttrs') or []):
        q = qa.get('quality', '')
        q_name = QUALITY_MAP.get(q, q.title())
        q_additions = parse_attrs(qa.get('attributes', []), name)
        
        # Deep merge: base_stats + q_additions
        cumulative = {}
        # Start with base stats
        for skill, locs in base_stats.items():
            cumulative[skill] = {}
            for loc, stat_map in locs.items():
                cumulative[skill][loc] = dict(stat_map)
        # Add quality additions
        for skill, locs in q_additions.items():
            if skill not in cumulative:
                cumulative[skill] = {}
            for loc, stat_map in locs.items():
                if loc not in cumulative[skill]:
                    cumulative[skill][loc] = {}
                for stat, val in stat_map.items():
                    cumulative[skill][loc][stat] = round(cumulative[skill][loc].get(stat, 0) + val, 4)
        
        if cumulative:
            quality_stats[q_name] = cumulative
        quality_values[q_name] = extract_item_value(item, rarity_key=q)

    kw_str = repr(keywords)
    req_str = repr(reqs) if reqs else '[]'
    base_str = format_stats(base_stats)
    qs_str = repr(quality_stats) if quality_stats else '{}'
    qv_str = repr(quality_values) if quality_values else '{}'

    return f'''
    {enum_name} = CraftedItem(
        name="{name}",
        uuid="item-{uuid}",
        base_stats={base_str},
        quality_stats={qs_str},
        quality_values={qv_str},
        slot="{slot}",
        keywords={kw_str},
        value={value},
        requirements={req_str}
    )
'''


def main():
    print("Loading categorized items from API cache...")
    with open(CACHE_FILE) as f:
        categories = json.load(f)

    # Collect all gear items
    all_gear = []
    for cat in categories:
        for subcat in cat.get('categories', []):
            for item in subcat.get('items', []):
                if item.get('gearType'):  # Has a gear slot = it's equipment
                    all_gear.append(item)

    print(f"Total gear items in API: {len(all_gear)}")

    # Get existing names
    existing = get_existing_names()
    print(f"Items already in equipment.py: {len(existing)}")

    # Get material names to exclude (items that are in materials.py shouldn't be in equipment.py)
    mat_content = Path('util/autogenerated/materials.py').read_text()
    material_names = set()
    for m in re.finditer(r'name="([^"]+)"', mat_content):
        material_names.add(m.group(1).lower())

    # Also exclude items with type "material" or "consumable" in the API
    # These are crafting inputs, not equipment.
    # 'lore' items (new type) provide no gameplay benefit yet — skip them too.
    EXCLUDE_TYPES = {'material', 'consumable', 'collectible', 'lore'}

    # Find missing items
    missing = []
    for i in all_gear:
        name_lower = i['name'].lower()
        if name_lower in existing:
            continue
        if name_lower in material_names:
            continue
        if i.get('type', '') in EXCLUDE_TYPES:
            continue
        missing.append(i)

    print(f"Missing from equipment.py: {len(missing)}")

    if not missing:
        print("Nothing to add!")
        return

    # Generate code
    new_code = []
    crafted_count = 0
    instance_count = 0

    for item in missing:
        item_type = item.get('type', '')
        is_crafted = item_type == 'crafted'

        if is_crafted:
            new_code.append(generate_crafted_item(item))
            crafted_count += 1
        else:
            new_code.append(generate_item_instance(item))
            instance_count += 1

    print(f"  ItemInstance: {instance_count}")
    print(f"  CraftedItem: {crafted_count}")

    # Insert before the lookup dictionaries
    content = EQUIP_FILE.read_text()
    insert_marker = '\n\n# Lookup dictionaries'
    if insert_marker not in content:
        insert_marker = '\n\nITEMS_BY_NAME'
    if insert_marker not in content:
        # Append at end of Item class
        insert_marker = '\n\n\n# Lookup'

    joined = ''.join(new_code)
    if insert_marker in content:
        content = content.replace(insert_marker, joined + insert_marker, 1)
    else:
        content = content.rstrip() + '\n' + joined + '\n'

    EQUIP_FILE.write_text(content)
    print(f"\nWrote {len(missing)} new items to equipment.py")

    # Verify
