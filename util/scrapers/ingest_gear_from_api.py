def extract_item_value(item, rarity_key=None):
    """Coins/value from itemValue.

    The API changed itemValue from a string tier (legacy, mapped via VALUE_MAP)
    to a dict: {'currency': 'none'|'money', 'value': None | {rarity: number}}.
    - legacy str  -> VALUE_MAP lookup
    - dict, value None -> 0 (e.g. Pet Egg / valueless items)
    - dict, value {rarity: n} -> the number for the item's rarity (or the given
      rarity_key for per-quality crafted values); falls back to the sole/max entry.
    """
    iv = item.get('itemValue')
    if isinstance(iv, str):
        return VALUE_MAP.get(iv, 0)
    if isinstance(iv, dict):
        val = iv.get('value')
        if isinstance(val, dict) and val:
            key = (rarity_key or item.get('quality') or item.get('rarity') or '').lower()
            if key in val and val[key] is not None:
                return val[key]
            nums = [v for v in val.values() if isinstance(v, (int, float))]
            if not nums:
                return 0
            return nums[0] if len(nums) == 1 else max(nums)
        return val or 0  # None -> 0, or a bare number
    return 0


def name_to_enum(name):
    """Convert item name to Python enum constant."""
    n = re.sub(r"[^\w\s-]", '', name)
    n = n.replace(' ', '_').replace('-', '_').upper()
    n = re.sub(r'_+', '_', n).strip('_')
    if n and n[0].isdigit():
        n = '_' + n
    return n


