#!/usr/bin/env python3
"""Ingest per-item trade flags from the WalkScape tools API.

The detailed item response now exposes three authoritative booleans:

    canBeTraded   — item may be traded between players (authoritative tradable)
    canBeBanked   — item may be stored in the bank
    canBeDropped  — item may be dropped

These are NOT part of the legacy class-shaped autogenerated modules
(equipment.py / materials.py / consumables.py), so rather than regenerate
those large files we emit a small side module keyed by item id. The catalog
(ui/catalog.py via app.py) stamps these onto every emitted item dict and
`is_tradable` prefers `canBeTraded` over the old type heuristic.

Keys: each item is stored under BOTH its API id (slug) AND its name-derived
id (the exact `_name_to_id` form the catalog uses), so a lookup by either
resolves — eggs are keyed in the catalog by API id, everything else by name.

Run:  python3 util/scrapers/ingest_item_trade_flags.py
Output: util/autogenerated/item_trade_flags.py
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Dict

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
from util.scrapers.tools_api_client import ToolsAPIClient  # noqa: E402
from util.scrapers.tools_api_transform import write_python_data_module  # noqa: E402


def _name_to_id(name: str) -> str:
    """Mirror ui/catalog.py ItemCatalog._name_to_id exactly."""
    return (name or "").lower().replace(" ", "_").replace("(", "").replace(")", "").replace("-", "_").replace("'", "")


def run(client: ToolsAPIClient, *, use_cache: bool = False) -> int:
    items = client.list("items", use_cache=use_cache)
    print(f"  [trade_flags] hydrating {len(items)} items for canBeTraded/Banked/Dropped …")
    flags: Dict[str, Dict[str, Any]] = {}
    done = 0
    for it in items:
        iid = it.get("id")
        if not iid:
            continue
        try:
            d = client.get("items", iid, use_cache=use_cache)
        except Exception as e:  # noqa: BLE001
            print(f"    [skip] items/{iid}: {e}", file=sys.stderr)
            continue
        entry = {
            "canBeTraded": bool(d.get("canBeTraded")) if d.get("canBeTraded") is not None else None,
            "canBeBanked": bool(d.get("canBeBanked")) if d.get("canBeBanked") is not None else None,
            "canBeDropped": bool(d.get("canBeDropped")) if d.get("canBeDropped") is not None else None,
        }
        # Store under the API id AND the catalog name-id so either lookup resolves.
        flags[iid] = entry
        name_id = _name_to_id(d.get("name") or "")
        if name_id and name_id not in flags:
            flags[name_id] = entry
        done += 1
        if done % 100 == 0:
            print(f"    … {done}/{len(items)}")

    out = Path(__file__).resolve().parent.parent / "autogenerated" / "item_trade_flags.py"
    write_python_data_module(
        str(out), "ITEM_TRADE_FLAGS", flags,
        docstring="Per-item trade flags {id|name_id: {canBeTraded, canBeBanked, canBeDropped}} from the tools API detailed response.",
    )
    print(f"  [trade_flags] wrote {len(flags)} keys ({done} items) → {out}")
    return done


if __name__ == "__main__":
    raise SystemExit(0 if run(ToolsAPIClient(), use_cache=False) else 1)
