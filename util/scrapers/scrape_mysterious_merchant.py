#!/usr/bin/env python3
"""
Scraper for the Mysterious Merchant wiki page.

Parses https://wiki.walkscape.app/wiki/Mysterious_Merchant and emits
util/autogenerated/mysterious_merchant.py with:

  CHIP_TYPES          chip_id -> {section, display_name, icon_path, items:[slug,...]}
  ITEM_TO_CHIP_TYPE   slug -> chip_id  (reverse index)
  CHIP_PRICE_BY_RARITY rarity tier (1..6) -> (sell_value, buy_price)

Design notes / why this works (see .kiro/specs/sell-for-chips):
  * The merchant page groups item tables under three H2 sections:
    "Skilling Chests", "Regional Chests", "Guild Chests". Section is taken
    from the nearest preceding H2 (NOT the chip icon, which is offset-by-one
    and mis-sections Woodcutting / Halfling Rebels).
  * Each item row's Value/Price cell links to its chip currency page with a
    title like "Agility chip" -- this is the RELIABLE per-row chip-type signal.
  * Item ids are the snake_case slug (= Item enum name lowercased), which is
    exactly the key used by character `owned_quantities`, so the sell logic
    can join directly.
  * Per spec Req 1.6 we do NOT store per-item prices; prices are derived from
    rarity via CHIP_PRICE_BY_RARITY. We DO validate each row's wiki value/price
    against the rarity schedule and fail loudly on mismatch (spec gap G2).
  * The chip-type set is whatever the wiki currently exposes -- we do NOT
    hardcode a count.
"""

import sys
import os
import re

sys.path.insert(0, os.path.dirname(__file__))
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.dirname(__file__))))

from bs4 import BeautifulSoup

from scraper_utils import (
    download_with_retry,
    get_cache_file,
    get_output_file,
    write_module_header,
)
from util.misc_utils import resolve_item_reference, build_all_item_lookups

MERCHANT_URL = "https://wiki.walkscape.app/wiki/Mysterious_Merchant"
CACHE_FILE = "mysterious_merchant.html"
OUTPUT_FILE = "mysterious_merchant.py"

SECTION_HEADINGS = {
    "skilling chests": "skilling",
    "regional chests": "regional",
    "guild chests": "guild",
}

CHIP_ICON_DIR = "assets/icons/chips"


def _chip_id_from_title(title: str) -> str:
    """'Agility chip' -> 'agility_chip', 'Chest chips' -> 'chest_chips'."""
    return re.sub(r"\s+", "_", title.strip().lower())


def _slug_from_ref(ref: str) -> str:
    """'Item.WALKING_STICK' -> 'walking_stick' (matches owned_quantities keys)."""
    return ref.split(".", 1)[1].lower()


def _cell_int(cell) -> int | None:
    m = re.search(r"-?\d[\d,]*", cell.get_text(" ", strip=True))
    return int(m.group(0).replace(",", "")) if m else None


def _find_chip_title(*cells) -> str | None:
    """Return the chip currency name from a Value/Price cell's <a title='X chip'>."""
    for cell in cells:
        for a in cell.find_all("a"):
            title = (a.get("title") or "").strip()
            # currency pages are titled like "Agility chip" / "Chest chips"
            if re.search(r"\bchips?$", title.lower()):
                # strip "Special:MyLanguage/" prefixes some links carry
                return title.split("/")[-1].strip()
    return None


def _section_for_table(table) -> str | None:
    h = table.find_previous(["h2", "h3"])
    while h is not None:
        txt = h.get_text(" ", strip=True).lower()
        for key, sect in SECTION_HEADINGS.items():
            if key in txt:
                return sect
        h = h.find_previous(["h2", "h3"])
    return None


def parse_rarity_schedule(content) -> dict[int, tuple[int, int]]:
    """Parse the intro Rarity/Value/Price table -> {tier: (sell, buy)}."""
    schedule: dict[int, tuple[int, int]] = {}
    for table in content.find_all("table"):
        rows = table.find_all("tr")
        if not rows:
            continue
        header = [c.get_text(" ", strip=True).lower() for c in rows[0].find_all(["th", "td"])]
        # The schedule table header is exactly Rarity / Value / Price (no "Item Name")
        if "value" in header and "price" in header and "item name" not in header:
            tier = 0
            for row in rows[1:]:
                cells = row.find_all(["td", "th"])
                if len(cells) < 3:
                    continue
                sell = _cell_int(cells[-2])
                buy = _cell_int(cells[-1])
                if sell is None or buy is None:
                    continue
                tier += 1
                schedule[tier] = (sell, buy)
            if schedule:
                return schedule
    return schedule


def collect_chip_icons(content) -> dict[str, str]:
    """Map chip_id -> wiki icon src basename (e.g. 'Agility_chip.svg')."""
    icons: dict[str, str] = {}
    for img in content.find_all("img"):
        alt = (img.get("alt") or "").strip()
        if re.search(r"\bchips?$", alt.lower()):
            chip_id = _chip_id_from_title(alt)
            src = img.get("src") or ""
            if src:
                icons[chip_id] = os.path.basename(src)
    return icons


def scrape(rescrape: bool = False) -> dict:
    html = download_with_retry(MERCHANT_URL, get_cache_file(CACHE_FILE),
                               max_retries=1 if not rescrape else 3)
    if not html:
        raise SystemExit("Failed to download Mysterious Merchant page")

    soup = BeautifulSoup(html, "html.parser")
    content = soup.find("div", class_="mw-parser-output") or soup

    schedule = parse_rarity_schedule(content)
    if not schedule:
        raise SystemExit("Could not parse the rarity Value/Price schedule table")
    value_to_tier = {sell: tier for tier, (sell, _buy) in schedule.items()}

    chip_icons = collect_chip_icons(content)
    lookups = build_all_item_lookups()

    chip_types: dict[str, dict] = {}
    item_to_chip: dict[str, str] = {}
    unresolved: list[str] = []
    price_mismatches: list[str] = []

    for table in content.find_all("table"):
        rows = table.find_all("tr")
        if not rows:
            continue
        header = [c.get_text(" ", strip=True).lower() for c in rows[0].find_all(["th", "td"])]
        if "item name" not in header:
            continue
        section = _section_for_table(table) or "skilling"

        for row in rows[1:]:
            cells = row.find_all(["td", "th"])
            if len(cells) < 4:
                continue
            icon_cell, name_cell, value_cell, price_cell = cells[0], cells[1], cells[-2], cells[-1]

            name_link = name_cell.find("a")
            item_name = (name_link.get("title").split("/")[-1].strip()
                         if name_link and name_link.get("title")
                         else name_cell.get_text(" ", strip=True))
            if not item_name:
                continue

            chip_title = _find_chip_title(value_cell, price_cell)
            if not chip_title:
                continue
            chip_id = _chip_id_from_title(chip_title)

            value = _cell_int(value_cell)
            price = _cell_int(price_cell)

            ref = resolve_item_reference(item_name, lookups)
            if not ref or not ref.startswith("Item."):
                unresolved.append(f"{item_name!r} (chip={chip_id}, ref={ref})")
                continue
            slug = _slug_from_ref(ref)

            # Validate wiki value/price against the rarity schedule (spec gap G2):
            # the value uniquely identifies the rarity tier; assert price agrees.
            tier = value_to_tier.get(value)
            if tier is None:
                price_mismatches.append(f"{item_name}: value {value} not in schedule")
            elif schedule[tier] != (value, price):
                price_mismatches.append(
                    f"{item_name}: wiki=({value},{price}) schedule[{tier}]={schedule[tier]}")

            block = chip_types.setdefault(chip_id, {
                "section": section,
                "display_name": chip_title,
                "icon_path": f"{CHIP_ICON_DIR}/{chip_icons.get(chip_id, '_unknown_chip.svg')}",
                "items": [],
            })
            if slug not in block["items"]:
                block["items"].append(slug)
            item_to_chip[slug] = chip_id

    # Fail loudly on unresolved item ids (spec Req 1.5)
    if unresolved:
        msg = "Unresolved merchant item ids (not found in catalog):\n  " + "\n  ".join(unresolved)
        raise SystemExit(msg)
    if price_mismatches:
        msg = "Merchant price/rarity-schedule mismatches:\n  " + "\n  ".join(price_mismatches)
        raise SystemExit(msg)

    return {
        "chip_types": chip_types,
        "item_to_chip": item_to_chip,
        "schedule": schedule,
        "chip_icons": chip_icons,
    }


def emit(data: dict) -> None:
    chip_types = data["chip_types"]
    item_to_chip = data["item_to_chip"]
    schedule = data["schedule"]

    out_path = get_output_file(OUTPUT_FILE)
    section_order = {"skilling": 0, "regional": 1, "guild": 2}
    ordered_chips = sorted(
        chip_types.items(),
        key=lambda kv: (section_order.get(kv[1]["section"], 9), kv[0]),
    )

    with open(out_path, "w", encoding="utf-8") as f:
        write_module_header(
            f,
            "Mysterious Merchant chip-trade data from the WalkScape wiki.",
            "scrape_mysterious_merchant.py",
        )
        f.write("# chip_id -> {section, display_name, icon_path, items:[item_slug, ...]}\n")
        f.write("CHIP_TYPES = {\n")
        for chip_id, block in ordered_chips:
            f.write(f"    {chip_id!r}: {{\n")
            f.write(f"        'section': {block['section']!r},\n")
            f.write(f"        'display_name': {block['display_name']!r},\n")
            f.write(f"        'icon_path': {block['icon_path']!r},\n")
            f.write(f"        'items': {sorted(block['items'])!r},\n")
            f.write("    },\n")
        f.write("}\n\n")

        f.write("# item slug -> chip_id (reverse index; slug == Item enum name lowercased)\n")
        f.write("ITEM_TO_CHIP_TYPE = {\n")
        for slug in sorted(item_to_chip):
            f.write(f"    {slug!r}: {item_to_chip[slug]!r},\n")
        f.write("}\n\n")

        f.write("# rarity tier (1..6) -> (sell_value, buy_price)\n")
        f.write("CHIP_PRICE_BY_RARITY = {\n")
        for tier in sorted(schedule):
            f.write(f"    {tier}: {schedule[tier]!r},\n")
        f.write("}\n")

    print(f"Wrote {out_path}")
    print(f"  chip types: {len(chip_types)}")
    print(f"  items mapped: {len(item_to_chip)}")
    print(f"  rarity tiers: {sorted(schedule)}")


def main():
    rescrape = "--rescrape" in sys.argv
    data = scrape(rescrape=rescrape)
    emit(data)
    # Summary by section
    by_section: dict[str, list[str]] = {}
    for chip_id, block in data["chip_types"].items():
        by_section.setdefault(block["section"], []).append(chip_id)
    for sect in ("skilling", "regional", "guild"):
        chips = sorted(by_section.get(sect, []))
        print(f"  {sect}: {len(chips)} chips -> {chips}")


if __name__ == "__main__":
    main()
