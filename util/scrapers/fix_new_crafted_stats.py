#!/usr/bin/env python3
"""
Re-parse stats for new API-ingested CraftedItems from the API cache.

Fixes:
1. mainSkillType mapping (gathering/artisan instead of global)
2. Cumulative quality stats (Normal = base, Good = Normal + diff, etc.)
3. Constant stats extracted to base_stats
4. Quality values from API itemValue + multipliers

Usage:
    python3 util/scrapers/fix_new_crafted_stats.py
"""
import json
import re
import copy
import math
import subprocess
from pathlib import Path

EQUIP = Path('util/autogenerated/equipment.py')
CACHE = Path('temp_gear_app_cache/api_items_categorized_fresh.json')
QUALITY_ORDER = ['Normal', 'Good', 'Great', 'Excellent', 'Perfect', 'Eternal']
API_QUALITY_MAP = {'common': 'Normal', 'uncommon': 'Good', 'rare': 'Great',
                   'epic': 'Excellent', 'legendary': 'Perfect', 'ethereal': 'Eternal'}

# Value tiers from the game
VALUE_MAP = {
    'none': 0, 'veryLow': 1, 'low': 2, 'lowMedium': 4, 'medium': 7,
    'mediumHigh': 11, 'high': 20, 'veryHigh': 34, 'extreme': 54,
    'veryExtreme': 75, 'legendary': 117, 'ethereal': 319,
}

# Quality value multipliers (derived from wiki-scraped items)
# Normal=1.0, Good≈2.02, Great≈3.07, Excellent≈4.13, Perfect≈5.79, Eternal≈9.36
QUALITY_MULTIPLIERS = {
    'Normal': 1.0, 'Good': 2.02, 'Great': 3.07,
    'Excellent': 4.13, 'Perfect': 5.79, 'Eternal': 9.36,
}

STAT_MAP = {
    'work_efficiency': 'work_efficiency',
    'double_action': 'double_action',
    'double_rewards': 'double_rewards',
    'chest_finding': 'chest_finding',
    'fine_material_finding': 'fine_material_finding',
    'find_collectibles': 'find_collectibles',
    'find_gems': 'find_gems',
    'find_bird_nests': 'find_bird_nests',
    'find_bird_nest': 'ItemFindingCategory.BIRD_NEST',
    'no_materials_consumed': 'no_materials_consumed',
    'quality_outcome': 'quality_outcome',
    'inventory_space': 'inventory_space',
    'item_finding': 'item_finding',
    'roll_special_table': 'ItemFindingCategory.ECTOPLASM',
}


def parse_attrs_correct(attrs):
    """Parse API attrs with correct mainSkillType handling."""
    stats = {}
    for attr in (attrs or []):
        attr_stats = attr.get('stats') or []
        reqs = attr.get('requirements') or []

        skill = 'global'
        location = 'global'
        for req in reqs:
            req_type = req.get('type', '')
            req_data = req.get('requirement', {})
            if req_type == 'mainSkill':
                skill = req_data.get('skill', 'global')
            elif req_type == 'mainSkillType':
                skill = req_data.get('type', 'global')
            elif req_type == 'location':
                location = req_data.get('location', 'global')
            elif req_type == 'locationHasKeywords':
                kws = req_data.get('keywords', [])
                if kws:
                    location = kws[0]
            elif req_type == 'realm':
                location = req_data.get('realm', 'global')

        for s in attr_stats:
            stat_name = s.get('stat', '')
            value = s.get('value', 0)
            is_percent = s.get('isPercent', True)
            is_negative = s.get('isNegative', False)

            if stat_name == 'steps_required':
                mapped = 'steps_percent' if is_percent else 'steps_add'
            elif stat_name == 'bonus_experience':
                mapped = 'bonus_xp_percent' if is_percent else 'bonus_xp_add'
            else:
                mapped = STAT_MAP.get(stat_name)

            if not mapped:
                continue

            if is_percent and mapped not in ('steps_add', 'bonus_xp_add', 'quality_outcome', 'inventory_space'):
                stored_value = round(value * 100, 4)
            else:
                stored_value = value

            if is_negative:
                stored_value = -abs(stored_value)

            if skill not in stats:
                stats[skill] = {}
            if location not in stats[skill]:
                stats[skill][location] = {}
            existing = stats[skill][location].get(mapped, 0)
            stats[skill][location][mapped] = round(existing + stored_value, 4)

    return stats


def deep_add(base, additions):
    result = copy.deepcopy(base)
    for skill, locs in additions.items():
        if skill not in result:
            result[skill] = {}
        for loc, stats in locs.items():
            if loc not in result[skill]:
                result[skill][loc] = {}
            for stat, val in stats.items():
                result[skill][loc][stat] = round(result[skill][loc].get(stat, 0) + val, 4)
    return result


def find_constant_stats(cumulative_qs):
    """Find stats identical across ALL quality tiers → move to base_stats."""
    stat_values = {}
    num_q = len(cumulative_qs)
    for q_stats in cumulative_qs.values():
        for skill, locs in q_stats.items():
            for loc, stats in locs.items():
                for stat, val in stats.items():
                    key = (skill, loc, stat)
                    if key not in stat_values:
                        stat_values[key] = []
                    stat_values[key].append(val)

    constant_keys = set()
    for key, vals in stat_values.items():
        if len(vals) == num_q and len(set(vals)) == 1:
            constant_keys.add(key)

    base = {}
    for skill, loc, stat in constant_keys:
        base.setdefault(skill, {}).setdefault(loc, {})[stat] = stat_values[(skill, loc, stat)][0]

    cleaned_qs = {}
    for q_name, q_stats in cumulative_qs.items():
        cleaned = {}
        for skill, locs in q_stats.items():
            for loc, stats in locs.items():
                remaining = {s: v for s, v in stats.items() if (skill, loc, s) not in constant_keys}
                if remaining:
                    cleaned.setdefault(skill, {})[loc] = remaining
        cleaned_qs[q_name] = cleaned

    return base, cleaned_qs


# Load API data
with open(CACHE) as f:
    categories = json.load(f)

api_items = {}
for cat in categories:
    for sub in cat.get('categories', []):
        for item in sub.get('items', []):
            api_items[item['name'].lower()] = item

# Read equipment.py
content = EQUIP.read_text()

# Find the new CraftedItems (quality_stats with 'Normal' key = API-ingested)
pattern = re.compile(
    r"(    (\w+) = CraftedItem\(\n"
    r"        name=\"([^\"]+)\",\n"
    r"        uuid=\"([^\"]+)\",\n)"
    r"        base_stats=(.+?),\n"
    r"        quality_stats=(\{.+?\}),\n"
    r"        quality_values=(\{.+?\}),",
    re.DOTALL
)

fixed = 0
offset = 0

for m in pattern.finditer(content):
    enum_name = m.group(2)
    name = m.group(3)
    uuid = m.group(4)

    # Only process items with 'Normal' in quality_stats (the new ones)
    qs_str = m.group(6)
    if "'Normal'" not in qs_str:
        continue

    # Find in API
    api_item = api_items.get(name.lower())
    if not api_item:
        print(f"  ⚠ {name}: not found in API cache")
        continue

    # Re-parse stats from API with correct skill mapping
    base_normal = parse_attrs_correct(api_item.get('itemAttrs', []))

    # Build cumulative quality stats
    cumulative = {}
    prev = copy.deepcopy(base_normal)
    cumulative['Normal'] = prev

    for qa in (api_item.get('itemQualityAttrs') or []):
        q_api = qa.get('quality', '')
        q_name = API_QUALITY_MAP.get(q_api, q_api.title())
        diff = parse_attrs_correct(qa.get('attributes', []))
        prev = deep_add(prev, diff)
        cumulative[q_name] = copy.deepcopy(prev)

    # Extract constant stats to base_stats
    base_stats, quality_stats = find_constant_stats(cumulative)

    # Compute quality values from API itemValue
    item_value_tier = api_item.get('itemValue', 'none')
    item_value_mod = api_item.get('itemValueModifier', 1.0) or 1.0
    base_value = VALUE_MAP.get(item_value_tier, 0)
    base_coin = max(1, math.floor(base_value * item_value_mod))

    quality_values = {}
    for q in QUALITY_ORDER:
        if q in cumulative:
            quality_values[q] = max(1, math.floor(base_coin * QUALITY_MULTIPLIERS.get(q, 1.0)))

    # Build replacement
    new_base = f"        base_stats={repr(base_stats) if base_stats else '{}'},"
    new_qs = f"        quality_stats={repr(quality_stats)},"
    new_qv = f"        quality_values={repr(quality_values)},"

    old_section = m.group(0)[len(m.group(1)):]
    new_section = f"{new_base}\n{new_qs}\n{new_qv}"

    start = m.start() + len(m.group(1)) + offset
    end = m.end() + offset
    content = content[:start] + new_section + content[end:]
    offset += len(new_section) - len(old_section)

    skill_info = list(base_stats.keys()) if base_stats else []
    q_skills = set()
    for qs in quality_stats.values():
        q_skills.update(qs.keys())
    print(f"  ✓ {name} (base: {skill_info}, quality: {list(q_skills)}, values: {quality_values.get('Normal', '?')}-{quality_values.get('Eternal', '?')})")
    fixed += 1

print(f"\nFixed {fixed} CraftedItems")

if fixed > 0:
    EQUIP.write_text(content)

r = subprocess.run(['python3', '-m', 'py_compile', str(EQUIP)], capture_output=True)
print("✓ Compiles OK" if r.returncode == 0 else f"✗ {r.stderr.decode()[:500]}")
