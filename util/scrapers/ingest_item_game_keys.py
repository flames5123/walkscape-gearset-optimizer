#!/usr/bin/env python3
"""Build the item -> game-export-key map for the Trading item identity contract.

The game's profile export writes each item under its internal key (e.g.
``birch_logs``, ``letter_from_a._a.``). A slug built from the display name does
NOT always match that key (``oak_log`` vs ``oak_logs``) and loses punctuation,
so Trading must store the real export key. The tools-API item detail ``id`` IS
that export key. We read it from the local scrape cache (no live call) and emit
a lookup keyed by BOTH the catalog name-id (``_name_to_id(name)``) and the exact
lowercased name, so the catalog can resolve game_key for any item.

Run: python3 util/scrapers/ingest_item_game_keys.py
Output: util/autogenerated/item_game_keys.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
from util.scrapers.tools_api_transform import write_python_data_module  # noqa: E402

CACHE = Path(__file__).resolve().parent.parent / "cache" / "tools_api_cache" / "items"


def _name_to_id(name: str) -> str:
    """Mirror ui/catalog.py ItemCatalog._name_to_id exactly."""
    return (name or "").lower().replace(" ", "_").replace("(", "").replace(")", "").replace("-", "_").replace("'", "")


def run() -> int:
    if not CACHE.is_dir():
        print(f"  [game_keys] cache dir not found: {CACHE}", file=sys.stderr)
        return 0
    keys: Dict[str, str] = {}
    n = 0
    for f in sorted(CACHE.glob("*.json")):
        try:
            d: Dict[str, Any] = json.loads(f.read_text())
        except Exception:
            continue
        if not isinstance(d, dict):
            continue
        export_key = d.get("id")
        name = d.get("name")
        if not export_key:
            continue
        # Identity + both catalog lookups resolve to the authoritative export key.
        keys[export_key] = export_key
        if name:
            keys[_name_to_id(name)] = export_key
            keys[name.lower()] = export_key
        n += 1
    out = Path(__file__).resolve().parent.parent / "autogenerated" / "item_game_keys.py"
    write_python_data_module(
        str(out), "ITEM_GAME_KEYS", keys,
        docstring="Lookup {export_key | name_id | lowercased_name: game_export_key} from the tools-API item detail id. Used to stamp the authoritative game item key onto /api/catalog items for Trading.",
    )
    print(f"  [game_keys] wrote {len(keys)} lookup keys from {n} items -> {out}")
    return n


if __name__ == "__main__":
    raise SystemExit(0 if run() else 1)
