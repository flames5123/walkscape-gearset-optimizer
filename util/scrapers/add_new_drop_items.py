#!/usr/bin/env python3
"""
Fetch new items from gear.walkscape.app that appear in drop tables
but are missing from our autogenerated files, and add them.

Items to add:
- Rabbit ears (Item, head, agility+hunting WE 2%)
- Swift sight goggles (Item, head, agility WE 35%)
- Weighted vest (Item, chest, agility WE -10%, BXP 20%, DR 6%)
- Halfmaw venom (Collectible, hunting WE 1%)
- Swampman article (Collectible - already exists as swamp_map_article.png)

Usage:
    python3 util/scrapers/add_new_drop_items.py
"""

import json
import sys
import os
from pathlib import Path
from urllib.request import Request, urlopen

sys.path.insert(0, '.')

API_BASE = 'https://gear.walkscape.app/api'

def fetch_item(item_id):
    req = Request(f"{API_BASE}/items/{item_id}", headers={'Accept': 'application/json', 'User-Agent': 'WalkscapeOptimizer/1.0'})
    with urlopen(req, timeout=10) as r:
        return json.loads(r.read())

def download_icon(icon_path, dest_path):
    """Download a PNG icon from the API."""
    url = f"https://gear.walkscape.app/api/icons/{icon_path}"
    req = Request(url, headers={'User-Agent': 'WalkscapeOptimizer/1.0'})
    dest = Path(dest_path)
    if dest.exists():
        print(f"  Icon already exists: {dest}")
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    with urlopen(req, timeout=10) as r:
        dest.write_bytes(r.read())
    print(f"  Downloaded icon: {dest}")

