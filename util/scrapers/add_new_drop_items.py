def add_collectible_items():
    """Add new CollectibleInstance entries to collectibles.py."""
    coll_path = Path('util/autogenerated/collectibles.py')
    content = coll_path.read_text()

    new_items = []

    # Halfmaw venom - hunting WE 1%
    if 'HALFMAW_VENOM' not in content:
        new_items.append('''
    HALFMAW_VENOM = CollectibleInstance(
        name="Halfmaw venom",
        stats={
            'hunting': {'global': {'work_efficiency': 1.0}},
        },
        requirements=[],
    )
''')
        print("  + HALFMAW_VENOM")

    if not new_items:
        print("  All collectible items already present")
        return

    # Insert before lookup dict
    insert_marker = '\n\nCOLLECTIBLES_BY_NAME'
    if insert_marker in content:
        content = content.replace(insert_marker, ''.join(new_items) + insert_marker)
    else:
        insert_marker = '\n\ndef by_export_name'
        if insert_marker in content:
            content = content.replace(insert_marker, ''.join(new_items) + insert_marker)

    coll_path.write_text(content)
    print(f"  Updated collectibles.py")


# ============================================================================
# DOWNLOAD ICONS
# ============================================================================

def download_icons():
    icons = [
        ('assets/icons/items/gear/rabbit_ears.png', 'assets/icons/items/equipment/rabbit_ears.png'),
        ('assets/icons/items/gear/skill_gear/agility/swift_sight_goggles.png', 'assets/icons/items/equipment/swift_sight_goggles.png'),
        ('assets/icons/items/gear/weighted_vest.png', 'assets/icons/items/equipment/weighted_vest.png'),
        ('assets/icons/items/materials/halfmaw_venom.png', 'assets/icons/items/collectibles/halfmaw_venom.png'),
    ]
    for api_path, local_path in icons:
        try:
            download_icon(api_path, local_path)
        except Exception as e:
            print(f"  ✗ Failed to download {api_path}: {e}")


# ============================================================================
# MAIN
# ============================================================================

if __name__ == '__main__':
    print("Adding new equipment items...")
    add_equipment_items()

    print("\nAdding new collectible items...")
    add_collectible_items()

    print("\nDownloading icons...")
    download_icons()

    print("\nVerifying compilation...")
    import subprocess
    for f in ['util/autogenerated/equipment.py', 'util/autogenerated/collectibles.py']:
        r = subprocess.run(['python3', '-m', 'py_compile', f], capture_output=True)
        if r.returncode == 0:
            print(f"  ✓ {f}")
        else:
            print(f"  ✗ {f}: {r.stderr.decode()}")

    print("\nRe-running activities scraper to resolve new item_refs...")
    r = subprocess.run(['python3', 'util/scrapers/scrape_activities.py'], capture_output=True, text=True)
    # Show just the missing items report
    lines = r.stdout.split('\n')
    for i, line in enumerate(lines):
        if 'Missing Items' in line or 'unique missing' in line or ('activities' in line and '-' in line):
            print(line)
    print("Done!")
