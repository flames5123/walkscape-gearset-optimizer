# ADD TO equipment.py
# ============================================================================

def add_equipment_items():
    """Add new ItemInstance entries to equipment.py."""
    equip_path = Path('util/autogenerated/equipment.py')
    content = equip_path.read_text()

    new_items = []

    # Rabbit ears - head, agility+hunting WE 2% each
    if 'RABBIT_EARS' not in content:
        new_items.append('''
    RABBIT_EARS = ItemInstance(
        name="Rabbit ears",
        uuid="item-rabbit_ears",
        stats={
            'agility': {'global': {'work_efficiency': 2.0}},
            'hunting': {'global': {'work_efficiency': 2.0}},
        },
        slot="head",
        keywords=['agility', 'hunting'],
        value=0,
        rarity='uncommon',
        location_reqs=[],
        gated_stats={},
        requirements=[{'type': 'skill', 'skill': 'Agility', 'level': 1}]
    )
''')
        print("  + RABBIT_EARS")

    # Swift sight goggles - head, agility WE 35%
    if 'SWIFT_SIGHT_GOGGLES' not in content:
        new_items.append('''
    SWIFT_SIGHT_GOGGLES = ItemInstance(
        name="Swift sight goggles",
        uuid="item-swift_sight_goggles",
        stats={
            'agility': {'global': {'work_efficiency': 35.0}},
        },
        slot="head",
        keywords=['agility'],
        value=0,
        rarity='epic',
        location_reqs=[],
        gated_stats={},
        requirements=[{'type': 'skill', 'skill': 'Agility', 'level': 60}]
    )
''')
        print("  + SWIFT_SIGHT_GOGGLES")

    # Weighted vest - chest, agility WE -10%, BXP 20%, DR 6%
    if 'WEIGHTED_VEST' not in content:
        new_items.append('''
    WEIGHTED_VEST = ItemInstance(
        name="Weighted vest",
        uuid="item-weighted_vest",
        stats={
            'agility': {'global': {'work_efficiency': -10.0, 'bonus_xp_percent': 20.0, 'double_rewards': 6.0}},
        },
        slot="chest",
        keywords=['heavy', 'agility'],
        value=0,
        rarity='epic',
        location_reqs=[],
        gated_stats={},
        requirements=[{'type': 'skill', 'skill': 'Agility', 'level': 40}]
    )
''')
        print("  + WEIGHTED_VEST")

    if not new_items:
        print("  All equipment items already present")
        return

    # Insert before the closing of the Item class (before ITEMS_BY_NAME or end of class)
    insert_marker = '\n\n# Lookup dictionaries'
    if insert_marker in content:
        content = content.replace(insert_marker, ''.join(new_items) + insert_marker)
    else:
        # Fallback: append before last line
        content = content.rstrip() + '\n' + ''.join(new_items) + '\n'

    equip_path.write_text(content)
    print(f"  Updated equipment.py")


