#!/usr/bin/env python3
"""
Merge the wiki's authoritative sell-capability into util/autogenerated/shops.py.

The WalkScape wiki is the source of truth for whether a shop accepts player
sales: each shop page's "Purchases" section reads "Nothing may be sold at this
shop." when it does not. The tools API has NO reliable flag for this (clothing /
cosmetic shops report onlyPurchaseSellingListItems=false yet still cannot be sold
to), so we overlay the wiki signal onto the shop data.

scrape_shops.py already parses this text when it regenerates shops.py from the
wiki. This standalone merge does the same thing WITHOUT the network / requests
dependency: it reads the cached wiki shop pages (util/cache/shops_cache/*.html)
and rewrites the `can_sell` field on each ShopInfo entry in shops.py to match.
Run it after any shop data refresh (wiki scrape or API scrape) to keep the
Peddle-To-The-Mettle checklist limited to shops you can actually sell at.

Usage:
    python3 util/scrapers/merge_wiki_can_sell.py            # apply
    python3 util/scrapers/merge_wiki_can_sell.py --dry-run  # preview only
"""
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SHOPS_PY = REPO_ROOT / 'util' / 'autogenerated' / 'shops.py'
CACHE_DIR = REPO_ROOT / 'util' / 'cache' / 'shops_cache'
SENTINEL = 'nothing may be sold at this shop'

# Matches:  name='Shop Name', building_type='...',
NAME_LINE = re.compile(r"^(\s*)name='(?P<name>(?:[^'\\]|\\.)*)', building_type=")


def wiki_can_sell(shop_name: str):
    """True/False from the cached wiki page, or None if no cached page."""
    page = CACHE_DIR / f'{shop_name}.html'
    if not page.exists():
        return None
    return SENTINEL not in page.read_text(encoding='utf-8').lower()


def main():
    dry_run = '--dry-run' in sys.argv
    lines = SHOPS_PY.read_text(encoding='utf-8').splitlines()
    out = []
    changed = []
    entry_start = re.compile(r'^\w+ = ShopInfo\($')
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        if not entry_start.match(line):
            out.append(line)
            i += 1
            continue
        # Collect the full ShopInfo(...) block up to the closing ')' at column 0.
        block = [line]
        j = i + 1
        while j < n and lines[j] != ')':
            block.append(lines[j])
            j += 1
        if j < n:
            block.append(lines[j])  # the closing ')'
        # Determine the shop name + wiki sell-capability.
        name = None
        name_idx = None
        for k, bl in enumerate(block):
            m = NAME_LINE.match(bl)
            if m:
                name = m.group('name').replace("\\'", "'").replace('\\\\', '\\')
                name_idx = k
                break
        # Strip any existing can_sell= line(s) from the block.
        had_can_sell = any(b.strip().startswith('can_sell=') for b in block)
        block = [b for b in block if not b.strip().startswith('can_sell=')]
        # Recompute name_idx after stripping (can_sell was never before the name line).
        can = wiki_can_sell(name) if name else None
        if can is False and name_idx is not None:
            indent = NAME_LINE.match(block[name_idx]).group(1)
            block.insert(name_idx + 1, f'{indent}can_sell=False,')
            if not had_can_sell:
                changed.append((name, 'ADD can_sell=False'))
        elif had_can_sell:
            changed.append((name or '?', 'REMOVE can_sell (now sellable)'))
        out.extend(block)
        i = j + 1

    print(f'shops.py entries scanned; {len(changed)} change(s):')
    for name, what in changed:
        print(f'  {what:34} {name}')
    if dry_run:
        print('(dry-run — no file written)')
        return
    SHOPS_PY.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'Wrote {SHOPS_PY}')


if __name__ == '__main__':
    main()
