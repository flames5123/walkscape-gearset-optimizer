#!/usr/bin/env python3
"""
Find consumables in the API that are missing from consumables.py and add them.
"""
import json, re, subprocess
from pathlib import Path

CACHE = Path('temp_gear_app_cache/api_items_categorized_fresh.json')
CONS_FILE = Path('util/autogenerated/consumables.py')

STAT_MAP = {
    'work_efficiency': 'work_efficiency',
    'double_action': 'double_action',
    'double_rewards': 'double_rewards',
    'steps_required': 'steps_add',
    'chest_finding': 'chest_finding',
    'fine_material_finding': 'fine_material_finding',
    'find_collectibles': 'find_collectibles',
    'find_gems': 'find_gems',
    'find_bird_nests': 'find_bird_nests',
    'find_bird_nest': 'ItemFindingCategory.BIRD_NEST',
    'no_materials_consumed': 'no_materials_consumed',
    'quality_outcome': 'quality_outcome',
    'bonus_experience': 'bonus_xp_percent',
    'inventory_space': 'inventory_space',
}

SKILL_NAMES = {
    'agility', 'carpentry', 'cooking', 'crafting', 'fishing',
    'foraging', 'hunting', 'mining', 'smithing', 'tailoring',
    'trinketry', 'woodcutting', 'global', 'gathering', 'artisan',
}

def name_to_enum(name):
    n = re.sub(r"[^\w\s-]", '', name)
    n = n.replace(' ', '_').replace('-', '_').upper()
    n = re.sub(r'_+', '_', n).strip('_')
    if n and n[0].isdigit():
        n = '_' + n
    return n

def clean_keywords(raw):
    cleaned = []
    for kw in (raw or []):
        kw_lower = kw.lower().strip()
        if kw_lower in SKILL_NAMES:
            continue
        display = kw_lower.replace('_', ' ').title()
        if not cleaned or display not in cleaned:
            cleaned.append(display)
    return cleaned

def parse_consumable_stats(item):
    """Parse consumable attributes into nested stats dict."""
    stats = {}
    for attr in item.get('itemAttrs', []) + item.get('materialAttrs', []):
        reqs = attr.get('requirements') or []
        skill = 'global'
        location = 'global'
        for req in reqs:
            if req.get('type') == 'mainSkill':
                skill = req.get('requirement', {}).get('skill', 'global')
            elif req.get('type') == 'location':
                location = req.get('requirement', {}).get('location', 'global')

        for s in attr.get('stats', []):
            stat_name = s.get('stat', '')
            value = s.get('value', 0)
            is_percent = s.get('isPercent', True)
            is_negative = s.get('isNegative', False)

            if stat_name == 'steps_required':
                mapped = 'steps_percent' if is_percent else 'steps_add'
            elif stat_name == 'bonus_experience':
                mapped = 'bonus_xp_percent' if is_percent else 'bonus_xp_add'
            else:
                mapped = STAT_MAP.get(stat_name)
            if not mapped:
                continue

            if is_percent and mapped not in ('steps_add', 'bonus_xp_add', 'quality_outcome', 'inventory_space'):
                stored = round(value * 100, 4)
            else:
                stored = value
            if is_negative:
                stored = -abs(stored)

            if skill not in stats:
                stats[skill] = {}
            if location not in stats[skill]:
                stats[skill][location] = {}
            stats[skill][location][mapped] = stats[skill][location].get(mapped, 0) + stored

    return stats

# Load API data
with open(CACHE) as f:
    categories = json.load(f)

api_consumables = []
for cat in categories:
    for sub in cat.get('categories', []):
        for item in sub.get('items', []):
            if item.get('type') == 'consumable' or item.get('consumableType'):
                api_consumables.append(item)

print(f"Consumables in API: {len(api_consumables)}")

# Get existing names
content = CONS_FILE.read_text()
existing = set()
for m in re.finditer(r'name="([^"]+)"', content):
    existing.add(m.group(1).lower())

missing = [c for c in api_consumables if c['name'].lower() not in existing]
print(f"Missing from consumables.py: {len(missing)}")

if not missing:
    print("Nothing to add!")
    exit(0)

for m in missing:
    print(f"  + {m['name']} ({m.get('consumableType', '?')})")

# Generate code
new_entries = []
for item in missing:
    name = item['name']
    enum = name_to_enum(name)
    keywords = clean_keywords(item.get('keywords', []))
    stats = parse_consumable_stats(item)
    duration = 1000  # Default
    value = 0

    # Format stats
    stats_str = repr(stats) if stats else '{}'

    entry = f"""
    {enum} = ConsumableItem(
        name="{name}",
        keywords={repr(keywords)},
        attributes={stats_str},
        duration={duration},
        value={value}
    )
"""
    new_entries.append(entry)

# Insert before the lookup section
insert_marker = '\n\n# Lookup'
if insert_marker not in content:
    insert_marker = '\nCONSUMABLES_BY_NAME'

joined = ''.join(new_entries)
if insert_marker in content:
    content = content.replace(insert_marker, joined + insert_marker, 1)
else:
    content = content.rstrip() + '\n' + joined + '\n'

CONS_FILE.write_text(content)
print(f"\nAdded {len(missing)} consumables")

r = subprocess.run(['python3', '-m', 'py_compile', str(CONS_FILE)], capture_output=True)
print("✓ Compiles OK" if r.returncode == 0 else f"✗ {r.stderr.decode()[:300]}")
