#!/usr/bin/env python3
"""
Migration script: Match generic items to real equipment items.

For each generic item that now has a real equivalent in equipment.py,
this script will:
1. Mark the real item as owned in the session's ui_config (user_overrides)
2. Copy quality from the generic item to the real item
3. Replace generic:: references in gearset slots with real item IDs
4. Mark the generic item as migrated

Run with --dry-run first to see what would change.

Usage:
    python3 util/scrapers/migrate_generic_to_real.py --dry-run
    python3 util/scrapers/migrate_generic_to_real.py --execute
"""

import re
import sys
import json
import sqlite3
from pathlib import Path

DRY_RUN = '--execute' not in sys.argv


def name_to_id(name):
    """Convert item name to catalog ID format."""
    return name.lower().replace(' ', '_').replace('(', '').replace(')', '').replace('-', '_').replace("'", '')


def get_real_items():
    """Extract all item names and types from equipment.py."""
    content = Path('util/autogenerated/equipment.py').read_text()
    items = {}
    # Match both ItemInstance and CraftedItem
    for m in re.finditer(r'name="([^"]+)"', content):
        items[m.group(1).lower()] = m.group(1)
    for m in re.finditer(r"name='([^']+)'", content):
        items[m.group(1).lower()] = m.group(1)
    
    # Determine which are crafted
    crafted = set()
    for m in re.finditer(r'(\w+)\s*=\s*CraftedItem\(', content):
        # Find the name for this CraftedItem
        start = m.end()
        name_match = re.search(r'name="([^"]+)"', content[start:start+200])
        if name_match:
            crafted.add(name_match.group(1).lower())
    
    return items, crafted


def main():
    real_items, crafted_items = get_real_items()
    print(f"Real items in equipment.py: {len(real_items)} ({len(crafted_items)} crafted)")

    db_path = 'sessions.db'
    if not Path(db_path).exists():
        # Try ui/ subdirectory
        db_path = 'ui/sessions.db'
        if not Path(db_path).exists():
            print("ERROR: sessions.db not found")
            sys.exit(1)

    db = sqlite3.connect(db_path)
    db.row_factory = sqlite3.Row

    # Get all generic gear items (not consumables/collectibles/pets/inputs)
    generics = db.execute(
        "SELECT id, name, slot, session_uuid, is_crafted, stats_json, "
        "quality_stats_json FROM generic_items "
        "WHERE slot NOT IN ('consumable', 'collectible', 'pet', 'input', '0') "
        "ORDER BY name"
    ).fetchall()

    print(f"Generic gear items in DB: {len(generics)}")
    print(f"Mode: {'DRY RUN' if DRY_RUN else 'EXECUTE'}")
    print()

    matched = []
    unmatched = []
    test_items = []

    for g in generics:
        name = g['name']
        name_lower = name.lower()

        # Skip test/example items
        if name_lower.startswith('example:') or name_lower.startswith('test '):
            test_items.append(name)
            continue

        # Check if already migrated (via name convention)
        # Skip items we've already processed

        if name_lower in real_items:
            matched.append({
                'generic_id': g['id'],
                'generic_name': name,
                'real_name': real_items[name_lower],
                'real_id': name_to_id(real_items[name_lower]),
                'slot': g['slot'],
                'session_uuid': g['session_uuid'],
                'is_crafted': bool(g['is_crafted']),
                'is_real_crafted': name_lower in crafted_items,
            })
        else:
            unmatched.append(name)

    print(f"Matched to real items: {len(matched)}")
    for m in matched:
        craft_label = " (crafted)" if m['is_real_crafted'] else ""
        print(f"  ✓ {m['generic_name']} → {m['real_name']}{craft_label} (slot: {m['slot']})")

    print(f"\nUnmatched (no real equivalent): {len(unmatched)}")
    for n in sorted(set(unmatched)):
        print(f"  ? {n}")

    print(f"\nTest/example items (skip): {len(test_items)}")

    if not DRY_RUN and matched:
        print(f"\n{'='*50}")
        print(f"Executing migration...")
        print(f"{'='*50}")

        # Group by session for efficiency
        by_session = {}
        for m in matched:
            by_session.setdefault(m['session_uuid'], []).append(m)

        sessions_updated = 0
        gearsets_updated = 0
        items_marked_owned = 0

        for session_uuid, items in by_session.items():
            # Load session ui_config
            row = db.execute(
                "SELECT ui_config FROM sessions WHERE uuid = ?",
                (session_uuid,)
            ).fetchone()
            if not row:
                continue

            ui_config = json.loads(row['ui_config'] or '{}')
            overrides = ui_config.setdefault('user_overrides', {})
            override_items = overrides.setdefault('items', {})

            session_changed = False

            for m in items:
                real_id = m['real_id']

                # Mark real item as owned (if not already)
                if real_id not in override_items or not override_items[real_id].get('has'):
                    if real_id not in override_items:
                        override_items[real_id] = {}
                    override_items[real_id]['has'] = True

                    # For crafted items, try to copy quality from generic
                    if m['is_real_crafted'] and m['is_crafted']:
                        # Generic crafted items store quality in the generic item's state
                        generic_state = override_items.get(f"generic::item::{m['generic_id']}", {})
                        quality = generic_state.get('quality', 'Normal')
                        override_items[real_id]['quality'] = quality
                        print(f"  ✓ {m['real_name']}: owned=true, quality={quality}")
                    else:
                        print(f"  ✓ {m['real_name']}: owned=true")

                    items_marked_owned += 1
                    session_changed = True

            # Update gearset references
            gearsets = db.execute(
                "SELECT id, name, slots_json FROM gear_sets WHERE session_uuid = ?",
                (session_uuid,)
            ).fetchall()

            for gs in gearsets:
                slots = json.loads(gs['slots_json']) if gs['slots_json'] else {}
                gs_changed = False
                for slot_name, item_data in slots.items():
                    if isinstance(item_data, dict) and item_data.get('id', '').startswith('generic::'):
                        # Match by name
                        generic_item_name = item_data.get('name', '').lower()
                        for m in items:
                            if generic_item_name == m['generic_name'].lower():
                                print(f"  Gearset '{gs['name']}': {slot_name} → {m['real_id']}")
                                item_data['id'] = m['real_id']
                                item_data.pop('generic', None)
                                gs_changed = True
                                break

                if gs_changed:
                    db.execute(
                        "UPDATE gear_sets SET slots_json = ? WHERE id = ?",
                        (json.dumps(slots), gs['id'])
                    )
                    gearsets_updated += 1

            # Save ui_config if changed
            if session_changed:
                db.execute(
                    "UPDATE sessions SET ui_config = ? WHERE uuid = ?",
                    (json.dumps(ui_config), session_uuid)
                )
                sessions_updated += 1

            # Mark generic items as migrated (best-effort, skip if column doesn't exist)
            for m in items:
                try:
                    db.execute(
                        "UPDATE generic_items SET additional_data = json_set("
                        "COALESCE(additional_data, '{}'), '$.migrated', 1) WHERE id = ?",
                        (m['generic_id'],)
                    )
                except sqlite3.OperationalError:
                    pass  # Column doesn't exist, skip

        db.commit()
        print(f"\nMigration complete!")
        print(f"  Sessions updated: {sessions_updated}")
        print(f"  Items marked owned: {items_marked_owned}")
        print(f"  Gearsets updated: {gearsets_updated}")
    elif DRY_RUN:
        print(f"\nDry run complete. Use --execute to apply changes.")

    db.close()


if __name__ == '__main__':
    main()
