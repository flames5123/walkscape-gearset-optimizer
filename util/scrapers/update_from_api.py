#!/usr/bin/env python3
"""
Master update script — pulls all fresh data from gear.walkscape.app API
and regenerates autogenerated files.

Run this whenever a game update drops new content.

Steps:
1. Refresh embargoed activity data (drop tables)
2. Fetch fresh categorized items (gear)
3. Fetch fresh materials list
4. Fetch fresh fine materials list
5. Ingest gear into equipment.py
6. Clean gear items out of materials.py
7. Add missing fine material variants
8. Re-run activities scraper (resolves item_refs with new data)
9. Patch any remaining item_refs
10. Verify all files compile

Usage:
    python3 util/scrapers/update_from_api.py
"""

import subprocess
import sys
import json
import time
from pathlib import Path
from urllib.request import Request, urlopen

API_BASE = 'https://gear.walkscape.app/api'
CACHE_DIR = Path('temp_gear_app_cache')

def fetch(path, filename, method='GET', body=None):
    """Fetch from API and save to cache."""
    url = f"{API_BASE}/{path}"
    headers = {'Accept': 'application/json', 'User-Agent': 'WalkscapeOptimizer/1.0'}
    data = json.dumps(body).encode() if body else None
    if data:
        headers['Content-Type'] = 'application/json'
    req = Request(url, data=data, headers=headers)
    with urlopen(req, timeout=15) as r:
        content = r.read()
    out = CACHE_DIR / filename
    out.write_bytes(content)
    return json.loads(content)

def run(script, desc):
    """Run a scraper script and report result."""
    print(f"\n{'='*50}")
    print(f"  {desc}")
    print(f"{'='*50}")
    r = subprocess.run([sys.executable, script], capture_output=False)
    if r.returncode != 0:
        print(f"  ✗ FAILED: {script}")
        return False
    return True

def compile_check(*files):
    """Verify files compile."""
    r = subprocess.run([sys.executable, '-m', 'py_compile'] + list(files), capture_output=True)
    if r.returncode == 0:
        print(f"  ✓ All files compile OK")
        return True
    print(f"  ✗ Compile error: {r.stderr.decode()[:300]}")
    return False


def main():
    print("=" * 60)
    print("Walkscape Optimizer — Full API Update")
    print("=" * 60)

    CACHE_DIR.mkdir(exist_ok=True)

    # ── Step 1: Refresh embargoed activities ──────────────────────
    print("\n[1/7] Refreshing embargoed activity drop tables...")
    run('util/scrapers/refresh_embargoed_activities.py',
        'Fetch embargoed activity data from live API')

    # ── Step 2: Fetch fresh categorized items ─────────────────────
    print("\n[2/7] Fetching fresh categorized items (gear)...")
    try:
        fetch('items/categorized_items', 'api_items_categorized_fresh.json')
        print("  ✓ Fetched categorized items")
    except Exception as e:
        print(f"  ✗ Failed: {e}")
        return

    # ── Step 3: Fetch fresh materials + fine materials ────────────
    print("\n[3/7] Fetching fresh materials data...")
    try:
        fetch('items/search?type=material&detailed=true', 'api_materials_detailed.json')
        fetch('items/fine_materials', 'api_fine_materials.json')
        print("  ✓ Fetched materials data")
    except Exception as e:
        print(f"  ✗ Failed: {e}")

    # ── Step 4: Ingest gear into equipment.py ─────────────────────
    print("\n[4/7] Ingesting new gear items into equipment.py...")
    run('util/scrapers/ingest_gear_from_api.py',
        'Add missing gear items to equipment.py')

    # ── Step 5: Clean gear items out of materials.py ──────────────
    print("\n[5/7] Cleaning gear items out of materials.py...")
    run('util/scrapers/cleanup_materials.py',
        'Remove gear items wrongly in materials.py')

    # ── Step 6: Add missing fine material variants ────────────────
    print("\n[6/7] Adding missing fine material variants...")
    run('util/scrapers/add_missing_fine_materials.py',
        'Add _FINE variants for all materials in fine_materials list')

    # ── Step 7: Re-run activities scraper ─────────────────────────
    print("\n[7/7] Re-running activities scraper (resolves item_refs)...")
    run('util/scrapers/scrape_activities.py',
        'Regenerate activities.py with fresh drop tables + resolved refs')

    # ── Final: Patch remaining item_refs ──────────────────────────
    print("\n[+] Patching any remaining unresolved item_refs...")
    run('util/scrapers/patch_activity_item_refs.py',
        'Patch item_ref=None entries in activities.py')

    # ── Compile check ─────────────────────────────────────────────
    print("\n[✓] Final compile check...")
    compile_check(
        'util/autogenerated/equipment.py',
        'util/autogenerated/materials.py',
        'util/autogenerated/activities.py',
        'util/autogenerated/recipes.py',
        'util/autogenerated/collectibles.py',
        'util/autogenerated/containers.py',
    )

    print("\n" + "=" * 60)
    print("Update complete!")
    print("=" * 60)


if __name__ == '__main__':
    main()
