#!/usr/bin/env python3
"""Merge the wiki's authoritative item "Value" for null-API items.

The tools API only publishes ``itemValue.value`` as a *vendor* sell price. For
NON-SELLABLE items (loot / cosmetics / achievement rewards) it is ``null`` with
``currency == 'none'`` -- yet the game still assigns these items a base
**Value** that counts toward the player's total wealth / bank value (e.g.
"Greedy piggy bank" has Value 375 on the wiki but Sellable: No).

Emitting 0 for these items under-counts total wealth. This scraper is the
durable, authoritative source: it reads every catalog item whose
``itemValue.value`` is null, fetches its wiki page, parses the infobox
"Value:" field, and writes the map to ``util/wiki_item_values.py``. The
total-wealth calculation (ui/app.py) overlays this value whenever the emitted
item value is 0.

Re-run after a data refresh (or when new non-sellables are added):

    python3 util/scrapers/merge_wiki_item_values.py            # fetch (cached)
    python3 util/scrapers/merge_wiki_item_values.py --rescrape # force refetch
"""
from __future__ import annotations

import glob
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import scraper_utils as su  # noqa: E402
from bs4 import BeautifulSoup  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
ITEMS_CACHE = REPO_ROOT / 'util' / 'cache' / 'tools_api_cache' / 'items'
HTML_CACHE = REPO_ROOT / 'util' / 'cache' / 'item_values_cache'
OUT_PY = REPO_ROOT / 'util' / 'wiki_item_values.py'
WIKI = 'https://wiki.walkscape.app/wiki/'


def null_value_items():
    """Return [(item_id, display_name)] for items whose API itemValue.value is null."""
    out = []
    for f in glob.glob(str(ITEMS_CACHE / '*.json')):
        if os.path.basename(f).startswith('_'):
            continue
        try:
            d = json.load(open(f))
        except Exception:
            continue
        if not isinstance(d, dict):
            continue
        iv = d.get('itemValue') or {}
        if iv.get('value') is None and d.get('id') and d.get('name'):
            out.append((d['id'], d['name']))
    return sorted(out)


def parse_wiki_value(html: str):
    """Return the infobox 'Value:' integer, or None. Ignores 'Fine Value:'."""
    if not html:
        return None
    soup = BeautifulSoup(html, 'html.parser')
    for tr in soup.find_all('tr'):
        cells = [c.get_text(strip=True) for c in tr.find_all(['th', 'td'])]
        # label cell is exactly "Value" (not "Fine Value")
        if cells and cells[0].rstrip(':') == 'Value':
            for c in cells[1:]:
                m = re.search(r'-?\d[\d,]*', c)
                if m:
                    return int(m.group(0).replace(',', ''))
    return None


def run(rescrape: bool = False):
    items = null_value_items()
    print(f'[wiki-values] {len(items)} null-API items to resolve …')
    values = {}
    missing = []
    for iid, name in items:
        page = name.replace(' ', '_')
        html = su.download_with_retry(f'{WIKI}{page}', HTML_CACHE / f'{page}.html')
        v = parse_wiki_value(html)
        if v and v > 0:
            values[iid] = v
        else:
            missing.append((iid, name, v))
    values = dict(sorted(values.items()))

    lines = [
        '#!/usr/bin/env python3',
        '"""Auto-generated by util/scrapers/merge_wiki_item_values.py — DO NOT EDIT.',
        '',
        'Wiki "Value" (base total-wealth value) for items whose tools-API',
        'itemValue.value is null (non-sellable loot / cosmetics / achievement',
        'rewards). The game counts these toward total wealth / bank value even',
        "though they can't be sold to a vendor, so ui/app.py overlays this value",
        'when the emitted item value is 0.',
        '"""',
        '',
        'WIKI_ITEM_VALUES = {',
    ]
    for iid, v in values.items():
        lines.append(f'    {iid!r}: {v},')
    lines += [
        '}',
        '',
        '',
        'def get_wiki_item_value(item_id: str) -> int:',
        '    """Base wiki Value for a null-API item, or 0 if unknown."""',
        '    return WIKI_ITEM_VALUES.get(item_id, 0)',
        '',
    ]
    OUT_PY.write_text('\n'.join(lines), encoding='utf-8')
    print(f'[wiki-values] wrote {len(values)} values → {OUT_PY}')
    print(f'[wiki-values] {len(missing)} items had no positive wiki Value '
          f'(treated as 0): e.g. {[m[0] for m in missing[:8]]}')
    return values


if __name__ == '__main__':
    run(rescrape='--rescrape' in sys.argv)
