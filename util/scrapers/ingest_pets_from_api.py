#!/usr/bin/env python3
"""
Ingest new pets from gear.walkscape.app API into pets.py.
Reads from api_items_categorized_fresh.json.
"""
import json, re, subprocess
import urllib.request
from pathlib import Path

API_BASE = 'https://gear.walkscape.app/api'
CACHE = Path('temp_gear_app_cache/api_items_categorized_fresh.json')
PETS_FILE = Path('util/autogenerated/pets.py')

STAT_MAP = {
    'work_efficiency': 'work_efficiency',
    'double_action': 'double_action',
    'double_rewards': 'double_rewards',
    'steps_required': 'steps_add',
    'chest_finding': 'chest_finding',
    'fine_material_finding': 'fine_material_finding',
    'find_collectibles': 'find_collectibles',
    'find_gems': 'find_gems',
    'find_bird_nests': 'find_bird_nests',
    'no_materials_consumed': 'no_materials_consumed',
    'quality_outcome': 'quality_outcome',
    # "That's A Wrap" passive: roll linens table twice.
    'find_linens': 'find_linens',
    'roll_linens': 'find_linens',
    'roll_linens_twice': 'find_linens',
    'linens_table': 'find_linens',
    'bonus_experience': 'bonus_xp_percent',
    'inventory_space': 'inventory_space',
}


def escape_str(s):
    if s is None:
        return "None"
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'") + "'"


def _clean_html(text):
    """Strip wiki/HTML-ish tags (<hl>, <object id=".."/>, etc.) from ability text."""
    if not text:
        return ''
    # <object id="climbing_gear" /> -> climbing gear
    text = re.sub(r'<object[^>]*id=\\?"([^"\\]+)\\?"[^>]*/?>', lambda m: m.group(1).replace('_', ' '), text)
    text = re.sub(r'<[^>]+>', '', text)
    return text.strip()


def _http_get_json(path, timeout=30):
    req = urllib.request.Request(f'{API_BASE}/{path}',
                                 headers={'Accept': 'application/json', 'User-Agent': 'WalkscapeOptimizer/1.0'})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def fetch_ability_defs():
    """Return {ability_id: {name, type, desc, cooldown, ...}} from /api/abilities.
    Best-effort: returns {} if the endpoint is unavailable."""
    try:
        data = _http_get_json('abilities')
        return {a['id']: a for a in data if a.get('id')}
    except Exception as e:
        print(f"  ⚠ Could not fetch ability defs: {e}")
        return {}


def name_to_enum(name):
    n = re.sub(r"[^\w\s-]", '', name)
    n = n.replace(' ', '_').replace('-', '_').upper()
    return re.sub(r'_+', '_', n).strip('_')

def _attr_scope(attr):
    """Resolve the (skill, location) scope for an attribute from its requirements.

    Shared by per-level pet stats and activatable-ability stat parsing so both
    honour the same mainSkill / activityType / location / realm rules.
    """
    skill, location = 'global', 'global'
    for req in (attr.get('requirements') or []):
        rt = req.get('type', '')
        rd = req.get('requirement', {}) or {}
        if rt == 'mainSkill':
            skill = rd.get('skill', 'global')
        elif rt == 'mainSkillType':
            skill = rd.get('type', 'global')
        elif rt == 'traveling':
            skill = 'traveling'
        elif rt == 'activityType':
            # e.g. Tortoise Shell Forge: bonus scoped to the 'smelting' activity type.
            kws = rd.get('keywords') or []
            if kws:
                skill = kws[0]
        elif rt == 'location':
            location = rd.get('location', 'global')
        elif rt == 'locationHasKeywords':
            kws = rd.get('keywords', []) or []
            if kws:
                location = kws[0]
        elif rt == 'realm':
            location = rd.get('realm', 'global')
    return skill, location


def _map_stat(s):
    """Map an API stat dict to (mapped_name, value). Returns (None, 0) if unknown.

    Percentages are stored *100 (0.2 -> 20.0) except for additive stats.
    """
    name = s.get('stat', '')
    value = s.get('value', 0)
    is_percent = s.get('isPercent', True)
    is_negative = s.get('isNegative', False)
    if name == 'steps_required':
        mapped = 'steps_percent' if is_percent else 'steps_add'
    elif name == 'bonus_experience':
        mapped = 'bonus_xp_percent' if is_percent else 'bonus_xp_add'
    else:
        mapped = STAT_MAP.get(name)
    if not mapped:
        return None, 0
    if is_percent and mapped not in ('steps_add', 'bonus_xp_add', 'quality_outcome', 'inventory_space'):
        v = round(value * 100, 4)
    else:
        v = value
    if is_negative:
        v = -abs(v)
    return mapped, v


def parse_level_stats_nested(level_data):
    """Parse a level's attributes into nested stats {skill: {location: {stat: value}}}.

    Mirrors ingest_gear_from_api.parse_attrs: skill/location come from the attr's
    requirements; percentages are stored *100 (0.05 -> 5.0). Collectible-gated /
    other conditional attrs on pets are rare; we emit all non-conditional stats.
    """
    stats = {}
    for attr in level_data.get('attributes', []):
        skill, location = _attr_scope(attr)
        for s in (attr.get('stats') or []):
            mapped, v = _map_stat(s)
            if mapped is None:
                continue
            d = stats.setdefault(skill, {}).setdefault(location, {})
            d[mapped] = round(d.get(mapped, 0) + v, 4)
    return stats


# Percentage stats — used only to render the human-readable ability effect blurb.
_PERCENT_STAT_LABELS = {
    'work_efficiency', 'double_action', 'double_rewards', 'chest_finding',
    'fine_material_finding', 'find_collectibles', 'find_gems', 'find_bird_nests',
    'no_materials_consumed', 'bonus_xp_percent', 'find_linens',
}


def _format_effect_stats(ability_stats):
    """Build a short '+20% Find collectibles' style summary from ability_stats,
    mirroring the wiki-scraped effect text on pets like the Tiger."""
    parts = []
    for _skill, locs in ability_stats.items():
        for _loc, sm in locs.items():
            for stat, v in sm.items():
                label = stat.replace('_', ' ')
                label = label[:1].upper() + label[1:]
                sign = '+' if v >= 0 else ''
                suffix = '%' if stat in _PERCENT_STAT_LABELS else ''
                parts.append(f"{sign}{v:g}{suffix} {label}")
    return ' '.join(parts)


def _ability_attr_stat(attr, s):
    """Map an ability attribute's stat to (mapped_name, value).

    Special-case ``roll_special_table``: the rolled loot table lives in the
    attribute's ``tables`` (e.g. Mummy's That's A Wrap rolls 'find_linens'), so
    the effective stat is that table's finding stat — NOT a fixed category like
    gear's item-name resolution.
    """
    if s.get('stat') == 'roll_special_table':
        for t in (attr.get('tables') or []):
            for tid in (t.get('tables') or []):
                mapped = STAT_MAP.get(tid)
                if mapped:
                    val = s.get('value', 0)
                    if s.get('isPercent', True):
                        val = round(val * 100, 4)
                    if s.get('isNegative', False):
                        val = -abs(val)
                    return mapped, val
        return None, 0
    return _map_stat(s)


def parse_ability_stats(detail):
    """Parse an ability detail JSON (from /api/abilities/{id}) into
    (ability_stats, duration, duration_unit).

    ability_stats is nested {skill: {location: {stat: value}}}; duration is the
    max effect duration (or None) and duration_unit is its unit ('steps' or
    'actions', or None). The unit varies per ability — Pixie's Party Mode is
    measured in steps, Tiger's The Hunt Is On in actions. Handles BOTH shapes:
      * activatable buffs — stats under data[].actions[].attributes (e.g. Pixie
        Party Mode, Tiger The Hunt Is On), with an effect duration; and
      * passives — stats under a TOP-LEVEL ``attributes`` list with empty data
        (e.g. Mummy's That's A Wrap: roll_special_table 0.07 -> find_linens).
    """
    stats = {}
    duration = None
    duration_unit = None

    def _consume(attr):
        skill, location = _attr_scope(attr)
        for s in (attr.get('stats') or []):
            mapped, v = _ability_attr_stat(attr, s)
            if mapped is None:
                continue
            d = stats.setdefault(skill, {}).setdefault(location, {})
            d[mapped] = round(d.get(mapped, 0) + v, 4)

    for block in (detail.get('data') or []):
        for action in (block.get('actions') or []):
            for attr in (action.get('attributes') or []):
                _consume(attr)
            dur = action.get('duration') or {}
            for key in ('steps', 'actions'):
                if dur.get(key) and dur[key] > (duration or 0):
                    duration = dur[key]
                    duration_unit = key
    # Passive abilities carry top-level attributes with empty `data`.
    for attr in (detail.get('attributes') or []):
        _consume(attr)
    return stats, duration, duration_unit


def _merge_stats(dst, src):
    """In-place additive merge of nested {skill: {loc: {stat: val}}} stat dicts."""
    for sk, locs in src.items():
        for loc, sm in locs.items():
            d = dst.setdefault(sk, {}).setdefault(loc, {})
            for k, v in sm.items():
                d[k] = round(d.get(k, 0) + v, 4)


def compute_passive_folds(pet_abilities, ability_defs=None):
    """Return [(unlock_level, ability_stats)] for each PASSIVE ability.

    Passive pet abilities (e.g. Mummy's That's A Wrap -> find_linens 7%) apply
    ALWAYS once unlocked, so their stats are folded into the pet's per-level
    _stats for every level >= unlock_level (rather than emitted as an activatable
    ability_stats, which would render a 'Use ability' checkbox). Shared by
    build_pet_code and the existing-pet stats-refresh so both stay consistent.
    """
    ability_defs = ability_defs or {}
    folds = []
    for a in (pet_abilities or []):
        aid = a.get('ability')
        d = ability_defs.get(aid, {})
        detail = fetch_ability_detail(aid)
        atype = d.get('type') or detail.get('type')
        if atype != 'passive':
            continue
        ast, _, _ = parse_ability_stats(detail)
        if ast:
            folds.append((a.get('unlockLevel', 1), ast))
    return folds


def build_cooldown_string(cooldown):
    """Build the 'charged by using items' string the UI popover parses from the
    API cooldown object. Returns None when there are no item inputs.

    The popover (gear-slot-grid.js) expects: 'This ability is charged by using
    items. One full charge requires N. X gained from Item ...'
    """
    if not isinstance(cooldown, dict):
        return str(cooldown) if cooldown else None
    inputs = [i for i in (cooldown.get('inputs') or []) if i.get('type') == 'item']
    if not inputs:
        return None
    # 'One full charge requires N' — N is the API's inputsNeeded (how many inputs
    # a full charge costs), NOT the sum of the per-item input values.
    needed = cooldown.get('inputsNeeded')
    if needed is None:
        needed = sum(int(i.get('value', 0) or 0) for i in inputs)
    parts = [f"This ability is charged by using items. One full charge requires {int(needed)}."]
    for i in inputs:
        item_name = str(i.get('item', '')).replace('_', ' ')
        item_name = item_name[:1].upper() + item_name[1:]
        parts.append(f"{int(i.get('value', 0) or 0)} gained from {item_name}")
    return ' '.join(parts)


ABILITY_CACHE_DIR = Path('util/cache/tools_api_cache/abilities')
_ABILITY_DETAIL_CACHE = {}


def fetch_ability_detail(ability_id):
    """Fetch full ability detail (data/cooldown/duration) for an ability.

    Cache-first: reads the repo's cached JSON under
    util/cache/tools_api_cache/abilities/ (the tools-api scrape's source of
    truth for ability defs, refreshed by the orchestrator). Falls back to a live
    /api/abilities/{id} fetch only when there is no cached copy. Returns {} on
    failure. Cache-first keeps the ingest deterministic and offline-friendly
    (tests never hit the network for cached abilities). Memoized per run.
    """
    if not ability_id:
        return {}
    if ability_id in _ABILITY_DETAIL_CACHE:
        return _ABILITY_DETAIL_CACHE[ability_id]
    detail = {}
    from urllib.parse import quote
    for fn in (f'{ability_id}.json', f'{quote(ability_id, safe="")}.json'):
        p = ABILITY_CACHE_DIR / fn
        if p.exists():
            try:
                detail = json.loads(p.read_text())
                break
            except Exception:
                pass
    if not detail:
        try:
            detail = _http_get_json(f'abilities/{ability_id}')
        except Exception:
            detail = {}
    _ABILITY_DETAIL_CACHE[ability_id] = detail
    return detail


def _xp_requirement_desc(pet_data):
    for req in pet_data.get('xpRequirements', []):
        rtype = req.get('type', '')
        rdata = req.get('requirement', {}) or {}
        opposite = req.get('opposite', False)
        if rtype == 'mainSkill':
            skill = rdata.get('skill', '').title()
            return f'Not doing {skill}.' if opposite else f'While doing {skill}.'
        elif rtype == 'realm':
            return f"While in {rdata.get('realm', '').title()}."
        elif rtype == 'locationHasKeywords':
            return f"While in {', '.join(rdata.get('keywords', []) or [])} location."
    return ''


def build_pet_code(pet_data, ability_defs=None):
    """Build the PetLevels block + per-level _stats assignments for a pet.

    Emits the same shape scrape_pets.py generates: a PetLevels(...) with PetInfo
    levels (incl. cumulative abilities), followed by
    ``ENUM._levels[L]._stats = {...}`` lines populated from the API attributes.
    """
    ability_defs = ability_defs or {}
    name = pet_data['name']
    enum = name_to_enum(name)
    egg_name = pet_data.get('egg', {}).get('name', f'{name} egg')
    levels = pet_data.get('levels', [])
    species = name.lower()
    req_desc = _xp_requirement_desc(pet_data)
    # [{unlockLevel, ability(id)}]
    pet_abilities = pet_data.get('abilities') or []

    lines = [f"    {enum} = PetLevels("]
    lines.append(f"        name='{name}',")
    lines.append(f"        egg_name='{egg_name}',")
    lines.append(f"        species='{species}',")
    lines.append(f"        levels={{")
    for level_data in levels:
        level = level_data['level']
        xp = level_data.get('xp')
        lines.append(f"            {level}: PetInfo(")
        lines.append(f"                name='{name}',")
        lines.append(f"                level={level},")
        lines.append(f"                egg_name='{egg_name}',")
        lines.append(f"                xp_required={xp},")
        lines.append(f"                requirement_to_gain_xp={escape_str(req_desc)},")
        # Cumulative abilities unlocked at or before this level.
        cum = [a for a in pet_abilities if a.get('unlockLevel', 10**9) <= level]
        if cum:
            lines.append("                abilities=[")
            for a in cum:
                aid = a.get('ability')
                d = ability_defs.get(aid, {})
                detail = fetch_ability_detail(aid)
                nm = d.get('name') or detail.get('name') or (aid or '').replace('_', ' ').title()
                effect = _clean_html(d.get('desc') or detail.get('desc', ''))
                # Rich activatable-buff fields (Tiger / Pixie shape) from the
                # per-ability detail endpoint — the list endpoint lacks these.
                ability_stats, duration, duration_unit = parse_ability_stats(detail)
                cd_obj = detail.get('cooldown') if isinstance(detail.get('cooldown'), (dict, str)) else d.get('cooldown')
                charges = cd_obj.get('charges') if isinstance(cd_obj, dict) else None
                cooldown_str = build_cooldown_string(cd_obj)
                atype = d.get('type') or detail.get('type')
                # Ability icon: API gives e.g. 'assets/icons/abilities/party_mode.png';
                # store just the basename slug (UI resolves /assets/icons/abilities/{slug}.svg).
                import os as _os
                icon_slug = _os.path.splitext(_os.path.basename(detail.get('icon') or d.get('icon') or ''))[0] or None
                # Append the '+X% Stat' summary to the effect blurb. Activatable
                # buffs also note duration; passives just list the stat.
                if ability_stats:
                    summary = _format_effect_stats(ability_stats)
                    if duration:
                        _unit = duration_unit or 'actions'
                        effect = f"{effect}Effect lasts for: {duration} {_unit} {summary}".strip()
                    elif atype == 'passive':
                        effect = f"{effect} {summary}".strip()
                lines.append("                    {")
                lines.append(f"                        'name': {escape_str(nm)},")
                if icon_slug:
                    lines.append(f"                        'icon': {escape_str(icon_slug)},")
                if effect:
                    lines.append(f"                        'effect': {escape_str(effect)},")
                if atype:
                    lines.append(f"                        'passive': {atype == 'passive'!r},")
                if cooldown_str:
                    lines.append(f"                        'cooldown': {escape_str(cooldown_str)},")
                if charges:
                    lines.append(f"                        'charges': {charges},")
                if duration:
                    lines.append(f"                        'duration': {duration},")
                    lines.append(f"                        'duration_unit': {escape_str(duration_unit or 'actions')},")
                # Passive abilities apply their stats ALWAYS (folded into _stats
                # below), so we do NOT emit ability_stats on the dict — that would
                # render a spurious "Use ability" checkbox. Only activatable buffs
                # carry ability_stats.
                if ability_stats and atype != 'passive':
                    lines.append(f"                        'ability_stats': {ability_stats!r},")
                lines.append("                    },")
            lines.append("                ],")
        lines.append(f"            ),")
    lines.append(f"        }}")
    lines.append(f"    )")
    lines.append("")
    # Passive abilities (e.g. Mummy's That's A Wrap -> find_linens 7%) apply
    # ALWAYS once unlocked, so fold their stats into every level >= unlockLevel.
    passive_folds = compute_passive_folds(pet_abilities, ability_defs)

    # Per-level _stats (StatsMixin) from API attributes (+ folded passives).
    for level_data in levels:
        level = level_data['level']
        st = parse_level_stats_nested(level_data)
        for unlock, ast in passive_folds:
            if level >= unlock:
                _merge_stats(st, ast)
        if not st:
            continue
        lines.append(f"    {enum}._levels[{level}]._stats = {{")
        for sk, locs in st.items():
            lines.append(f"        '{sk}': {{")
            for loc, sm in locs.items():
                lines.append(f"            '{loc}': {{")
                for k, v in sm.items():
                    lines.append(f"                '{k}': {v},")
                lines.append("            },")
            lines.append("        },")
        lines.append("    }")
    return '\n'.join(lines)


def main():
    with open(CACHE) as f:
        categories = json.load(f)
    
    # Find pet data
    all_pets = []
    for cat in categories:
        for sub in cat.get('categories', []):
            if sub.get('title') == 'All Pets':
                all_pets = sub.get('items', [])
    
    print(f"Pets in API: {len(all_pets)}")
    
    content = PETS_FILE.read_text()
    existing = set(re.findall(r'([A-Z_]+) = PetLevels\(', content))
    print(f"Existing pets: {existing}")
    
    new_pets = []
    for pet in all_pets:
        enum = name_to_enum(pet['name'])
        if enum not in existing:
            new_pets.append(pet)
            print(f"  NEW: {pet['name']} ({len(pet.get('levels', []))} levels)")
    
    if not new_pets:
        print("No new pets to add.")
    # Generate code
    ability_defs = fetch_ability_defs()
    new_code = []
    for pet in new_pets:
        new_code.append('\n' + build_pet_code(pet, ability_defs) + '\n')

    # Insert pet PetLevels blocks at the end of the Pet class (before class Egg).
    egg_class_marker = '\nclass Egg:'
    if egg_class_marker in content:
        content = content.replace(egg_class_marker, ''.join(new_code) + egg_class_marker, 1)
    else:
        print("  ⚠ Could not find 'class Egg:' marker; pets not inserted")

    # Register pets in the PETS_BY_NAME lookup (ALL_PET_LEVELS derives from it).
    pet_map_lines = [f"    {escape_str(pet['name'])}: Pet.{name_to_enum(pet['name'])},"
                     for pet in new_pets]
    if pet_map_lines and 'PETS_BY_NAME = {\n' in content:
        content = content.replace('PETS_BY_NAME = {\n',
                                  'PETS_BY_NAME = {\n' + '\n'.join(pet_map_lines) + '\n', 1)
    else:
        print("  ⚠ Could not find PETS_BY_NAME; pets not registered in lookup")

    # Also add eggs as EggInfo entries + EGGS_BY_NAME mappings (matching the
    # generated pets.py format: Egg.<X>_EGG = EggInfo(name, pet_name, xp_to_hatch)).
    egg_blocks = []
    egg_map_lines = []
    for pet in new_pets:
        egg_name = pet.get('egg', {}).get('name', f"{pet['name']} egg")
        egg_enum = name_to_enum(egg_name)
        pet_levels = pet.get('levels', [])
        hatch = pet_levels[0].get('xp') if pet_levels else None
        block = (f"    {egg_enum} = EggInfo(\n"
                 f"        name={escape_str(egg_name)},\n"
                 f"        pet_name={escape_str(pet['name'])},\n")
        if hatch is not None:
            block += f"        xp_to_hatch={hatch},\n"
        block += "    )\n"
        egg_blocks.append(block)
        egg_map_lines.append(f"    {escape_str(egg_name)}: Egg.{egg_enum},")

    # Insert EggInfo blocks right after the Egg class docstring.
    egg_anchor = 'class Egg:\n    """Enum-like class for all eggs."""\n\n'
    if egg_blocks and egg_anchor in content:
        content = content.replace(egg_anchor, egg_anchor + '\n'.join(egg_blocks) + '\n', 1)
    else:
        print("  ⚠ Could not find Egg class anchor; eggs not inserted")
    # Insert into the EGGS_BY_NAME lookup dict.
    if egg_map_lines and 'EGGS_BY_NAME = {\n' in content:
        content = content.replace('EGGS_BY_NAME = {\n',
                                  'EGGS_BY_NAME = {\n' + '\n'.join(egg_map_lines) + '\n', 1)
    
    # ── Update EXISTING pets' _stats from the API (guarded: stats only) ────────
    # The API is the reliable structured source for pet stats (skill/location via
    # requirements). Refresh only the per-level _stats that differ, and ONLY for
    # pets already in pets.py — abilities, rare names, and xp are left untouched
    # (the API is poorer there). Picks up e.g. the Mummy WE increase and the
    # Camel steps_add sign fix without a full regen.
    try:
        import os as _os, sys as _sys
        if _os.getcwd() not in _sys.path:
            _sys.path.insert(0, _os.getcwd())
        import util.walkscape_constants  # noqa: F401 — import order
        from util.autogenerated.pets import PETS_BY_NAME as _CUR
    except Exception as e:
        print(f"  ⚠ Could not load current pets for stats-update: {e}")
        _CUR = {}
    updated = []
    for pet in all_pets:
        nm = pet['name']; enum = name_to_enum(nm)
        if nm not in _CUR:
            continue  # new pet — already emitted above
        cur = _CUR[nm]
        # Passive-ability stats (folded into always-on _stats) are refreshed from
        # the API here too — this is how e.g. Mummy's That's A Wrap find_linens is
        # kept current for an EXISTING pet. Without folding, the recompute would
        # drop find_linens (it lives on the ability, not a level attribute).
        folds = compute_passive_folds(pet.get('abilities') or [], ability_defs)
        for L in pet.get('levels', []):
            lvl = L['level']
            api_stats = parse_level_stats_nested(L)
            for unlock, ast in folds:
                if lvl >= unlock:
                    _merge_stats(api_stats, ast)
            info = cur.get_level(lvl)
            cur_stats = getattr(info, '_stats', {}) if info else {}
            # Preserve existing steps_add/steps_percent: the API's steps sign is
            # unreliable for pets (e.g. Camel desert steps is +2, but the API
            # encodes it as value=2 isNegative=True). Never let the update flip a
            # steps sign — keep whatever pets.py already has (drop API-only steps).
            for _sk, _locs in list(api_stats.items()):
                for _loc, _sm in list(_locs.items()):
                    for _stk in ('steps_add', 'steps_percent'):
                        if _stk in _sm:
                            _curv = cur_stats.get(_sk, {}).get(_loc, {}).get(_stk)
                            if _curv is not None:
                                _sm[_stk] = _curv
                            else:
                                del _sm[_stk]
            if api_stats == cur_stats:
                continue
            new_line = f"    {enum}._levels[{lvl}]._stats = {api_stats!r}\n"
            pat = re.compile(r'^    ' + re.escape(enum) + r'\._levels\[' + str(lvl) + r'\]\._stats = .*\n', re.M)
            if pat.search(content):
                content = pat.sub(lambda m: new_line, content, count=1)
                updated.append(f"{nm} L{lvl}")
            else:
                print(f"  ⚠ No existing _stats line for {nm} L{lvl}; skipped (needs insert)")
    if updated:
        print(f"Updated stats for existing pets: {', '.join(updated)}")

    PETS_FILE.write_text(content)
    print(f"\nAdded {len(new_pets)} new pets")
    
    r = subprocess.run(['python3', '-m', 'py_compile', str(PETS_FILE)], capture_output=True)
    print("✓ Compiles OK" if r.returncode == 0 else f"✗ {r.stderr.decode()[:300]}")


if __name__ == '__main__':
    main()
