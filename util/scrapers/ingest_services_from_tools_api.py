#!/usr/bin/env python3
"""
Ingest services from the WalkScape tools API and regenerate a parallel
`util/autogenerated/services.py` file.

This script does NOT replace `scrape_services.py` or `services.py` yet —
it produces a sibling file so the two can be diffed during migration.

Flow:
    1. Pull all services from /services/ (28 templates).
    2. Hydrate each with /services/id/{id} (stats, requirements, tier).
    3. Pull all locations via /locations/ + /locations/id/{loc}; each
       location's `serviceList` tells us which services exist where.
    4. Emit one ServiceInstance per (service × location) pair, matching
       the existing services.py dataclass shape, to services.py.
    5. Print a summary (+ optional full diff via --diff).

Usage:
    python3 util/scrapers/ingest_services_from_tools_api.py
    python3 util/scrapers/ingest_services_from_tools_api.py --diff
    python3 util/scrapers/ingest_services_from_tools_api.py --no-cache
"""

from __future__ import annotations

