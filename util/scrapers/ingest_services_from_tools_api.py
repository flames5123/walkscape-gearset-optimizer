def _render_dict(d: Any) -> str:
    """Render a dict/tuple/list/scalar as a Python literal with int keys preserved."""
    if isinstance(d, dict):
        inner = ', '.join(f'{_render_key(k)}: {_render_dict(v)}' for k, v in d.items())
        return '{' + inner + '}'
    if isinstance(d, list):
        return '[' + ', '.join(_render_dict(v) for v in d) + ']'
    if isinstance(d, str):
        return repr(d)
    if isinstance(d, bool):
        return 'True' if d else 'False'
    if isinstance(d, (int, float)):
        if isinstance(d, float) and d == int(d):
            return f'{int(d)}.0'
        return str(d)
    return repr(d)


def _render_key(k: Any) -> str:
    if isinstance(k, int) and not isinstance(k, bool):
        return str(k)
    return repr(k)


def emit_python(rows: List[TransformedService]) -> str:
    """Render the full services.py content."""
    rows = sorted(rows, key=lambda r: r.enum_key)
    lines = [_FILE_HEADER]
    for row in rows:
        lines.append(f'    {row.enum_key} = ServiceInstance(')
        lines.append(f'        name={row.name!r},')
        lines.append(f'        category={row.category_enum},')
        lines.append(f'        tier={row.tier!r},')
        lines.append(f'        location={row.location_enum},')
        lines.append(f'        requirements={_render_dict(row.requirements)},')
        lines.append(f'        stats={_render_dict(row.stats)},')
        lines.append(f'        gated_stats={_render_dict(row.gated_stats)},')
        lines.append('    )')
        lines.append('')
    lines.append(_FILE_FOOTER)
    return '\n'.join(lines).rstrip() + '\n'


