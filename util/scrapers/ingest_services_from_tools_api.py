# Transform constants
# ────────────────────────────────────────────────────────────────────────

# API stat name → current-schema stat name. Anything not listed is passed
# through unchanged (after snake_case normalization, which the API already
# gives us).
STAT_NAME_MAP: Dict[str, str] = {
    'steps_required': 'steps_add',
    'bonus_experience': 'bonus_xp_percent',
}

# When isPercent=True we multiply by 100 for display, EXCEPT for stats
# that are stored as raw integer/float values in the current schema.
RAW_VALUE_STATS = frozenset({'steps_add', 'steps_required', 'inventory_space'})

# Skills that can serve as a "category" for a crafting service. If the API
# says relatedSkills=[] (non-crafting services) we skip.
CRAFTING_SERVICE_TYPE = 'crafting'

# Keyword → display name for the "Equipment" portion of the tier label.
#   API keywords: ["sawmill"], tier "basic" → tier='Basic Sawmill'
#   API keywords: ["trinketry_bench"], tier "advanced" → 'Advanced Trinketry Bench'
EQUIPMENT_KEYWORDS = {
    'forge', 'kitchen', 'loom', 'sawmill', 'trinketry_bench', 'workshop',
}


# ────────────────────────────────────────────────────────────────────────
# Intermediate data model (matches services.py shape)
# ────────────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class TransformedService:
    """A single (service template × location) pair ready to serialize."""

    # Canonical order that attrs appear in the emitted file
    enum_key: str
    name: str
    category_enum: str              # e.g. 'Skill.CARPENTRY'
    tier: str
    location_enum: str              # e.g. 'Location.AZURAZERA'
    requirements: Dict[str, Any]
    stats: Dict[str, Any]
    gated_stats: Dict[str, Any]
    api_service_id: str
    api_location_id: str


# ────────────────────────────────────────────────────────────────────────
# Helpers
# ────────────────────────────────────────────────────────────────────────

def _display_stat_value(stat_entry: Dict[str, Any], stat_name: str) -> float:
    """Convert a raw API stat value into the current-schema display value.

    Note: API `value` is already signed (e.g. work_efficiency=-0.2 for -20%).
    The `isNegative` flag is a display hint indicating the stat has a
    "bad" effect on the player — NOT a sign multiplier. For additive stats
    like `steps_required`, value=+5 / isNegative=true means "adds 5 steps"
    which is correctly positive in the current-schema.
    """
    value = float(stat_entry.get('value', 0.0))
    is_percent = bool(stat_entry.get('isPercent', False))
    if is_percent and stat_name not in RAW_VALUE_STATS:
        value *= 100
    # Round to 4 dp to mirror the wiki-scraped values (0.1 → 10.0, not 10.00001)
    value = round(value, 4)
    # Squash trailing .0 only when representation is an integer
    if value == int(value):
        return float(int(value))
    return value


def _normalize_stat_name(api_stat_name: str) -> str:
    return STAT_NAME_MAP.get(api_stat_name, api_stat_name)


def _derive_category(api_service: Dict[str, Any]) -> Optional[str]:
    """Map API relatedSkills[0] → 'Skill.XYZ'. None if no valid skill."""
    related = api_service.get('relatedSkills') or []
    if not related:
        return None
    first = related[0].strip()
    if not first:
        return None
    return f'Skill.{first.upper()}'


def _derive_tier(api_service: Dict[str, Any]) -> str:
    """Build the current-schema tier string e.g. 'Basic Kitchen'."""
    tier = (api_service.get('tier') or 'basic').strip().capitalize()
    keywords = api_service.get('keywords') or []
    equipment = next(
        (kw for kw in keywords if kw in EQUIPMENT_KEYWORDS),
        keywords[0] if keywords else '',
    )
    equipment_display = equipment.replace('_', ' ').title() if equipment else ''
    return f'{tier} {equipment_display}'.strip()


def _strip_parenthetical(name: str) -> str:
    """'Alight Kitchen (Basic)' → 'Alight Kitchen'."""
    return re.sub(r'\s*\([^)]*\)\s*$', '', name).strip()


def _parse_reputation_requirement(req: Dict[str, Any]) -> Optional[Tuple[str, int]]:
    """Extract (faction_key, level) from a gameData reputation requirement.

    Returns None if this isn't a reputation gate.
    """
    if req.get('type') != 'gameData':
        return None
    body = req.get('requirement') or {}
    gd_id = body.get('gameDataId', '')
    if not gd_id.endswith('Reputation'):
        return None
    faction_camel = gd_id[: -len('Reputation')]
    # halflingRebelsReputation → halfling_rebels
    faction_key = re.sub(r'(?<!^)([A-Z])', r'_\1', faction_camel).lower()
    # level is JSON-encoded in `data` e.g. '{"double":"5.0"}'
    raw_data = body.get('data', '')
    try:
        parsed = json.loads(raw_data) if isinstance(raw_data, str) else raw_data
        level_str = parsed.get('double') or parsed.get('int') or '0'
        level = int(float(level_str))
    except (TypeError, ValueError, json.JSONDecodeError):
        level = 0
    return (faction_key, level)


def _extract_requirements(api_service: Dict[str, Any]) -> Dict[str, Any]:
    """Flatten service-level requirements[] into the current-schema dict."""
    out: Dict[str, Any] = {
        'keyword_counts': {},
        'skill': {},
        'reputation': {},
        'access': [],
    }
    for req in api_service.get('requirements', []) or []:
        rtype = req.get('type')
        body = req.get('requirement') or {}

        if rtype == 'skillLevel':
            skill_key = (body.get('skill') or '').capitalize()
            level = int(body.get('level', 0))
            if skill_key:
                out['skill'][skill_key] = level

        elif rtype == 'gameData':
            rep = _parse_reputation_requirement(req)
            if rep:
                faction_key, level = rep
                out['reputation'][faction_key] = level

        elif rtype == 'distinctKeywordItemsEquipped':
            qty = int(body.get('quantity', 0))
            for kw in (body.get('keywords') or []):  # keywords may be absent OR null
                # Convert API snake_case → wiki-style space-separated
                out['keyword_counts'][kw.replace('_', ' ')] = qty

        elif rtype == 'haveCoins':
            coins = int(body.get('coins', 0))
            out['access'].append({'type': 'coins', 'coins': coins})

        elif rtype == 'itemAnywhere':
            out['access'].append({'type': 'item', 'item': body.get('item')})

        else:
            # Preserve unknown requirement types verbatim for manual review
            out['access'].append({'type': rtype, **body})
    return out


def _extract_stats_and_gated(
    api_service: Dict[str, Any],
) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """Split `attributes[]` into unconditional stats and reputation-gated stats.

    Returns (stats, gated_stats) where:
      stats = {skill: {location_scope: {stat: value}}}
      gated_stats = {'reputation': {faction: {level: {skill: {loc_scope: {stat: value}}}}}}

    location_scope is always 'global' here because services are already
    deployed to one specific location — scope is encoded in the outer
    ServiceInstance.location field.
    """
    stats: Dict[str, Any] = {}
    gated: Dict[str, Any] = {}

    for attr in api_service.get('attributes', []) or []:
        attr_reqs = attr.get('requirements') or []
        main_skill = None
        rep_gate: Optional[Tuple[str, int]] = None
        for r in attr_reqs:
            if r.get('type') == 'mainSkill':
                skill = (r.get('requirement') or {}).get('skill')
                if skill:
                    main_skill = skill.lower()
            elif r.get('type') == 'gameData':
                maybe = _parse_reputation_requirement(r)
                if maybe:
                    rep_gate = maybe

        # Default target bucket
        target_skill = main_skill or 'global'

        for stat_entry in attr.get('stats') or []:
            api_name = stat_entry.get('stat')
            if not api_name:
                continue
            stat_name = _normalize_stat_name(api_name)
            value = _display_stat_value(stat_entry, stat_name)

            if rep_gate:
                faction, level = rep_gate
                rep_root = gated.setdefault('reputation', {})
                faction_root = rep_root.setdefault(faction, {})
                level_root = faction_root.setdefault(level, {})
                # gated uses 'global'/'global' nesting for skill/location scope
                skill_scope = target_skill if main_skill else 'global'
                skill_root = level_root.setdefault(skill_scope, {})
                loc_root = skill_root.setdefault('global', {})
                loc_root[stat_name] = value
            else:
                skill_root = stats.setdefault(target_skill, {})
                loc_root = skill_root.setdefault('global', {})
                loc_root[stat_name] = value

    return stats, gated


def _location_enum_key(api_location_id: str) -> str:
    """azurazera → AZURAZERA."""
    return api_location_id.upper()


def _enum_key(service_name: str, location_id: str) -> str:
    """'Basic Kitchen' + 'azurazera' → 'BASIC_KITCHEN_AZURAZERA'."""
    base = re.sub(r'[^A-Za-z0-9]+', '_', service_name).strip('_').upper()
    return f'{base}_{location_id.upper()}'


# ────────────────────────────────────────────────────────────────────────
# Transform
# ────────────────────────────────────────────────────────────────────────

def transform(
    api_services: Dict[str, Dict[str, Any]],
    api_locations: Dict[str, Dict[str, Any]],
    *,
    valid_location_keys: Optional[set] = None,
) -> List[TransformedService]:
    """Convert API data into a sorted list of TransformedService rows.

    `api_services` — {service_id: detail_dict}
    `api_locations` — {location_id: detail_dict}
    `valid_location_keys` — optional allow-list of Location.XYZ names; if
        provided, any location not in the set is skipped with a warning.
    """
    rows: List[TransformedService] = []

    for loc_id in sorted(api_locations.keys()):
        loc_detail = api_locations[loc_id]
        loc_enum_attr = _location_enum_key(loc_id)
        if valid_location_keys and loc_enum_attr not in valid_location_keys:
            print(
                f'  [skip] location {loc_id!r} has no Location.{loc_enum_attr}',
                file=sys.stderr,
            )
            continue

        service_ids = loc_detail.get('serviceList') or []
        for svc_id in service_ids:
            svc = api_services.get(svc_id)
            if not svc:
                print(
                    f'  [warn] location {loc_id} references unknown service {svc_id}',
                    file=sys.stderr,
                )
                continue
            if svc.get('serviceType') != CRAFTING_SERVICE_TYPE:
                continue  # skip wardrobe, mysteriousMerchant, etc.
            category = _derive_category(svc)
            if category is None:
                continue  # unclassifiable — skip

            rows.append(TransformedService(
                enum_key=_enum_key(_strip_parenthetical(svc['name']), loc_id),
                name=_strip_parenthetical(svc['name']),
                category_enum=category,
                tier=_derive_tier(svc),
                location_enum=f'Location.{loc_enum_attr}',
                requirements=_extract_requirements(svc),
                stats=_extract_stats_and_gated(svc)[0],
                gated_stats=_extract_stats_and_gated(svc)[1],
                api_service_id=svc_id,
                api_location_id=loc_id,
            ))

    # Stable deterministic ordering: category → tier → name → location
    rows.sort(key=lambda r: (r.category_enum, r.tier, r.name, r.location_enum))
    return rows


