class ServiceInstance(StatsMixin):
    """Represents a crafting service location."""
    def __init__(self, name: str, category: Skill, tier: str, location: Location, requirements: dict, stats: dict, gated_stats: dict):
        self.name = name
        self.category = category  # Skill object (e.g., Skill.CARPENTRY)
        self.tier = tier
        self.location = location
        self.requirements = requirements
        self._stats = stats  # {skill: {location: {stat: value}}}
        self.gated_stats = gated_stats  # Includes reputation gates

    def is_valid_for_recipe(self, recipe) -> bool:
        """
        Check if this service can be used for the given recipe.
        Advanced services can craft Basic recipes (backwards compatible).

        Args:
            recipe: Recipe object with .service attribute

        Returns:
            True if service is valid for recipe, False otherwise
        """
        recipe_service = recipe.service.lower()

        # Get service category name
        service_category = self.category.value.lower() if hasattr(self.category, "value") else self.category.lower()
        service_tier = self.tier.lower()
        # Service display name (e.g. 'Cursed Loom') — distinct from tier
        # ('Advanced Loom') and used by the spectral / wraithwater
        # services where the recipe spells the full name+tier
        # ('Advanced Cursed Loom') but the catalog stores the body in
        # `name` and the rank in `tier`. Bug d4271b8b: without
        # name-based matching, all 5 'Advanced Cursed *' recipes
        # (Loom/Forge/Workshop/Sawmill/Kitchen) end up with NO valid
        # service, fall into the no-service optimizer path, and the
        # optimizer is free to evaluate gear at any unlocked location
        # — picking Jarvonia and recommending Bert's Skis even though
        # the recipe must be performed at Wraithwater where the skis
        # contribute zero stats.
        service_name = (self.name or '').lower()

        # Extract the service type from the recipe requirement and this service's tier
        # e.g. "basic workshop" → "workshop", "advanced forge" → "forge"
        recipe_type_words = recipe_service.replace('basic ', '').replace('advanced ', '').strip()
        service_type_words = service_tier.replace('basic ', '').replace('advanced ', '').strip()
        # Same body-extraction for service.name so 'Cursed Loom'
        # → 'cursed loom' and matches the recipe's stripped body.
        service_name_words = service_name.replace('basic ', '').replace('advanced ', '').strip()

        # Types must match (workshop=workshop, forge=forge, etc.). Try
        # tier-body first, then name-body — name match handles
        # 'Advanced Cursed Loom' recipes against the Cursed Loom service.
        types_match = (
            recipe_type_words == service_type_words
            or recipe_type_words == service_name_words
        )

        if not types_match:
            # Also allow category match as fallback (e.g. Skill.CRAFTING matches "workshop")
            if (
                service_category not in recipe_service
                and recipe_type_words not in service_tier
                and recipe_type_words not in service_name
            ):
                return False

        # Check tier compatibility — Advanced can do Basic, but not vice versa
        recipe_is_basic = "basic" in recipe_service
        recipe_is_advanced = "advanced" in recipe_service
        service_is_basic = "basic" in service_tier
        service_is_advanced = "advanced" in service_tier

        if types_match:
            if recipe_is_advanced and service_is_basic:
                return False  # Basic cannot do Advanced recipes
            return True  # Exact match or advanced doing basic

        # Category-based match (e.g. Skill.CRAFTING for "workshop" recipes)
        if service_category in recipe_service:
            if recipe_is_advanced and service_is_basic:
                return False
            return True

        return False

    def is_unlocked(self, character, gearset=None) -> bool:
        """
        Check if service is unlocked for character with optional gearset validation.

        Args:
            character: Character object
            gearset: Optional Gearset object for checking gear requirements

        Returns:
            True if unlocked, False otherwise
        """
        # Check skill requirements
        for skill, required_level in self.requirements.get('skill', {}).items():
            if character.get_skill_level(skill.lower()) < required_level:
                return False

        # Check reputation requirements
        for faction, required_amount in self.requirements.get('reputation', {}).items():
            if character.reputation.get(faction, 0) < required_amount:
                return False

        # Check access requirements (coins, items, etc.)
        # Access entries shaped like {'type': 'coins', 'coins': N} require the
        # character to have at least N coins. Other access types (items,
        # legacy "Region Access" strings) are tolerated so they don't false-
        # positive a lock — they're handled elsewhere (region_unlocks etc.).
        for access in self.requirements.get('access', []) or []:
            if isinstance(access, dict) and access.get('type') == 'coins':
                required_coins = int(access.get('coins', 0) or 0)
                char_coins = int(getattr(character, 'coins', 0) or 0)
                if char_coins < required_coins:
                    return False

        # Check keyword requirements (needs gearset)
        if gearset:
            keyword_counts = self.requirements.get('keyword_counts', {})
            for keyword, required_count in keyword_counts.items():
                if required_count <= 0:
                    continue

                # Count items with this keyword
                count = sum(
                    1 for slot, item in gearset.get_all_items()
                    if item and hasattr(item, 'keywords') and
                    any(keyword.lower() == kw.lower() for kw in item.keywords)
                )
                if count < required_count:
                    return False

        return True


