def collect_valid_location_keys() -> set:
    """Import Location lazily to build the allow-list of attr names.

    Reads from the regenerated ``util.autogenerated.locations`` (the
    API-derived Location class, now the source of truth after the
    tools-API cutover).
    """
    try:
        from util.autogenerated.locations import Location
    except Exception:
        return set()
    return {
        name for name in dir(Location)
        if not name.startswith('_') and name.isupper()
    }


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--no-cache', action='store_true',
                   help='Bypass the on-disk cache for this run')
    p.add_argument('--diff', action='store_true',
                   help='Print a unified diff vs util/autogenerated/services.py')
    p.add_argument('--prod', action='store_true',
                   help='Use the production API endpoint instead of dev')
    p.add_argument('--out', default='util/autogenerated/services.py',
                   help='Output file (relative to repo root)')
    args = p.parse_args()

    base_url = (
        'https://tools-api.dev.walkscape.app' if args.prod
        else 'https://tools-api-dev.dev.walkscape.app'
    )
    client = ToolsAPIClient(base_url=base_url)
    use_cache = not args.no_cache

    print(f'[ingest] using {client.base_url} (cache={"on" if use_cache else "off"})')

    # 1. Pull all services with detail
    print('[ingest] fetching services …')
    svc_list = client.list('services', use_cache=use_cache)
    api_services: Dict[str, Dict[str, Any]] = {}
    for s in svc_list:
        sid = s['id']
        api_services[sid] = client.get('services', sid, use_cache=use_cache)
    print(f'[ingest]   {len(api_services)} service templates hydrated')

    # 2. Pull all locations with detail (for serviceList)
    print('[ingest] fetching locations …')
    loc_list = client.list('locations', use_cache=use_cache)
    api_locations: Dict[str, Dict[str, Any]] = {}
    for loc in loc_list:
        lid = loc['id']
        api_locations[lid] = client.get('locations', lid, use_cache=use_cache)
    print(f'[ingest]   {len(api_locations)} locations hydrated')

    # 3. Transform
    valid_keys = collect_valid_location_keys()
    rows = transform(api_services, api_locations, valid_location_keys=valid_keys)
    print(f'[ingest] produced {len(rows)} service instances')

    # 4. Emit
    out_path = Path(args.out)
    if not out_path.is_absolute():
        out_path = Path(__file__).resolve().parent.parent.parent / out_path
    content = emit_python(rows)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding='utf-8')
    print(f'[ingest] wrote {out_path} ({len(content)} bytes)')

    # 5. Summary
    by_category: Dict[str, int] = {}
    for r in rows:
        by_category[r.category_enum] = by_category.get(r.category_enum, 0) + 1
    print('[ingest] breakdown by category:')
    for cat, count in sorted(by_category.items()):
        print(f'           {cat:25s} {count}')

    # 6. Optional diff vs existing services.py
    if args.diff:
        wiki = (
            Path(__file__).resolve().parent.parent / 'autogenerated' / 'services.py'
        )
        if wiki.exists():
            diff = difflib.unified_diff(
                wiki.read_text(encoding='utf-8').splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=str(wiki),
                tofile=str(out_path),
                n=2,
            )
            sys.stdout.writelines(diff)

    return 0


