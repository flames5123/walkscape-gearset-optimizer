#!/usr/bin/env python3
"""
Ingest shops from the WalkScape tools API and regenerate a parallel
`util/autogenerated/shops_from_api.py` file.

Now that the tools API exposes shop prices (fixedPrice / priceMultiplier +
addedPrice), shops can be sourced from the API instead of the wiki. This
script mirrors the precedent set by `ingest_services_from_tools_api.py`:
it produces a SIBLING file so the API output can be diffed against the
wiki-scraped `shops.py` before we flip the source of truth.

What the tools API PROVIDES for shops:
    - /shops/            -> [{id, name, soldItems}]
    - /shops/id/{id}     -> {id, name, soldItems, onlyPurchaseSellingListItems,
                             shoppingLists:[{name, desc, sellingList,
                               items:[{item:{id,quality,tag}, type, quantity,
                                       priceMultiplier, addedPrice, fixedPrice}]}]}
    - /items/id/{id}     -> {id, name, type, itemValue, ...}  (name/type/base value)
    - /buildings/id/{id} -> {id, name, type}                  (building_type)
    - /locations/id/{id} -> {name, faction, buildingList, ...} (region + which
                             buildings/shops live where)

What the API does NOT provide (gaps vs the wiki shops.py — logged at the end):
    - currency: no field. Everything is modelled as coins via fixedPrice /
      multiplier. The wiki distinguished 'adventurers_guild_token'. We default
      to 'coins' and print which shops the current wiki shops.py marks with a
      non-coin currency so a human can reconcile before retiring scrape_shops.py.
    - stock: no field. The wiki had a per-item stock column. We default to 1.
    - building_type: not on the shop object, but recovered from /buildings.

Price resolution per sold item:
    price = fixedPrice                                   if fixedPrice is not None
          = round(itemValue * priceMultiplier + addedPrice)   otherwise

Usage:
    python3 util/scrapers/ingest_shops_from_api.py
    python3 util/scrapers/ingest_shops_from_api.py --dry-run   # summary only, no write
    python3 util/scrapers/ingest_shops_from_api.py --diff      # unified diff vs shops.py
    python3 util/scrapers/ingest_shops_from_api.py --no-cache  # bypass tools-api disk cache
    python3 util/scrapers/ingest_shops_from_api.py --out util/autogenerated/shops.py  # overwrite (careful!)
"""
from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

# Allow running as a plain script from the repo root.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
from util.scrapers.tools_api_client import ToolsAPIClient, ToolsAPIError
from util.misc_utils import build_all_item_lookups, resolve_item_reference, name_to_enum

DEFAULT_OUT = Path('util/autogenerated/shops_from_api.py')
WIKI_SHOPS = Path('util/autogenerated/shops.py')

# tools-api item.type -> shops.py item_type label
ITEM_TYPE_MAP = {
    'loot': 'Loot',
    'tool': 'Tool',
    'consumable': 'Consumable',
    'material': 'Material',
    'container': 'Container',
    'collectible': 'Collectible',
    'cosmetic': 'Cosmetic',
    'pet': 'Pet',
}


def humanize(s: str) -> str:
    """'clothingShop' -> 'Clothing shop'; 'jarvonia' -> 'Jarvonia'."""
    if not s:
        return ''
    spaced = re.sub(r'(?<=[a-z0-9])(?=[A-Z])', ' ', str(s))
    spaced = spaced.replace('_', ' ').strip()
    return spaced[:1].upper() + spaced[1:].lower() if spaced else ''


def escape_str(s: str) -> str:
    return str(s).replace('\\', '\\\\').replace("'", "\\'")


def _faction_to_region(faction) -> str:
    """location.faction may be a string id or a dict — normalise to a region label."""
    if isinstance(faction, dict):
        faction = faction.get('name') or faction.get('id') or ''
    return humanize(faction) if faction else 'Unknown'


def build_location_index(client: ToolsAPIClient):
    """Map building_id -> {region, location} using /locations buildingList + faction."""
    idx = {}
    for loc in client.list('locations'):
        detail = client.get('locations', loc['id'])
        region = _faction_to_region(detail.get('faction'))
        loc_name = detail.get('name') or humanize(loc['id'])
        for bid in detail.get('buildingList', []) or []:
            # First location wins; shops usually live in exactly one location.
            idx.setdefault(bid, {'region': region, 'location': loc_name})
    return idx


def item_detail_cache(client: ToolsAPIClient):
    """Lazily resolve item id -> {name, type, itemValue} with a local memo."""
    memo = {}

    def get(item_id: str):
        if item_id in memo:
            return memo[item_id]
        try:
            d = client.get('items', item_id)
        except ToolsAPIError:
            d = {}
        memo[item_id] = {
            'name': d.get('name') or humanize(item_id),
            'type': (d.get('type') or 'loot'),
            # itemValue shape: {"currency": "money"|"none", "value": {quality: amount} | null}
            'item_value': d.get('itemValue') or {},
        }
        return memo[item_id]

    return get


def _base_value(item_value: dict, quality: str) -> int:
    """Extract the quality-appropriate base value from an itemValue dict."""
    vmap = item_value.get('value') if isinstance(item_value, dict) else None
    if not isinstance(vmap, dict) or not vmap:
        return 0
    return int(vmap.get(quality) or vmap.get('common') or next(iter(vmap.values())) or 0)


def resolve_price(entry: dict, item_value: dict) -> int:
    """fixedPrice if present, else base_value(quality) * priceMultiplier + addedPrice."""
    fixed = entry.get('fixedPrice')
    if fixed is not None:
        return int(fixed)
    mult = entry.get('priceMultiplier', 1) or 1
    added = entry.get('addedPrice', 0) or 0
    quality = (entry.get('item') or {}).get('quality') or 'common'
    return int(round(_base_value(item_value, quality) * mult + added))


def build_shops(client: ToolsAPIClient):
    """Return (shops list, warnings) where each shop is a dict matching shops.py."""
    loc_index = build_location_index(client)
    get_item = item_detail_cache(client)
    lookups = build_all_item_lookups()
    warnings = []

    shops = []
    for stub in client.list('shops'):
        sid = stub['id']
        detail = client.get('shops', sid)

        # building_type from /buildings (shop id == building id)
        try:
            building_type = humanize(client.get('buildings', sid).get('type', ''))
        except ToolsAPIError:
            building_type = ''

        loc = loc_index.get(sid, {})
        region = loc.get('region', 'Unknown')
        location = loc.get('location', '')

        # Canonical set of sold item ids — only surface these (skip player
        # sell-back lists). soldItems is the shop's authoritative sell list.
        sold = set(detail.get('soldItems') or [])

        inventory = []
        seen = set()
        for sl in detail.get('shoppingLists', []) or []:
            for entry in sl.get('items', []) or []:
                item = entry.get('item') or {}
                iid = item.get('id')
                if not iid or iid not in sold or iid in seen:
                    continue
                seen.add(iid)
                info = get_item(iid)
                price = resolve_price(entry, info['item_value'])
                item_type = ITEM_TYPE_MAP.get(info['type'], info['type'].capitalize())
                item_ref = resolve_item_reference(info['name'], lookups)
                inventory.append({
                    'item_name': info['name'],
                    'stock': int(entry.get('quantity') or 1),  # API has no stock; use bundle qty
                    'price': price,
                    'currency': 'coins',  # API has no currency field (see warnings)
                    'item_type': item_type,
                    'item_ref': item_ref,
                })

        # Any soldItems not covered by a shoppingList entry (no price data)
        for iid in sold:
            if iid in seen:
                continue
            info = get_item(iid)
            inventory.append({
                'item_name': info['name'],
                'stock': 1,
                'price': 0,
                'currency': 'coins',
                'item_type': ITEM_TYPE_MAP.get(info['type'], info['type'].capitalize()),
                'item_ref': resolve_item_reference(info['name'], lookups),
            })
            warnings.append(f"{humanize(stub['name'])}: '{info['name']}' in soldItems has no price entry (set to 0)")

        shops.append({
            'name': detail.get('name') and humanize(detail['name']) or humanize(sid),
            'building_type': building_type,
            'location': location,
            'region': region,
            'inventory': inventory,
        })

    return shops, warnings


def render_module(shops) -> str:
    lines = [
        '#!/usr/bin/env python3',
        '"""',
        'Shop data from the WalkScape tools API',
        'Auto-generated by ingest_shops_from_api.py',
        'DO NOT EDIT MANUALLY',
        '',
        'NOTE: currency defaults to \'coins\' (the tools API has no currency field).',
        'Reconcile adventurers_guild_token shops against the wiki shops.py before use.',
        '"""',
        '',
        'from dataclasses import dataclass, field',
        'from typing import List, Optional, Dict',
        '',
        '',
        '@dataclass',
        'class ShopItem:',
        '    """An item sold in a shop."""',
        '    item_name: str',
        '    stock: int',
        '    price: int',
        "    currency: str  # 'coins' or 'adventurers_guild_token' or material name",
        '    item_type: str  # Loot, Tool, Consumable, Material, Container, Collectible, Cosmetic',
        '    item_ref: Optional[str] = None',
        '',
        '',
        '@dataclass',
        'class ShopInfo:',
        '    """Information about a shop."""',
        '    name: str',
        '    building_type: str',
        '    location: str',
        '    region: str',
        '    requirements: List[str] = field(default_factory=list)',
        '    inventory: List[ShopItem] = field(default_factory=list)',
        '',
        '',
        '# ============================================================================',
        '# SHOP DATA',
        '# ============================================================================',
    ]

    regions = {}
    for shop in shops:
        regions.setdefault(shop['region'], []).append(shop)

    var_names = []
    for region, region_shops in regions.items():
        lines += ['', f'# --- {region} ---', '']
        for shop in region_shops:
            var_name = name_to_enum(shop['name'])
            var_names.append(var_name)
            inv = shop.get('inventory', [])
            lines.append(f'{var_name} = ShopInfo(')
            lines.append(f"    name='{escape_str(shop['name'])}', building_type='{escape_str(shop['building_type'])}',")
            lines.append(f"    location='{escape_str(shop['location'])}', region='{escape_str(shop['region'])}',")
            if inv:
                lines.append('    inventory=[')
                for it in inv:
                    ref = f"'{it['item_ref']}'" if it.get('item_ref') else 'None'
                    lines.append(
                        f"        ShopItem('{escape_str(it['item_name'])}', {it['stock']}, "
                        f"{it['price']}, '{it['currency']}', '{it['item_type']}', {ref}),"
                    )
                lines.append('    ],')
            lines.append(')')
            lines.append('')

    lines += [
        '',
        '# ============================================================================',
        '# LOOKUP HELPERS',
        '# ============================================================================',
        '',
        'ALL_SHOPS: List[ShopInfo] = [',
    ]
    for i in range(0, len(var_names), 4):
        lines.append('    ' + ', '.join(var_names[i:i + 4]) + ',')
    lines += [
        ']',
        '',
        'SHOPS_BY_NAME: Dict[str, ShopInfo] = {shop.name: shop for shop in ALL_SHOPS}',
        '',
        '',
        'def get_shop_item_names() -> set:',
        '    """Get flat set of all equipment/collectible item names sold in shops."""',
        '    names = set()',
        '    for shop in ALL_SHOPS:',
        '        for item in shop.inventory:',
        "            if item.item_type in ('Loot', 'Tool', 'Collectible'):",
        '                names.add(item.item_name)',
        '    return names',
        '',
        '',
        'def get_items_by_shop() -> Dict[str, List[str]]:',
        '    """Get equipment/collectible item names grouped by shop name."""',
        '    result = {}',
        '    for shop in ALL_SHOPS:',
        '        items = []',
        '        for item in shop.inventory:',
        "            if item.item_type in ('Loot', 'Tool', 'Collectible'):",
        '                items.append(item.item_name)',
        '        if items:',
        '            result[shop.name] = items',
        '    return result',
        '',
    ]
    return '\n'.join(lines)


def report_currency_gap():
    """Print which shops the wiki shops.py marks with a non-coin currency."""
    if not WIKI_SHOPS.exists():
        return
    txt = WIKI_SHOPS.read_text(encoding='utf-8')
    non_coin = sorted(set(re.findall(r"ShopItem\([^)]*?,\s*'((?!coins')[a-z_]+)'\s*,", txt)))
    if non_coin:
        print("\n⚠ Currency gap — the tools API has NO currency field, so all items")
        print("  were emitted as 'coins'. The wiki shops.py uses these non-coin currencies:")
        for c in non_coin:
            print(f"    - {c}")
        print("  Reconcile these before retiring scrape_shops.py / flipping shops.py.")


def main():
    ap = argparse.ArgumentParser(description='Ingest shops from the WalkScape tools API.')
    ap.add_argument('--out', default=str(DEFAULT_OUT), help='output file (default sibling shops_from_api.py)')
    ap.add_argument('--dry-run', action='store_true', help='print a summary; do not write')
    ap.add_argument('--diff', action='store_true', help='print a unified diff vs the current wiki shops.py')
    ap.add_argument('--no-cache', action='store_true', help='bypass the tools-api disk cache')
    args = ap.parse_args()

    try:
        client = ToolsAPIClient(cache_ttl_seconds=0 if args.no_cache else 24 * 3600)
    except ToolsAPIError as e:
        print(f"✗ Could not initialise tools-api client: {e}")
        return 1

    print("Fetching shops from the tools API...")
    shops, warnings = build_shops(client)
    total_items = sum(len(s['inventory']) for s in shops)
    print(f"  {len(shops)} shops, {total_items} sold items")

    module_src = render_module(shops)

    if args.diff:
        old = WIKI_SHOPS.read_text(encoding='utf-8').splitlines(keepends=True) if WIKI_SHOPS.exists() else []
        diff = difflib.unified_diff(old, module_src.splitlines(keepends=True),
                                    fromfile='shops.py (wiki)', tofile=f'{args.out} (api)')
        sys.stdout.writelines(diff)
        print()

    if args.dry_run:
        print(f"\n[dry-run] would write {len(module_src.splitlines())} lines to {args.out}")
    else:
        out = Path(args.out)
        out.write_text(module_src, encoding='utf-8')
        print(f"✓ Wrote {out} ({len(module_src.splitlines())} lines)")

    if warnings:
        print(f"\n⚠ {len(warnings)} soldItems had no price entry (emitted price=0):")
        for w in warnings[:20]:
            print(f"    - {w}")
        if len(warnings) > 20:
            print(f"    ... and {len(warnings) - 20} more")

    report_currency_gap()
    return 0


if __name__ == '__main__':
    sys.exit(main())
