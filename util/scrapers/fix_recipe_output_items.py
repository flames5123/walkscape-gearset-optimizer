#!/usr/bin/env python3
"""
Fix output_item=None in recipes.py by matching recipe names to items
in equipment.py, materials.py, and consumables.py.
"""
import re, subprocess
from pathlib import Path

def extract_names(filepath, class_names):
    """Extract {name.lower(): 'Type.ENUM'} from a file."""
    content = Path(filepath).read_text()
    lookup = {}
    for class_name, type_prefix in class_names:
        pattern = rf'^\s+([A-Z_0-9]+)\s*=\s*{class_name}\s*\('
        for m in re.finditer(pattern, content, re.MULTILINE):
            enum_name = m.group(1)
            start = m.end()
            name_match = re.search(r'name="([^"]+)"', content[start:start+500])
            if not name_match:
                name_match = re.search(r"name='([^']+)'", content[start:start+500])
            if name_match:
                lookup[name_match.group(1).lower()] = f"{type_prefix}.{enum_name}"
    # Also handle DICT['Name'] pattern
    dict_pattern = r"^\s+([A-Z_0-9]+)\s*=\s*\w+\['([^']+)'\]"
    for m in re.finditer(dict_pattern, content, re.MULTILINE):
        name = m.group(2).lower()
        if name not in lookup and class_names:
            lookup[name] = f"{class_names[0][1]}.{m.group(1)}"
    return lookup

# Build lookup
lookup = {}
lookup.update(extract_names('util/autogenerated/equipment.py', [
    ('ItemInstance', 'Item'), ('CraftedItem', 'Item'), ('AchievementItem', 'Item'),
]))
lookup.update(extract_names('util/autogenerated/materials.py', [('MaterialInstance', 'Material')]))
lookup.update(extract_names('util/autogenerated/consumables.py', [('ConsumableItem', 'Consumable')]))
print(f"Lookup: {len(lookup)} items")

# Read recipes.py
content = Path('util/autogenerated/recipes.py').read_text()

# Find recipes with output_item=None and try to resolve from recipe name
# Recipe names like "Make a tatty garb" -> output is "Tatty garb"
# "Cut a birch plank" -> "Birch plank"
# "Smelt a bronze bar" -> "Bronze bar"
PREFIXES = [
    'Make a ', 'Make an ', 'Make ', 'Cut a ', 'Cut an ', 'Smelt a ', 'Smelt an ',
    'Cook a ', 'Cook an ', 'Cook ', 'Craft a ', 'Craft an ', 'Craft ',
    'Create a ', 'Create an ', 'Woodwork a ', 'Woodwork an ',
    'Weave into ', 'Brew a ', 'Brew ',
]

# Find all RecipeInstance blocks with output_item=None
pattern = r"(RecipeInstance\(\s*\n\s*name='([^']+)',\s*\n\s*output_item=None,)"

patched = 0
def fix_output(m):
    global patched
    block = m.group(1)
    recipe_name = m.group(2)
    
    # Try to extract output name from recipe name
    output_name = recipe_name
    for prefix in PREFIXES:
        if recipe_name.startswith(prefix):
            output_name = recipe_name[len(prefix):]
            break
    
    # Look up the output item
    ref = lookup.get(output_name.lower())
    if not ref:
        # Try with "a " or "an " removed
        for article in ['a ', 'an ']:
            if output_name.lower().startswith(article):
                ref = lookup.get(output_name[len(article):].lower())
                if ref:
                    break
    
    if ref:
        patched += 1
        return block.replace("output_item=None", f"output_item='{ref}'")
    return block

new_content = re.sub(pattern, fix_output, content)

if new_content != content:
    Path('util/autogenerated/recipes.py').write_text(new_content)
    print(f"Patched {patched} recipe output_items")
else:
    print("No changes")

# Show remaining None
remaining = re.findall(r"name='([^']+)',\s*\n\s*output_item=None", new_content)
print(f"Still None: {len(remaining)}")
for r in remaining:
    print(f"  ? {r}")

r = subprocess.run(['python3', '-m', 'py_compile', 'util/autogenerated/recipes.py'], capture_output=True)
print("✓ Compiles OK" if r.returncode == 0 else f"✗ {r.stderr.decode()[:300]}")
