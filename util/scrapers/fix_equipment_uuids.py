#!/usr/bin/env python3
"""
Fix equipment UUIDs by fetching real UUIDs from the WalkScape tools API.

Uses POST https://tools-api-dev.dev.walkscape.app/items/ids (Bearer auth),
via the shared ToolsAPIClient, which accepts:
    {"ids": ["item_name_1", "item_name_2"], "target": "base"}
and returns:
    {"item_name_1": "real-uuid-here", "item_name_2": "real-uuid-here"}

This script finds all items with fake 'item-{name}' UUIDs and replaces them.
The API key is loaded by ToolsAPIClient (env WALKSCAPE_TOOLS_API_KEY or the
.walkscape_tools_api_key file at the repo root).

Usage:
    python3 util/scrapers/fix_equipment_uuids.py
"""
import re
import sys
import subprocess
from pathlib import Path

# Allow running as a plain script (python3 util/scrapers/fix_equipment_uuids.py)
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
from util.scrapers.tools_api_client import ToolsAPIClient, ToolsAPIError

EQUIP = Path('util/autogenerated/equipment.py')
# UUID form to request from the tools API ("base" is the tools-api default).
TARGET = 'base'

content = EQUIP.read_text()

# Find all fake UUIDs: uuid="item-{name}" (no real UUID embedded)
# These are items where the UUID is just "item-{export_name}"
fake_pattern = re.compile(r'uuid="item-([a-z0-9_\'\-]+)"')

# Collect all export names that need real UUIDs
export_names = set()
for m in fake_pattern.finditer(content):
    full_uuid = m.group(0)  # uuid="item-xxx"
    export_name = m.group(1)
    # Skip if it already has a real UUID embedded (item-name-{uuid})
    # Real UUIDs have 5 hex groups: 8-4-4-4-12
    if re.search(r'[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$', export_name):
        continue
    export_names.add(export_name)

print(f"Found {len(export_names)} items with fake UUIDs")

if not export_names:
    print("Nothing to fix!")
    exit(0)

# Resolve real UUIDs via the shared tools-api client (Bearer auth, rate
# limiting, and retry/backoff are handled internally). Batch to stay well
# under the API's per-request limits.
BATCH_SIZE = 100
export_list = sorted(export_names)
uuid_map = {}

try:
    client = ToolsAPIClient()
except ToolsAPIError as e:
    print(f"✗ Could not initialise tools-api client: {e}")
    exit(1)

for i in range(0, len(export_list), BATCH_SIZE):
    batch = export_list[i:i + BATCH_SIZE]
    try:
        result = client.resolve_ids(batch, target=TARGET)
        uuid_map.update(result)
        print(f"  Batch {i // BATCH_SIZE + 1}: got {len(result)} UUIDs")
    except ToolsAPIError as e:
        print(f"  Batch {i // BATCH_SIZE + 1} failed: {e}")

print(f"\nResolved {len(uuid_map)} UUIDs from API")

# Replace fake UUIDs with real ones
fixed = 0
not_found = []
echoed = []
for export_name in sorted(export_names):
    real_uuid = uuid_map.get(export_name)
    # Echo guard: the tools API returns the queried id unchanged when it
    # can't resolve it (unlike the old gear API, which omitted misses). An
    # echoed value is NOT a real UUID — skip it and leave the entry alone so
    # we never overwrite a good/placeholder uuid with garbage.
    if real_uuid and real_uuid != export_name:
        old = f'uuid="item-{export_name}"'
        new = f'uuid="{real_uuid}"'
        if old in content:
            content = content.replace(old, new)
            fixed += 1
    elif real_uuid == export_name:
        echoed.append(export_name)
    else:
        not_found.append(export_name)

if fixed > 0:
    EQUIP.write_text(content)

print(f"\n✓ Fixed {fixed} UUIDs")
if echoed:
    print(f"⚠ {len(echoed)} items echoed back unchanged (unresolved, left untouched):")
    for name in echoed:
        print(f"  - {name}")
if not_found:
    print(f"⚠ {len(not_found)} items not found in API:")
    for name in not_found:
        print(f"  - {name}")

# Verify it compiles
r = subprocess.run(['python3', '-m', 'py_compile', str(EQUIP)], capture_output=True)
print("\n✓ Compiles OK" if r.returncode == 0 else f"\n✗ {r.stderr.decode()[:300]}")
