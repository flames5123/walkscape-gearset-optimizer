#!/usr/bin/env python3
import json, re
from pathlib import Path

fine_list = json.loads(Path('temp_gear_app_cache/api_fine_materials.json').read_text())
content = Path('util/autogenerated/materials.py').read_text()

existing = set()
for m in re.finditer(r'name="([^"]+)"', content):
    existing.add(m.group(1).lower())

missing_base = []
missing_fine = []
for item_id in fine_list:
    display = item_id.replace('_', ' ')
    if display.lower() not in existing:
        missing_base.append(display)
    fine_display = f"{display} (fine)"
    if fine_display not in existing:
        missing_fine.append(f"{display} (Fine)")

print(f"Missing base: {len(missing_base)}")
for m in sorted(missing_base):
    print(f"  {m}")
print(f"Missing fine: {len(missing_fine)}")
for m in sorted(missing_fine):
    print(f"  {m}")
