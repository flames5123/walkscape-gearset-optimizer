# Currency
# ────────────────────────────────────────────────────────────────────────

# The API treats every monetary item as `type=currency`, but the legacy
# `Currency` enum only exposed Coins (a virtual currency referenced via
# `itemValue.currency='money'` rather than as an item) and the
# Adventurers' guild token. Code at numerous sites compares against
# `Currency.COIN` / `'Currency.COIN'` strings, so COIN must always exist.
#
# We synthesize COIN as a fixed entry, then add every other currency-typed
# item from the API. This keeps the legacy lookups working while exposing
# the fuller currency catalogue the API now publishes (skill chips, etc.).

# Items the OLD enum has — synthesize these fixed entries first.
_LEGACY_COIN_NAME = 'Coins'
_LEGACY_AGT_API_ID = 'adventurers_guild_token'


def emit_currency(out_path: Optional[Path] = None) -> Path:
    """Generate currency.py in the OLD shape.

    Surface (matches util/autogenerated/currency.py):
      - class CurrencyInstance (name: str)
      - class Currency: COIN, ADVENTURERS_GUILD_TOKEN, plus every other
                        type=currency item (skill chips, etc.).
      - CURRENCIES_BY_NAME: dict[name -> Currency.attr]
      - resolve_currency(name) -> str | None
    """
    items = load_all_details('items')
    currencies = [d for d in items.values() if d.get('type') == 'currency']
    # Sort by id for deterministic output.
    currencies.sort(key=lambda d: d.get('id') or '')

    # Build (enum_name, display_name) tuples. COIN is always first.
    rows: List[Tuple[str, str]] = [('COIN', _LEGACY_COIN_NAME)]
    seen_enum_names = {'COIN'}
    for d in currencies:
        name = d.get('name')
        if not name:
            continue
        enum_name = to_enum_name(name)
        # avoid collisions
        base = enum_name
        n = 1
        while enum_name in seen_enum_names:
            n += 1
            enum_name = f'{base}_{n}'
        seen_enum_names.add(enum_name)
        rows.append((enum_name, name))

    lines: List[str] = []
    lines.append('#!/usr/bin/env python3')
    lines.append('"""')
    lines.append('Currency data for Walkscape')
    lines.append('Auto-generated from the WalkScape tools API')
    lines.append('Drop-in replacement for util/autogenerated/currency.py')
    lines.append('DO NOT EDIT MANUALLY')
    lines.append('"""')
    lines.append('')
    lines.append('')
    lines.append('class CurrencyInstance:')
    lines.append('    """Represents a currency type."""')
    lines.append('')
    lines.append('    def __init__(self, name: str):')
    lines.append('        self.name = name')
    lines.append('')
    lines.append('    def __str__(self) -> str:')
    lines.append('        return self.name')
    lines.append('')
    lines.append('    def __repr__(self) -> str:')
    lines.append('        return f"Currency({self.name})"')
    lines.append('')
    lines.append('')
    lines.append('class Currency:')
    lines.append('    """All currencies in Walkscape."""')
    lines.append('')
    for enum_name, display_name in rows:
        lines.append(f'    {enum_name} = CurrencyInstance(name={py_str(display_name)})')
    lines.append('')
    lines.append('')
    lines.append('# Lookup dictionary for quick access')
    lines.append('CURRENCIES_BY_NAME = {')
    for enum_name, display_name in rows:
        lines.append(f'    {py_str(display_name)}: Currency.{enum_name},')
    lines.append('}')
    lines.append('')
    lines.append('')
    lines.append('def resolve_currency(name: str):')
    lines.append('    """')
    lines.append('    Resolve a currency name to a Currency enum reference string.')
    lines.append('')
    lines.append('    Args:')
    lines.append('        name: Currency name (e.g., "Coins", "Adventurers\' guild token")')
    lines.append('')
    lines.append('    Returns:')
    lines.append('        String reference like "Currency.COIN" or None if not found')
    lines.append('    """')
    lines.append('    if name in CURRENCIES_BY_NAME:')
    lines.append('        currency = CURRENCIES_BY_NAME[name]')
    lines.append('        for attr_name in dir(Currency):')
    lines.append('            if not attr_name.startswith("_"):')
    lines.append('                if getattr(Currency, attr_name) is currency:')
    lines.append('                    return f"Currency.{attr_name}"')
    lines.append('')
    lines.append('    name_lower = name.lower()')
    lines.append('    for currency_name, currency_obj in CURRENCIES_BY_NAME.items():')
    lines.append('        if currency_name.lower() == name_lower:')
    lines.append('            for attr_name in dir(Currency):')
    lines.append('                if not attr_name.startswith("_"):')
    lines.append('                    if getattr(Currency, attr_name) is currency_obj:')
    lines.append('                        return f"Currency.{attr_name}"')
    lines.append('')
    lines.append('    return None')
    lines.append('')

    if out_path is None:
        out_path = AUTOGEN_DIR / 'currency.py'
    write_file(out_path, '\n'.join(lines))
    return out_path


