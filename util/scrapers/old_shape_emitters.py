def _api_icon_to_legacy(icon: Optional[str]) -> Optional[str]:
    """`assets/icons/locations/castle_green.png` → `castle_green_icon.svg`.

    The legacy locations file stored just the icon-filename portion. Some
    UI code keys off the `_icon.svg` suffix; preserve that pattern. If the
    API icon is missing or malformed, return None.
    """
    if not icon:
        return None
    base = os.path.basename(icon)
    name, _ext = os.path.splitext(base)
    if not name:
        return None
    # legacy convention is lowercased name + `_icon.svg`
    return f'{name.lower()}_icon.svg'


def _location_regions(detail: Dict[str, Any]) -> List[str]:
    """Build the legacy `regions` list from API fields.

    Order: primary faction code first, then sub-factions, then every
    keyword on the location (e.g. ``underwater``, ``snowy``, ``spectral``).
    Mirrors the original wiki scraper's ordering, but appends *all*
    keywords so location-keyword-scoped item stats (matched generically
    via ``LocationInfo.is_in_region``) light up automatically as the
    API publishes new keywords.
    """
    regions: List[str] = []
    faction = detail.get('faction')
    if faction:
        code = _FACTION_TO_REGION.get(faction, faction)
        regions.append(code)
    for sf in detail.get('subFactions') or []:
        if sf and sf not in regions:
            regions.append(sf)
    for kw in detail.get('keywords') or []:
        if kw and kw not in regions:
            regions.append(kw)
    return regions


