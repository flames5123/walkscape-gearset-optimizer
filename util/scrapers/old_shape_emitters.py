# The API models Item-Finding gear as a generic ``roll_special_table`` stat
# whose semantics live in the attr's referenced loot table (e.g.
# ``gain_ten_money`` → gold pieces). The legacy/wiki data instead used a
# dedicated ``ItemFindingCategory.<CAT>`` stat key (or a raw find_* stat for
# the few non-category tables). Map each special table to the legacy stat key
# so the IF-category optimizer and dominance pruner can read these stats.
# Verified against the legacy equipment.py for one item per table.
_SPECIAL_TABLE_TO_STAT: Dict[str, str] = {
    'find_basic_chests':               'ItemFindingCategory.SKILL_CHEST',
    'find_ectoplasm_drop':             'ItemFindingCategory.ECTOPLASM',
    'find_trash_junk_items':           'ItemFindingCategory.RANDOM_PIECE_OF_JUNK',
    'gain_bird_nest_drop':             'ItemFindingCategory.BIRD_NEST',
    'gain_coin_pouch_drop':            'find_coin_pouch',
    'gain_crustacean_table':           'ItemFindingCategory.CRUSTACEAN',
    'gain_fishing_bait_table':         'ItemFindingCategory.FISHING_BAIT',
    'gain_gold_nugget_drop':           'ItemFindingCategory.GOLD_NUGGET',
    'gain_one_adventurers_guild_token': 'ItemFindingCategory.ADVENTURERS_GUILD_TOKENS',
    'gain_plant_fiber_table':          'ItemFindingCategory.FIBROUS_PLANT',
    'gain_ten_money':                  'ItemFindingCategory.GOLD_PIECES',
    'gem_pouch_table':                 'ItemFindingCategory.RANDOM_GEM',
    'sea_shells_1_10_drop':            'ItemFindingCategory.SEA_SHELLS',
}


def _special_table_stat_key(attr: Dict[str, Any]) -> Optional[str]:
    """Resolve a ``roll_special_table`` attr to its legacy stat key.

    The category is determined by the referenced loot table id in the
    attr's ``tables`` field. Returns None if no known table is referenced.
    """
    for t in attr.get('tables') or []:
        for tid in t.get('tables') or []:
            mapped = _SPECIAL_TABLE_TO_STAT.get(str(tid))
            if mapped:
                return mapped
    return None


def _extract_attribute_stats(
    item_attrs: Optional[List[Dict[str, Any]]],
    default_skill_scope: str = 'global',
    include_activity_gated: bool = False,
) -> Dict[str, Any]:
    """Convert an item's `itemAttrs[]` into the legacy nested stats dict.

    Output shape: ``{skill: {location: {stat: value}}}`` matching the
    format used by `StatsMixin._stats`. Skill scope comes from
    ``mainSkill`` requirements; location scope comes from ``realm`` or
    ``locationHasKeywords`` requirements (the API uses both — older
    items still carry ``realm``, newer migrated items use
    ``locationHasKeywords``). Without either, stats land under
    ``'global'`` for both axes.

    Each ``itemAttrs`` entry may carry a ``mainSkill`` requirement which
    scopes the stat to that skill (e.g. work efficiency on a hatchet
    while doing woodcutting). Without a ``mainSkill`` the stat lands
    under ``default_skill_scope`` (typically ``'global'``).
    """
    out: Dict[str, Any] = {}
    if not item_attrs:
        return out

    for attr in item_attrs:
        # Activity-gated stats (e.g. Zippy kicksled's -5 steps while
        # sledding) are scoped to a specific activity via an `activityType`
        # requirement. The legacy ItemInstance stats shape has no
        # per-activity axis yet, so emitting them under 'global' is WRONG --
        # it would apply the bonus to every activity. Skip them here so they
        # do not pollute ungated stats; the gated-stats builder calls this
        # with include_activity_gated=True to extract the payload for the
        # legacy `activity` gated_stats (see zippy_kicksled).
        if (not include_activity_gated and any(
                (r.get('type') == 'activityType'
                 or (r.get('requirement') or {}).get('activity'))
                for r in (attr.get('requirements') or []))):
            continue
        # Find skill scope (mainSkill) and location scope (realm or
        # locationHasKeywords). Scan all requirements — an attr can carry
        # both a skill scope and a location scope simultaneously.
        target_skill = default_skill_scope
        target_loc = 'global'
        for r in attr.get('requirements') or []:
            rtype = r.get('type')
            rdata = r.get('requirement') or {}
            if rtype == 'mainSkill':
                api_skill = rdata.get('skill')
                if api_skill:
                    target_skill = _legacy_skill_name(api_skill)
            elif rtype == 'mainSkillType':
                # Skill-CATEGORY scope (gathering/artisan/utility). The
                # downstream skill matcher treats these as groups containing
                # their member skills (e.g. Aerofibril shorts -> 'utility',
                # which matches all utility skills). Mirrors the pet emitter.
                stype = rdata.get('type')
                if stype:
                    target_skill = str(stype)
            elif rtype == 'traveling':
                # "While travelling" stats live under the 'traveling' skill
                # scope (the travel optimizer's TRAVEL skill = agility +
                # traveling). e.g. Map of Erdwise, Medieval sneakers, the
                # map items, Pathfinder, Travelers kit.
                target_skill = 'traveling'
            elif rtype == 'realm':
                realm = rdata.get('realm')
                if realm:
                    # Normalize the API realm slug to the legacy location
                    # keyword used by locations.py and the UI decoder
                    # (e.g. 'grand_duchy_of_trellin_erdwise' -> 'gdte').
                    # Unmapped values pass through unchanged. Without this the
                    # stat scopes to a key no location carries, so the bonus
                    # never applies and the UI shows the raw slug.
                    target_loc = _FACTION_TO_REGION.get(str(realm), str(realm))
            elif rtype == 'locationHasKeywords':
                kws = rdata.get('keywords') or []
                # Today's API only emits single-keyword location scopes
                # (verified across all 55 items + 12 pets). If a
                # multi-keyword conjunction ever appears, we'd need a
                # composite scope — for now pick the first and let the
                # downstream matcher's `is_in_region` handle it.
                # `opposite: true` negates the scope (e.g. Medieval sneakers'
                # "while NOT underwater"); the consumer reads this as a
                # '!'-prefixed location key (e.g. '!underwater').
                if kws:
                    kw0 = _FACTION_TO_REGION.get(str(kws[0]), str(kws[0]))
                    target_loc = ('!' if r.get('opposite') else '') + kw0

        for stat_entry in attr.get('stats') or []:
            api_name = stat_entry.get('stat')
            if not api_name:
                continue
            is_percent = bool(stat_entry.get('isPercent', False))
            if api_name == 'roll_special_table':
                # Item-Finding gear: resolve the IF-category (or raw find_*)
                # stat key from the attr's referenced loot table.
                stat_name = _special_table_stat_key(attr) or _normalize_stat_name(api_name)
            else:
                # isPercent-aware split handles steps_required ->
                # steps_percent/steps_add and bonus_experience ->
                # bonus_xp_percent/bonus_xp_add (matches the gear/consumable
                # ingest scripts).
                stat_name = _normalize_stat_name(api_name, is_percent)
            # A `bonus_experience` stat carrying a `skill` field is a
            # skill-specific FLAT base-XP bonus (e.g. Petal finder ->
            # foraging_base_xp), NOT the generic bonus_xp_add. Matches the
            # pre-migration/legacy shape. Only petal_finder has this today.
            if (api_name == 'bonus_experience' and stat_entry.get('skill')
                    and not is_percent):
                stat_name = f"{str(stat_entry['skill']).lower()}_base_xp"
            value = _display_stat_value(stat_entry)
            skill_root = out.setdefault(target_skill, {})
            loc_root = skill_root.setdefault(target_loc, {})
            # Sum if multiple itemAttrs map to the same skill+location+stat
            if stat_name in loc_root:
                loc_root[stat_name] = round(loc_root[stat_name] + value, 4)
            else:
                loc_root[stat_name] = value
    return out


def _extract_buff_stats(
    buffs: Optional[List[Dict[str, Any]]],
    *,
    fine: bool = False,
) -> Dict[str, Any]:
    """Convert a consumable's `buffs[]` into the legacy nested stats dict.

    Consumables expose stats via `buffs[].data[].buffs[].attributes`
    (common) and `buffs[].data[].buffs[].fineAttributes` (fine quality).
    Pass ``fine=True`` to extract the fine variant.
    """
    out: Dict[str, Any] = {}
    if not buffs:
        return out

    field = 'fineAttributes' if fine else 'attributes'
    for buff in buffs:
        for data_entry in buff.get('data') or []:
            for inner_buff in data_entry.get('buffs') or []:
                attrs = inner_buff.get(field) or []
                # buffs are global-global; no mainSkill scoping
                attr_stats = _extract_attribute_stats(attrs, 'global')
                # merge attr_stats into out
                for skill, locs in attr_stats.items():
                    skill_root = out.setdefault(skill, {})
                    for loc, kv in locs.items():
                        loc_root = skill_root.setdefault(loc, {})
                        for stat, val in kv.items():
                            if stat in loc_root:
                                loc_root[stat] = round(loc_root[stat] + val, 4)
                            else:
                                loc_root[stat] = val
    return out


def _legacy_requirements_from_api(api_reqs: Optional[List[Dict[str, Any]]]) -> List[Dict[str, Any]]:
    """Convert API `requirements[]` into the legacy list-of-dicts format.

    Legacy format examples:
      - {'type': 'skill', 'skill': 'hunting', 'level': 10}
      - {'type': 'reputation', 'faction': 'syrenthia', 'amount': 100}

    Drops any requirement type not in the legacy vocabulary.
    """
    if not api_reqs:
        return []
    out: List[Dict[str, Any]] = []
    for req in api_reqs:
        rtype = req.get('type')
        rdata = req.get('requirement') or {}
        if rtype == 'skillLevel':
            skill = rdata.get('skill')
            level = rdata.get('level')
            if skill and level is not None:
                out.append({
                    'type': 'skill',
                    'skill': skill,
                    'level': int(level),
                })
    return out


