# Map API item type → legacy Item enum class. Used for resolving
# item_ref strings inside DropEntry(...). Returns None if the type
# doesn't have a clean legacy equivalent.
_TYPE_TO_ENUM = {
    'material': 'Material',
    'consumable': 'Consumable',
    'collectible': 'Collectible',
    'container': 'Container',
    'currency': 'Currency',
    'egg': 'Egg',
}


def _resolve_item_ref(
    row_item_id: Optional[str],
    items_by_id: Dict[str, Dict[str, Any]],
) -> Optional[str]:
    """Resolve a tableRow.rowItemID to a legacy 'Class.ENUM_NAME' string."""
    if not row_item_id:
        return None
    detail = items_by_id.get(row_item_id)
    if not detail:
        return None
    api_type = detail.get('type')
    enum_class: Optional[str] = None
    if api_type in _TYPE_TO_ENUM:
        enum_class = _TYPE_TO_ENUM[api_type]
    elif api_type in ('crafted', 'loot'):
        # Equipment vs loot_items: gearType determines which.
        if detail.get('gearType'):
            enum_class = 'Item'
        else:
            # Drop-only items (e.g. compass_trinket) are filed under
            # legacy Material in the autogenerated tree.
            enum_class = 'Material'
    if not enum_class:
        return None
    return f'{enum_class}.{to_enum_name(row_item_id)}'


def _container_table_to_dropentries(
    subtable: Dict[str, Any],
    items_by_id: Dict[str, Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Convert one API subtable into a list of DropEntry kwargs dicts.

    chance_percent per row = subtable_weight × (row_weight / sum_row_weights) × 100
    """
    rows = subtable.get('tableRows') or []
    if not rows:
        return []
    total_row_weight = sum((r.get('rowWeight') or 0) for r in rows)
    if not total_row_weight:
        return []
    sub_weight = subtable.get('weight') or 0
    out: List[Dict[str, Any]] = []
    for r in rows:
        row_w = r.get('rowWeight') or 0
        chance = sub_weight * (row_w / total_row_weight) * 100
        chance = round(chance, 4)
        if r.get('isMoney'):
            entry = {
                'item_name': 'Coins',
                'item_ref': None,
                'min_qty': r.get('rowMinimumAmount'),
                'max_qty': r.get('rowMaximumAmount'),
                'chance_percent': chance,
            }
        else:
            iid = r.get('rowItemID')
            name = r.get('name') or (
                items_by_id.get(iid, {}).get('name') if iid else None
            ) or (iid or '')
            entry = {
                'item_name': name,
                'item_ref': _resolve_item_ref(iid, items_by_id),
                'min_qty': r.get('rowMinimumAmount'),
                'max_qty': r.get('rowMaximumAmount'),
                'chance_percent': chance,
            }
        out.append(entry)
    return out


# Map API subtable type → legacy ContainerInfo field name.
_API_SUBTABLE_TO_LEGACY_FIELD = {
    'money':     'valuables_table',
    'common':    'common_table',
    'uncommon':  'uncommon_table',
    'rare':      'rare_table',
    'epic':      'epic_table',
    'legendary': 'legendary_table',
    'ethereal':  'ethereal_table',
}


def _container_type(detail: Dict[str, Any]) -> str:
    """Classify a container as 'skill_chest' or 'unique_openable'."""
    keywords = detail.get('keywords') or []
    if 'skilling_chest' in keywords:
        return 'skill_chest'
    return 'unique_openable'


def emit_containers(out_path: Optional[Path] = None) -> Path:
    """Generate containers.py in the OLD shape.

    Surface (matches util/autogenerated/containers.py):
      - ROLLS_PER_CHEST = 4
      - @dataclass class ContainerInfo with main/valuables/common/...
        ethereal table fields.
      - class Container with one attribute per chest.
      - CONTAINERS_BY_NAME, SKILL_CHESTS, UNIQUE_OPENABLES indexes.

    Note: legacy `main_table` is left as `[]` because the Tools API
    does not publish the per-roll material drops the wiki had (Fishbone,
    Wine, etc. for the Agility chest). Document this gap; the UI's
    catalog page handles `main_table=None`/`[]` gracefully.
    """
    items = load_all_details('items')
    loot_tables = load_all_details('loot_tables')
    containers = [d for d in items.values() if d.get('type') == 'container']
    containers.sort(key=lambda d: d.get('id') or '')
    items_by_id = {iid: d for iid, d in items.items()}

    rendered_entries: List[str] = []
    container_names: List[str] = []  # for CONTAINERS_BY_NAME ordering
    container_enum_attrs: List[Tuple[str, str]] = []  # (enum_attr, display_name)

    for d in containers:
        cid = d.get('id') or ''
        name = d.get('name') or cid
        ctype = _container_type(d)

        # Find the loot table id for this container.
        table_specs = d.get('tables') or []
        table_ids: List[str] = []
        for ts in table_specs:
            for t in ts.get('tables') or []:
                if t and t not in table_ids:
                    table_ids.append(t)

        # Collect drops by legacy table-field name.
        per_field: Dict[str, List[Dict[str, Any]]] = {}
        for tid in table_ids:
            tbl = loot_tables.get(tid)
            if not tbl:
                continue
            # Typed rarity subtables → valuables/common/.../ethereal fields.
            for st in tbl.get('subTables') or []:
                api_type = st.get('type')
                legacy_field = _API_SUBTABLE_TO_LEGACY_FIELD.get(api_type)
                if not legacy_field:
                    continue
                rows = _container_table_to_dropentries(st, items_by_id)
                if rows:
                    per_field.setdefault(legacy_field, []).extend(rows)

            # Top-level tableRows are the chest's MAIN per-roll drops
            # (sea shells, pearls, materials, etc.). The probability mass
            # they share is whatever the populated rarity subtables and
            # noDropChance leave behind: empty rarity tiers revert their
            # weight to the main pool. main_fraction = 1 - Σ(weight of
            # subtables that actually carry rows) - noDropChance. Verified
            # against the wiki Coral chest (sea shell w10 → 0.95×10/35×100
            # = 27.143%, matching the legacy scrape).
            populated_sub_weight = 0.0
            for st in tbl.get('subTables') or []:
                if st.get('tableRows'):
                    populated_sub_weight += (st.get('weight') or 0)
            no_drop = tbl.get('noDropChance') or 0
            main_fraction = 1.0 - populated_sub_weight - no_drop
            top_rows = tbl.get('tableRows') or []
            if top_rows and main_fraction > 0:
                synthetic_main = {'weight': main_fraction, 'tableRows': top_rows}
                main_rows = _container_table_to_dropentries(synthetic_main, items_by_id)
                if main_rows:
                    per_field.setdefault('main_table', []).extend(main_rows)

        enum_attr = to_enum_name(cid)
        container_enum_attrs.append((enum_attr, name))

        # Render the ContainerInfo(...) block.
        lines: List[str] = []
        lines.append(f'    {enum_attr} = ContainerInfo(')
        lines.append(f'        name={py_str(name)},')
        lines.append(f'        container_type={py_str(ctype)},')
        # Always emit main_table (even if empty) so consumer code that
        # iterates chest.main_table without a None guard stays safe.
        if not per_field.get('main_table'):
            lines.append('        main_table=[],')
        for legacy_field in (
            'main_table',
            'valuables_table', 'common_table', 'uncommon_table',
            'rare_table', 'epic_table', 'legendary_table', 'ethereal_table',
        ):
            entries = per_field.get(legacy_field) or []
            if not entries:
                continue
            lines.append(f'        {legacy_field}=[')
            for e in entries:
                qty = (
                    f'Quantity(min_qty={e["min_qty"]}, max_qty={e["max_qty"]})'
                    if e["min_qty"] is not None and e["max_qty"] is not None
                    else 'None'
                )
                ref = py_dq(e['item_ref']) if e['item_ref'] else 'None'
                lines.append(
                    f'            DropEntry(item_name={py_str(e["item_name"])}, '
                    f'item_ref={ref}, quantity={qty}, '
                    f'chance_percent={e["chance_percent"]:.4f}),'
                )
            lines.append('        ],')
        # Trailing newline with closing
        lines.append('    )')
        lines.append('')
        rendered_entries.append('\n'.join(lines))

    # ── Render file ────────────────────────────────────────────────────
    out: List[str] = []
    out.append('#!/usr/bin/env python3')
    out.append('"""')
    out.append('Containers (chests) data from the WalkScape tools API')
    out.append('Drop-in replacement for util/autogenerated/containers.py')
    out.append('DO NOT EDIT MANUALLY')
    out.append('"""')
    out.append('')
    out.append('from typing import Dict, List, Optional')
    out.append('from dataclasses import dataclass')
    out.append('from util.item_utils import Quantity, DropEntry')
    out.append('')
    out.append('# Number of rolls per chest')
    out.append('ROLLS_PER_CHEST = 4')
    out.append('')
    out.append('')
    out.append('@dataclass')
    out.append('class ContainerInfo:')
    out.append('    """Detailed information about a container (chest)."""')
    out.append('    name: str')
    out.append('    container_type: str')
    out.append('    main_table: List[DropEntry] = None')
    out.append('    valuables_table: List[DropEntry] = None')
    out.append('    common_table: List[DropEntry] = None')
    out.append('    uncommon_table: List[DropEntry] = None')
    out.append('    rare_table: List[DropEntry] = None')
    out.append('    epic_table: List[DropEntry] = None')
    out.append('    legendary_table: List[DropEntry] = None')
    out.append('    ethereal_table: List[DropEntry] = None')
    out.append('')
    out.append('    def __post_init__(self):')
    out.append('        """Build lookup dictionaries for fast access."""')
    out.append('        table_list = [self.main_table, self.valuables_table, self.common_table,')
    out.append('                      self.uncommon_table, self.rare_table, self.epic_table,')
    out.append('                      self.legendary_table, self.ethereal_table]')
    out.append('        self._all_drops = []')
    out.append('        for table in table_list:')
    out.append('            if table:')
    out.append('                self._all_drops.extend(table)')
    out.append('        self._all_drops.sort(key=lambda d: d.item_name.lower())')
    out.append('        self._drop_rate_by_name = {}')
    out.append('        for drop in self._all_drops:')
    out.append('            if drop.chance_percent and drop.chance_percent > 0:')
    out.append('                self._drop_rate_by_name[drop.item_name.lower()] = drop.chance_percent')
    out.append('')
    out.append('    def get_all_drops(self) -> List[DropEntry]:')
    out.append('        """Get all drops from all loot tables."""')
    out.append('        return self._all_drops')
    out.append('')
    out.append('    def get_drop_rate(self, item) -> Optional[float]:')
    out.append('        """Get drop rate (chance percent per roll) for an item.')
    out.append('')
    out.append('        Args:')
    out.append('            item: a string (item name) or an object with a .name attribute')
    out.append('                  (e.g. Material.CORAL, Item.WALKING_STICK).')
    out.append('        Returns:')
    out.append('            Chance percent per roll (e.g. 6.0 for 6%), or None if not found.')
    out.append('        """')
    out.append('        if isinstance(item, str):')
    out.append('            item_name = item')
    out.append('        elif hasattr(item, "name"):')
    out.append('            item_name = item.name')
    out.append('        else:')
    out.append('            return None')
    out.append('        return self._drop_rate_by_name.get(item_name.lower())')
    out.append('')
    out.append('    def get_chance_per_chest(self, item) -> Optional[float]:')
    out.append('        """Get chance per chest (across all ROLLS_PER_CHEST rolls) for an item."""')
    out.append('        chance_per_roll = self.get_drop_rate(item)')
    out.append('        if chance_per_roll:')
    out.append('            # 1 - (1 - p)^rolls, accounting for independent rolls per chest.')
    out.append('            return (1 - pow(1 - chance_per_roll / 100.0, ROLLS_PER_CHEST)) * 100.0')
    out.append('        return None')
    out.append('')
    out.append('    def get_expected_chests_per_item(self, item) -> Optional[float]:')
    out.append('        """Expected chests to open to get one of the specified item."""')
    out.append('        chance_per_chest = self.get_chance_per_chest(item)')
    out.append('        if chance_per_chest and chance_per_chest > 0:')
    out.append('            return 1.0 / (chance_per_chest / 100.0)')
    out.append('        return None')
    out.append('')
    out.append('')
    out.append('class Container:')
    out.append('    """Enum-style access to all containers."""')
    out.append('')
    for body in rendered_entries:
        out.append(body)

    # Indexes
    out.append('')
    out.append('# Lookup dictionaries')
    out.append('CONTAINERS_BY_NAME = {')
    for enum_attr, name in container_enum_attrs:
        out.append(f'    {py_str(name)}: Container.{enum_attr},')
    out.append('}')
    out.append('')
    out.append('SKILL_CHESTS = [c for c in CONTAINERS_BY_NAME.values() if c.container_type == "skill_chest"]')
    out.append('UNIQUE_OPENABLES = [c for c in CONTAINERS_BY_NAME.values() if c.container_type == "unique_openable"]')
    out.append('')

    if out_path is None:
        out_path = AUTOGEN_DIR / 'containers.py'
    write_file(out_path, '\n'.join(out))
    return out_path


