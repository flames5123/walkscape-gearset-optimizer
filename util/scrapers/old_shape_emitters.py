# API gearType → legacy slot name. Mostly identity, with one rename.
_GEARTYPE_TO_SLOT = {
    'tool': 'tools',  # legacy uses plural
}

# API quality keys → legacy quality keys (for CraftedItem.quality_stats /
# quality_values dicts). The API publishes increments per quality tier;
# the emitter accumulates them into the legacy cumulative format.
_API_QUALITY_TO_LEGACY = {
    'common':    'Normal',     # itemAttrs base, not from itemQualityAttrs
    'uncommon':  'Good',
    'rare':      'Great',
    'epic':      'Excellent',
    'legendary': 'Perfect',
    'ethereal':  'Eternal',
}
_LEGACY_QUALITY_ORDER = ['Normal', 'Good', 'Great', 'Excellent', 'Perfect', 'Eternal']


def _slot_from_geartype(gear_type: Optional[str]) -> str:
    if not gear_type:
        return ''
    return _GEARTYPE_TO_SLOT.get(gear_type, gear_type)


def _equipment_keywords(detail: Dict[str, Any]) -> List[str]:
    """TitleCase the API keywords; drop ones that duplicate slot/skill info."""
    kws = detail.get('keywords') or []
    gear_type = detail.get('gearType')
    # Drop 'global' and the gearType keyword (it duplicates the slot field),
    # EXCEPT 'ring' -- the UI/consumer groups ring-slot items by the 'ring'
    # keyword, so dropping it broke ring grouping. Keep 'ring'; still drop
    # 'tool' and the rest.
    drop = {'global'}
    if gear_type and gear_type != 'ring':
        drop.add(gear_type)
    out: List[str] = []
    seen: set = set()
    for kw in kws:
        if kw in drop:
            continue
        # legacy used Title Case with space-separated words
        legacy = kw.replace('_', ' ').title()
        # Keep "Misc." style and acronyms straight
        if legacy.lower() in seen:
            continue
        seen.add(legacy.lower())
        out.append(legacy)
    return out


def _equipment_value(detail: Dict[str, Any]) -> int:
    """Coin value for the base (common) tier.

    The API publishes itemValue.value as either a scalar int or a dict
    keyed by quality. Most items have 'common' keyed, but rare/epic loot
    drops only publish their own quality (e.g. 'rare': 455). Fall back
    to the item's own quality field, then to the first available value.
    """
    iv = detail.get('itemValue') or {}
    val = iv.get('value')
    if val is None:
        return 0
    if isinstance(val, dict):
        # Try 'common' first (most common case)
        if val.get('common') is not None:
            return int(val['common'])
        # Fall back to the item's own quality (e.g. rare-only drops)
        own_quality = detail.get('quality')
        if own_quality and val.get(own_quality) is not None:
            return int(val[own_quality])
        # Last resort: first non-null value in canonical quality order
        for q in ('uncommon', 'rare', 'epic', 'legendary', 'ethereal'):
            if val.get(q) is not None:
                return int(val[q])
        return 0
    return int(val)


def _equipment_quality_values(detail: Dict[str, Any]) -> Dict[str, int]:
    """Build quality_values dict for crafted items: {Normal: N, Good: N, ...}."""
    iv = detail.get('itemValue') or {}
    val = iv.get('value')
    if not isinstance(val, dict):
        return {}
    out: Dict[str, int] = {}
    for api_q, legacy_q in _API_QUALITY_TO_LEGACY.items():
        if api_q in val and val[api_q] is not None:
            out[legacy_q] = int(val[api_q])
    return out


