                    # Fine Material Finding bonus applies multiplicatively.
                    # 2026-05-26 (jwbail): Use the outer fine_chance_multiplier
                    # computed at the top of the function — it sums FMF from
                    # ALL sources (stats, collectibles, consumable, input_item).
                    # The previous local recomputation here only summed
                    # stats + collectibles, missing consumable+input AND
                    # double-counting collectibles when stats was a pre-merged
