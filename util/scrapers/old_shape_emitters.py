def emit_item_finding(out_path: Optional[Path] = None) -> Path:
    """Generate item_finding.py from the loot_tables API.

    Each ItemFindingCategory maps to a loot table whose top-level
    ``tableRows`` ARE the category's drops. The per-drop chance is the
    row's weight share: ``rowWeight / Σ(rowWeights) × 100`` (rounded to 3
    decimals), and drops are ordered by chance desc then name asc — the
    legacy wiki file's shape. Money rows render as Currency.COIN.
    """
    items = load_all_details('items')
    loot_tables = load_all_details('loot_tables')

    # (enum_name, display_name, loot_table_id) in the legacy file order.
    categories = [
        ('ADVENTURERS_GUILD_TOKENS', "Adventurers' Guild Tokens", 'gain_one_adventurers_guild_token'),
        ('BIRD_NEST',                'Bird Nest',                  'gain_bird_nest_drop'),
        ('CRUSTACEAN',               'Crustacean',                 'gain_crustacean_table'),
        ('ECTOPLASM',                'Ectoplasm',                  'find_ectoplasm_drop'),
        ('FIBROUS_PLANT',            'Fibrous Plant',              'gain_plant_fiber_table'),
        ('FISHING_BAIT',             'Fishing Bait',               'gain_fishing_bait_table'),
        ('GOLD_NUGGET',              'Gold Nugget',                'gain_gold_nugget_drop'),
        ('GOLD_PIECES',              'Gold Pieces',                'gain_ten_money'),
        ('RANDOM_GEM',               'Random Gem',                 'gem_pouch_table'),
        ('RANDOM_PIECE_OF_JUNK',     'Random Piece of Junk',       'find_trash_junk_items'),
        ('SEA_SHELLS',               'Sea Shells',                 'sea_shells_1_10_drop'),
        ('SKILL_CHEST',              'Skill Chest',                'find_basic_chests'),
    ]

    def _category_drops(table_id: str) -> List[Dict[str, Any]]:
        d = loot_tables.get(table_id) or {}
        rows = d.get('tableRows') or []
        total = sum((r.get('rowWeight') or 0) for r in rows)
        if not total:
            return []
        out: List[Dict[str, Any]] = []
        for r in rows:
            chance = round((r.get('rowWeight') or 0) / total * 100, 3)
            if r.get('isMoney'):
                name, ref = 'Coins', 'Currency.COIN'
            else:
                iid = r.get('rowItemID')
                name = (items.get(iid, {}) or {}).get('name') or iid or ''
                ref = _resolve_item_ref(iid, items)
            out.append({
                'item_name': name,
                'item_ref': ref,
                'min_qty': r.get('rowMinimumAmount') or 1,
                'max_qty': r.get('rowMaximumAmount') or 1,
                'chance_percent': chance,
            })
        # Order: chance desc, then item name asc (matches legacy shape).
        out.sort(key=lambda e: (-e['chance_percent'], e['item_name']))
        return out

    lines: List[str] = []
    lines.append('#!/usr/bin/env python3')
    lines.append('"""')
    lines.append('Item Finding Items - category to item mappings')
    lines.append('Auto-generated from the WalkScape tools API loot_tables.')
    lines.append('DO NOT EDIT MANUALLY')
    lines.append('"""')
    lines.append('')
    lines.append('from typing import List')
    lines.append('from util.item_utils import Quantity, DropEntry')
    lines.append('')
    lines.append('')
    lines.append('class CategoryInstance:')
    lines.append('    """Represents an item finding category with its drop table."""')
    lines.append('    def __init__(self, name: str, drops: List[DropEntry]):')
    lines.append('        self.name = name')
    lines.append('        self.drops = drops  # List of DropEntry with relative chances')
    lines.append('')
    lines.append('    def expand_with_chance(self, base_chance: float) -> List[DropEntry]:')
    lines.append('        """Expand this category to actual drops with adjusted chances.')
    lines.append('')
    lines.append('        actual_chance = base_chance * (drop.chance_percent / 100.0)')
    lines.append('        """')
    lines.append('        expanded = []')
    lines.append('        for drop in self.drops:')
    lines.append('            actual_chance = base_chance * (drop.chance_percent / 100.0)')
    lines.append('            expanded.append(DropEntry(')
    lines.append('                item_name=drop.item_name,')
    lines.append('                item_ref=drop.item_ref,')
    lines.append('                quantity=drop.quantity,')
    lines.append('                chance_percent=actual_chance')
    lines.append('            ))')
    lines.append('        return expanded')
    lines.append('')
    lines.append('    def __repr__(self):')
    lines.append('        return f"CategoryInstance({self.name}, {len(self.drops)} items)"')
    lines.append('')
    lines.append('')
    lines.append('class ItemFindingCategory:')
    lines.append('    """All item finding categories."""')
    lines.append('')
    for enum_name, display, table_id in categories:
        drops = _category_drops(table_id)
        lines.append(f'    {enum_name} = CategoryInstance(')
        lines.append(f'        name={py_str(display)},')
        lines.append('        drops=[')
        for e in drops:
            ref_lit = py_str(e['item_ref']) if e['item_ref'] else 'None'
            lines.append(
                f"            DropEntry(item_name={py_str(e['item_name'])}, "
                f"item_ref={ref_lit}, "
                f"quantity=Quantity(min_qty={int(e['min_qty'])}, max_qty={int(e['max_qty'])}), "
                f"chance_percent={float(e['chance_percent'])}),"
            )
        lines.append('        ]')
        lines.append('    )')
        lines.append('')

    if out_path is None:
        out_path = AUTOGEN_DIR / 'item_finding.py'
    write_file(out_path, '\n'.join(lines))
    return out_path


