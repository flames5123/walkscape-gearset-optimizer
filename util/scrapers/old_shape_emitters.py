        pname = pet.get('name') or pid
        egg = pet.get('egg') or {}
        egg_name = egg.get('name') or ''
        levels_api = pet.get('levels') or []
        cumulative_xp = _accumulate_xp(levels_api)

        rare_name, rare_export_name = _PET_RARE_METADATA.get(pid, ('', ''))
        species = pid

        enum_attr = to_enum_name(pid)
        pet_attrs.append((enum_attr, pname))

        # Render PetLevels(...) constructor
        lines: List[str] = []
        lines.append(f'    {enum_attr} = PetLevels(')
        lines.append(f'        name={py_str(pname)},')
        lines.append(f'        egg_name={py_str(egg_name)},')
