def _format_cooldown(cd: Optional[Dict[str, Any]]) -> Optional[str]:
    """Render an API cooldown dict as a human-readable legacy string."""
    if not cd:
        return None
    parts = []
    if cd.get('hours'):
        parts.append(f"{cd['hours']}h")
    if cd.get('minutes'):
        parts.append(f"{cd['minutes']}m")
    if cd.get('seconds'):
        parts.append(f"{cd['seconds']}s")
    if cd.get('days'):
        parts.append(f"{cd['days']}d")
    if cd.get('steps'):
        # Format with thousand separators to match legacy
        parts.append(f"{cd['steps']:,} steps")
    if cd.get('actions'):
        parts.append(f"{cd['actions']} actions")
    return ' '.join(parts) if parts else None


_OBJECT_TAG_RE = re.compile(r'<object id="([^"]+)"\s*/>')
_SKILL_TAG_RE = re.compile(r'<skill skill="([^"]+)"\s*/>')


def _strip_html(text: Optional[str]) -> str:
    """Render API ability `desc` text to plain English with substitutions.

    The API has things like '<object id="myriadian_arc" />' that should
    become 'Myriadian Arc', and '<skill skill="foraging"/>' that should
    become 'Foraging'. Legacy descriptions used title-case transforms.
    """
    if not text:
        return ''
    def _sub(m):
        oid = m.group(1)
        return oid.replace('_', ' ').title()
    text = _OBJECT_TAG_RE.sub(_sub, text)
    text = _SKILL_TAG_RE.sub(_sub, text)
    return text


def _extract_pet_attribute_stats(level_attrs: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Convert pet level attributes to nested {skill: {location: {stat: value}}}.

    Pets use ``mainSkillType`` (gathering/artisan/utility) for skill
    scoping AND either ``realm`` or ``locationHasKeywords`` for location
    scoping. Both are richer than the ``_extract_attribute_stats``
    default — handle them inline here. The API is migrating pets from
    ``realm`` → ``locationHasKeywords`` (e.g. camel: ``wrentmark`` →
    ``[desert]``, reindeer: ``jarvonia`` → ``[snowy]``); accept both so
    we work during and after the migration.
    """
    out: Dict[str, Any] = {}
    for attr in level_attrs or []:
        # Determine skill scope from mainSkillType, default 'global'
        # Determine location scope from realm or locationHasKeywords,
        # default 'global'
        target_skill = 'global'
        target_loc = 'global'
        for r in attr.get('requirements') or []:
            rtype = r.get('type')
            rdata = r.get('requirement') or {}
            if rtype == 'mainSkill':
                # Specific-skill scope (e.g. Chicken→foraging, Gecko→mining,
                # Tortoise→smithing/agility). Most pets scope per individual
                # skill via mainSkill, NOT the broader mainSkillType group.
                api_skill = rdata.get('skill')
                if api_skill:
                    target_skill = _legacy_skill_name(api_skill)
            elif rtype == 'mainSkillType':
                # Skill-group scope (gathering/artisan/utility) — used by
                # camel/reindeer. The downstream skill matcher treats these
                # as groups containing their member skills.
                stype = rdata.get('type')
                if stype:
                    target_skill = str(stype)
            elif rtype == 'traveling':
                # "While travelling" stats live under the 'traveling' skill
                # scope (e.g. Reindeer's snowy WE while travelling).
                target_skill = 'traveling'
            elif rtype == 'activityType':
                # Activity-keyword scope (e.g. Tortoise L4's smelting bonus
                # is scoped to the 'smelting' activity keyword). The legacy
                # data keys these stats under the keyword as the skill scope.
                kws = rdata.get('keywords') or []
                if kws:
                    target_skill = str(kws[0])
            elif rtype == 'realm':
                realm = rdata.get('realm')
                if realm:
                    target_loc = str(realm)
            elif rtype == 'locationHasKeywords':
                kws = rdata.get('keywords') or []
                # Today's API only emits single-keyword location scopes
                # for pets (verified across all 12 location-scoped pet
                # attrs). Pick the first if a multi-keyword conjunction
                # ever appears.
                # `opposite: true` negates the scope (read downstream as a
                # '!'-prefixed location key).
                if kws:
                    target_loc = ('!' if r.get('opposite') else '') + str(kws[0])

        for stat_entry in attr.get('stats') or []:
            api_name = stat_entry.get('stat')
            if not api_name:
                continue
            is_percent = bool(stat_entry.get('isPercent', False))
            if api_name == 'roll_special_table':
                # Item-Finding gear: resolve the IF-category (or raw find_*)
                # stat key from the attr's referenced loot table.
                stat_name = _special_table_stat_key(attr) or _normalize_stat_name(api_name)
            else:
                # isPercent-aware split handles steps_required ->
                # steps_percent/steps_add and bonus_experience ->
                # bonus_xp_percent/bonus_xp_add (matches the gear/consumable
                # ingest scripts).
                stat_name = _normalize_stat_name(api_name, is_percent)
            value = _display_stat_value(stat_entry)
            skill_root = out.setdefault(target_skill, {})
            loc_root = skill_root.setdefault(target_loc, {})
            if stat_name in loc_root:
                loc_root[stat_name] = round(loc_root[stat_name] + value, 4)
            else:
                loc_root[stat_name] = value
    return out


def _ability_dict_for_level(
    pet_abilities: List[Dict[str, Any]],
    abilities_by_id: Dict[str, Dict[str, Any]],
    level: int,
) -> List[Dict[str, Any]]:
    """Build the legacy abilities list for a pet at a given level.

    Includes every ability whose ``unlockLevel <= level`` (the API still
    supplies the unlock gating). For known abilities the full legacy dict
    comes from ``_PET_ABILITY_OVERRIDE`` (the API can't reconstruct the
    charge text, duration, ability_stats, instant-action metadata, or
    passive flags). A best-effort dict is built from the API detail for
    any ability not in the overlay (e.g. a future pet).
    """
    out: List[Dict[str, Any]] = []
    for entry in pet_abilities or []:
        unlock = entry.get('unlockLevel') or 1
        if unlock > level:
            continue
        aid = entry.get('ability')
        override = _PET_ABILITY_OVERRIDE.get(aid)
        if override is not None:
            # Copy so each level gets an independent dict (preserves the
            # overlay's key order for rendering).
            out.append(dict(override))
            continue
        # Fallback: best-effort dict from the API ability detail.
        ability = abilities_by_id.get(aid) or {}
        name = ability.get('name') or (aid.replace('_', ' ').title() if aid else '')
        info: Dict[str, Any] = {
            'name': name,
            'effect': _strip_html(ability.get('desc') or ''),
        }
        cd_str = _format_cooldown(ability.get('cooldown'))
        if cd_str:
            info['cooldown'] = cd_str
        out.append(info)
    return out


def _accumulate_xp(levels_api: List[Dict[str, Any]]) -> Dict[int, int]:
    """API publishes per-level XP increments; legacy stores cumulative."""
    out: Dict[int, int] = {}
    cumulative = 0
    for L in sorted(levels_api, key=lambda x: x.get('level') or 0):
        cumulative += int(L.get('xp') or 0)
        out[int(L.get('level') or 0)] = cumulative
    return out


def emit_pets(out_path: Optional[Path] = None) -> Path:
    """Generate pets.py in the OLD shape.

    Surface (matches util/autogenerated/pets.py):
      - @dataclass class EggInfo
      - @dataclass class PetInfo(StatsMixin) [with __post_init__]
      - class PetLevels [container with LEVEL_X attrs and get_level()]
      - class Pet [enum-like, populated with PetLevels]
      - class Egg [enum-like, populated with EggInfo]
      - PETS_BY_NAME, PETS_BY_RARE_EXPORT_NAME, ALL_PET_LEVELS,
        EGGS_BY_NAME, SMELTING_RECIPE_NAMES, get_instant_actions_pet
    """
    pets = load_all_details('pets')
    abilities = load_all_details('abilities')
    pets_sorted = sorted(pets.values(), key=lambda d: d.get('id') or '')

    # Build the rendered class body for class Pet
    rendered_pet_blocks: List[str] = []
