# Some currencies that show up in itemValue.currency; map to the legacy
# Currency.* enum reference string.
_CURRENCY_API_TO_LEGACY_REF = {
    'adventurers_guild_token': 'Currency.ADVENTURERS_GUILD_TOKEN',
}


def _material_keywords(detail: Dict[str, Any]) -> List[str]:
    """Reproduce the legacy material keywords list from API keywords.

    The legacy format is TitleCase, often deduplicated and human-friendly
    (e.g. ['Arrows', 'Light']). The API uses lowercase snake_case (e.g.
    ['arrows', 'light', 'hunting']).

    The legacy keywords are mostly TitleCased and exclude the skill
    keyword (which is duplicated from `requirements`). Mirror that.
    """
    api_kws = detail.get('keywords') or []
    # Skip skill names that are also in requirements
    skill_reqs = {
        (r.get('requirement') or {}).get('skill')
        for r in detail.get('requirements') or []
        if r.get('type') == 'skillLevel'
    }
    out: List[str] = []
    seen: set = set()
    for kw in api_kws:
        if kw in skill_reqs:
            continue
        # legacy uses TitleCase; .replace('_', ' ').title()
        legacy = kw.replace('_', ' ')
        # Special: 'misc' → 'Misc.'
        if legacy.lower() == 'misc':
            legacy = 'Misc.'
        else:
            legacy = legacy.title()
        if legacy.lower() in seen:
            continue
        seen.add(legacy.lower())
        out.append(legacy)
    return out


def _material_value(item_value: Dict[str, Any], fine: bool) -> int:
    """Pull the (maybe-fine) coin value from an API itemValue dict."""
    val = item_value.get('value')
    if val is None:
        return 0
    if isinstance(val, dict):
        # nested {common, fine}
        v = val.get('fine' if fine else 'common', 0) or 0
        return int(v)
    # scalar
    return int(val)


def _material_special_sell(detail: Dict[str, Any], fine: bool) -> Optional[Tuple[int, str]]:
    """Build a (qty, 'Currency.X') tuple if this item sells for a non-money currency."""
    iv = detail.get('itemValue') or {}
    cur = iv.get('currency')
    if not cur or cur in ('money', 'none'):
        return None
    legacy_ref = _CURRENCY_API_TO_LEGACY_REF.get(cur)
    if not legacy_ref:
        return None
    val = iv.get('value')
    if val is None:
        return None
    if isinstance(val, dict):
        qty = val.get('fine' if fine else 'common', 0) or 0
    else:
        qty = val
    return (int(qty), legacy_ref)


def emit_materials(out_path: Optional[Path] = None) -> Path:
    """Generate materials.py in the OLD shape.

    Surface (matches util/autogenerated/materials.py):
      - class MaterialInstance(StatsMixin)
      - class Material with one attribute per material (common AND fine
        variants emitted as separate enum entries).
      - Material.by_export_name(export_name) classmethod.
    """
    items = load_all_details('items')
    materials = [d for d in items.values() if d.get('type') == 'material']
    materials.sort(key=lambda d: d.get('id') or '')

    rows: List[Tuple[str, Dict[str, Any]]] = []  # (enum_name, kwargs_dict)
    seen_enum: set = set()

    def _push(enum_name: str, name: str, keywords: List[str], value: int,
              special_sell, stats: Dict[str, Any], requirements: List[Dict[str, Any]]):
        base = enum_name
        n = 1
        while enum_name in seen_enum:
            n += 1
            enum_name = f'{base}_{n}'
        seen_enum.add(enum_name)
        rows.append((enum_name, {
            'name': name,
            'keywords': keywords,
            'value': value,
            'special_sell': special_sell,
            'stats': stats,
            'requirements': requirements,
        }))

    for d in materials:
        mid = d.get('id') or ''
        name = d.get('name') or mid
        keywords = _material_keywords(d)
        value_common = _material_value(d.get('itemValue') or {}, fine=False)
        special_common = _material_special_sell(d, fine=False)
        # Stats come from the API's materialAttrs (per-material skill stats
        # the wiki used to attach by hand); skill-level gate comes from the
        # item's top-level requirements.
        stats = _extract_attribute_stats(d.get('materialAttrs'), 'global')
        reqs = _legacy_requirements_from_api(d.get('requirements'))

        _push(
            to_enum_name(mid),
            name,
            keywords,
            value_common,
            special_common,
            stats,
            reqs,
        )

        # Fine variant
        if d.get('canBeFine'):
            fine_name = f'{name} (Fine)'
            value_fine = _material_value(d.get('itemValue') or {}, fine=True)
            special_fine = _material_special_sell(d, fine=True)
            _push(
                to_enum_name(mid) + '_FINE',
                fine_name,
                keywords,
                value_fine,
                special_fine,
                stats,
                reqs,
            )

    # ── Render file ────────────────────────────────────────────────────
    lines: List[str] = []
    lines.append('#!/usr/bin/env python3')
    lines.append('"""')
    lines.append('Auto-generated materials data from the WalkScape tools API')
    lines.append('Drop-in replacement for util/autogenerated/materials.py')
    lines.append('DO NOT EDIT MANUALLY')
    lines.append('"""')
    lines.append('')
    lines.append('from typing import List, Optional, Tuple, Any, Dict')
    lines.append('from util.stats_mixin import StatsMixin')
    lines.append('')
    lines.append('class MaterialInstance(StatsMixin):')
    lines.append('    """Base class for material instances. Optionally has stats (e.g., arrows with WE)."""')
    lines.append('    def __init__(self, name: str, keywords: List[str], value: int, '
                 'special_sell: Optional[Tuple[int, str]] = None, '
                 'stats: Optional[Dict] = None, requirements: Optional[List] = None):')
    lines.append('        self.name = name')
    lines.append('        self.keywords = keywords')
    lines.append('        self.value = value')
    lines.append('        self._stats = stats or {}')
    lines.append('        self.gated_stats = {}')
    lines.append('        self.requirements = requirements or []')
    lines.append('        self._special_sell_ref = special_sell')
    lines.append('        self._special_sell_cached = None')
    lines.append('')
    lines.append('    @property')
    lines.append('    def special_sell(self):')
    lines.append('        """Lazily resolve special_sell reference."""')
    lines.append('        if self._special_sell_cached is not None or self._special_sell_ref is None:')
    lines.append('            return self._special_sell_cached')
    lines.append('        qty, ref_str = self._special_sell_ref')
    lines.append('        if ref_str.startswith("Currency."):')
    lines.append('            from util.autogenerated.currency import Currency')
    lines.append('        self._special_sell_cached = (qty, eval(ref_str))')
    lines.append('        return self._special_sell_cached')
    lines.append('')
    lines.append('    def __repr__(self):')
    lines.append('        return f"MaterialInstance({self.name})"')
    lines.append('')
    lines.append('    def has_fine_material(self) -> bool:')
    lines.append('        """Check if this material has a fine counterpart."""')
    lines.append('        enum_name = self.name.upper().replace(" ", "_").replace("(", "").replace(")", "").replace("-", "_").replace("\'", "")')
    lines.append('        fine_enum_name = enum_name + "_FINE"')
    lines.append('        return hasattr(Material, fine_enum_name)')
    lines.append('')
    lines.append('')
    lines.append('class Material:')
    lines.append('    """All materials"""')
    lines.append('')
    for enum_name, kwargs in rows:
        # render multi-line MaterialInstance(...) call to mimic legacy style
        kw_lines: List[str] = []
        kw_lines.append(f'        name={py_str(kwargs["name"])}')
        kw_lines.append(f'        keywords={_format_keywords(kwargs["keywords"])}')
        kw_lines.append(f'        value={kwargs["value"]}')
        if kwargs['special_sell'] is not None:
            qty, ref = kwargs['special_sell']
            kw_lines.append(f'        special_sell=({qty}, {py_str(ref)})')
        else:
            kw_lines.append('        special_sell=None')
        if kwargs['stats']:
            kw_lines.append(f'        stats={_format_stats_dict(kwargs["stats"])}')
        if kwargs['requirements']:
            kw_lines.append(f'        requirements={_format_requirements(kwargs["requirements"])}')
        joined = ',\n'.join(kw_lines)
        lines.append(f'    {enum_name} = MaterialInstance(')
        lines.append(joined)
        lines.append('    )')
        lines.append('')
    lines.append('    @classmethod')
    lines.append('    def by_export_name(cls, export_name: str):')
    lines.append('        """Look up material by export name (e.g., "spruce_logs" or "spruce_logs_fine")"""')
    lines.append('        const_name = export_name.upper()')
    lines.append('        if hasattr(cls, const_name):')
    lines.append('            return getattr(cls, const_name)')
    lines.append('        return None')
    lines.append('')

    if out_path is None:
        out_path = AUTOGEN_DIR / 'materials.py'
    write_file(out_path, '\n'.join(lines))
    return out_path


