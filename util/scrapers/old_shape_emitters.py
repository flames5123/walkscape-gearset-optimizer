def emit_services(out_path: Optional[Path] = None) -> Path:
    """Generate services.py in the OLD shape (drop-in for services.py).

    Surface (matches util/autogenerated/services.py):
      - class Service: enum-style attributes per (service × location) pair
      - SERVICES_BY_NAME, SERVICES_BY_CATEGORY lookup dicts

    Implementation note: the heavy lifting lives in
    util/scrapers/ingest_services_from_tools_api.py (which fetches services
    from the API, hydrates them with /services/id/{id}, joins against
    locations, and emits the file). This wrapper just invokes that
    pipeline so old_shape_emitters owns a single canonical entry point.
    """
    from util.scrapers import ingest_services_from_tools_api as ing
    from util.scrapers.tools_api_client import ToolsAPIClient
    client = ToolsAPIClient()
    svc_list = client.list('services', use_cache=True)
    api_services: Dict[str, Dict[str, Any]] = {
        s['id']: client.get('services', s['id'], use_cache=True)
        for s in svc_list
    }
    loc_list = client.list('locations', use_cache=True)
    api_locations: Dict[str, Dict[str, Any]] = {
        loc['id']: client.get('locations', loc['id'], use_cache=True)
        for loc in loc_list
    }
    rows = ing.transform(
        api_services, api_locations,
        valid_location_keys=ing.collect_valid_location_keys(),
    )
    content = ing.emit_python(rows)
    if out_path is None:
        out_path = REPO_ROOT / 'util' / 'autogenerated' / 'services.py'
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding='utf-8')
    return out_path


def emit_export_names(out_path: Optional[Path] = None) -> Path:
    """Generate export_names.py in the OLD shape (drop-in for export_names.py).

    Surface (matches util/autogenerated/export_names.py):
      - class ExportNames: enum-style slug constants (e.g. ABSORBING_AMULET = "absorbing_amulet")
      - _build_item_mapping / _build_consumable_mapping / _build_material_mapping
      - get_item_mapping / get_consumable_mapping / get_material_mapping (lazy)
      - get_export_name_mapping (combined)
      - get_item_from_export_name(name, item_type=None) helper
      - EXPORT_NAME_TO_ITEM alias

    Implementation: reads the already-emitted equipment / consumables /
    materials drop-in files for their enum keys, then optionally validates
    the base slugs via POST /items/ids?target=base. Must run AFTER those
    emitters.
    """
    import util.walkscape_constants  # noqa: F401  (break circular import)
    from util.autogenerated import equipment as _eq
    from util.autogenerated import consumables as _co
    from util.autogenerated import materials as _ma

    # Collect enum keys → slugs. Slug = enum_key.lower(). FINE variants
    # already appear as separate constants in materials/consumables.
    item_keys = sorted(
        n for n in dir(_eq.Item)
        if not n.startswith('_')
        and isinstance(getattr(_eq.Item, n),
                       (_eq.ItemInstance, _eq.CraftedItem, _eq.AchievementItem))
    )
    cons_keys = sorted(
        n for n in dir(_co.Consumable)
        if not n.startswith('_')
        and isinstance(getattr(_co.Consumable, n), _co.ConsumableItem)
    )
    mat_keys = sorted(
        n for n in dir(_ma.Material)
        if not n.startswith('_')
        and isinstance(getattr(_ma.Material, n), _ma.MaterialInstance)
    )

    # Validate base (non-fine) slugs round-trip via POST /items/ids?target=base.
    # The endpoint returns the canonical internal id for valid slugs and
    # echoes the input back for unknown ids. We only collect a "valid"
    # set so tests can spot-check round-tripping; we always emit every
    # slug we find in the entity files so the file remains a complete
    # drop-in even if the API misses a few during validation.
    base_slugs: List[str] = []
    for k in item_keys + cons_keys + mat_keys:
        slug = k.lower()
        if not slug.endswith('_fine'):
            base_slugs.append(slug)
    try:
        from util.scrapers.tools_api_client import ToolsAPIClient
        _client = ToolsAPIClient()
        _resolved = _client.lookup_internal_ids(base_slugs, target='base')
        _validated_count = sum(
            1 for s in base_slugs if _resolved.get(s) and _resolved[s] != s
        )
    except Exception as _exc:  # noqa: BLE001
        _validated_count = -1  # validation skipped (e.g. offline)

    # ── Render ─────────────────────────────────────────────────────────
    lines: List[str] = []
    lines.append('#!/usr/bin/env python3')
    lines.append('"""')
    lines.append('Export name to item/consumable/material mapping.')
    lines.append(
        'Auto-generated by util/scrapers/old_shape_emitters.py:emit_export_names'
    )
    lines.append('DO NOT EDIT MANUALLY')
    lines.append('')
    lines.append(
        'Drop-in replacement for util/autogenerated/export_names.py — exposes '
        'class ExportNames + lookup helpers, sourced from the tools API.'
    )
    lines.append(
        f'API base-slug round-trip validation count: {_validated_count} '
        f'/ {len(base_slugs)} (-1 = skipped).'
    )
    lines.append('"""')
    lines.append('')
    lines.append('from typing import Optional, Union, TYPE_CHECKING')
    lines.append('')
    lines.append('if TYPE_CHECKING:')
    lines.append('    from util.autogenerated.equipment import Item')
    lines.append('    from util.autogenerated.consumables import Consumable')
    lines.append('    from util.autogenerated.materials import Material')
    lines.append('')
    lines.append('')
    lines.append('class ExportNames:')
    lines.append('    """Mapping from export names to items/consumables/materials"""')
    lines.append('')
    for k in sorted(set(item_keys + cons_keys + mat_keys)):
        lines.append(f'    {k} = "{k.lower()}"')
    lines.append('')
    lines.append('')

    # Lazy mapping cache
    lines.append('_EXPORT_NAME_TO_ITEM = None')
    lines.append('_EXPORT_NAME_TO_CONSUMABLE = None')
    lines.append('_EXPORT_NAME_TO_MATERIAL = None')
    lines.append('_EXPORT_NAME_TO_ANY = None')
    lines.append('')

    # _build_item_mapping
    lines.append('def _build_item_mapping():')
    lines.append('    """Build the export name to Item mapping."""')
    lines.append('    from util.autogenerated.equipment import Item')
    lines.append('    return {')
    for k in item_keys:
        lines.append(f'        "{k.lower()}": Item.{k},')
    lines.append('    }')
    lines.append('')
    lines.append('')

    # _build_consumable_mapping
    lines.append('def _build_consumable_mapping():')
    lines.append('    """Build the export name to Consumable mapping."""')
    lines.append('    from util.autogenerated.consumables import Consumable')
    lines.append('    return {')
    for k in cons_keys:
        lines.append(f'        "{k.lower()}": Consumable.{k},')
    lines.append('    }')
    lines.append('')
    lines.append('')

    # _build_material_mapping
    lines.append('def _build_material_mapping():')
    lines.append('    """Build the export name to Material mapping."""')
    lines.append('    from util.autogenerated.materials import Material')
    lines.append('    return {')
    for k in mat_keys:
        lines.append(f'        "{k.lower()}": Material.{k},')
    lines.append('    }')
    lines.append('')
    lines.append('')

    # Lazy accessors + combined mapping + lookup helper (verbatim from legacy
    # except using the equipment / consumables / materials modules above)
    lines.append('def get_item_mapping():')
    lines.append('    """Get the export name to Item mapping (lazy loaded)."""')
    lines.append('    global _EXPORT_NAME_TO_ITEM')
    lines.append('    if _EXPORT_NAME_TO_ITEM is None:')
    lines.append('        _EXPORT_NAME_TO_ITEM = _build_item_mapping()')
    lines.append('    return _EXPORT_NAME_TO_ITEM')
    lines.append('')
    lines.append('def get_consumable_mapping():')
    lines.append('    """Get the export name to Consumable mapping (lazy loaded)."""')
    lines.append('    global _EXPORT_NAME_TO_CONSUMABLE')
    lines.append('    if _EXPORT_NAME_TO_CONSUMABLE is None:')
    lines.append('        _EXPORT_NAME_TO_CONSUMABLE = _build_consumable_mapping()')
    lines.append('    return _EXPORT_NAME_TO_CONSUMABLE')
    lines.append('')
    lines.append('def get_material_mapping():')
    lines.append('    """Get the export name to Material mapping (lazy loaded)."""')
    lines.append('    global _EXPORT_NAME_TO_MATERIAL')
    lines.append('    if _EXPORT_NAME_TO_MATERIAL is None:')
    lines.append('        _EXPORT_NAME_TO_MATERIAL = _build_material_mapping()')
    lines.append('    return _EXPORT_NAME_TO_MATERIAL')
    lines.append('')
    lines.append('def get_export_name_mapping():')
    lines.append('    """Get combined mapping of all export names (lazy loaded)."""')
    lines.append('    global _EXPORT_NAME_TO_ANY')
    lines.append('    if _EXPORT_NAME_TO_ANY is None:')
    lines.append('        _EXPORT_NAME_TO_ANY = {}')
    lines.append('        _EXPORT_NAME_TO_ANY.update(get_item_mapping())')
    lines.append('        _EXPORT_NAME_TO_ANY.update(get_consumable_mapping())')
    lines.append('        _EXPORT_NAME_TO_ANY.update(get_material_mapping())')
    lines.append('    return _EXPORT_NAME_TO_ANY')
    lines.append('')
    lines.append('')
    lines.append(
        'def get_item_from_export_name(export_name: str, '
        'item_type: str = None) -> Optional[Union[object, object, object]]:'
    )
    lines.append('    """Look up Item/Consumable/Material from an export name string,')
    lines.append('    handling quality and _fine suffixes.')
    lines.append('')
    lines.append('    Args:')
    lines.append('        export_name: e.g. "iron_sword", "beer", "bronze_bar"')
    lines.append('        item_type: optional "equipment" / "consumable" / "material"')
    lines.append('            to avoid loading all mappings.')
    lines.append('    """')
    lines.append('    export_lower = export_name.lower()')
    lines.append('    if item_type == "equipment":')
    lines.append('        mapping = get_item_mapping()')
    lines.append('    elif item_type == "consumable":')
    lines.append('        mapping = get_consumable_mapping()')
    lines.append('    elif item_type == "material":')
    lines.append('        mapping = get_material_mapping()')
    lines.append('    else:')
    lines.append('        mapping = get_export_name_mapping()')
    lines.append('    item = mapping.get(export_lower)')
    lines.append('    if item:')
    lines.append('        return item')
    lines.append('    # Quality suffix (equipment): "_common" → NORMAL, etc.')
    lines.append('    quality_map = {')
    lines.append('        "_common": "NORMAL", "_uncommon": "GOOD",')
    lines.append('        "_rare": "GREAT", "_epic": "EXCELLENT",')
    lines.append('        "_legendary": "PERFECT", "_ethereal": "ETERNAL",')
    lines.append('    }')
    lines.append('    for suffix, quality_name in quality_map.items():')
    lines.append('        if export_lower.endswith(suffix):')
    lines.append('            base_name = export_lower[:-len(suffix)]')
    lines.append('            base_item = mapping.get(base_name)')
    lines.append('            if base_item and hasattr(base_item, quality_name):')
    lines.append('                return getattr(base_item, quality_name)')
    lines.append('    # _fine suffix (consumables/materials): try direct then base')
    lines.append('    if export_lower.endswith("_fine"):')
    lines.append('        base_name = export_lower[:-5]')
    lines.append('        fine_item = mapping.get(export_lower)')
    lines.append('        if fine_item:')
    lines.append('            return fine_item')
    lines.append('        base_item = mapping.get(base_name)')
    lines.append('        if base_item:')
    lines.append('            return base_item')
    lines.append('    else:')
    lines.append('        fine_name = export_lower + "_fine"')
    lines.append('        fine_item = mapping.get(fine_name)')
    lines.append('        if fine_item:')
    lines.append('            return fine_item')
    lines.append('    return None')
    lines.append('')
    lines.append('')
    lines.append('# Backward compatibility aliases')
    lines.append('EXPORT_NAME_TO_ITEM = get_item_mapping')
    lines.append('')

    content = '\n'.join(lines)

    if out_path is None:
        out_path = REPO_ROOT / 'util' / 'autogenerated' / 'export_names.py'
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding='utf-8')
    return out_path


