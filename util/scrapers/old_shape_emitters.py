def emit_recipes(out_path: Optional[Path] = None) -> Path:
    """Generate recipes.py in the OLD shape.

    Surface (matches util/autogenerated/recipes.py):
      - @dataclass class RecipeInstance with get_output_item_object()
      - top-level recipe instances (BIRCH_HUNTING_BOW = RecipeInstance(...))
      - RECIPES_BY_NAME index
      - RECIPES_BY_SKILL index
      - class Recipe enum-like with one attribute per recipe
    """
    recipes = load_all_details('recipes')
    items = load_all_details('items')
    loot_tables = load_all_details('loot_tables')

    recipes_sorted = sorted(recipes.values(), key=lambda d: d.get('id') or '')

    rendered: List[str] = []
    enum_names: List[Tuple[str, str]] = []  # (enum_attr, recipe_name)
    seen: set = set()

    for d in recipes_sorted:
        rid = d.get('id') or ''
        rname = d.get('name') or rid
        skill, level = _recipe_skill_level(d.get('requirements') or [])
        service = _recipe_service(d.get('requirements') or [])
        output_ref, output_qty = _resolve_recipe_output(d.get('itemRewards') or {}, items)
        materials = _legacy_materials_groups(d.get('materials') or [], items)
        # XP
        xp_map = d.get('xpRewards') or {}
        primary_skill_lower = (skill or '').lower() if skill else ''
        base_xp = xp_map.get(primary_skill_lower) if primary_skill_lower else None
        if base_xp is None and xp_map:
            # fallback: first value
            base_xp = next(iter(xp_map.values()))
        base_steps = d.get('workRequired') or 0
        max_eff = d.get('maxWorkEfficiency')
        if max_eff is not None:
            max_eff = round(float(max_eff) - 1.0, 4)
        drop_table = _recipe_drop_table(d.get('tables') or [], loot_tables, items)

        # Compute enum-attr name. Legacy uses output_item-derived names
        # (e.g. BIRCH_HUNTING_BOW from output Item.BIRCH_HUNTING_BOW),
        # not recipe ID. Fall back to recipe ID if no output ref.
        if output_ref and '.' in output_ref:
            enum_attr = output_ref.split('.', 1)[1]
        else:
            enum_attr = to_enum_name(rid)
        # Variant recipes carry a parenthetical tag in their name
        # (e.g. "Create a copper bar (Scrap)"). Append that tag as an
        # enum suffix so the PRIMARY recipe keeps the clean output-based
        # name and variants are stable/descriptive (COPPER_BAR vs
        # COPPER_BAR_SCRAP) — matching the legacy wiki naming rather than
        # an order-dependent _2 suffix.
        _variant = re.search(r'\(([^)]+)\)', rname or '')
        if _variant:
            enum_attr = f'{enum_attr}_{to_enum_name(_variant.group(1))}'
        # Legacy enum-name overrides (inconsistent wiki naming the default
        # scheme can't reproduce — see _RECIPE_ENUM_NAME_OVERRIDES). The
        # override wins over both the output-derived name and the variant
        # suffix so the emitted `Recipe.*` surface matches what consumers
        # reference (e.g. Recipe.SMITH_A_BRONZE_SWORD, Recipe.INTO_ECTOPLASM).
        if rname in _RECIPE_ENUM_NAME_OVERRIDES:
            enum_attr = _RECIPE_ENUM_NAME_OVERRIDES[rname]
        base = enum_attr
        n = 1
        while enum_attr in seen:
            n += 1
            enum_attr = f'{base}_{n}'
        seen.add(enum_attr)
        enum_names.append((enum_attr, rname))

        rendered.append(_render_recipe_instance(
            enum_attr=enum_attr,
            name=rname,
            output_item=output_ref,
            skill=skill or 'Carpentry',  # fallback so emitted code is valid
            level=level,
            service=service,
            quantity=output_qty,
            materials=materials,
            base_xp=base_xp or 0.0,
            base_steps=base_steps,
            max_efficiency=max_eff if max_eff is not None else 0.5,
            drop_table=drop_table,
        ))

    # ── Render file ────────────────────────────────────────────────────
    out: List[str] = []
    out.append('#!/usr/bin/env python3')
    out.append('"""')
    out.append('Auto-generated recipe data from the WalkScape tools API')
    out.append('Drop-in replacement for util/autogenerated/recipes.py')
    out.append('DO NOT EDIT MANUALLY')
    out.append('"""')
    out.append('')
    out.append('from dataclasses import dataclass')
    out.append('from typing import List, Tuple, Optional, Union')
    out.append('from util.walkscape_constants import Material, Item, Consumable')
    out.append('')
    out.append('@dataclass')
    out.append('class RecipeInstance:')
    out.append('    """Represents a crafting recipe."""')
    out.append('    name: str')
    out.append('    output_item: Optional[str]')
    out.append('    skill: str')
    out.append('    level: int')
    out.append('    service: str')
    out.append('    quantity: int')
    out.append('    materials: List[List[Tuple[int, object]]]')
    out.append('    base_xp: float')
    out.append('    base_steps: int')
    out.append('    max_efficiency: float')
    out.append('    drop_table: Optional[List] = None')
    out.append('')
    out.append('    def get_output_item_object(self):')
    out.append('        """Resolve output_item string reference to actual object."""')
    out.append('        if not self.output_item:')
    out.append('            return None')
    out.append('        if "." in self.output_item:')
    out.append('            class_name, attr_name = self.output_item.split(".", 1)')
    out.append('            if class_name == "Material":')
    out.append('                return getattr(Material, attr_name, None)')
    out.append('            elif class_name == "Item":')
    out.append('                return getattr(Item, attr_name, None)')
    out.append('            elif class_name == "Consumable":')
    out.append('                return getattr(Consumable, attr_name, None)')
    out.append('        return None')
    out.append('')
    out.append('')
    for body in rendered:
        out.append(body)
    out.append('')
    out.append('# Build lookup dictionaries from module globals')
    out.append('RECIPES_BY_NAME = {')
    out.append('    r.name: r for r in globals().values()')
    out.append('    if isinstance(r, RecipeInstance)')
    out.append('}')
    out.append('')
    out.append('RECIPES_BY_SKILL = {}')
    out.append('for _r in RECIPES_BY_NAME.values():')
    out.append('    if _r.skill not in RECIPES_BY_SKILL:')
    out.append('        RECIPES_BY_SKILL[_r.skill] = []')
    out.append('    RECIPES_BY_SKILL[_r.skill].append(_r)')
    out.append('del _r')
    out.append('')
    out.append('# Enum-style access')
    out.append('class Recipe:')
    out.append('    """Enum-style access to recipes."""')
    seen_enum: set = set()
    for enum_attr, rname in sorted(enum_names):
        # Avoid clobbering on duplicate output items
        attr = enum_attr
        n = 1
        while attr in seen_enum:
            n += 1
            attr = f'{enum_attr}_{n}'
        seen_enum.add(attr)
        out.append(f'    {attr} = RECIPES_BY_NAME[{py_str(rname)}]')
    out.append('')

    if out_path is None:
        out_path = AUTOGEN_DIR / 'recipes.py'
    write_file(out_path, '\n'.join(out))
    return out_path


def _render_recipe_instance(
    *,
    enum_attr: str,
    name: str,
    output_item: Optional[str],
    skill: str,
    level: int,
    service: str,
    quantity: int,
    materials: List[List[Tuple[int, str]]],
    base_xp: float,
    base_steps: int,
    max_efficiency: float,
    drop_table: List[Dict[str, Any]],
) -> str:
    lines: List[str] = []
    lines.append(f'{enum_attr} = RecipeInstance(')
    lines.append(f'    name={py_str(name)},')
    lines.append(f'    output_item={py_str(output_item)},')
    lines.append(f'    skill={py_str(skill)},')
    lines.append(f'    level={int(level)},')
    lines.append(f'    service={py_str(service)},')
    lines.append(f'    quantity={int(quantity)},')
    lines.append('    materials=[')
    for group in materials:
        items_str = ', '.join(f'({qty}, {ref})' for qty, ref in group)
        lines.append(f'        [{items_str}],')
    lines.append('    ],')
    lines.append(f'    base_xp={float(base_xp)},')
    lines.append(f'    base_steps={int(base_steps)},')
    lines.append(f'    max_efficiency={float(max_efficiency)},')
    if drop_table:
        lines.append('    drop_table=[')
        for d in drop_table:
            # Render dict literal with consistent ordering
            parts = [
                f'{py_str("item_name")}: {py_str(d["item_name"])}',
                f'{py_str("item_ref")}: {py_str(d["item_ref"]) if d.get("item_ref") else "None"}',
                f'{py_str("item_type")}: {py_str(d["item_type"])}',
                f'{py_str("quantity")}: {int(d["quantity"])}',
                f'{py_str("quantity_min")}: {int(d["quantity_min"])}',
                f'{py_str("quantity_max")}: {int(d["quantity_max"])}',
                f'{py_str("chance_percent")}: {float(d["chance_percent"])}',
            ]
            # Multi-roll tables (rollAmount > 1) carry the count so
            # downstream math multiplies the per-roll chance linearly.
            # Single-roll drops omit the key (matches legacy wiki shape).
            if d.get('multi_roll_count'):
                parts.append(
                    f'{py_str("multi_roll_count")}: {int(d["multi_roll_count"])}'
                )
            lines.append('        {' + ', '.join(parts) + '},')
        lines.append('    ],')
    lines.append(')')
    lines.append('')
    return '\n'.join(lines)


