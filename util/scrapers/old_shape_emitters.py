        if rare_export_name:
            lines.append(f'        rare_export_name={py_str(rare_export_name)},')
        lines.append(f'        species={py_str(species)},')
        lines.append('        levels={')
        for L in sorted(levels_api, key=lambda x: x.get('level') or 0):
            lvl = int(L.get('level') or 0)
            xp = cumulative_xp.get(lvl, 0)
            ability_dicts = _ability_dict_for_level(
                pet.get('abilities') or [], abilities, lvl,
            )
            lines.append(f'            {lvl}: PetInfo(')
            lines.append(f'                name={py_str(pname)},')
            lines.append(f'                level={lvl},')
            lines.append(f'                egg_name={py_str(egg_name)},')
            lines.append(f'                xp_required={xp},')
