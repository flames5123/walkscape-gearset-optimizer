def _ap_reward_legacy_type_and_ref(api_item_id: str, items_by_id: Dict[str, Dict[str, Any]]) -> Tuple[str, Optional[str]]:
    """Return (legacy_item_type, item_ref) for an AP-reward item ID."""
    detail = items_by_id.get(api_item_id) or {}
    api_type = detail.get('type') or 'loot'
    legacy_type = _AP_ITEM_TYPE_TO_LEGACY.get(api_type, 'Loot')
