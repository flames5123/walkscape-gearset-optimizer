def cache_dir(entity: str) -> Path:
    """Return the cache directory for a tools-api entity (e.g. 'items')."""
    return CACHE_DIR / entity


def load_list(entity: str) -> List[Dict[str, Any]]:
    """Load the list endpoint payload from cache (e.g. /items list)."""
    p = cache_dir(entity) / '_list.json'
    with open(p, 'r', encoding='utf-8') as f:
        return json.load(f)


def load_detail(entity: str, eid: str) -> Dict[str, Any]:
    """Load the detail payload for a single entity from cache."""
    p = cache_dir(entity) / f'{eid}.json'
    with open(p, 'r', encoding='utf-8') as f:
        return json.load(f)


def load_all_details(entity: str) -> Dict[str, Dict[str, Any]]:
    """Load every detail payload under cache/tools_api_cache/<entity>."""
    out: Dict[str, Dict[str, Any]] = {}
    d = cache_dir(entity)
    if not d.is_dir():
        return out
    for fname in os.listdir(d):
        if fname == '_list.json' or not fname.endswith('.json'):
            continue
        eid = fname[:-len('.json')]
        with open(d / fname, 'r', encoding='utf-8') as f:
            out[eid] = json.load(f)
    return out


# ────────────────────────────────────────────────────────────────────────
# Identifier / string rendering helpers
# ────────────────────────────────────────────────────────────────────────

_ENUM_NAME_TRANSLATION = str.maketrans({
    ' ': '_', '-': '_', "'": '', '"': '', ',': '', '.': '_',
    '(': '', ')': '', '/': '_', '\\': '_', ':': '_', ';': '',
    '!': '', '?': '', '+': 'PLUS', '&': 'AND', '%': 'PCT',
    '\u2019': '',  # right single quote
    '\u2018': '',  # left single quote
    '\u2013': '_', '\u2014': '_',  # en/em dash
})


def to_enum_name(s: str) -> str:
    """Convert an arbitrary string to a Python enum-style attribute name."""
    if not s:
        return '_'
    s = s.translate(_ENUM_NAME_TRANSLATION)
    s = re.sub(r'_+', '_', s).strip('_').upper()
    if not s:
        return '_'
    if s[0].isdigit():
        s = '_' + s
    return s


def py_str(s: Optional[str]) -> str:
    """Render a string (or None) as a Python literal."""
    if s is None:
        return 'None'
    return repr(s)


def py_num(x) -> str:
    """Render a number as a Python literal, dropping the spurious trailing
    '.0' on whole-valued floats (e.g. 10.0 -> '10', 0.0 -> '0') while keeping
    real fractions intact (0.9848 -> '0.9848'). Matches the legacy autogen's
    int-style for whole weights and reduces diff noise."""
    f = float(x)
    return str(int(f)) if f.is_integer() else repr(f)


def py_dq(s: Optional[str]) -> str:
    """Render a string as a DOUBLE-quoted literal to match the legacy autogen
    style for item_ref in activities/containers. Falls back to py_str (single)
    only if the value needs escaping (contains a quote/backslash/newline) —
    item_refs are simple 'Class.ENUM' tokens so that path is never hit."""
    if s is None:
        return 'None'
    if any(c in s for c in '"\\\n\r\t\''):
        return py_str(s)
    return '"' + s + '"'


def py_list_of_strs(items: Optional[Iterable[Optional[str]]]) -> str:
    """Render an iterable of strings (or None) as `['a', 'b']`."""
    if items is None:
        return 'None'
    parts = [py_str(s) for s in items]
    return '[' + ', '.join(parts) + ']'


def write_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8')


