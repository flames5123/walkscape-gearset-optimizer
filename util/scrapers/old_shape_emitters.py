# OLD legacy keyword vocabulary expected by the optimizer (pluralized,
# spaced). The terrain modifiers in the API publish their requirements
# explicitly (`distinctKeywordItemsEquipped` and `skillLevel`); we derive
# the legacy keyword_counts / *_level keys from those.

# Map keyword id (snake_case) → legacy keyword string (space-separated).
# Most are just snake → space, but some need explicit overrides.
_KEYWORD_ID_TO_LEGACY = {
    'light_source': 'light source',
    'diving_gear': 'diving gear',
    'advanced_diving_gear': 'advanced diving gear',
    'expert_diving_gear': 'expert diving gear',
    'underwater_map': 'underwater map',
    'mysterious_northern_map': 'mysterious northern map',
    'jarvonian_border_check': 'jarvonian border check',
    'black_eye_peak_wilderness_permit': 'black eye peak wilderness permit',
    'spring_bat_tracking_completion': 'spring bat tracking completion',
    'charter_of_the_drowned': 'charter of the drowned',
}


def _normalize_keyword(kid: str) -> str:
    """Convert an API keyword id to the legacy keyword string."""
    if kid in _KEYWORD_ID_TO_LEGACY:
        return _KEYWORD_ID_TO_LEGACY[kid]
    return kid.replace('_', ' ')


def _legacy_reqs_from_terrain_modifier(detail: Dict[str, Any]) -> Dict[str, Any]:
    """Convert a terrain_modifier detail into legacy route-requirement parts.

    Returns a dict with optional keys:
      - 'agility_level' / 'fishing_level' / etc. (int)
      - 'keyword_counts' (dict[str, int])
    """
    out: Dict[str, Any] = {}
    kw_counts: Dict[str, int] = {}
    for req in detail.get('requirements') or []:
        rtype = req.get('type')
        rdata = req.get('requirement') or {}
        if rtype == 'distinctKeywordItemsEquipped':
            qty = rdata.get('quantity') or 0
            for k in rdata.get('keywords') or []:
                kid = k.get('id') if isinstance(k, dict) else k
                if not kid:
                    continue
                legacy = _normalize_keyword(kid)
                kw_counts[legacy] = max(kw_counts.get(legacy, 0), qty)
        elif rtype == 'skillLevel':
            skill = rdata.get('skill')
            level = rdata.get('level')
            if skill and level:
                out[f'{skill}_level'] = int(level)
        elif rtype == 'abilityAvailable':
            # Route gated by a travel ability (e.g. navigate_desert ->
            # ('ability', 'Navigate Desert')). Matches the legacy `requires`.
            ab = rdata.get('ability')
            if ab:
                out['requires'] = ('ability', ab.replace('_', ' ').title())
        elif rtype == 'itemAnywhereWithYou':
            # Route gated by carrying a collectible (charter, letter of
            # passage, etc.) -> ('collectible', 'Collectible.<ENUM>').
            item = rdata.get('item')
            if item:
                out['requires'] = ('collectible', f'Collectible.{to_enum_name(item)}')
    if kw_counts:
        out['keyword_counts'] = kw_counts
    return out


def _route_requirements_from_modifiers(
    mod_ids: Iterable[str],
    terrain_mod_details: Dict[str, Dict[str, Any]],
) -> Dict[str, Any]:
    """Combine multiple terrain modifier requirements into one legacy dict."""
    combined: Dict[str, Any] = {}
    kw_counts: Dict[str, int] = {}
    for mid in mod_ids:
        detail = terrain_mod_details.get(mid)
        if not detail:
            continue
        parts = _legacy_reqs_from_terrain_modifier(detail)
        for k, v in parts.items():
            if k == 'keyword_counts':
                for kw, count in v.items():
                    kw_counts[kw] = max(kw_counts.get(kw, 0), count)
            elif k == 'requires':
                # Single ability/collectible gate per route (last wins).
                combined['requires'] = v
            else:
                # take max for numeric levels too
                if k in combined:
                    combined[k] = max(combined[k], v)
                else:
                    combined[k] = v
    if kw_counts:
        combined['keyword_counts'] = kw_counts
    return combined


def emit_routes(out_path: Optional[Path] = None) -> Path:
    """Generate routes.py in the OLD shape.

    Surface (matches util/autogenerated/routes.py):
      - imports Location from util.autogenerated.locations
      - RAW_ROUTES: dict[(Location.A, Location.B) -> {'distance': int,
                                                       'agility_level': int?,
                                                       'keyword_counts': dict?}]

    The API publishes one entry per location pair (`from-to`). The legacy
    file expanded to BOTH directions. Mirror that here.
    """
    routes = load_list('routes')
    terrain_mod_details = load_all_details('terrain_modifiers')

    # Build a lookup id -> enum-attr-name from the locations cache so we
    # can render Location.X.
    location_details = load_all_details('locations')
    id_to_enum = {
        loc_id: to_enum_name(loc_id)
        for loc_id in location_details.keys()
    }

    lines: List[str] = []
    lines.append('#!/usr/bin/env python3')
    lines.append('"""')
    lines.append('Walkscape Routes Data')
    lines.append('Raw route data from the WalkScape tools API.')
    lines.append('Drop-in replacement for util/autogenerated/routes.py')
    lines.append('DO NOT EDIT MANUALLY')
    lines.append('"""')
    lines.append('')
    lines.append('from util.autogenerated.locations import Location')
    lines.append('')
    lines.append('RAW_ROUTES = {')

    # Build a stable, deterministic two-way listing.
    expanded: List[Tuple[str, str, Dict[str, Any]]] = []
    for r in routes:
        locs = r.get('locations') or []
        if len(locs) != 2:
            continue
        a, b = locs
        if a not in id_to_enum or b not in id_to_enum:
            continue
        distance = r.get('distance')
        if distance is None:
            continue
        # Combine modifiers across all option groups (a route can list
        # multiple alternative gating sets — pick the union as the
        # "needed" requirements; downstream callers can be more nuanced
        # but the legacy format collapsed to a single requirement set).
        all_mods: List[str] = []
        for opt in r.get('options') or []:
            for m in opt.get('terrainModifiers') or []:
                if m and m not in all_mods:
                    all_mods.append(m)
        reqs = _route_requirements_from_modifiers(all_mods, terrain_mod_details)

        # The ability/collectible `requires` gate is DIRECTION-sensitive: an
        # option group marks each endpoint true/false in `options.options`,
        # and the gate only applies when travelling FROM a `true` endpoint
        # (e.g. you need the letter to ENTER Jarvonia, not to leave). Compute
        # it per direction. Keyword/level requirements stay on both.
        req_fwd = req_rev = None
        for opt in r.get('options') or []:
            omap = opt.get('options') or {}
            mreq = _route_requirements_from_modifiers(
                opt.get('terrainModifiers') or [], terrain_mod_details).get('requires')
            if not mreq:
                continue
            if omap.get(a):
                req_fwd = mreq
            if omap.get(b):
                req_rev = mreq

        base: Dict[str, Any] = {'distance': int(distance)}
        if 'agility_level' in reqs:
            base['agility_level'] = reqs['agility_level']
        if 'fishing_level' in reqs:
            base['fishing_level'] = reqs['fishing_level']
        if 'keyword_counts' in reqs:
            base['keyword_counts'] = reqs['keyword_counts']

        fwd = dict(base)
        if req_fwd:
            fwd['requires'] = req_fwd
        rev = dict(base)
        if req_rev:
            rev['requires'] = req_rev
        expanded.append((a, b, fwd))
        # reverse direction with its own (possibly absent) gate
        expanded.append((b, a, rev))

    expanded.sort(key=lambda t: (id_to_enum[t[0]], id_to_enum[t[1]]))

    for a, b, entry in expanded:
        a_attr = id_to_enum[a]
        b_attr = id_to_enum[b]
        # Render the entry with deterministic key order.
        items = []
        if 'distance' in entry:
            items.append(f"'distance': {entry['distance']}")
        if 'requires' in entry:
            items.append(f"'requires': {entry['requires']!r}")
        if 'agility_level' in entry:
            items.append(f"'agility_level': {entry['agility_level']}")
        if 'fishing_level' in entry:
            items.append(f"'fishing_level': {entry['fishing_level']}")
        if 'keyword_counts' in entry:
            kc = entry['keyword_counts']
            kc_items = ', '.join(
                f'{py_str(k)}: {v}' for k, v in sorted(kc.items())
            )
            items.append(f"'keyword_counts': {{{kc_items}}}")
        lines.append(
            f'    (Location.{a_attr}, Location.{b_attr}): '
            + '{' + ', '.join(items) + '},'
        )
    lines.append('}')
    lines.append('')

    if out_path is None:
        out_path = AUTOGEN_DIR / 'routes.py'
    write_file(out_path, '\n'.join(lines))
    return out_path


