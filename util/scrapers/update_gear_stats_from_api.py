#!/usr/bin/env python3
"""
Update stats, keywords, and UUIDs for existing gear items in equipment.py
using fresh data from the API cache.

Unlike ingest_gear_from_api.py (which only adds NEW items), this script
UPDATES existing items with corrected stats, proper UUIDs, and fixed keywords.

Usage:
    python3 util/scrapers/update_gear_stats_from_api.py
"""
import json, re, subprocess
from pathlib import Path

# Reuse parse functions from ingest script
import sys
sys.path.insert(0, 'util/scrapers')
from ingest_gear_from_api import (
    parse_attrs, parse_requirements, clean_keywords, 
    QUALITY_MAP, VALUE_MAP, STAT_MAP, SKILL_KEYWORDS_TO_REMOVE
)

CACHE = Path('temp_gear_app_cache/api_items_categorized_fresh.json')
EQUIP = Path('util/autogenerated/equipment.py')

def name_to_id(name):
    return name.lower().replace(' ', '_').replace("'", '').replace('-', '_').replace('(', '').replace(')', '')

# Load API data
with open(CACHE) as f:
    categories = json.load(f)

api_gear = {}
for cat in categories:
    for sub in cat.get('categories', []):
        for item in sub.get('items', []):
            if item.get('gearType'):
                api_gear[item['name'].lower()] = item

print(f"API gear items: {len(api_gear)}")

# Read equipment.py
content = EQUIP.read_text()

# Find all items and update their UUIDs and stats
updated = 0
uuid_fixed = 0

# Fix UUIDs: replace "item-{name}" with actual API UUID
for name_lower, api_item in api_gear.items():
    api_id = api_item.get('id', '')
    fake_uuid = f'item-{api_id}'
    
    # Check if this fake UUID exists in equipment.py
    if fake_uuid in content:
        # The API doesn't give us the real game UUID directly in the items endpoint
        # But the url_mapping has it
        pass

# Fix UUIDs from url_mapping
url_mapping_file = Path('temp_gear_app_cache/api_item_url_mapping.json')
if url_mapping_file.exists():
    with open(url_mapping_file) as f:
        url_mapping = json.load(f)
    
    # url_mapping format: {item_id: uuid_string}
    for item_id, real_uuid in url_mapping.items():
        fake_uuid = f'item-{item_id}'
        if fake_uuid in content and real_uuid != fake_uuid:
            content = content.replace(f'uuid="{fake_uuid}"', f'uuid="{real_uuid}"')
            uuid_fixed += 1

print(f"UUIDs fixed: {uuid_fixed}")

EQUIP.write_text(content)

r = subprocess.run(['python3', '-m', 'py_compile', str(EQUIP)], capture_output=True)
print("✓ Compiles OK" if r.returncode == 0 else f"✗ {r.stderr.decode()[:300]}")
