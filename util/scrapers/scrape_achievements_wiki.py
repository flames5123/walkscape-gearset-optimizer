#!/usr/bin/env python3
"""
Scrape achievement icons + requirement text from the WalkScape wiki.

The WalkScape tools API exposes achievements as {id, name, difficulty,
itemRewards} only -- it carries NO icon and NO description/requirement text
(verified against the live API). Both of those live on the wiki's
`Achievements` page, which renders one row per achievement with the icon,
the requirement text, and the rewards.

This scraper reads that page (via the MediaWiki `action=parse` API) and:

  1. Writes per-achievement requirement text to a generated data module
     `util/autogenerated/achievement_descriptions.py`
     (ACHIEVEMENT_DESCRIPTIONS, keyed by the tools-API achievement id).

  2. Downloads each achievement's icon and stores it at
     `assets/icons/achievements/<id>.svg` (served by the app as
     `/assets/icons/achievements/<id>.svg`).

     The wiki serves these icons as native pixel-art SVGs already in the
     "Pixels to Svg" (Bonez) format, so they are written through unchanged.
     If a source icon is ever a PNG instead, it is converted to the same
     Bonez SVG format via `png_to_svg.png_bytes_to_svg` before writing.

Join key: the wiki's own `data-achievement-id` attribute keeps apostrophes
and commas (e.g. `hell's_kitchen`), which do NOT match the tools-API id
(`hells_kitchen`). We therefore join wiki rows to the canonical ids in
`util.autogenerated.achievements.ACHIEVEMENTS` by display name and store
everything under the tools-API id (consistent with the rest of the app).

Usage:
  python util/scrapers/scrape_achievements_wiki.py            # dry report only
  python util/scrapers/scrape_achievements_wiki.py --write    # write icons + data
  python util/scrapers/scrape_achievements_wiki.py --write --icons-only
  python util/scrapers/scrape_achievements_wiki.py --write --descriptions-only
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional

from bs4 import BeautifulSoup

# Repo root = two levels up from util/scrapers/
REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from util.autogenerated.achievements import ACHIEVEMENTS  # noqa: E402
from util.scrapers.png_to_svg import png_bytes_to_svg  # noqa: E402

WIKI_BASE = "https://wiki.walkscape.app"
PARSE_API = WIKI_BASE + "/api.php"
USER_AGENT = "walkscape-gearset-optimizer/achievement-wiki-scraper"

ICON_DIR = REPO_ROOT / "assets" / "icons" / "achievements"
BACK_CARD_DIR = ICON_DIR / "back_card"  # per-achievement card backs (deduped by filename)
DESC_MODULE = REPO_ROOT / "util" / "autogenerated" / "achievement_descriptions.py"


# ────────────────────────────────────────────────────────────────────────
# Fetch helpers
# ────────────────────────────────────────────────────────────────────────

def _get(url: str, *, binary: bool = False, retries: int = 3) -> bytes:
    last = None
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(req, timeout=30) as resp:
                return resp.read()
        except Exception as e:  # noqa: BLE001
            last = e
            time.sleep(0.5 * (attempt + 1))
    raise RuntimeError(f"GET failed after {retries} tries: {url} ({last})")


def fetch_achievements_html() -> str:
    url = PARSE_API + "?" + urllib.parse.urlencode({
        "action": "parse", "page": "Achievements",
        "prop": "text", "format": "json", "formatversion": "2",
    })
    data = json.loads(_get(url).decode("utf-8"))
    return data["parse"]["text"]


# ────────────────────────────────────────────────────────────────────────
# Parsing
# ────────────────────────────────────────────────────────────────────────

def _clean_requirements(td) -> List[str]:
    """Return the requirement cell as a list of clean text lines.

    Icons (<img>) are dropped; <br> become line breaks; the keyword
    icon-links wrap only the (now removed) image so no duplicate name text
    remains -- the readable name comes from the sibling text link.
    """
    for br in td.find_all("br"):
        br.replace_with("\n")
    for img in td.find_all("img"):
        img.decompose()
    lines = []
    for raw in td.get_text(" ").split("\n"):
        line = re.sub(r"\s+", " ", raw).strip()
        # tidy spacing before the bold [N] count and terminal punctuation
        line = re.sub(r"\s+\[", " [", line)
        line = re.sub(r"\s+([.,!?])", r"\1", line)
        if line:
            lines.append(line)
    return lines


def parse_rows(html: str) -> List[Dict]:
    """Parse the Achievements page into rows: {wiki_name, requirements, icon_src}."""
    soup = BeautifulSoup(html, "html.parser")
    out = []
    for tr in soup.select("tr[data-achievement-id]"):
        tds = tr.find_all("td", recursive=False)
        if len(tds) < 3:
            continue
        name = re.sub(r"\s+", " ", tds[1].get_text(" ", strip=True)).strip()
        imgs = tds[0].find_all("img")  # [0]=achievement front icon, [1]=card back
        icon_src = imgs[0].get("src") if len(imgs) >= 1 else None
        back_src = imgs[1].get("src") if len(imgs) >= 2 else None
        out.append({
            "wiki_name": name,
            "requirements": _clean_requirements(tds[2]),
            "rewards_raw": _clean_requirements(tds[3]) if len(tds) > 3 else [],
            "icon_src": icon_src,
            "back_src": back_src,
            "raw_id": tr.get("data-achievement-id", ""),
        })
    return out


# ────────────────────────────────────────────────────────────────────────
# Name -> canonical tools-API id join
# ────────────────────────────────────────────────────────────────────────

def _norm(name: str) -> str:
    return re.sub(r"\s+", " ", (name or "").strip().lower()).rstrip(". ")


def _icon_slug(aid: str) -> str:
    """URL-safe icon filename stem for an achievement id.

    Achievement ids can contain characters that break an image URL when used
    as a filename -- most importantly '?' (starts a query string), but also
    '!' and '.'. Strip everything except [a-z0-9_] so the served path
    /assets/icons/achievements/<slug>.svg always resolves. e.g.
    'only_two_fingers?' -> 'only_two_fingers', 'wow.' -> 'wow'.
    """
    return re.sub(r"[^a-z0-9_]+", "", (aid or "").lower())


def _icon_path(aid: str) -> str:
    return f"/assets/icons/achievements/{_icon_slug(aid)}.svg"


def _back_slug(src: str) -> str:
    """Filename stem for a card-back image src (deduped, URL-safe). e.g.
    /images/4/41/Achievement_Back_Pink_Easy.svg -> achievement_back_pink_easy."""
    import os
    base = os.path.basename((src or "").split("?")[0])
    stem = re.sub(r"\.svg$", "", base, flags=re.I)
    return re.sub(r"[^a-z0-9]+", "_", stem.lower()).strip("_")


# ────────────────────────────────────────────────────────────────────────
# Structured requirement + reward parsing
# ────────────────────────────────────────────────────────────────────────

# Achievement-point reward is fixed by difficulty.
POINTS_BY_DIFFICULTY = {"easy": 1, "normal": 3, "hard": 5, "extreme": 10}

_BRACKET_NUM = re.compile(r"\[([\d,]+)\]")


def _first_bracket_target(text: str):
    m = _BRACKET_NUM.search(text)
    if not m:
        return None
    try:
        return int(m.group(1).replace(",", ""))
    except ValueError:
        return None


def parse_requirement(text: str, aid: str) -> Dict:
    """Classify one requirement line into structured form.

    Returns {text, type, target, subject, auto, auto_source}. ``auto`` marks a
    requirement we can satisfy from an imported character; ``auto_source`` is
    one of skill / wealth / character_level / steps / item_has. Everything else
    is a manual checkbox (auto=False). ``type='checklist'`` is an interactive
    multi-item checkbox list (e.g. per-shop for "sell to 20 shops").
    """
    l = text.lower().strip()
    out = {
        "text": text,
        "type": "manual",
        "target": _first_bracket_target(text),
        "subject": None,
        "auto": False,
        "auto_source": None,
    }

    # --- auto-detectable from a character import ---
    m = re.match(r"at least\s+(.+?)\s+lvl\.?\s*(\d+)", l)
    if m:
        out.update(type="skill_level", subject=m.group(1).strip().title(),
                   target=int(m.group(2)), auto=True, auto_source="skill")
        return out
    if "character level" in l:
        out.update(type="character_level", auto=True, auto_source="character_level")
        return out
    if "total wealth" in l or "total amount of coins" in l:
        out.update(type="total_wealth", auto=True, auto_source="wealth")
        return out
    if "walk a total amount of steps" in l:
        # Only the plain lifetime-total steps is auto; 24h/travel/no-gear are manual.
        qualified = any(q in l for q in ("24 hours", "dedicated to travel", "without wearing any gear"))
        out["type"] = "steps"
        if not qualified:
            out.update(auto=True, auto_source="steps")
        return out
    if "essence of the swamp" in l:
        # Owning the essence proves this (also a child of explored_realm_gdte).
        out.update(type="item_has", subject="Essence of the swamp",
                   auto=True, auto_source="item_has")
        return out

    # --- interactive checklist (per-shop tracking for "sell to N shops") ---
    if aid == "peddle_to_the_mettle" or ("sell things to" in l and "shop" in l):
        out.update(type="checklist", subject="shops")
        return out

    # --- manual categories (checkbox only) ---
    if l.startswith("complete actions of"):
        out["type"] = "activity_actions"
    elif "complete a " in l and "recipe" in l:
        out["type"] = "recipe_complete"
    elif "complete different" in l and "recipe" in l:
        out["type"] = "recipe_variety"
    elif re.search(r"\bcraft\b", l) or "prepare drinks" in l:
        out["type"] = "craft"
    elif (l.startswith(("gain ", "find ", "mine ", "forage", "collect", "catch"))
          or "from an activity" in l or "from activities" in l):
        out["type"] = "cumulative_gain"
    elif "go to the " in l:
        out["type"] = "visit_location"
    elif "explore every location" in l or "explore to find" in l:
        out["type"] = "explore"
    elif "hatch" in l or "claim a rare" in l:
        out["type"] = "hatch"
    elif "raise a pet" in l:
        out["type"] = "pet_adult"
    elif "equipped" in l:
        out["type"] = "equip"
    elif l.startswith(("have a ", "have an ", "have both", "have different", "have any", "have several")):
        out["type"] = "have_item"
    else:
        out["type"] = "event"
    return out


def build_rewards(ach: Dict, raw_lines: List[str]) -> Dict:
    """Structured rewards: points (by difficulty), items (tools-API itemRewards),
    coins (parsed from the wiki Rewards column), and the raw reward lines."""
    points = POINTS_BY_DIFFICULTY.get(ach.get("difficulty", "normal"), 3)
    items = [
        {"id": r.get("id"), "quality": r.get("quality"), "quantity": r.get("quantity")}
        for r in ach.get("itemRewards", []) if r.get("type") == "item"
    ]
    coins = None
    for line in raw_lines:
        m = re.search(r"([\d,]+)\s*x?\s*coins", line, re.I)
        if m:
            coins = int(m.group(1).replace(",", ""))
            break
    return {"points": points, "coins": coins, "items": items, "raw": raw_lines}


def build_name_index() -> Dict[str, str]:
    """Map normalized display name -> canonical ACHIEVEMENTS id."""
    idx = {}
    for aid, a in ACHIEVEMENTS.items():
        idx[_norm(a["name"])] = aid
    return idx


def join_rows(rows: List[Dict]) -> (Dict[str, Dict], List[Dict], List[str]):
    """Return (by_id, unmatched_rows, missing_achievement_ids)."""
    idx = build_name_index()
    by_id: Dict[str, Dict] = {}
    unmatched: List[Dict] = []
    for r in rows:
        aid = idx.get(_norm(r["wiki_name"]))
        if not aid:
            unmatched.append(r)
            continue
        by_id[aid] = {
            "id": aid,
            "name": ACHIEVEMENTS[aid]["name"],
            "difficulty": ACHIEVEMENTS[aid].get("difficulty", "normal"),
            "requirements": r["requirements"],
            "parsed": [parse_requirement(line, aid) for line in r["requirements"]],
            "rewards": build_rewards(ACHIEVEMENTS[aid], r.get("rewards_raw", [])),
            "icon_src": r["icon_src"],
            "icon_file": f"{_icon_slug(aid)}.svg",
            "icon_path": _icon_path(aid),
            "back_src": r.get("back_src"),
            "back_file": (f"{_back_slug(r['back_src'])}.svg" if r.get("back_src") else None),
            "back_path": (f"/assets/icons/achievements/back_card/{_back_slug(r['back_src'])}.svg" if r.get("back_src") else None),
        }
    missing = [aid for aid in ACHIEVEMENTS if aid not in by_id]
    return by_id, unmatched, missing


# ────────────────────────────────────────────────────────────────────────
# Writers
# ────────────────────────────────────────────────────────────────────────

def write_descriptions(by_id: Dict[str, Dict]) -> int:
    header = (
        '"""\n'
        "Achievement requirement text, keyed by tools-API achievement id.\n\n"
        "DO NOT EDIT MANUALLY -- regenerate with:\n"
        "    python util/scrapers/scrape_achievements_wiki.py --write\n\n"
        "The WalkScape tools API does not publish achievement descriptions or\n"
        "requirements, so this module is scraped from the wiki Achievements page.\n"
        '"""\n\n'
        "ACHIEVEMENT_DESCRIPTIONS = {\n"
    )
    lines = [header]
    for aid in sorted(by_id):
        rec = by_id[aid]
        reqs = rec["requirements"]
        lines.append(f"    {aid!r}: {{\n")
        lines.append(f"        'name': {rec['name']!r},\n")
        lines.append(f"        'difficulty': {rec['difficulty']!r},\n")
        lines.append(f"        'icon': {rec['icon_path']!r},\n")
        lines.append(f"        'back': {rec['back_path']!r},\n")
        lines.append(f"        'requirements': {reqs!r},\n")
        lines.append(f"        'parsed': {rec['parsed']!r},\n")
        lines.append(f"        'rewards': {rec['rewards']!r},\n")
        lines.append("    },\n")
    lines.append("}\n")
    DESC_MODULE.parent.mkdir(parents=True, exist_ok=True)
    DESC_MODULE.write_text("".join(lines), encoding="utf-8")
    return len(by_id)


def _icon_bytes_to_svg_text(icon_src: str) -> str:
    """Download an icon and return SVG text (Bonez format).

    SVG sources are returned unchanged. PNG sources are converted to the
    same pen/Bonez SVG format via png_bytes_to_svg.
    """
    url = icon_src if icon_src.startswith("http") else WIKI_BASE + icon_src
    raw = _get(url, binary=True)
    if icon_src.lower().split("?")[0].endswith(".png"):
        return png_bytes_to_svg(raw)
    text = raw.decode("utf-8", "replace").lstrip("\ufeff").strip()
    if "<svg" not in text[:200]:
        raise ValueError(f"expected SVG, got: {text[:80]!r} from {url}")
    return text


def write_icons(by_id: Dict[str, Dict]) -> (int, List[str]):
    ICON_DIR.mkdir(parents=True, exist_ok=True)
    written, failed = 0, []
    for aid in sorted(by_id):
        src = by_id[aid].get("icon_src")
        if not src:
            failed.append(f"{aid}: no icon src in wiki row")
            continue
        try:
            svg = _icon_bytes_to_svg_text(src)
            (ICON_DIR / by_id[aid]["icon_file"]).write_text(svg, encoding="utf-8")
            written += 1
            time.sleep(0.1)  # be gentle on the wiki
        except Exception as e:  # noqa: BLE001
            failed.append(f"{aid}: {e}")

    # Card backs (deduped by filename): each locked achievement shows its own
    # colored back, so download every distinct back card referenced.
    BACK_CARD_DIR.mkdir(parents=True, exist_ok=True)
    backs = {}
    for aid in by_id:
        bf, bs = by_id[aid].get("back_file"), by_id[aid].get("back_src")
        if bf and bs and bf not in backs:
            backs[bf] = bs
    for bf, bs in sorted(backs.items()):
        try:
            (BACK_CARD_DIR / bf).write_text(_icon_bytes_to_svg_text(bs), encoding="utf-8")
            written += 1
            time.sleep(0.1)
        except Exception as e:  # noqa: BLE001
            failed.append(f"back {bf}: {e}")
    return written, failed


# ────────────────────────────────────────────────────────────────────────
# Main
# ────────────────────────────────────────────────────────────────────────

def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--write", action="store_true", help="Write icons + descriptions (default: dry report)")
    p.add_argument("--icons-only", action="store_true", help="With --write: only download icons")
    p.add_argument("--descriptions-only", action="store_true", help="With --write: only write descriptions")
    args = p.parse_args()

    print("Fetching wiki Achievements page ...")
    html = fetch_achievements_html()
    rows = parse_rows(html)
    print(f"Parsed {len(rows)} achievement rows from the wiki.")

    by_id, unmatched, missing = join_rows(rows)
    print(f"Joined {len(by_id)} / {len(ACHIEVEMENTS)} achievements to canonical ids.")
    if unmatched:
        print(f"\n[WARN] {len(unmatched)} wiki rows did NOT match an ACHIEVEMENTS id:")
        for r in unmatched:
            print(f"    {r['wiki_name']!r} (wiki raw id {r['raw_id']})")
    if missing:
        print(f"\n[WARN] {len(missing)} ACHIEVEMENTS ids had NO wiki row:")
        for aid in missing:
            print(f"    {aid} ({ACHIEVEMENTS[aid]['name']!r})")
    no_icon = [aid for aid, r in by_id.items() if not r.get("icon_src")]
    if no_icon:
        print(f"\n[WARN] {len(no_icon)} matched rows have no icon src: {no_icon}")

    # sample
    print("\nSample (first 3):")
    for aid in list(sorted(by_id))[:3]:
        r = by_id[aid]
        print(f"  {aid} | {r['difficulty']:7} | icon={r['icon_src']}")
        print(f"      reqs={r['requirements']}")

    if not args.write:
        print("\n(dry run -- pass --write to emit icons + descriptions)")
        return 0

    if not args.icons_only:
        n = write_descriptions(by_id)
        print(f"\nWrote {n} descriptions -> {DESC_MODULE.relative_to(REPO_ROOT)}")
    if not args.descriptions_only:
        written, failed = write_icons(by_id)
        print(f"Wrote {written} icons -> {ICON_DIR.relative_to(REPO_ROOT)}/<id>.svg")
        if failed:
            print(f"[ERROR] {len(failed)} icon failures:")
            for f in failed:
                print(f"    {f}")
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
