"""scan_runtime_eval — populate items_requiring_runtime_eval.

Items end up in this table when their effective stats depend on character
state in a way the precomputed dominators can't express. As of v1:

  - 'custom_stat': items with a player-selectable custom stat
    (Screwdriver, Petal Finder, etc.). These have non-empty `custom_stat`
    on their ItemInstance.
  - 'ap_dependent': AchievementItem instances (e.g. Omni-Tool) whose stats
    accumulate as character.achievement_points crosses thresholds.

This list extends naturally as new conditional-stat patterns ship — add
detection logic here, no schema change.
"""

from typing import Optional, Set


def scan_runtime_eval(db, changed_slugs: Optional[Set[str]] = None) -> int:
    """Populate items_requiring_runtime_eval.

    Idempotent — uses INSERT OR REPLACE.

    Args:
        db: sqlite3 connection
        changed_slugs: if provided, only re-scan items whose slug is in this
                       set. Required because an unrelated equipment item that
                       was previously NOT runtime-eval shouldn't be re-checked
                       on every consumables-only refresh.

    Returns:
        Number of rows inserted or replaced.
    """
    import util.walkscape_constants  # noqa: F401
    from util.autogenerated.equipment import Item, ItemInstance, AchievementItem
    from .build_item_ids import get_item_id_map

    item_id_map = get_item_id_map(db)
    cursor = db.cursor()
    affected = 0

    for attr_name in dir(Item):
        if attr_name.startswith("_"):
            continue
        slug = attr_name.lower()
        if changed_slugs is not None and slug not in changed_slugs:
            continue
        v = getattr(Item, attr_name, None)

        reason = None
        if isinstance(v, AchievementItem):
            reason = "ap_dependent"
        elif isinstance(v, ItemInstance):
            # ItemInstance with a `custom_stat` field set
            cs = getattr(v, "custom_stat", None)
            if cs:
                reason = "custom_stat"
            else:
                # Some items have gated_stats that must be evaluated per-character
                # at request time (not expressible as static dominators): the
                # activity_completion custom-stat toggle, and gated EQUIPMENT
                # whose stats live under a character-derivable gate
                # (explore_realm / item_ownership / total_collectibles). Without
                # this, those items have empty base stats -> no dominators row ->
                # compute_effective_owned_bitmap Phase 1 drops them, so they were
                # invisible to stale detection (2026-08-11, jwbail).
                gs = getattr(v, "gated_stats", None) or {}
                from .build_dominators import GATED_SCOPE_TYPES
                if "activity_completion" in gs or any(g in gs for g in GATED_SCOPE_TYPES):
                    reason = "gated_stat"

        if reason is None:
            # If changed_slugs is provided and this item was previously in the
            # table but no longer qualifies, remove it.
            if changed_slugs is not None:
                item_id = item_id_map.get((slug, "normal"))
                if item_id is not None:
                    cursor.execute(
                        "DELETE FROM items_requiring_runtime_eval WHERE item_id = ?",
                        (item_id,),
                    )
                    if cursor.rowcount > 0:
                        affected += 1
            continue

        # AchievementItem and ItemInstance both store at quality='normal'
        item_id = item_id_map.get((slug, "normal"))
        if item_id is None:
            # Item not in master index yet — skipped (build_item_ids should
            # have run first; if not, idempotent re-run will pick it up)
            continue

        cursor.execute(
            "INSERT OR REPLACE INTO items_requiring_runtime_eval (item_id, reason) "
            "VALUES (?, ?)",
            (item_id, reason),
        )
        affected += 1

    db.commit()
    return affected


def get_runtime_eval_set(db) -> set:
    """Return set of item_ids requiring runtime eval."""
    cursor = db.cursor()
    cursor.execute("SELECT item_id FROM items_requiring_runtime_eval")
    return {row[0] for row in cursor.fetchall()}
