"""target_items — v2 keyword-based classifier for 'Fastest Target Item Activities'.

Replaces the fixed 15-category scheme with:
  (1) CURRENCY groups (adventurers_guild_tokens, sea_shells): sell-value,
      metric = units/1k steps (HIGHER better).
  (2) SINGLE-ITEM FINDING groups (ectoplasm, gold_nugget, bird_nest):
      items with exactly 1 drop in their ItemFindingCategory.
      metric = steps/item.
  (3) KEYWORD MATERIAL groups: each item -> its highest-priority meaningful
      keyword. metric = steps/item.
  (4) OTHER group: items with no meaningful keyword. metric = steps/item.

SINGLE SOURCE OF TRUTH used by both worker (build_target_items_jobs) and
enumerator (enumerate_applicable_sources).
"""

from typing import Optional, Tuple, List, Dict, Set

from .normalize import normalize_item_id


# ============================================================================
# CONSTANTS
# ============================================================================

# Noise keywords (demoted — never chosen if any non-noise keyword exists;
# if an item's ONLY keywords are noise it falls through to the 'Other' group).
NOISE_KEYWORDS: Set[str] = {
    # Weight classes
    'Light', 'Heavy', 'Medium', 'Ultra Light',
    # Bare skill names
    'Agility', 'Foraging', 'Hunting', 'Cooking', 'Mining', 'Woodcutting',
    'Smithing', 'Tailoring', 'Trinketry', 'Fishing', 'Crafting', 'Carpentry',
    # Generics
    'Misc.', 'Global',
    # 2026-08-12 (jwbail): fold these standalone categories into 'Other' —
    # they are single-item / sell-for-AGT groups that don't warrant their own
    # section. Curiosity items are farmed purely for AGT (tracked by the AGT
    # currency group), Arrows is one item, and Offcut/Processed/Trash are
    # low-value byproducts.
    'Arrows', 'Offcut', 'Processed', 'Trash', 'Curiosity',
}

# Keyword merges: source -> canonical
KEYWORD_MERGES: Dict[str, str] = {
    'Rough Gem': 'Gem',
    # 2026-08-12 (jwbail): Mushrooms are cooking ingredients — merge into the
    # Ingredient group rather than showing a separate Mushroom category.
    'Mushroom': 'Ingredient',
}

# Currency group slugs (NOT per-item — one leaf per currency)
CURRENCY_GROUPS = {
    'adventurers_guild_tokens': "Adventurers' Guild Tokens",
    'sea_shells': 'Sea Shells',
}

# Single-item finding groups (detected from ItemFindingCategory).
# Order here is the canonical display order (line 2 of the layout):
# Bird Nest, Ectoplasm.
# 2026-08-14 (jwbail): Gold nugget removed from finding groups — it is a real
# mining material (keyword 'Nugget') and now classifies into the 'Nugget'
# material group alongside Silver nugget (which is native-drop-only, no IFC
# expansion). Keeps the two nuggets together and consistent.
FINDING_GROUPS = {
    'bird_nest': 'Bird Nest',
    'ectoplasm': 'Ectoplasm',
}

# Item refs that belong to finding groups (pulled OUT of keyword groups)
_FINDING_REFS: Set[str] = frozenset([
    'Material.ECTOPLASM',
    'Container.BIRD_NEST',
])

# Ref -> finding group slug
_FINDING_REF_TO_SLUG: Dict[str, str] = {
    'Material.ECTOPLASM': 'ectoplasm',
    'Container.BIRD_NEST': 'bird_nest',
}


# ============================================================================
# KEYWORD FREQUENCY MAP (lazy, module-level cache)
# ============================================================================

_keyword_freq_cache: Optional[Dict[str, int]] = None


def _build_keyword_frequency_map() -> Dict[str, int]:
    """Count how many distinct items carry each non-noise keyword across ALL
    activity drops (materials only). Used to pick 'rarest' keyword."""
    global _keyword_freq_cache
    if _keyword_freq_cache is not None:
        return _keyword_freq_cache

    freq: Dict[str, int] = {}
    seen_refs: Set[str] = set()

    try:
        from util.autogenerated.activities import ACTIVITIES_BY_NAME
    except ImportError:
        _keyword_freq_cache = {}
        return _keyword_freq_cache

    for activity in ACTIVITIES_BY_NAME.values():
        all_drops = list(getattr(activity, 'drop_table', None) or []) + \
                    list(getattr(activity, 'secondary_drop_table', None) or [])
        for d in all_drops:
            item_ref = getattr(d, 'item_ref', '') or ''
            if not item_ref or item_ref in seen_refs:
                continue
            # Exclusions
            if _is_excluded_ref(item_ref):
                continue
            if item_ref in _FINDING_REFS:
                continue
            seen_refs.add(item_ref)

            keywords = _get_keywords_for_drop(d)
            for kw in keywords:
                canonical = KEYWORD_MERGES.get(kw, kw)
                if canonical not in NOISE_KEYWORDS:
                    freq[canonical] = freq.get(canonical, 0) + 1

    _keyword_freq_cache = freq
    return _keyword_freq_cache


def _reset_keyword_freq_cache():
    """Reset cache (for testing)."""
    global _keyword_freq_cache
    _keyword_freq_cache = None


# ============================================================================
# HELPERS
# ============================================================================

def _is_excluded_ref(item_ref: str) -> bool:
    """Return True if this item_ref is excluded from target_items entirely."""
    if not item_ref:
        return True
    # Gear/tools
    if item_ref.startswith('Item.'):
        return True
    # Collectibles
    if item_ref.startswith('Collectible.'):
        return True
    # Coins
    if item_ref == 'Currency.COIN':
        return True
    # Chests (Container.*) EXCEPT bird nest
    if item_ref.startswith('Container.') and item_ref != 'Container.BIRD_NEST':
        return True
    # Eggs
    if item_ref.startswith('Egg.'):
        return True
    # Currency items that are themselves the currency tokens (handled as currency groups)
    if item_ref == 'Currency.ADVENTURERS_GUILD_TOKEN':
        return True
    # Sea shell has its own 'sea_shells' currency group (a sell-value aggregate
    # that folds direct drops + fine shells + shell-bearing chests, handled
    # separately in the worker). It carries no meaningful keyword, so
    # classify_item would otherwise dump the per-item leaf into 'Other' — making
    # Sea Shells show up in BOTH its own category AND 'Other' (user report
    # 565a534d, 2026-08-26). Exclude the per-item leaf so it only appears under
    # the Sea Shells group. Mirrors the Curiosity exclusion in classify_item
    # (value already tracked by the AGT currency group).
    if item_ref == 'Material.SEA_SHELL':
        return True
    return False


def _get_keywords_for_drop(drop) -> List[str]:
    """Extract keyword strings from a drop (resolves item_object if needed)."""
    kw = getattr(drop, 'item_keywords', None)
    if kw is not None:
        return list(kw)
    item_object = None
    try:
        item_object = drop.item_object
    except Exception:
        pass
    if item_object is not None:
        kw = getattr(item_object, 'keywords', None)
        if kw is not None:
            return list(kw)
    return []


def _has_fine_material(drop) -> bool:
    """Return True if the drop has a fine variant."""
    hf = getattr(drop, 'has_fine_material', None)
    if hf is not None:
        if callable(hf):
            try:
                return bool(hf())
            except Exception:
                return False
        return bool(hf)
    item_object = None
    try:
        item_object = drop.item_object
    except Exception:
        pass
    if item_object is not None:
        io_hf = getattr(item_object, 'has_fine_material', None)
        if io_hf is not None:
            try:
                return bool(io_hf()) if callable(io_hf) else bool(io_hf)
            except Exception:
                pass
    return False


def keyword_to_slug(kw: str) -> str:
    """Convert a keyword like 'Hunting Product' to a group slug 'hunting_product'."""
    return kw.lower().replace(' ', '_').replace('.', '')


def _fine_variant_exists(item_ref: str) -> bool:
    """Return True if a `<NAME>_FINE` catalog sibling exists for this ref.

    `_has_fine_material` only reflects the base item's `has_fine_material`
    flag, which is set for MATERIAL items but NOT for consumables — so drops
    like Beer / Wine (Consumable.BEER, Consumable.WINE), which DO have
    Beer (Fine) / Wine (Fine) variants (Consumable.BEER_FINE / WINE_FINE),
    were never emitting a fine row (user report 2026-08-13: "Fine beer and
    fine wine should show under alcohol"). This mirrors the authoritative
    `<NAME>_FINE` catalog check used by util/ag_token_value.get_drop_fine_ag_token_value.
    """
    if not item_ref or '.' not in item_ref:
        return False
    try:
        cls_name, attr = item_ref.split('.', 1)
        fine_attr = attr + '_FINE'
        if cls_name == 'Material':
            from util.autogenerated.materials import Material
            return hasattr(Material, fine_attr)
        if cls_name == 'Consumable':
            from util.autogenerated.consumables import Consumable
            return hasattr(Consumable, fine_attr)
    except Exception:
        return False
    return False


# ============================================================================
# CORE CLASSIFIER
# ============================================================================

def classify_item(item_name: str, item_ref: str, keywords: List[str]) -> Optional[Tuple[str, str]]:
    """Classify a single material/container item into (group_slug, group_label) or None.

    Implements groups (2) finding, (3) keyword, (4) other.
    Currency items are excluded (handled separately in the worker).
    Gear/tools/collectibles/chests/coins/eggs are excluded -> None.

    Args:
        item_name: Display name (e.g. 'Rough ruby')
        item_ref: Reference string (e.g. 'Material.ROUGH_RUBY')
        keywords: List of keyword strings from item_object.keywords

    Returns:
        (group_slug, group_label) or None if excluded.
    """
    if not item_name or item_name == 'Nothing' or not item_ref:
        return None

    if _is_excluded_ref(item_ref):
        return None

    # 2026-08-13 (jwbail): Curiosity-keyword items (Adventurers' enamel pin,
    # Halfmaw scales/teeth, Name tag, Unidentified remains, Strange fur, etc.)
    # are farmed purely to SELL for AGT — that value is already tracked by the
    # Adventurers' Guild Tokens currency group, so running a per-item
    # optimization for them is wasted work. Exclude them from the report
    # entirely instead of dumping them in 'Other'. (The AGT currency
    # aggregation is independent of classify_item, so the AGT/1k rows still
    # include these drops' sell value.)
    if any(str(k).lower() == 'curiosity' for k in (keywords or [])):
        return None

    # (2) Finding groups — single-item categories
    if item_ref in _FINDING_REF_TO_SLUG:
        slug = _FINDING_REF_TO_SLUG[item_ref]
        return (slug, FINDING_GROUPS[slug])

    # (3) Keyword material groups — pick highest-priority meaningful keyword
    freq = _build_keyword_frequency_map()

    # Apply merges and filter noise
    meaningful = []
    for kw in keywords:
        canonical = KEYWORD_MERGES.get(kw, kw)
        if canonical not in NOISE_KEYWORDS:
            meaningful.append(canonical)

    if not meaningful:
        # (4) Other — no meaningful keyword
        return ('other', 'Other')

    # Pick the RAREST keyword (fewest items carry it), with special rules:
    # - Plant beats Ingredient (explicit override)
    # - Tie-break alphabetical
    has_plant = 'Plant' in meaningful
    has_ingredient = 'Ingredient' in meaningful

    def sort_key(kw):
        count = freq.get(kw, 9999)
        # Force Plant to outrank Ingredient when both present:
        # Give Plant a sort key guaranteed lower than Ingredient's
        if has_plant and has_ingredient:
            if kw == 'Plant':
                count = -1  # Always first among the Plant/Ingredient pair
            elif kw == 'Ingredient':
                count = max(count, 0)  # Ensure Ingredient is after Plant
        return (count, kw)

    meaningful.sort(key=sort_key)
    chosen = meaningful[0]
    slug = keyword_to_slug(chosen)
    return (slug, chosen)


def classify_drop_entry_all(drop, include_fine: bool = True) -> List[Tuple[str, str, str, str, bool]]:
    """Classify a drop into (group_slug, item_slug, display_name, item_ref, is_fine) tuples.

    Returns 0-2 tuples: base classification + optional fine variant.
    Currency drops (AGT, sea_shell as currency) are handled separately in the worker.

    Args:
        drop: A DropEntry-like object with item_name, item_ref, etc.
        include_fine: If True, also emit fine variant when applicable.

    Returns:
        List of (group_slug, item_slug, display_name, item_ref, is_fine).
    """
    item_name = getattr(drop, 'item_name', None) or ''
    item_ref = getattr(drop, 'item_ref', None) or ''
    if not item_name or item_name == 'Nothing' or not item_ref:
        return []

    keywords = _get_keywords_for_drop(drop)
    result = classify_item(item_name, item_ref, keywords)
    if result is None:
        return []

    group_slug, group_label = result
    item_slug = normalize_item_id(item_name)
    results = [(group_slug, item_slug, item_name, item_ref, False)]

    # Fine variant
    if include_fine and (_has_fine_material(drop) or _fine_variant_exists(item_ref)):
        # 2026-08-12 (jwbail): do NOT emit a fine Sea shell row. Fine sea shells
        # are only relevant while actively sea-shell farming (their value is
        # already folded into the 'Sea Shells' currency aggregate at 10x). A
        # standalone 'Sea shell (Fine)' material row is noise. Gold nugget fine
        # and all other fine variants remain included.
        # 2026-08-13 (jwbail): _fine_variant_exists also picks up CONSUMABLE fine
        # variants (Beer/Wine -> Beer (Fine)/Wine (Fine) under Alcohol) that the
        # material-only has_fine_material flag misses.
        if item_ref != 'Material.SEA_SHELL':
            fine_name = f"{item_name} (Fine)"
            fine_slug = normalize_item_id(fine_name)
            results.append((group_slug, fine_slug, fine_name, item_ref, True))

    return results


def get_item_keywords_for_drop(drop) -> List[str]:
    """Extract searchable keywords for a drop entry (for frontend search box)."""
    kws = _get_keywords_for_drop(drop)
    kws = list(kws)
    item_ref = getattr(drop, 'item_ref', None) or ''
    if '.' in item_ref:
        prefix = item_ref.split('.')[0].lower()
        if prefix and prefix not in kws:
            kws.append(prefix)
    # Add the group label for searchability
    item_name = getattr(drop, 'item_name', None) or ''
    classification = classify_item(item_name, item_ref, kws[:])  # don't pass modified list
    if classification:
        group_slug, group_label = classification
        if group_label and group_label not in kws:
            kws.append(group_label)
    return kws


# ============================================================================
# GROUP METADATA (canonical ordered list for frontend mirroring)
# ============================================================================

def build_target_groups() -> List[Tuple[str, str, str]]:
    """Build the canonical ordered list of (group_slug, group_label, kind).

    kind in {'currency', 'finding', 'material', 'other'}.
    Order: currency first, then finding, then material (alphabetical), then other.
    """
    groups: List[Tuple[str, str, str]] = []

    # Currency groups
    for slug, label in CURRENCY_GROUPS.items():
        groups.append((slug, label, 'currency'))

    # Finding groups
    for slug, label in FINDING_GROUPS.items():
        groups.append((slug, label, 'finding'))

    # Material keyword groups — discover from all activity drops
    material_slugs: Dict[str, str] = {}  # slug -> label
    try:
        from util.autogenerated.activities import ACTIVITIES_BY_NAME
        seen_refs: Set[str] = set()
        for activity in ACTIVITIES_BY_NAME.values():
            all_drops = list(getattr(activity, 'drop_table', None) or []) + \
                        list(getattr(activity, 'secondary_drop_table', None) or [])
            for d in all_drops:
                item_ref = getattr(d, 'item_ref', '') or ''
                if not item_ref or item_ref in seen_refs:
                    continue
                seen_refs.add(item_ref)
                item_name = getattr(d, 'item_name', '') or ''
                keywords = _get_keywords_for_drop(d)
                result = classify_item(item_name, item_ref, keywords)
                if result is None:
                    continue
                slug, label = result
                if slug not in FINDING_GROUPS and slug != 'other':
                    material_slugs[slug] = label
    except ImportError:
        pass

    for slug in sorted(material_slugs.keys()):
        groups.append((slug, material_slugs[slug], 'material'))

    # Other group
    groups.append(('other', 'Other', 'other'))

    return groups


# Module-level cached groups (lazy)
_target_groups_cache: Optional[List[Tuple[str, str, str]]] = None


def get_target_groups() -> List[Tuple[str, str, str]]:
    """Get or build the cached target groups list."""
    global _target_groups_cache
    if _target_groups_cache is None:
        _target_groups_cache = build_target_groups()
    return _target_groups_cache


def _reset_target_groups_cache():
    """Reset cache (for testing)."""
    global _target_groups_cache
    _target_groups_cache = None


