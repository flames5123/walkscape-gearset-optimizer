"""
Regression test: the stale-detection enumerator must NOT flag an ungeared
activity as applicable — otherwise its scope has no result row and the red (!)
never clears (re-running Optimize yields "0/0 optimizations").

Companion to the build-time gate (_activity_required_gear_owned) and the
read-path filter (filter_ungeared_activities). This is the THIRD path:
enumerate_applicable_sources -> detect_stale_scopes. _activity_applicable
deliberately skips keyword_counts, so the new _activity_gear_feasible gate is
what keeps Casbrant's Grave diving activities out of the applicable set when no
diving gear is owned.
"""

import os
import sys
import unittest

_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

import util.walkscape_constants  # noqa: E402,F401
from util.autogenerated.activities import ACTIVITIES_BY_NAME  # noqa: E402
from util.stats_report.state_snapshot import CharacterStateSnapshot  # noqa: E402
from util.stats_report.applicable_sources import (  # noqa: E402
    _activity_gear_feasible,
    _catalog_lookup_cache,
)
from util.optimization_utils import item_satisfies_required_keyword  # noqa: E402


def _snapshot(owned_items):
    """Minimal snapshot; only owned_items matters for _activity_gear_feasible."""
    return CharacterStateSnapshot(
        owned_items=frozenset(owned_items),
        ring_quantities={},
        hidden_items=frozenset(),
        hidden_consumables_fine=frozenset(),
        custom_stats={},
        skills_xp={},
        reputation={},
        achievement_points=0,
        coins=0,
        steps=0,
    )


def _first_diving_activity():
    for act in ACTIVITIES_BY_NAME.values():
        kc = (getattr(act, "requirements", {}) or {}).get("keyword_counts", {}) or {}
        if kc.get("advanced diving gear", 0) >= 1:
            return act
    return None


def _owned_slugs_satisfying(activity):
    """Build a set of (slug,'normal') owning enough catalog items to satisfy
    every keyword_counts requirement of the activity."""
    kc = (getattr(activity, "requirements", {}) or {}).get("keyword_counts", {}) or {}
    catalog = _catalog_lookup_cache()
    owned = set()
    for keyword, count in kc.items():
        picked = 0
        for slug, item in catalog.items():
            if picked >= int(count or 0):
                break
            try:
                if item_satisfies_required_keyword(item, keyword, activity):
                    owned.add((slug, "normal"))
                    picked += 1
            except Exception:
                continue
    return owned


class StaleEnumeratorGearGateTest(unittest.TestCase):
    def setUp(self):
        self.activity = _first_diving_activity()
        self.assertIsNotNone(self.activity, "No diving-gear-gated activity found.")

    def test_not_feasible_when_no_gear_owned(self):
        self.assertFalse(
            _activity_gear_feasible(self.activity, _snapshot(set())),
            "Ungeared diving activity must NOT be enumerated as applicable "
            "(would strand a red (!) that never clears).",
        )

    def test_feasible_when_gear_owned(self):
        owned = _owned_slugs_satisfying(self.activity)
        # Sanity: we actually resolved gear for every required keyword.
        self.assertTrue(owned, "Could not resolve any satisfying gear from catalog.")
        self.assertTrue(
            _activity_gear_feasible(self.activity, _snapshot(owned)),
            "Diving activity must be applicable once all required gear is owned.",
        )

    def test_ungated_activity_always_feasible(self):
        no_req = None
        for act in ACTIVITIES_BY_NAME.values():
            kc = (getattr(act, "requirements", {}) or {}).get("keyword_counts", {}) or {}
            if not kc:
                no_req = act
                break
        self.assertIsNotNone(no_req)
        self.assertTrue(_activity_gear_feasible(no_req, _snapshot(set())))


if __name__ == "__main__":
    unittest.main()
