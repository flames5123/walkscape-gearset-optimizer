    def by_export_name(cls, export_name: str):
        """Look up material by export name (e.g., "spruce_logs" or "spruce_logs_fine")"""
        const_name = export_name.upper()
        if hasattr(cls, const_name):
            return getattr(cls, const_name)
        return None
