def is_gearset_complete(gearset_dict: dict, character) -> bool:
    """
    Check if a gearset has all required slots filled.
    
    Args:
        gearset_dict: Dictionary mapping slot names to items
        character: Character object (for tool slot count)
        
    Returns:
        True if all slots filled, False otherwise
    """
    # Required gear slots (always 12)
    required_gear_slots = [
        'head', 'cape', 'neck', 'chest', 'hands', 'legs', 'feet',
        'ring1', 'ring2', 'back', 'primary', 'secondary'
    ]
    
    # Check gear slots
    for slot in required_gear_slots:
        if slot not in gearset_dict or gearset_dict[slot] is None:
            return False
    
    # Check tool slots (use cached value from character for performance)
    max_tool_slots = character.get_tool_slots()
    
    for i in range(max_tool_slots):
        slot = f'tool{i}'
        if slot not in gearset_dict or gearset_dict[slot] is None:
            return False
    
    return True

def item_satisfies_required_keyword(item, keyword, activity) -> bool:
    """
    True if `item` counts toward an activity's required `keyword`.

    Normally this is just "does the item carry the keyword". But if the activity
    has a keyword_level_requirement for that keyword (e.g. Mine violite ore needs
    a Pickaxe that itself requires Mining 60), the item ALSO has to meet that
    minimum skill-level requirement to count. A Spectral pickaxe (Mining 55) has
    the 'pickaxe' keyword but does NOT satisfy a Mining-60 requirement, so it must
    not be counted as fulfilling the requirement during gear selection.
    """
    from util.walkscape_constants import item_has_keyword
    if not item_has_keyword(item, keyword):
        return False
    reqs = getattr(activity, 'requirements', {}) or {}
    kw_lower = str(keyword).lower()
    for r in reqs.get('keyword_level_requirements', []):
        if str(r.get('keyword', '')).lower() != kw_lower:
            continue
        req_skill = str(r.get('skill', '')).lower()
        req_level = r.get('level', 0)
        meets = any(
            x.get('type') == 'skill'
            and str(x.get('skill', '')).lower() == req_skill
            and x.get('level', 0) >= req_level
            for x in (getattr(item, 'requirements', []) or [])
        )
        if not meets:
            return False
    return True


def gearset_meets_keyword_level_requirements(items, activity) -> bool:
    """
    Check tool-keyword minimum-skill-level requirements for an activity.

    Some activities have an "Other Requirement" such as:
        "Have a Pickaxe equipped that requires at least Mining level 60."
    This gates on the equip-level (tier) of the equipped tool, not the
    character's own skill level. For each requirement {keyword, skill, level},
    at least one equipped item must (a) carry that keyword and (b) have its own
    skill requirement for `skill` be >= `level`.

    Args:
        items: Iterable of equipped item instances (None entries allowed).
        activity: Activity object with a `.requirements` dict that may contain
                  a 'keyword_level_requirements' list.

    Returns:
        True if all keyword-level requirements are satisfied (or none exist).
    """
    reqs = getattr(activity, 'requirements', {}) or {}
    keyword_level_requirements = reqs.get('keyword_level_requirements', [])
    if not keyword_level_requirements:
        return True

    for req in keyword_level_requirements:
        req_kw = str(req.get('keyword', '')).lower()
        req_skill = str(req.get('skill', '')).lower()
        req_level = req.get('level', 0)
        if not req_kw:
            continue
        satisfied = False
        for item in items:
            if not item or not getattr(item, 'keywords', None):
                continue
            if not any(req_kw == str(kw).lower() for kw in item.keywords):
                continue
            for r in (getattr(item, 'requirements', []) or []):
                if (r.get('type') == 'skill'
                        and str(r.get('skill', '')).lower() == req_skill
                        and r.get('level', 0) >= req_level):
                    satisfied = True
                    break
            if satisfied:
                break
        if not satisfied:
            return False
    return True

def meets_activity_requirements(gearset_dict: dict, activity, character, input_item=None) -> bool:
    """
    Check if a gearset meets activity requirements.
    
    Uses the unified keyword_counts structure where all gear requirements
    are stored as {keyword: count} pairs.
    
    Args:
        gearset_dict: Dictionary mapping slot names to items
        activity: Activity object with requirements
        character: Character object
        input_item: Optional input item (e.g. arrows) that satisfies keyword requirements
        
    Returns:
        True if requirements met, False otherwise
    """
    # Check skill requirements
    for skill, required_level in activity.skill_requirements.items():
        char_level = character.get_skill_level(skill.lower())
        if char_level < required_level:
            return False
    
    # Check reputation requirements
    for faction, required_amount in activity.requirements.get("reputation", {}).items():
        char_rep = character.reputation.get(faction, 0)
        if char_rep < required_amount:
            return False
    
    # Check achievement points
    required_ap = activity.requirements.get("achievement_points", 0)
    if required_ap > 0:
        from util.walkscape_globals import ACHIEVEMENT_POINTS
        if int(ACHIEVEMENT_POINTS) < required_ap:
            return False
    
    # Check all keyword requirements from keyword_counts
    items = [item for item in gearset_dict.values() if item is not None]
    keyword_counts = activity.requirements.get("keyword_counts", {})
    
    # Check specific item requirements (e.g., "Have item Spectral saw equipped")
    item_requirements = activity.requirements.get("item_requirements", [])
    if item_requirements:
        # Equipped crafted/quality items render their name with a quality
        # suffix, e.g. "Spectral saw (Normal)". Match the required base name
        # against BOTH the full name and the suffix-stripped base name so a
        # required item like "Spectral saw" is satisfied by any quality.
        equipped_names = set()
        for item in items:
            nm = getattr(item, 'name', None)
            if not nm:
                continue
            nm = nm.lower()
            equipped_names.add(nm)
            base = re.sub(r'\s*\([^)]*\)\s*$', '', nm).strip()
            if base:
                equipped_names.add(base)
        for required_name in item_requirements:
            if required_name.lower() not in equipped_names:
                return False
    
    # Build set of keywords satisfied by the input item (e.g. arrows for hunting)
    input_item_keywords = set()
    if input_item and hasattr(input_item, 'keywords'):
        input_item_keywords = {kw.lower() for kw in input_item.keywords}
    elif not input_item and hasattr(activity, 'input_items') and activity.input_items:
        # No input selected — pre-satisfy keywords from activity's input_items definitions
        for ii in activity.input_items:
            if getattr(ii, 'type', '') == 'keyword':
                kw = getattr(ii, 'reference', '').lower()
                if kw:
                    input_item_keywords.add(kw)
    
    for keyword, required_count in keyword_counts.items():
        if required_count <= 0:
            continue
        
        # Count items with this keyword
        count = sum(
            1 for item in items
            if hasattr(item, "keywords") and
            any(keyword.lower() in kw.lower() for kw in item.keywords)
        )
        
        # Input item (e.g. arrows) can satisfy keyword requirements
        if count < required_count and keyword.lower() in input_item_keywords:
            count += 1
        
        if count < required_count:
            return False
    
    # Check tool keyword minimum-skill-level requirements (e.g. a pickaxe that
    # itself requires at least Mining level 60). Enforced in addition to the
    # plain keyword_counts "have a pickaxe" check above.
    if not gearset_meets_keyword_level_requirements(items, activity):
        return False
    
    return True


