def validate_tool_keywords(tools: list, excluded_keywords: Optional[Set[str]] = None) -> bool:
    """
    Validate that tools don't share non-excluded keywords.

    Also enforces "Banned Keyword Groups" where only one item from any keyword
    in the group can be equipped (e.g., Fishing rod/net/cage/spear are mutually exclusive).

    Args:
        tools: List of tool items
        excluded_keywords: Set of keywords that can be shared (e.g., 'tool', 'light source')

    Returns:
        True if valid (no keyword conflicts), False otherwise
    """
    if excluded_keywords is None:
        from util.walkscape_constants import EXCLUDED_TOOL_KEYWORDS
        excluded_keywords = EXCLUDED_TOOL_KEYWORDS

    from util.walkscape_constants import BANNED_KEYWORD_GROUPS

    # Track keywords seen
    seen_keywords = set()
    # Track which banned groups have been used
    used_groups = set()

    for tool in tools:
        if tool is None:
            continue

        if not hasattr(tool, 'keywords'):
            continue

        # Track banned groups this specific tool occupies. A single tool can
        # carry multiple keywords from the same banned group (e.g. Spectral
        # fishing cagespear has both 'Fishing cage' and 'Fishing spear'); it
        # only counts once toward the mutual-exclusion limit.
        tool_groups = set()

        for keyword in tool.keywords:
            keyword_lower = keyword.lower()

            # Skip excluded keywords
            if keyword_lower in excluded_keywords:
                continue

            # Check banned keyword groups
            for i, group in enumerate(BANNED_KEYWORD_GROUPS):
                if keyword_lower in group:
                    if i in used_groups and i not in tool_groups:
                        # Another tool already occupies this banned group
                        return False
                    tool_groups.add(i)
                    break

            # Check for individual keyword conflict
            if keyword_lower in seen_keywords:
                return False

            seen_keywords.add(keyword_lower)

        # After processing this tool's keywords, commit its banned-group usage
        used_groups.update(tool_groups)

    return True

def validate_uuid_uniqueness(items: list, character, allow_ring_duplicates: bool = True) -> bool:
    """
    Validate that items don't exceed owned quantities.
    
    For tools: Each UUID can only be used once (strict uniqueness)
    For rings: Can use same UUID multiple times if owned quantity permits,
               but each specific item object (quality variant) can't exceed its own quantity
    For gear: Each UUID can only be used once (strict uniqueness)
    
    Args:
        items: List of item objects (can include None)
        character: Character object with inventory
        allow_ring_duplicates: If True, allow multiple rings if quantity permits
        
    Returns:
        True if valid (within owned quantities), False otherwise
    """
    # Count UUIDs used and specific item objects used
    uuid_counts = {}
    uuid_to_item = {}  # Track which item each UUID belongs to
    item_identity_counts = {}  # Track specific item objects (by identity) for quality-aware validation
    
    for item in items:
        if item is None:
            continue
        
        if not hasattr(item, 'uuid'):
            continue
        
        uuid = item.uuid
        uuid_counts[uuid] = uuid_counts.get(uuid, 0) + 1
        uuid_to_item[uuid] = item
        
        # Track by item identity (different quality variants are different objects)
        item_id = id(item)
        item_identity_counts[item_id] = item_identity_counts.get(item_id, 0) + 1
    
    # Build UUID cache if not already cached on character (performance optimization)
    if not hasattr(character, '_uuid_cache'):
        character._uuid_cache = {}
        for inv_item, qty in character.items.items():
            if hasattr(inv_item, 'uuid'):
                uuid = inv_item.uuid
                character._uuid_cache[uuid] = character._uuid_cache.get(uuid, 0) + qty
    
    # Check against owned quantities using cache
    for uuid, count_used in uuid_counts.items():
        owned_qty = character._uuid_cache.get(uuid, 0)
        item = uuid_to_item[uuid]
        
        # For tools: strict uniqueness (can only use each UUID once)
        if hasattr(item, 'slot') and item.slot == 'tools':
            if count_used > 1:
                return False
        # For rings: allow duplicates if owned quantity permits
        elif hasattr(item, 'slot') and item.slot == 'ring' and allow_ring_duplicates:
            if count_used > owned_qty:
                return False
        # For all other gear: strict uniqueness (can only use each UUID once)
        else:
            if count_used > 1:
                return False
    
    # Additional check: verify per-item-object counts don't exceed per-object owned quantities
    # This prevents using 2x Excellent when you only own 1 Excellent + 1 Good
    for item in items:
        if item is None or not hasattr(item, 'uuid'):
            continue
        if not (hasattr(item, 'slot') and item.slot == 'ring' and allow_ring_duplicates):
            continue
        
        item_id = id(item)
        count_used = item_identity_counts.get(item_id, 0)
        if count_used <= 1:
            continue
        
        # Check how many of this specific item object the character owns
        item_owned = 0
        for inv_item, qty in character.items.items():
            if inv_item is item:
                item_owned = qty
                break
        
        if count_used > max(item_owned, 1):
            return False
    
    return True

