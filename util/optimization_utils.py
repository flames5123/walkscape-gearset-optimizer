#!/usr/bin/env python3
"""
Shared optimization utilities for gearset optimization.

Provides common functions used across activity, crafting, and travel optimizers
including item filtering, quality ranking, and stat caching.
"""

# Standard library imports
import re
from typing import Dict, List, Optional, Set, Tuple

# ============================================================================
# PET-SKILL-XP PREFERENCE (bug e5145503)
# ============================================================================
#
# Some pets gain XP only while their owner is doing a specific skill
# (e.g. Tiger -> Hunting, Mummy -> Tailoring, Gecko -> Mining,
# Chicken -> Foraging). Players generally want to equip those pets
# whenever they're doing the matching skill so the pet keeps levelling
# up — even if a different pet (e.g. Camel with a tiny global
# +inventory_space stat) would score marginally better on raw metrics.
#
# This module exposes two helpers:
#   * pet_gains_xp_for_skill — checks one pet's
#     `requirement_to_gain_xp` string.
#   * filter_pets_to_skill_xp_relevant — narrows a candidate pool to
#     skill-XP-relevant pets when at least one such (unmaxed) pet is
#     available; otherwise returns the pool unchanged.
#
# Only matches the "While doing <Skill>." pattern. Area-based
# ('While in the Wrentmark area.'), location-based ('While in
# Underwater location.'), and negative ('Not doing Agility.')
# requirements do NOT qualify — those pets earn XP from being
# somewhere/avoiding-something, not from the player's active skill.
#

_PET_XP_SKILL_RE = re.compile(
    r'^\s*while\s+doing\s+([a-z]+)\s*\.?\s*$', re.IGNORECASE
)


def pet_gains_xp_for_skill(pet_info, skill) -> bool:
    """True if ``pet_info`` gains XP from doing the given ``skill``.

    Looks at ``pet_info.requirement_to_gain_xp``. Matches the exact
    "While doing <Skill>." pattern (case-insensitive). All other
    requirement shapes (area, location, negative) return False.

    Both arguments may be None/empty — returns False in those cases
    rather than raising.
    """
    if not pet_info or not skill:
        return False
    req = getattr(pet_info, 'requirement_to_gain_xp', None)
    if not req:
        return False
    m = _PET_XP_SKILL_RE.match(req)
    if not m:
        return False
    return m.group(1).lower() == str(skill).strip().lower()


def _pet_has_global_find_stat(pet_info, find_stats) -> bool:
    """True if ``pet_info`` carries a 'global'-skill-scoped find stat whose
    name is in ``find_stats``.

    Pet stats are nested {skill: {location: {stat: value}}}. A pet whose only
    universally-applicable stat is a global "find" stat (e.g. the Level 4 Mummy
    /Tiger's global +find_collectibles) genuinely boosts the corresponding drop
    category on ANY activity, regardless of the pet's skill specialization.
    """
    if not find_stats:
        return False
    stats = getattr(pet_info, '_stats', None)
    if not isinstance(stats, dict):
        return False
    glob = stats.get('global')
    if not isinstance(glob, dict):
        return False
    for by_loc in glob.values():
        if isinstance(by_loc, dict):
            for stat_name, value in by_loc.items():
                if value and stat_name in find_stats:
                    return True
    return False


def filter_pets_to_skill_xp_relevant(pet_pool, skill, *, pets_by_name=None,
                                     keep_if_global_find_stats=None):
    """Narrow a pet candidate pool to skill-XP-relevant pets when possible.

    If ``skill`` is set and at least one pet in ``pet_pool`` gains XP
    from doing that skill AND is not at max level for its species,
    return the subset of pets meeting both conditions. Otherwise
    return ``pet_pool`` unchanged (as a new list).

    The "not at max level" condition exists because a maxed pet can't
    benefit from extra XP — at that point we let the regular
    stat-based selection take over and pick whatever scores best.

    ``keep_if_global_find_stats`` (bug 2d4f5491): when the optimization is
    targeting a "find" category (e.g. a collectibles report), the skill-XP
    preference must NOT exclude a pet whose global find stat directly boosts
    the target drop. For example, optimizing Alligator hunting → a collectible
    would otherwise narrow the pool to the Tiger (Hunting-XP) and drop the
    Mummy (global +find_collectibles) — even though the Mummy makes the
    collectible drop faster. Any pet carrying a global find stat in this set
    is UNIONED back into the returned pool (never removed), so the optimizer
    scores both and picks whichever is genuinely faster for the target.

    Args:
        pet_pool: iterable of PetInfo instances (the candidates the
            optimizer would otherwise test in the 'pet' slot).
        skill: active skill name (e.g. 'hunting', 'tailoring'). Case
            insensitive.
        pets_by_name: optional override for
            ``util.autogenerated.pets.PETS_BY_NAME``. Tests use this
            to avoid loading the real catalog. If None, the real
            catalog is imported lazily.
        keep_if_global_find_stats: optional set of find-stat names
            (e.g. {'find_collectibles'}) relevant to the current
            optimization target. Pets with a matching global-scoped
            find stat are always retained in the candidate pool.

    Returns:
        A new list. The skill-XP subset (or full pool) plus any
        target-relevant find-stat pets unioned in.
    """
    if not pet_pool:
        return []
    pool = list(pet_pool)
    if not skill:
        return pool

    if pets_by_name is None:
        # Lazy import — keeps util modules loadable without the
        # autogenerated catalog (e.g. for unit tests with mocks).
        from util.autogenerated.pets import PETS_BY_NAME as _PBN
        pets_by_name = _PBN

    relevant = []
    for pet in pool:
        if not pet_gains_xp_for_skill(pet, skill):
            continue
        species_name = getattr(pet, 'name', None)
        if not species_name:
            continue
        pet_levels = pets_by_name.get(species_name)
        if pet_levels is None:
            continue
        try:
            levels = pet_levels._levels
        except AttributeError:
            continue
        if not levels:
            continue
        max_level = max(levels.keys())
        current_level = getattr(pet, 'level', 0) or 0
        if current_level >= max_level:
            # Already maxed — XP preference doesn't apply, fall back
            # to stat-based selection.
            continue
        relevant.append(pet)

    # Base pool: the skill-XP subset when non-empty, else the full pool
    # (the pre-existing behavior).
    base = relevant if relevant else pool

    # Bug 2d4f5491: union in any pet carrying a target-relevant global find
    # stat that the base pool dropped. This never removes candidates — it only
    # re-admits find-stat pets the skill-XP narrowing would otherwise exclude,
    # so the optimizer can still score (and prefer) them for a find-category
    # target like a collectibles report.
    if keep_if_global_find_stats:
        result = list(base)
        for pet in pool:
            if pet in result:
                continue
            if _pet_has_global_find_stat(pet, keep_if_global_find_stats):
                result.append(pet)
        return result

    return base


