# DOMINANCE PRUNING
# ============================================================================

def prune_dominated_items(
    items: list,
    skill: str,
    location,
    character,
    relevant_stats: Set[str]
) -> list:
    """
    Remove items that are strictly dominated by another item in the same slot.
    
    An item A is dominated by item B if:
    - A and B fit the same slot
    - For every stat in relevant_stats, B's value >= A's value
    - For at least one stat, B's value > A's value
    
    This safely removes items that can never be optimal, reducing the search
    space without affecting result quality.
    
    Args:
        items: List of item objects (already filtered for relevance)
        skill: Skill name (e.g., 'smithing')
        location: Location object or None
        character: Character object
        relevant_stats: Set of stat names to compare on
        
    Returns:
        Filtered list with dominated items removed
    """
    if not items or not relevant_stats:
        return items
    
    # Group items by their effective slot (ring1/ring2 → ring, tool0-5 → tools)
    items_by_slot = {}
    for item in items:
        if not hasattr(item, 'slot'):
            continue
        slot = item.slot
        if slot not in items_by_slot:
            items_by_slot[slot] = []
        items_by_slot[slot].append(item)
    
    # Items with set-piece gated stats cannot be fairly compared in isolation
    # (their bonuses only unlock when multiple set pieces are equipped), so
    # protect them from being pruned away. They can still dominate other items.
    # Example: Treasure Hunter Hat has only 1% DR as base stats, so it looks
    # dominated by any other hat, but with 3 pieces equipped it grants +20%
    # find_collectibles — a huge bonus that only the set-aware optimizer will find.
    def _has_set_piece_gates(item):
        gated = getattr(item, 'gated_stats', None)
        return bool(gated) and 'set_pieces' in gated and bool(gated['set_pieces'])
    
    # For each slot group, find dominated items
    dominated = set()
    
    for slot, slot_items in items_by_slot.items():
        if len(slot_items) <= 1:
            continue
        
        # Pre-compute stats for all items in this slot
        item_stats = []
        for item in slot_items:
            stats = item.get_stats_for_skill(skill, location=location, character=character)
            # Extract only relevant stats, normalizing so higher is always better.
            # For stats where lower is better (steps_add, steps_percent), negate the value.
            LOWER_IS_BETTER = {'steps_add', 'steps_percent'}
            relevant = {}
            for s in relevant_stats:
                val = stats.get(s, 0.0)
                if s in LOWER_IS_BETTER:
                    val = -val  # Negate so higher is better
                relevant[s] = val
            item_stats.append((item, relevant))
        
        # Check each pair
        for i, (item_a, stats_a) in enumerate(item_stats):
            if id(item_a) in dominated:
                continue
            
            # Protect items with set-piece gated stats from being pruned away.
            # Their stats in isolation grossly understate their value because
            # set bonuses only activate when multiple pieces are equipped.
            if _has_set_piece_gates(item_a):
                continue
            
            # Number of DISTINCT other items that must dominate item_a before
            # it is safe to prune. The ring slot is filled TWICE (ring1 + ring2),
            # so an item dominated by only ONE other item is still the best
            # available pick for the SECOND ring slot once the dominator occupies
            # the first. Pruning it there is wrong.
            #
            # Bug 28230b27: farming collectibles, Collection ring dominated
            # Gold jade ring (both give find_collectibles, but Collection ring
            # also carries inventory_space + a little fine_material_finding).
            # Gold jade got pruned, Collection ring took ring1, and Fine pearl
            # ring (which survived on its fine_material_finding) was the best
            # remaining candidate for ring2 -- so the optimizer equipped a
            # useless-for-collectibles FMF ring instead of the user's owned
            # find_collectibles ring. A ring is only truly redundant when >= 2
            # OTHER items dominate it (enough to fill both ring slots).
            required_dominators = 2 if slot == 'ring' else 1
            dominator_count = 0

            for j, (item_b, stats_b) in enumerate(item_stats):
                if i == j:
                    continue
                
                # For rings: the same base item at a different quality is NOT a
                # dominator -- you can equip both copies across ring1 + ring2, so
                # a higher-quality variant doesn't make the lower one redundant.
                if slot == 'ring' and hasattr(item_a, 'uuid') and hasattr(item_b, 'uuid'):
                    if item_a.uuid == item_b.uuid:
                        continue
                    # Also check by base name (crafted items at different qualities
                    # may have different UUIDs but same base name)
                    name_a = item_a.name.split(' (')[0] if ' (' in item_a.name else item_a.name
                    name_b = item_b.name.split(' (')[0] if ' (' in item_b.name else item_b.name
                    if name_a == name_b:
                        continue
                
                # Check if item_b dominates item_a
                # B must be >= A on all stats, and > on at least one
                all_geq = True
                any_greater = False
                
                for stat in relevant_stats:
                    val_a = stats_a.get(stat, 0.0)
                    val_b = stats_b.get(stat, 0.0)
                    
                    if val_b < val_a:
                        all_geq = False
                        break
                    if val_b > val_a:
                        any_greater = True
                
                if all_geq and any_greater:
                    dominator_count += 1
                    if dominator_count >= required_dominators:
                        dominated.add(id(item_a))
                        break  # enough dominators -- item_a can be pruned
    
    # Filter out dominated items
    result = [item for item in items if id(item) not in dominated]
    return result


