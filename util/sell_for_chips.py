#!/usr/bin/env python3
"""
Sell for Chips -- pure projection logic.

Given the player's owned item quantities, project how many chips of each type
they would earn by selling loot items to the Mysterious Merchant, and what they
could buy back with those chips (projection only -- see spec G4, v1 does not
track a running balance).

The merchant data comes from util/autogenerated/mysterious_merchant.py:
    CHIP_TYPES[chip_id]         -> {section, display_name, icon_path, items:[slug]}
    ITEM_TO_CHIP_TYPE[slug]     -> chip_id
    CHIP_PRICE_BY_RARITY[tier]  -> (sell_value, buy_price)

`compute_sell_plan` is pure: it takes an `item_lookup` (slug -> item info) so it
can be unit-tested without the full catalog. `build_merchant_item_lookup()` is a
convenience that builds that lookup from the autogenerated Item enum for the API.
"""

from __future__ import annotations

import re

from util.autogenerated import mysterious_merchant as mm

# rarity string -> rarity tier (1..6) used to index CHIP_PRICE_BY_RARITY
RARITY_TO_TIER = {
    "common": 1,
    "uncommon": 2,
    "rare": 3,
    "epic": 4,
    "legendary": 5,
    "ethereal": 6,
}

# The wiki spells the keyword "Upgradeable"; accept the spec's "upgradable" too.
_UPGRADABLE_KEYWORDS = {"upgradeable", "upgradable"}

_SECTION_ORDER = {"skilling": 0, "regional": 1, "guild": 2}
_SECTION_DISPLAY = {
    "skilling": "Skilling Chests",
    "regional": "Regional Chests",
    "guild": "Guild Chests",
}


def _tier(rarity) -> int | None:
    if rarity is None:
        return None
    return RARITY_TO_TIER.get(str(rarity).lower())


def _prices(rarity) -> tuple[int, int] | None:
    """Return (sell_value, buy_price) for an item's rarity, or None if unknown."""
    tier = _tier(rarity)
    if tier is None:
        return None
    return mm.CHIP_PRICE_BY_RARITY.get(tier)


def _is_upgradable(keywords) -> bool:
    return any(str(k).lower() in _UPGRADABLE_KEYWORDS for k in (keywords or []))


def _rarity_sort_key(rarity):
    """Sort by rarity tier ascending (common first), unknown last."""
    return _tier(rarity) or 99


def build_current_chips(currencies):
    """
    Map a character's raw currencies map ({ "<Currency name>": qty }) to
    { chip_id: qty } using the chip display names. Non-chip currencies
    (Coins, tokens, ...) are ignored.
    """
    if not currencies:
        return {}
    # display_name (lowercased) -> chip_id
    name_to_id = {block["display_name"].lower(): chip_id
                  for chip_id, block in mm.CHIP_TYPES.items()}
    out = {}
    for name, qty in currencies.items():
        if not qty:
            continue
        chip_id = name_to_id.get(str(name).strip().lower())
        if chip_id is None:
            # also try the slugified form (e.g. "Agility chip" -> "agility_chip")
            slug = re.sub(r"\s+", "_", str(name).strip().lower())
            chip_id = slug if slug in mm.CHIP_TYPES else None
        if chip_id is not None:
            out[chip_id] = out.get(chip_id, 0) + int(qty)
    return out


def _keep_reservation(slot) -> int:
    """Keep 2 of ring-slot items, 1 of everything else (spec Req 4.3)."""
    return 2 if str(slot).lower() == "ring" else 1


def _decide(qty, slot, keywords, override):
    """
    Decide how many copies to sell/keep for one owned merchant item.

    Precedence (spec Task 4): force_keep > force_sell > upgradable > reservation.
    Returns (sell_qty, keep_qty, reason).
    """
    if override == "force_keep":
        return 0, qty, "force_keep"
    if override == "force_sell":
        return qty, 0, "force_sell"
    if _is_upgradable(keywords):
        return 0, qty, "upgradable"
    reserve = _keep_reservation(slot)
    keep = min(reserve, qty)
    sell = qty - keep
    reason = "ring_pair" if reserve == 2 else "last_copy"
    return sell, keep, reason


def build_merchant_item_lookup():
    """
    Build {slug: {name, rarity, slot, keywords}} for every merchant item from
    the autogenerated Item enum. Used by the API; kept out of compute_sell_plan
    so the core logic stays pure/testable.
    """
    # Imported lazily so unit tests of compute_sell_plan don't need the enum.
    import util.walkscape_constants  # noqa: F401  (resolves circular import order)
    from util.autogenerated.equipment import Item

    lookup = {}
    for slug in mm.ITEM_TO_CHIP_TYPE:
        item = getattr(Item, slug.upper(), None)
        if item is None:
            continue
        lookup[slug] = {
            "name": getattr(item, "name", slug),
            "rarity": getattr(item, "rarity", None),
            "slot": getattr(item, "slot", None),
            "keywords": list(getattr(item, "keywords", []) or []),
        }
    return lookup


def _build_buy_preview(chip_id, pool_total, item_lookup, owned_quantities=None):
    """Build the buy-preview rows for one chip type (all items in the pool)."""
    owned_quantities = owned_quantities or {}
    rows = []
    for slug in mm.CHIP_TYPES[chip_id]["items"]:
        info = item_lookup.get(slug, {})
        prices = _prices(info.get("rarity"))
        if prices is None:
            continue
        _sell, buy_price = prices
        max_affordable = pool_total // buy_price if buy_price > 0 else 0
        shortfall = max(0, buy_price - pool_total)
        rows.append({
            "item_id": slug,
            "name": info.get("name", slug),
            "rarity": info.get("rarity"),
            "buy_price": buy_price,
            "max_affordable": max_affordable,
            "shortfall": shortfall,
            "owned": int(owned_quantities.get(slug, 0) or 0),
            "upgradable": _is_upgradable(info.get("keywords")),
            "is_ring": str(info.get("slot")).lower() == "ring",
        })
    rows.sort(key=lambda r: (r["buy_price"], r["name"]))
    return rows


def compute_sell_plan(owned_quantities, item_lookup, force_overrides=None, current_chips=None):
    """
    Pure projection of merchant chip earnings + buy preview.

    Args:
        owned_quantities: {slug: qty} -- total owned per item (slug = Item enum
            name lowercased, matching character owned_quantities).
        item_lookup: {slug: {name, rarity, slot, keywords}} -- item metadata.
        force_overrides: {slug: 'force_sell' | 'force_keep'} -- user overrides.

    Returns a SellPlan dict:
        {
          "sections": [ {id, display_name, chip_types: [ChipTypeBlock]} ],
          "totals_by_chip": {chip_id: total_chips_earned},
        }
    """
    force_overrides = force_overrides or {}
    current_chips = current_chips or {}

    # chip_id -> accumulating block
    blocks: dict[str, dict] = {}

    def _block(chip_id):
        if chip_id not in blocks:
            ct = mm.CHIP_TYPES[chip_id]
            blocks[chip_id] = {
                "chip_type": chip_id,
                "display_name": ct["display_name"],
                "icon_path": ct["icon_path"],
                "section": ct["section"],
                "selling": [],
                "held_back": [],
                "pool_total": 0,
                "current_owned": int(current_chips.get(chip_id, 0) or 0),
            }
        return blocks[chip_id]

    for slug, qty in owned_quantities.items():
        if not qty or qty <= 0:
            continue
        chip_id = mm.ITEM_TO_CHIP_TYPE.get(slug)
        if chip_id is None:
            continue  # not a merchant loot item -- ignore (spec: not_loot kept silently)
        info = item_lookup.get(slug, {})
        prices = _prices(info.get("rarity"))
        if prices is None:
            continue
        sell_value, _buy = prices

        override = force_overrides.get(slug)
        sell_qty, keep_qty, reason = _decide(
            qty, info.get("slot"), info.get("keywords"), override)

        block = _block(chip_id)
        if sell_qty > 0:
            subtotal = sell_qty * sell_value
            block["selling"].append({
                "item_id": slug,
                "name": info.get("name", slug),
                "rarity": info.get("rarity"),
                "qty": sell_qty,
                "unit_value": sell_value,
                "subtotal": subtotal,
                "owned": qty,
            })
            block["pool_total"] += subtotal
        if keep_qty > 0:
            block["held_back"].append({
                "item_id": slug,
                "name": info.get("name", slug),
                "rarity": info.get("rarity"),
                "qty": keep_qty,
                "reason": reason,
                "owned": qty,
            })

    # Buy preview + ordering
    totals_by_chip = {}
    current_by_chip = {}
    for chip_id, block in blocks.items():
        block["buy_preview"] = _build_buy_preview(chip_id, block["pool_total"], item_lookup, owned_quantities)
        # Order selling + held-back by rarity (common first) then alphabetically.
        block["selling"].sort(key=lambda r: (_rarity_sort_key(r["rarity"]), r["name"]))
        block["held_back"].sort(key=lambda r: (_rarity_sort_key(r["rarity"]), r["name"]))
        totals_by_chip[chip_id] = block["pool_total"]
        if block["current_owned"]:
            current_by_chip[chip_id] = block["current_owned"]

    # Group into sections in skilling/regional/guild order, chips sorted by name
    sections = []
    for sect in ("skilling", "regional", "guild"):
        chip_blocks = [b for b in blocks.values() if b.get("section") == sect]
        if not chip_blocks:
            continue
        chip_blocks.sort(key=lambda b: b["display_name"])
        sections.append({
            "id": sect,
            "display_name": _SECTION_DISPLAY[sect],
            "chip_types": chip_blocks,
        })

    # 'section' was internal bookkeeping -- drop it from the response blocks.
    for b in blocks.values():
        b.pop("section", None)

    return {"sections": sections, "totals_by_chip": totals_by_chip,
            "current_by_chip": current_by_chip}
