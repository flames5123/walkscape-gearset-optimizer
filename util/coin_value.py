def get_drop_coin_value(drop) -> float:
    """Return the coin sell value for a single DropEntry.

    Resolves from drop.item_ref directly (avoids the item_object loader and
    its circular import through util.walkscape_constants).

    Returns 0 when the drop isn't sellable (e.g. Collectibles) or the ref
    can't be resolved.
    """
    if drop.item_ref is None:
        # Coins drop - item_name is 'Coins' (chest valuables table entries)
        if drop.item_name == 'Coins':
            return 1.0
        return 0.0

    try:
        ref = drop.item_ref
        if ref == 'Currency.COIN':
            return 1.0
        if ref.startswith('Container.'):
            return float(CHEST_COIN_VALUES.get(ref, 0))
        if ref.startswith('Material.'):
            from util.autogenerated.materials import Material
            attr_name = ref.split('.', 1)[1]
            if hasattr(Material, attr_name):
                obj = getattr(Material, attr_name)
                return float(obj.value or 0)
        elif ref.startswith('Item.'):
            from util.autogenerated.equipment import Item
            attr_name = ref.split('.', 1)[1]
            if hasattr(Item, attr_name):
                obj = getattr(Item, attr_name)
                return float(obj.value or 0)
        elif ref.startswith('Consumable.'):
            from util.autogenerated.consumables import Consumable
            attr_name = ref.split('.', 1)[1]
            if hasattr(Consumable, attr_name):
                obj = getattr(Consumable, attr_name)
                if hasattr(obj, 'value'):
                    return float(obj.value or 0)
    except Exception:
        pass
    return 0.0


def get_drop_fine_coin_value(drop) -> float:
    """Return the coin sell value of the Fine variant of a drop, or 0."""
    if not drop.item_ref:
        return 0.0
    try:
        if drop.item_ref.startswith('Material.'):
            from util.autogenerated.materials import Material
            fine_name = drop.item_ref.split('.', 1)[1] + '_FINE'
            if hasattr(Material, fine_name):
                return float(getattr(Material, fine_name).value or 0)
        elif drop.item_ref.startswith('Consumable.'):
            from util.autogenerated.consumables import Consumable
            fine_name = drop.item_ref.split('.', 1)[1] + '_FINE'
            if hasattr(Consumable, fine_name):
                return float(getattr(Consumable, fine_name).value or 0)
    except Exception:
        pass
    return 0.0


def is_chest_drop(drop) -> bool:
    """Return True when the drop's item_ref points at a Container.*.

    Used by the 'no_chests' variant of the coins target to strip out all
    chest contributions (both the chest itself and whatever nested
    drops would roll out of it — those never appear in an activity's
    drop table, so it's sufficient to drop Container.* entries).
    """
    return bool(drop.item_ref and drop.item_ref.startswith('Container.'))


