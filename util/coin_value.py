"""
Coin-value helpers used by the optimizer and the UI to:
  - Look up coin_value / fine_coin_value for a single drop entry.
  - Aggregate expected coins/step (and steps/coin) for an activity given a
    stats dict and the drop_rates dict produced by
    Activity.get_expected_drop_rate.

Provides two synthetic targets used by the gearset optimizer:

  - 'cat:coins'           - total coins earned per step, including chests.
  - 'cat:coins_no_chests' - same, but with all Container.* drops excluded.

Chest values for skill chests live in CHEST_COIN_VALUES below. The wiki
publishes "Average Value(Per Chest)" for most skill chests; Hunting and
Tailoring are computed locally via chest_coin_value.py (same 4-roll
formula, plus 1% fine-material bonus).
"""

