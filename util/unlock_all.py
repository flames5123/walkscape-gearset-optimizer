"""Helpers for the optimizer "Unlock all" mode.

When the user enables "Unlock all" in Global Optimization Settings, the optimizer
should treat every item/stat as fully unlocked — every requirement gate
(achievement points, faction reputation, skill levels, %/total skill level,
character level) satisfied, and every AP/level/reputation/total-wealth-gated
stat resolved at its maximum bracket.

Rather than editing the requirement-checking logic (``is_unlocked`` and friends),
we build the optimization character with MAXED gating attributes. Because every
gate is checked against those attributes, maxing them makes every item both
equippable and resolves its gated stats at max. This is intentionally
non-destructive: callers pass a per-run copy of the character config / export;
the stored session is never mutated.

Custom-stat gates (explored realms, one-time activities) are handled separately
by ``util.custom_stats_catalog.apply_all_stats_override`` — "Unlock all" implies
that override too.
"""

from util.walkscape_constants import level_to_xp
from util.autogenerated.skills import SKILLS
from util.autogenerated.factions import FACTIONS

# Skill levels cap at 99 (see stats_mixin's ``len(skills) * 99`` total-level math).
MAX_SKILL_LEVEL = 99
# A value large enough to clear any AP / reputation / total-wealth / steps gate.
_HUGE = 10 ** 12


def _camel(snake: str) -> str:
    parts = str(snake).split('_')
    return parts[0] + ''.join(p.capitalize() for p in parts[1:])


def maxed_skill_xp_map() -> dict:
    """{skill_id: xp-at-level-99} for every skill."""
    xp = level_to_xp(MAX_SKILL_LEVEL)
    return {sid: xp for sid in SKILLS}


def maxed_skill_level_map() -> dict:
    """{skill_id: 99} for every skill (character_config display 'skills')."""
    return {sid: MAX_SKILL_LEVEL for sid in SKILLS}


def maxed_reputation_map() -> dict:
    """A reputation dict that clears every faction gate.

    Requirement + gated-stat checks key reputation by the snake_case faction id
    (e.g. ``halfling_rebels``). We additionally include camelCase and the API
    ``<faction>Reputation`` key so any casing used downstream is covered.
    """
    rep = {}
    for fid, meta in FACTIONS.items():
        for key in (fid, _camel(fid), (meta or {}).get('reputation')):
            if key:
                rep[key] = _HUGE
    return rep


def _apply_common_maxes(out: dict) -> None:
    out['steps'] = max(int(out.get('steps') or 0), _HUGE)
    out['achievement_points'] = _HUGE
    out['coins'] = max(int(out.get('coins') or 0), _HUGE)
    out['reputation'] = {**(out.get('reputation') or {}), **maxed_reputation_map()}


def apply_unlock_all_to_game_export(export, enabled=True):
    """Return a copy of a GAME-EXPORT dict (skills stored as XP) with all gating
    attributes maxed. Used by the worker minimal_export path."""
    if not enabled:
        return export
    out = dict(export or {})
    out['skills'] = {**(out.get('skills') or {}), **maxed_skill_xp_map()}
    _apply_common_maxes(out)
    return out


def apply_unlock_all_to_character_config(cc, enabled=True):
    """Return a copy of a CHARACTER_CONFIG dict (skills_xp = XP, skills = levels)
    with all gating attributes maxed. Used by the crafting-tree path."""
    if not enabled:
        return cc
    out = dict(cc or {})
    out['skills_xp'] = {**(out.get('skills_xp') or {}), **maxed_skill_xp_map()}
    out['skills'] = {**(out.get('skills') or {}), **maxed_skill_level_map()}
    _apply_common_maxes(out)
    return out
