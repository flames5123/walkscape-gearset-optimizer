#!/usr/bin/env python3
"""
Travel route finder using Dijkstra's shortest path algorithm.

Builds a directed graph from RAW_ROUTES and finds the shortest path
(by total distance) between any two locations.
"""

import heapq
from typing import Dict, List, Optional, Tuple

from util.autogenerated.locations import Location, LocationInfo
from util.autogenerated.routes import RAW_ROUTES


# ============================================================================
# GRAPH BUILDING
# ============================================================================

def _build_adjacency_list() -> Dict[str, List[Tuple[str, int, dict]]]:
    """
    Build directed adjacency list from RAW_ROUTES.

    Returns:
        Dict mapping location attr name (lowercase) to list of
        (neighbor_attr_name, distance, route_info) tuples.
    """
    # Build a reverse lookup: LocationInfo -> attr name
    loc_to_attr = {}
    for attr_name in dir(Location):
        if attr_name.startswith('_'):
            continue
        loc = getattr(Location, attr_name)
        if isinstance(loc, LocationInfo):
            loc_to_attr[id(loc)] = attr_name.lower()

    graph = {}
    for (start_loc, end_loc), route_info in RAW_ROUTES.items():
        start_id = loc_to_attr.get(id(start_loc))
        end_id = loc_to_attr.get(id(end_loc))
        if start_id is None or end_id is None:
            continue

        if start_id not in graph:
            graph[start_id] = []
        graph[start_id].append((end_id, route_info['distance'], route_info))

    return graph


# Build once at module load
_GRAPH = _build_adjacency_list()

# Build location name lookup
_LOC_NAMES = {}
_LOC_ICONS = {}
for _attr in dir(Location):
    if _attr.startswith('_'):
        continue
    _loc = getattr(Location, _attr)
    if isinstance(_loc, LocationInfo):
        _LOC_NAMES[_attr.lower()] = _loc.name
        _LOC_ICONS[_attr.lower()] = _loc.icon_name


# ============================================================================
# SHORTEST PATH
# ============================================================================

def find_shortest_path(start_id: str, end_id: str) -> Optional[List[dict]]:
    """
    Find the shortest path between two locations using Dijkstra's algorithm.

    Args:
        start_id: Start location ID (lowercase attr name, e.g. 'kallaheim')
        end_id: End location ID (lowercase attr name, e.g. 'centaham')

    Returns:
        Ordered list of RouteSegment dicts from start to end, or None if
        no path exists. Each segment dict has keys:
            start, start_name, end, end_name, distance, requirements
    """
    if start_id == end_id:
        return []

    if start_id not in _LOC_NAMES or end_id not in _LOC_NAMES:
        return None

    # Dijkstra
    dist = {start_id: 0}
    prev = {}  # node -> (prev_node, edge_info)
    visited = set()
    heap = [(0, start_id)]

    while heap:
        d, node = heapq.heappop(heap)

        if node in visited:
            continue
        visited.add(node)

        if node == end_id:
            break

        for neighbor, edge_dist, route_info in _GRAPH.get(node, []):
            if neighbor in visited:
                continue
            new_dist = d + edge_dist
            if new_dist < dist.get(neighbor, float('inf')):
                dist[neighbor] = new_dist
                prev[neighbor] = (node, route_info)
                heapq.heappush(heap, (new_dist, neighbor))

    # No path found
    if end_id not in prev:
        return None

    # Reconstruct path
    segments = []
    current = end_id
    while current in prev:
        prev_node, route_info = prev[current]
        segments.append({
            'start': prev_node,
            'start_name': _LOC_NAMES[prev_node],
            'start_icon': _LOC_ICONS.get(prev_node),
            'end': current,
            'end_name': _LOC_NAMES[current],
            'end_icon': _LOC_ICONS.get(current),
            'distance': route_info['distance'],
            'requirements': {
                'keyword_counts': route_info.get('keyword_counts', {}),
            },
        })
        current = prev_node

    segments.reverse()
    return segments
