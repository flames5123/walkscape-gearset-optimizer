def _stat_scope_skill(recipe) -> str:
    """Return the skill key used for GEAR/SERVICE/COLLECTIBLE stat scoping.

    Bar-smelting recipes (those in SMELTING_RECIPE_NAMES) are categorized as
    "smithing" but additionally pick up "smelting"-scoped stats — e.g. the
    Tortoise L4 "+2 bonus XP while doing Smelting recipes". Routing them to the
    "smelting" scope makes Skill.SMELTING.matches_skill() include smithing +
    smelting + artisan + global, so they get every smithing-scope stat PLUS the
    smelting ones. All other recipes keep their own skill, so non-smelting
    smithing recipes are unaffected.

    This only changes STAT SCOPING. Skill-level/XP-base logic still keys off
    recipe.skill ("smithing"); Character.get_skill_level() aliases "smelting"
    back to "smithing" so level/WE/QO bonuses stay correct.
    """
    base = (recipe.skill or '').lower() if getattr(recipe, 'skill', None) else ''
    if base == 'smithing':
        try:
            from util.autogenerated.pets import SMELTING_RECIPE_NAMES
            if getattr(recipe, 'name', None) in SMELTING_RECIPE_NAMES:
                return 'smelting'
        except Exception:
            pass
    return base

