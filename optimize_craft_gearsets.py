def _target_item_targets_for_scoring():
    """Collect every unique target_item referenced by SORTING_PRIORITY for
    duplicable target-item metrics (MATERIALS_PER_CHEST, STEPS_PER_CHEST_RECIPE).

    Per-target scoring lets the user distinguish between e.g.
    "Materials per chest" and "Materials per Adventurers' Guild Token"
    in the same sort list, producing different gearset choices for each.
    Without this, every target_item entry fell back to the bare
    `materials_per_chest` score (chest_finding only), making it
    impossible to optimize for IF-category drops like AGT or bird nests.

    Yields:
        target strings such as 'cat:chests', 'cat:if:adventurers_guild_tokens',
        deduplicated in priority order. Covers both MATERIALS_PER_CHEST
        and STEPS_PER_CHEST_RECIPE (which share the same per-target
        finding stat — the only difference is whether we score materials
        or steps per drop).
    """
    from util.walkscape_constants import Sorting
    seen = set()
    target_enums = (Sorting.MATERIALS_PER_CHEST, Sorting.STEPS_PER_CHEST_RECIPE)
    for raw in SORTING_PRIORITY:
        if not isinstance(raw, SortingEntry):
            continue
        if raw.sort not in target_enums:
            continue
        if not raw.target:
            continue
        if raw.target in seen:
            continue
        seen.add(raw.target)
        yield raw.target


# IF category → gearset stat key. Each IF "cat:if:<snake>" target maps
# to an `ItemFindingCategory.<UPPER>` stat value aggregated from gear,
# collectibles, and consumables. The stat is a direct drop-rate bonus in
# percent points (e.g. `ItemFindingCategory.ADVENTURERS_GUILD_TOKENS` = 1.0
# means +1% chance per reward roll).
#
# The snake → UPPER conversion is deterministic (toUpper + keep underscores)
# so we don't need to enumerate every category here; the scorer just
# calls `_if_category_stat_key(target)`.
def _if_category_stat_key(target: str) -> Optional[str]:
    """Extract the ItemFindingCategory stat key for a cat:if:* target.

    Returns None for non-IF targets. Strips '_fine' suffix since fine
    variants use the same category stat on gear, just with a fine
    material modifier applied at roll time.
    """
    if not isinstance(target, str) or not target.startswith('cat:if:'):
        return None
    cat = target[len('cat:if:'):]
    if cat.endswith('_fine'):
        cat = cat[:-len('_fine')]
    return f'ItemFindingCategory.{cat.upper()}'


def _compute_materials_per_target_item(target, materials_per_craft,
                                       chest_rate_with_bonus, double_rewards,
                                       total_stats, recipe=None):
    """Compute materials-per-target-item for a specific `target` string.

    `target` is the UI-level category value attached to a
    MATERIALS_PER_CHEST SortingEntry — e.g. 'cat:chests',
    'cat:if:adventurers_guild_tokens'. Each category is scored using the
    corresponding finding stat on the aggregated gearset:

      - cat:chests:              chest_finding
      - cat:collectibles:        find_collectibles (0.1% base rate)
      - cat:fine:                fine_material_finding (1% base rate)
      - cat:if:<snake>:          ItemFindingCategory.<UPPER> (0.5% base rate)
      - cat:if:<snake>_fine:     ItemFindingCategory.<UPPER> × fine_material_finding

    Returns the materials consumed per 1 target-item drop. Higher finding
    stats → fewer materials per drop (better). For unknown / unresolved
    targets, falls back to the bare chest formula so the scorer remains
    valid.

    NOTE on DR: `materials_per_craft` already has (1+DR) factored in
    (materials_per_craft = (1-NMC)/(1+DR), i.e. materials per PRIMARY
    ITEM produced). Drops from finding stats scale with reward rolls,
    which is also (1+DR) — so the rolls' (1+DR) CANCELS materials' (1+DR).
    Correct formula per the Walkscape wiki (Double Rewards Mechanics):

      chests per action   = chest_rate × (1+DR)
      materials per action = (1-NMC)
      materials per chest  = (1-NMC) / (chest_rate × (1+DR))

    And materials_per_craft / chest_rate = ((1-NMC)/(1+DR)) / chest_rate
                                         = (1-NMC) / (chest_rate × (1+DR))

    So we divide by `eff_rate` alone — NOT by `eff_rate × (1+DR)`. The
    earlier `× (1+DR)` factor double-counted DR and biased the optimizer
    toward high-DR gear (e.g. Journeyman Perfect over Merfolk) in the
    steps_per_chest_recipe composition below (since steps_per_craft
    already has /(1+DR) built in).
    """
    if not isinstance(target, str):
        return materials_per_craft / chest_rate_with_bonus if chest_rate_with_bonus > 0 else 999999.0

    # Chest targets — identical to the bare metric.
    if target == 'cat:chests':
        eff_rate = chest_rate_with_bonus
    elif target == 'cat:collectibles':
        # Collectibles have a tiny base rate (~0.1%).
        fc = total_stats.get('find_collectibles', 0.0) if total_stats else 0.0
        eff_rate = 0.001 * (1 + fc)
    elif target == 'cat:fine':
        # Fine material drop baseline ≈ 1% × (1 + FMF).
        fmf = total_stats.get('fine_material_finding', 0.0) if total_stats else 0.0
        eff_rate = 0.01 * (1 + fmf)
    elif target.startswith('cat:if:'):
        # Item Finding category drops — e.g. Adventurers' Guild Tokens,
        # bird nests, ectoplasm, random gem.
        #
        # The ItemFindingCategory.<CAT> stat value (in percent) is the
        # drop chance DIRECTLY — not a multiplicative bonus on top of
        # some base rate. Adventuring amulet with
        # `ItemFindingCategory.ADVENTURERS_GUILD_TOKENS: 1.0` gives
        # +1% chance per craft for an AGT. total_stats already sums the
        # stat across all equipped gear, so:
        #   eff_rate = total_stats[stat_key] / 100
        # No base rate, no chest_finding multiplier. The game's own
        # CategoryInstance.expand_with_chance (util/autogenerated/item_finding.py
        # line 25) confirms this: `actual_chance = base_chance * (drop.chance_percent / 100.0)`
        # where `base_chance` IS the summed stat value.
        #
        # Double-rewards still applies (an RNG roll that doubles the
        # output on success). fine_material_finding layers on top only
        # for `_fine` targets.
        stat_key = _if_category_stat_key(target)
        if_stat_percent = total_stats.get(stat_key, 0.0) if stat_key else 0.0
        eff_rate = if_stat_percent / 100.0
        if target.endswith('_fine'):
            fmf = total_stats.get('fine_material_finding', 0.0) if total_stats else 0.0
            eff_rate = eff_rate * (1 + fmf)
    elif target in ('cat:coins', 'cat:coins_no_chests'):
        # Coin aggregate targets: eff_rate = expected coins per craft,
        # so materials_per_coin = materials_per_craft / coins_per_craft
        # and steps_per_coin = steps_per_craft / coins_per_craft.
        # Value is stashed in total_stats by the caller (see
        # calculate_craft_metrics) before this function is invoked.
        coin_key = '_coins_per_craft_with_chests' if target == 'cat:coins' \
                   else '_coins_per_craft_no_chests'
        eff_rate = float((total_stats or {}).get(coin_key, 0.0) or 0.0)
    elif target == 'cat:sea_shells':
        # Sea shell aggregate target — same shape as cat:coins.
        # eff_rate = expected sea shells per craft, computed by
        # util/shell_value.compute_shells_per_craft_for_recipe and
        # stashed in total_stats by the caller.
        eff_rate = float((total_stats or {}).get('_shells_per_craft', 0.0) or 0.0)
    elif target.startswith('cat:drop:'):
        # Recipe drop_table entries (Additional Recipe Outputs on the
        # wiki) — e.g. Silver Nugget from bar smelting. Unlike cat:if:*
        # these drops have a fixed per-roll chance in the recipe's
        # drop_table and aren't gated by an ItemFindingCategory stat.
        #
        # Expected drops per craft action:
        #     rolls × (chance_percent / 100) × qty
        # where `rolls` is multi_roll_count (defaults to 1 for single-
        # roll drops) and chance_percent is ALREADY per-roll (inverted
        # from the wiki's compound "at least one drop" chance by the
        # scraper — see scrape_recipes.parse_additional_recipe_outputs).
        #
        # For _fine variants, the fine rate baseline is 1% × (1 + FMF)
        # of the base drop (mirrors the cat:fine and drops-section.js
        # recipe-path conventions).
        #
        # DR cancels out the same way as in the cat:chests branch —
        # mats_per_craft already has /(1+DR), and reward rolls scale
        # by (1+DR). See the DR-cancellation note in the docstring.
        DROP_CATEGORY_ITEM_REFS = {
            'cat:drop:silver_nugget': 'Material.SILVER_NUGGET',
            'cat:drop:silver_nugget_fine': 'Material.SILVER_NUGGET',
        }
        item_ref = DROP_CATEGORY_ITEM_REFS.get(target)
        eff_rate = 0.0
        if item_ref and recipe is not None and recipe.drop_table:
            for drop in recipe.drop_table:
                if not drop or drop.get('item_ref') != item_ref:
                    continue
                per_roll = (drop.get('chance_percent', 0.0) or 0.0) / 100.0
                rolls = drop.get('multi_roll_count') or 1
                qty = drop.get('quantity') or 1
                eff_rate = rolls * per_roll * qty
                if target.endswith('_fine'):
                    fmf = total_stats.get('fine_material_finding', 0.0) if total_stats else 0.0
                    eff_rate = eff_rate * 0.01 * (1 + fmf)
                break
        # If the item isn't in this recipe's drop_table, eff_rate stays
        # 0 → fallback below returns 999999.0 → the UI's NA-in-yellow
        # path already gates the UI side, so this just means a selected
        # but unavailable target scores as "never" (big number).
    else:
        # Unknown — fall back to chest finding.
        eff_rate = chest_rate_with_bonus

    if eff_rate <= 0:
        return 999999.0
    return materials_per_craft / eff_rate


def _quality_targets_for_scoring():
    """Collect every unique target quality referenced by SORTING_PRIORITY.
    
    Duplicable crafting metrics (materials_for_target / steps_for_target /
    total_crafts) can appear multiple times in the priority list with
    different target qualities (e.g. "minimize materials for Perfect"
    then "minimize materials for Great" as a tiebreaker). Each gets a
    composite key so the comparator can see them independently.
    
    Sources (in order):
      1. Each SortingEntry in SORTING_PRIORITY whose enum is one of the
         quality-targeted metrics and that carries a target quality.
      2. The legacy module-level TARGET_QUALITY (used by the CLI and by
         worker paths that still set a single headline quality).
    
    Yields quality strings (e.g. 'Perfect', 'Great') in priority order,
    deduplicated.
    """
    QUALITY_METRIC_KEYS = {'materials_for_target', 'steps_for_target', 'total_crafts'}
    seen = set()
    
    for raw in SORTING_PRIORITY:
        if not isinstance(raw, SortingEntry):
            continue
        if raw.sort.metric_key not in QUALITY_METRIC_KEYS:
            continue
        if not raw.target:
            continue
        if raw.target in seen:
            continue
        seen.add(raw.target)
        yield raw.target
    
    # Legacy CLI fallback
    if TARGET_QUALITY and TARGET_QUALITY not in seen:
        seen.add(TARGET_QUALITY)
        yield TARGET_QUALITY


def calculate_craft_metrics(
    gearset_dict: dict,
    recipe,
    service,
    character,
    target_quality: str,
    target_quantity: int,
    consumable=None,
    budget_materials: int = 0,
    budget_target: int = 0
) -> Tuple[Dict[str, float], Dict[str, float]]:
    """
    Calculate all metrics for a crafting gearset (like activity optimizer pattern).
    
    Per-quality evaluation: materials_for_target, steps_for_target, and
    total_crafts are computed for every quality referenced by
    SORTING_PRIORITY (plus the legacy `target_quality` parameter for
    display / CLI compatibility). Each quality's values are stored at
    composite keys like "materials_for_target::Great" so that duplicable
    priority entries with different target qualities can be compared
    independently. The FIRST quality evaluated also gets written to the
    bare keys so old callers and display code keep working unchanged.
    
    Args:
        target_quality: The legacy "headline" quality for the CLI and
            display. When SORTING_PRIORITY contains no quality-targeted
            SortingEntry values, this is the only quality evaluated.
    
    Returns:
        Tuple of (metrics_dict, stats_dict)
    """
    # Get all items including consumable.
    #
    # Bug 3bb938f4: "Optimize for consumables" did nothing on crafting tree
    # nodes because the worker sets CONSUMABLE_ITEMS / INCLUDE_CONSUMABLES on
    # this module, but optimize_for_service used to call us with a fixed
    # consumable=None and never iterate. The new consumable greedy pass in
    # optimize_for_service picks a winner and stows it on
    # gearset_dict['consumable']; we honour that here so the chosen
    # consumable's stats are baked into the score for both the greedy pass
    # and subsequent local search. Mirrors the activity optimizer pattern in
    # optimize_activity_gearsets.calculate_gearset_metrics.
    #
    # The 'consumable' slot is excluded from the gear-items list so we don't
    # double-count it (it's added explicitly below).
    items = [
        item for slot, item in gearset_dict.items()
        if item is not None and slot != 'consumable'
    ]
    if consumable is None:
        consumable = gearset_dict.get('consumable')
    if consumable:
        items.append(consumable)
    
    # Aggregate stats
    skill = _stat_scope_skill(recipe)
    location = service.location if service else SELECTED_LOCATION
    
    total_stats = aggregate_gearset_stats(
        items=items,
        skill=skill,
        location=location,
        character=character,
        include_level_bonus=True,
        include_collectibles=True, 
        activity_level=recipe.level
    )
    
    # Instant-actions mode: zero out step-influencing stats before scoring.
    # WE, flat steps, and pct steps are irrelevant when actions complete instantly.
    # DA, DR, NMC, QO and all other non-step stats are preserved.
    if INSTANT_ACTIONS:
        total_stats = dict(total_stats)  # shallow copy — don't mutate original
        total_stats['work_efficiency'] = 0.0
        total_stats['steps_add'] = 0
        total_stats['steps_percent'] = 0.0
    
    # Add service stats
    if service:
        service_stats = service.get_stats_for_skill(
            skill=skill,
            location=location,
            character=character
        )
        for stat_name, stat_value in service_stats.items():
            total_stats[stat_name] = total_stats.get(stat_name, 0.0) + stat_value
    
    # Calculate crafting metrics using total_stats
    metrics = calculate_crafting_metrics(
        base_steps=recipe.base_steps,
        base_xp=recipe.base_xp,
        max_efficiency=recipe.max_efficiency,
        total_stats=total_stats
    )

    # ------------------------------------------------------------------
    # Item-Finding bonus on the recipe target output (bug af9d3e86 +
    # 79ec57d9 / 2026-05-31). When the recipe's `output_item` is an item
    # that an `ItemFindingCategory.X` stat ALSO drops (e.g. Spectral gear
    # / Ghost trap pack drop Material.ECTOPLASM via
    # `ItemFindingCategory.ECTOPLASM` while at a `ghostly` location),
    # those bonus drops are extra "free" target items per craft. The
    # optimizer was ignoring them, so on `Weave into ectoplasm`
    # Backpack (0 useful stats) tied / beat Ghost trap pack (+5%
    # ItemFindingCategory.ECTOPLASM). Fix: scale `expected_steps_per_item`
    # by `output_qty / (output_qty + if_target_bonus_per_roll)` — every
    # downstream metric (`steps_for_target::Q`, `total_tree_steps_for_target`,
    # `steps_for_budget`) reads the scaled value, so all sort axes credit
    # the bonus consistently.
    #
    # Math (bonus is "fractional drops of target_ref per reward roll"):
    #   per cycle: items = (output_qty + bonus) * (1+DA) * (1+DR)
    #   steps_per_item = current_steps / [(1+DA)*(1+DR)*(output_qty+bonus)]
    #                  = expected_steps_per_item * output_qty / (output_qty + bonus)
    # The constant `output_qty` factor cancels across all gearsets so
    # ranking is unchanged for recipes WITHOUT a matching IF stat.
    _output_item_ref = str(getattr(recipe, 'output_item', '') or '')
    _output_qty_for_if = max(1.0, float(getattr(recipe, 'quantity', 1) or 1))
    if _output_item_ref:
        from util.item_utils import if_target_bonus_per_roll as _if_bonus
        _if_bonus_per_roll = _if_bonus(total_stats, _output_item_ref)
        if _if_bonus_per_roll > 0:
            _bonus_factor = _output_qty_for_if / (_output_qty_for_if + _if_bonus_per_roll)
            metrics['expected_steps_per_item'] *= _bonus_factor
            # Stash for any caller that wants to introspect the credit
            # (logging / debug). Doesn't change scoring.
            metrics['_if_target_bonus_per_roll'] = _if_bonus_per_roll
            metrics['_if_target_bonus_factor'] = _bonus_factor

    # The IF target-bonus factor also has to be applied to the per-target
    # MATERIALS and TOTAL_CRAFTS metrics below — not just steps. The IF
    # drops are extra copies of the target item per craft, so they cut the
    # number of crafts (and thus the materials) needed per target item by
    # the same factor. `expected_steps_per_item` was already scaled above,
    # so `steps_for_target` (derived from it) already credits IF; without
    # scaling here, `materials_for_target` / `total_crafts` did NOT, so a
    # recipe tree node sorting on materials or crafts scored IF gear (e.g.
    # Ghost trap pack / ItemFindingCategory.ECTOPLASM on "Cut into
    # ectoplasm") identically to a neutral inventory backpack and never
    # picked it. Defaults to 1.0 when the gearset has no matching IF stat,
    # so recipes without IF gear are unaffected.
    _if_bonus_factor = metrics.get('_if_target_bonus_factor', 1.0)

    # Quality outcome is shared across all target qualities (depends only
    # on recipe level + QO stat).
    quality_weights = calculate_quality_weights(recipe.level, total_stats.get('quality_outcome', 0.0))
    metrics['perfect_percentage'] = quality_weights['percentages'].get('Perfect', 0.0)
    
    # Collect the set of qualities to evaluate. Always include the
    # headline target_quality first so the bare keys get a value even
    # when SORTING_PRIORITY is empty.
    qualities_to_score = []
    seen_qualities = set()
    # Start with the legacy headline quality (for CLI / display)
    if target_quality and target_quality not in seen_qualities:
        qualities_to_score.append(target_quality)
        seen_qualities.add(target_quality)
    # Then every quality referenced by the priority list
    for q in _quality_targets_for_scoring():
        if q not in seen_qualities:
            qualities_to_score.append(q)
            seen_qualities.add(q)
    
    # Compute per-quality metrics at composite keys.
    first_quality = True
    # Tree-aware downstream cost setup. CHILD_INPUT_SPECS is a list of
    # {item_ref, req_amount, child_steps_per_item}. The downstream cost
    # depends on the gearset's NMC / DR / quality_pct_Q, so it has to be
    # computed inside this per-quality loop. See module docstring on
    # CHILD_INPUT_SPECS for the formula derivation.
    _child_input_specs = CHILD_INPUT_SPECS or []
    _has_tree_inputs = bool(_child_input_specs)
    if _has_tree_inputs:
        _NMC_total = total_stats.get('no_materials_consumed', 0.0)
        _DR_total = total_stats.get('double_rewards', 0.0)
        _output_qty = max(1.0, float(getattr(recipe, 'quantity', 1) or 1))

    # Bug dbd467bd-d35 (COFA on elderhide leather): non-quality recipes
    # (Material / Consumable outputs) don't have in-game quality tiers —
    # every craft produces target_quantity outputs, period. The
    # quality_weights['percentages'] returned by calculate_quality_weights
    # is computed from QO + recipe_level and gives e.g. ~72% for "Normal"
    # on a level-50 recipe (not 100%). Using that percentage to scale
    # q_expected_crafts and quality_prob makes the optimizer think non-
    # quality recipes need 1/0.72 ≈ 1.39 crafts per output, which:
    #   (a) inflates q_total_steps for the local recipe (proportional
    #       inflation across all gearsets — doesn't change ranking by
    #       itself), and
    #   (b) inflates the tree-aware downstream cost by 1/quality_prob
    #       AND penalizes gear with QO (because QO shifts the
    #       distribution toward higher quality tiers, LOWERING the
    #       Normal-tier percentage and INCREASING q_expected_crafts).
    # The actual tree calculator (ui/crafting_tree.calculate_node_metrics)
    # uses quality_prob = 1.0 for non-root nodes, so the optimizer's
    # TOTAL_TREE_STEPS metric was disagreeing with the real tree total.
    # On the user's tree, COFA (WE+20%, steps_add -5, QO+20) actually
    # gave LOWER total tree steps (146.55 per leather) than Coral cape
    # (NMC+3, 148.64 per leather) under the real formula, but the
    # optimizer's mis-scaled formula scored Coral 206.52 < COFA 210.77
    # and picked Coral. Detect non-quality recipes and override the
    # target_percentage to 100 (effectively quality_prob=1.0) so the
    # formula matches the actual tree rollup.
    _output_ref = str(getattr(recipe, 'output_item', '') or '')
    _is_non_quality_recipe = not _output_ref.startswith('Item.')

    for q in qualities_to_score:
        if _is_non_quality_recipe:
            # No quality variation — every craft = 1 output set at "Normal".
            # Override regardless of which q label is being scored so that
            # bare keys (`steps_for_target`, `total_tree_steps_for_target`)
            # populated from the headline q also use 1.0.
            target_percentage = 100.0
        else:
            target_percentage = quality_weights['percentages'].get(q, 0.0)
        if target_percentage <= 0:
            q_expected_crafts = float('inf')
            q_total_materials = float('inf')
            q_total_steps = float('inf')
        else:
            # Use raw expected crafts (no math.ceil) so the optimizer's score
            # matches the UI's swap-metric label in column-2 popups, which
            # uses `100.0 / targetPct` without ceiling (item-selection-popup.js
            # _computeMetricFromStats). Ceiling here creates step-function
            # discontinuities in materials_for_target / total_crafts: a swap
            # that genuinely improves quality_outcome (raw crafts 143.99 ->
            # 141.06) can ROUND UP differently (144 vs 142), and when paired
            # with a small materials_per_craft increase from losing NMC, the
            # ceiled mat_for_target jumps WORSE while the raw value is BETTER.
            # Bug 37fd9e90 (2026-05-22 oranges): user's UI showed ethernite
            # ring (Good) lowering mat/perfect from 77.6 -> 77.5 (raw), but
            # the optimizer scored it 77.57 -> 78.07 (ceil) and refused the
            # swap. The optimizer must use the same monotonic raw value the
            # UI shows so its picks line up with what the user sees.
            q_expected_crafts = (100.0 / target_percentage) * target_quantity
            q_total_materials = metrics['materials_per_craft'] * q_expected_crafts
            q_total_steps = metrics['expected_steps_per_item'] * q_expected_crafts
            # Credit the IF target bonus on the MATERIALS and CRAFTS metrics.
            # `expected_steps_per_item` was already IF-scaled before this
            # loop, so `q_total_steps` (computed just above from the UNSCALED
            # `q_expected_crafts`) already credits IF exactly once — do NOT
            # re-scale it here. Only `materials_for_target` and `total_crafts`
            # still need the factor. `materials_per_craft` (per craft action)
            # is intentionally left unscaled: IF adds free target items, it
            # does not change how much material a single craft consumes.
            q_total_materials *= _if_bonus_factor
            q_expected_crafts *= _if_bonus_factor
        
        metrics[f'materials_for_target::{q}'] = q_total_materials
        metrics[f'steps_for_target::{q}'] = q_total_steps
        metrics[f'total_crafts::{q}'] = q_expected_crafts

        # Tree-aware total: recipe steps PLUS downstream cost of producing
        # the input materials at this quality. Mirrors the rollup formula
        # in ui.crafting_tree.calculate_node_metrics:
        #   input_ratio = (req_amount × (1-NMC)) / (output_qty × (1+DR) × quality_pct)
        #   downstream_per_target = sum(input_ratio × child_steps_per_item)
        # then total_tree_steps = q_total_steps + downstream_per_target × target_quantity.
        if _has_tree_inputs:
            if target_percentage <= 0:
                metrics[f'total_tree_steps_for_target::{q}'] = float('inf')
            else:
                _quality_prob = target_percentage / 100.0  # quality_weights stores percentages
                _denom = _output_qty * (1.0 + _DR_total) * _quality_prob
                if _denom <= 0:
                    metrics[f'total_tree_steps_for_target::{q}'] = float('inf')
                else:
                    _downstream_per_target = 0.0
                    for _spec in _child_input_specs:
                        _req = float(_spec.get('req_amount', 0) or 0)
                        _cost = float(_spec.get('child_steps_per_item', 0) or 0)
                        if _req <= 0 or _cost <= 0:
                            continue
                        _input_ratio = (_req * (1.0 - _NMC_total)) / _denom
                        _downstream_per_target += _input_ratio * _cost
                    _downstream_total = _downstream_per_target * target_quantity
                    metrics[f'total_tree_steps_for_target::{q}'] = q_total_steps + _downstream_total
        else:
            # Fallback: when no children are wired in (single-recipe / non-
            # tree callers), tree-aware metric just mirrors steps_for_target
            # so a sort priority of TOTAL_TREE_STEPS still produces a valid
            # ranking — it just degenerates to TOTAL_STEPS.
            metrics[f'total_tree_steps_for_target::{q}'] = q_total_steps

        if first_quality:
            # Headline values — consumed by display code and any legacy
            # callers that read the bare keys directly.
            metrics['materials_for_target'] = q_total_materials
            metrics['steps_for_target'] = q_total_steps
            metrics['total_crafts'] = q_expected_crafts
            metrics['total_tree_steps_for_target'] = metrics[f'total_tree_steps_for_target::{q}']
            first_quality = False

    # Per-target materials_per_target_item composite keys.
    # The bare `materials_per_chest` key was already written by
    # calculate_crafting_metrics (chest_finding only). Here we add
    # target-specific variants so users can sort for different IF
    # categories (AGT, bird nests, ectoplasm, etc.) and get gearsets
    # actually tailored to that drop source.
    #
    # Without these composite keys, every `Materials / Target item` entry
    # — regardless of the chosen IF category — scored the same (chest
    # finding). SortingEntry.metric_key produces the composite key we
    # read here; the optimizer's lookup helpers already fall back to the
    # bare key when a composite isn't present, so untargeted or unknown
    # targets keep working.
    chest_finding = total_stats.get('chest_finding', 0.0) if total_stats else 0.0
    base_chest_rate = 0.004
    chest_rate_with_bonus = base_chest_rate * (1 + chest_finding)
    mats_per_craft = metrics['materials_per_craft']
    steps_per_craft = metrics['expected_steps_per_item']

    # Precompute expected coins per craft for the two coin targets.
    # Stashed back into total_stats as private keys so
    # _compute_materials_per_target_item can read them without a
    # signature change. Covers:
    #   - primary output (quality-weighted for equipment)
    #   - side drops (e.g. Silver nugget on smelting bars)
    #   - chest drops × (1 + chest_finding) — only for the with-chests variant
    try:
        from util.coin_value import compute_coins_per_craft_for_recipe
        _coin_targets_seen = {
            raw.target for raw in SORTING_PRIORITY
            if isinstance(raw, SortingEntry)
            and raw.sort in (Sorting.MATERIALS_PER_CHEST, Sorting.STEPS_PER_CHEST_RECIPE)
            and raw.target in ('cat:coins', 'cat:coins_no_chests')
        }
        if _coin_targets_seen:
            _coin_per_craft = compute_coins_per_craft_for_recipe(
                recipe, quality_weights.get('percentages', {}), total_stats
            )
            if total_stats is not None:
                total_stats['_coins_per_craft_with_chests'] = _coin_per_craft['with_chests']
                total_stats['_coins_per_craft_no_chests'] = _coin_per_craft['no_chests']
    except Exception:
        # Coins scoring is best-effort — fall through on any issue so the
        # rest of the metrics still populate cleanly.
        pass

    # 2026-05-31: same pattern for sea shells. compute_shells_per_craft_for_recipe
    # rolls up shell-bearing chest drops (Coral/Sunken/Chest of Syrenthia
    # via CHEST_SHELL_VALUES, modulated by chest_finding) plus any direct
    # Sea shell side drops in the recipe's drop_table. Almost no recipes
    # produce sea shells so the shell target rarely fires here, but the
    # symmetry with coins keeps the scoring contract uniform.
    try:
        from util.shell_value import compute_shells_per_craft_for_recipe
        _shell_targets_seen = any(
            isinstance(raw, SortingEntry)
            and raw.sort in (Sorting.MATERIALS_PER_CHEST, Sorting.STEPS_PER_CHEST_RECIPE)
            and raw.target == 'cat:sea_shells'
            for raw in SORTING_PRIORITY
        )
        if _shell_targets_seen:
            _shells_per_craft = compute_shells_per_craft_for_recipe(recipe, total_stats)
            if total_stats is not None:
                total_stats['_shells_per_craft'] = _shells_per_craft
    except Exception:
        pass
    
    # Expose key aggregated stats in the metrics dict so debug logs
    # elsewhere can see what the scorer actually used. These are NOT
    # read by any sorting logic — purely diagnostic.
    if total_stats is not None:
        metrics['chest_finding_total'] = total_stats.get('chest_finding', 0.0)
        metrics['work_efficiency_total'] = total_stats.get('work_efficiency', 0.0)
        metrics['double_rewards_total'] = total_stats.get('double_rewards', 0.0)
        metrics['double_action_total'] = total_stats.get('double_action', 0.0)
        metrics['no_materials_consumed_total'] = total_stats.get('no_materials_consumed', 0.0)
        metrics['steps_add_total'] = total_stats.get('steps_add', 0.0)
        metrics['steps_percent_total'] = total_stats.get('steps_percent', 0.0)
        metrics['chest_rate_with_bonus'] = chest_rate_with_bonus
        metrics['work_efficiency_cap'] = recipe.max_efficiency
        # "Effective" WE is what actually enters the formula (capped)
        metrics['work_efficiency_used'] = min(total_stats.get('work_efficiency', 0.0), recipe.max_efficiency)
    
    for target in _target_item_targets_for_scoring():
        m_per_chest = _compute_materials_per_target_item(
            target=target,
            materials_per_craft=mats_per_craft,
            chest_rate_with_bonus=chest_rate_with_bonus,
            double_rewards=total_stats.get('double_rewards', 0.0) if total_stats else 0.0,
            total_stats=total_stats,
            recipe=recipe,
        )
        metrics[f'materials_per_chest::{target}'] = m_per_chest
        # Steps per target item = (steps per craft) × (crafts per target item)
        # = steps_per_craft × (m_per_chest / mats_per_craft)
        # Fall back to a huge sentinel when mats_per_craft is 0 so the
        # comparator still works without division-by-zero.
        if mats_per_craft > 0 and m_per_chest < 999999.0:
            metrics[f'steps_per_chest_recipe::{target}'] = steps_per_craft * (m_per_chest / mats_per_craft)
        else:
            metrics[f'steps_per_chest_recipe::{target}'] = 999999.0
    # Bare steps_per_chest_recipe key (fallback when no target specified)
    # uses the chest_finding path so untargeted entries still score.
    # NOTE: same DR-cancellation as in _compute_materials_per_target_item —
    # steps_per_craft (= expected_steps_per_item) already has /(1+DR), and
    # reward rolls scale by (1+DR), so the two cancel. Don't multiply by
    # (1+DR) here or we double-count DR and bias toward high-DR gear.
    if mats_per_craft > 0:
        bare_m_per_chest = mats_per_craft / max(chest_rate_with_bonus, 1e-9)
        metrics['steps_per_chest_recipe'] = steps_per_craft * (bare_m_per_chest / mats_per_craft)
    else:
        metrics['steps_per_chest_recipe'] = 999999.0

    # Budget metric: steps to produce target items from limited materials
    if budget_materials > 0 and budget_target > 0:
        # How many crafts can we do with our material budget?
        # Each recipe uses N base materials per craft, reduced by DR/NMC
        base_materials_per_recipe = sum(qty for group in recipe.materials for qty, _ in group)
        actual_materials_per_craft = base_materials_per_recipe * metrics['materials_per_craft']
        max_crafts_from_budget = budget_materials / actual_materials_per_craft if actual_materials_per_craft > 0 else 0
        
        if max_crafts_from_budget >= budget_target:
            # We have enough materials — steps = target * steps_per_item
            metrics['steps_for_budget'] = budget_target * metrics['expected_steps_per_item']
        else:
            # Not enough materials — impossible, use a very high value
            metrics['steps_for_budget'] = float('inf')
    else:
        metrics['steps_for_budget'] = float('inf')
    
    return metrics, total_stats

