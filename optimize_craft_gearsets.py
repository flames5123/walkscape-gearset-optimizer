def _item_matches_debug(item):
    """True if item's name contains any debug-tagged substring."""
    if not item or not DEBUG_ITEM_NAMES:
        return False
    name = getattr(item, 'name', '').lower()
    return any(tag in name for tag in DEBUG_ITEM_NAMES)

def _gearset_has_debug_item(gearset):
    """True if any slot in gearset holds a debug-tagged item."""
    if not DEBUG_ITEM_NAMES:
        return False
    for item in gearset.values():
        if _item_matches_debug(item):
            return True
    return False

