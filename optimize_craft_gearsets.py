# ============================================================================
# TREE-AWARE OPTIMIZATION
# ============================================================================
# When a recipe is being optimized as part of a crafting tree, the per-node
# optimizer needs to score gearsets by total tree cost (recipe steps + cost
# of producing the input materials), NOT just the local recipe's steps.
# Otherwise the optimizer prefers gear that minimizes recipe time (WE/DA/DR)
# even when raising Quality Outcome would be cheaper overall by cutting the
# number of crafts needed (and therefore input materials gathered downstream).
#
# CHILD_INPUT_SPECS is a list of dicts shaped:
#   [
#     {
#       'item_ref': 'Material.bones',          # for diagnostics only
#       'req_amount': 5,                        # base recipe quantity per craft
#       'child_steps_per_item': 797.0,          # steps to produce 1 unit of this child
#     },
#     ...
#   ]
#
# When this list is non-empty, calculate_craft_metrics computes:
#   total_tree_steps_for_target::Q = steps_for_target::Q
#                                  + downstream_steps_per_target_Q
#                                    × q_expected_crafts × output_per_craft_Q
# where downstream_steps_per_target_Q is the sum over children of
#   input_ratio_Q × child_steps_per_item, and input_ratio_Q depends on the
# gearset's NMC, DR, and quality_pct_Q (which depends on QO). This mirrors
# the rollup formula in ui.crafting_tree.calculate_node_metrics.
#
# When the list is empty (default), no tree-aware metric is emitted — single-
# recipe and non-tree callers behave exactly as before.
CHILD_INPUT_SPECS = []

