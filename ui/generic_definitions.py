    def clone_community_definition(self, session_uuid: str, def_type: str,
                                   def_id: str) -> Optional[dict]:
        """Clone a community definition into the user's session.

        Loads the original definition by id, creates a new copy under the
        given session with a fresh UUID and timestamps. The clone is private
        by default (is_public=False) so the user can decide whether to share.

        Args:
            session_uuid: Target session UUID (the cloner).
            def_type: 'activity', 'recipe', or 'service'.
            def_id: UUID of the community definition to clone.

        Returns:
            The newly created definition dict, or None if the source was not
            found or def_type is invalid.
        """
        original = self.db.get_generic_definition(def_type, def_id)
        if not original:
            return None

        if def_type == 'activity':
            return self.db.save_generic_activity(
                session_uuid=session_uuid,
                name=original['name'],
                skill=original['skill'],
                location=original['location'],
                base_steps=original['base_steps'],
                base_xp=original.get('base_xp', 0),
                max_efficiency=original['max_efficiency'],
                required_level=original.get('required_level', 1),
                is_public=False,
            )
        elif def_type == 'recipe':
            return self.db.save_generic_recipe(
                session_uuid=session_uuid,
                name=original['name'],
                skill=original['skill'],
                base_steps=original['base_steps'],
                base_xp=original.get('base_xp', 0),
                max_efficiency=original['max_efficiency'],
                required_level=original.get('required_level', 1),
                service_id=original.get('service_id'),
                is_public=False,
            )
        elif def_type == 'service':
            stats = original.get('stats', {})
            stats_json = json.dumps(stats) if isinstance(stats, dict) else stats
            return self.db.save_generic_service(
                session_uuid=session_uuid,
                name=original['name'],
                skill=original['skill'],
                location=original['location'],
                stats_json=stats_json,
                is_public=False,
            )
        elif def_type == 'item':
            keywords = original.get('keywords', [])
            keywords_json = json.dumps(keywords) if isinstance(keywords, list) else keywords
            stats = original.get('stats', {})
            stats_json = json.dumps(stats) if isinstance(stats, dict) else stats
            quality_stats = original.get('quality_stats')
            quality_stats_json = json.dumps(quality_stats) if isinstance(quality_stats, dict) else quality_stats
            return self.db.save_generic_item(
                session_uuid=session_uuid,
                name=original['name'],
                icon=original.get('icon', '⚡'),
                icon_color=original.get('icon_color'),
                slot=original['slot'],
                keywords=keywords_json,
                stats_json=stats_json,
                quality_stats_json=quality_stats_json,
                rarity=original.get('rarity', 'common'),
                is_crafted=original.get('is_crafted', False),
                is_public=False,
                contributed_by=original.get('contributed_by'),
            )
        return None

