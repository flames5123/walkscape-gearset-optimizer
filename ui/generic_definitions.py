    @staticmethod
    def to_service_instance(generic_service: dict) -> 'GenericServiceInstance':
        """Convert a generic service dict (from DB) to a ServiceInstance-compatible object.

        The flat ``stats_json`` stored in the database (e.g.
        ``{"work_efficiency": 5.0, "double_rewards": 3.0}``) is converted to
        the nested format ``{skill: {location: {stat: value}}}`` that the
        optimizer and ``StatsMixin`` consumers expect.

        Args:
            generic_service: Dict with keys from the ``generic_services`` table
                (name, skill, location, stats_json).

        Returns:
            A ``GenericServiceInstance`` instance consumable by the optimizer.
        """
        skill = generic_service['skill']
        location = generic_service['location']

        # Parse flat stats from DB
        raw_stats = generic_service.get('stats_json', '{}')
        if isinstance(raw_stats, str):
            flat_stats = json.loads(raw_stats)
        else:
            flat_stats = raw_stats

        # Convert flat → nested: {skill: {location: {stat: value}}}
        nested_stats: Dict[str, Dict[str, Dict[str, float]]] = {}
        if flat_stats:
            nested_stats[skill] = {location: dict(flat_stats)}

        return GenericServiceInstance(
            name=generic_service['name'],
            category=skill,
            tier='Generic',
            location=location,
            requirements={},
            _stats=nested_stats,
            gated_stats={},
        )

    @staticmethod
    def to_item_instance(generic_item: dict):
        """Convert a generic item dict (from DB) to an ItemInstance-compatible object.

        Args:
            generic_item: Dict with keys from the ``generic_items`` table.

        Returns:
            ``GenericItemInstance`` for non-crafted items, or
            ``GenericCraftedItem`` for crafted items.
        """
        item_uuid = f"generic::item::{generic_item['id']}"
        stats = generic_item.get('stats', {})
        if isinstance(stats, str):
            stats = json.loads(stats)

        # Parse requirements from DB
        requirements = []
        # Try requirements_json first (activities/recipes use this)
        req_json = generic_item.get('requirements_json', '{}')
        if isinstance(req_json, str):
            try:
                req_data = json.loads(req_json) if req_json else {}
            except json.JSONDecodeError:
                req_data = {}
        else:
            req_data = req_json or {}
        if isinstance(req_data, dict):
            requirements = req_data.get('requirements', [])
        
        # Also check gated_stats_json for requirements (items store them here)
        if not requirements:
            gated_raw = generic_item.get('gated_stats_json') or generic_item.get('gated_stats') or '{}'
            if isinstance(gated_raw, str):
                try:
                    gated_data = json.loads(gated_raw) if gated_raw else {}
                except json.JSONDecodeError:
                    gated_data = {}
            else:
                gated_data = gated_raw or {}
            if isinstance(gated_data, dict) and 'requirements' in gated_data:
                requirements = gated_data['requirements']

        if generic_item.get('is_crafted'):
            quality_stats = generic_item.get('quality_stats', {})
            if isinstance(quality_stats, str):
                quality_stats = json.loads(quality_stats) if quality_stats else {}
            return GenericCraftedItem(
                name=generic_item['name'],
                uuid=item_uuid,
                slot=generic_item['slot'],
                keywords=generic_item.get('keywords', []),
                base_stats=stats,
                quality_stats=quality_stats or {},
                icon=generic_item.get('icon', '⚡'),
                icon_color=generic_item.get('icon_color'),
                requirements=requirements,
            )
        else:
            return GenericItemInstance(
                name=generic_item['name'],
                uuid=item_uuid,
                slot=generic_item['slot'],
                keywords=generic_item.get('keywords', []),
                rarity=generic_item.get('rarity', 'common'),
                _stats=stats,
                icon=generic_item.get('icon', '⚡'),
                icon_color=generic_item.get('icon_color'),
                requirements=requirements,
            )

