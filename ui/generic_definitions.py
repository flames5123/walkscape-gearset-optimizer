class GenericServiceInstance:
    """ServiceInstance-compatible object for generic services.

    Matches the interface of ``util.autogenerated.services.ServiceInstance``
    so the optimizer can consume it without modification.  Implements a
    minimal ``get_stats_for_skill()`` so callers that use the StatsMixin
    protocol work correctly.
    """

    def __init__(self, name: str, category: str, tier: str, location: str,
                 requirements: Dict[str, Any],
                 _stats: Dict[str, Dict[str, Dict[str, float]]],
                 gated_stats: Dict[str, Any]):
        self.name = name
        self.category = category
        self.tier = tier
        self.location = location
        self.requirements = requirements
        self._stats = _stats
        self.gated_stats = gated_stats

    def get_stats_for_skill(self, skill=None, location=None, **kwargs) -> Dict[str, float]:
        """Return flat stat dict for the given skill and location.

        Mimics ``StatsMixin.get_stats_for_skill`` just enough for the
        optimizer pipeline.  Generic services store stats in the nested
        format ``{skill: {location: {stat: value}}}``.  We merge the
        ``global`` key (if any) with the location-specific key.
        """
        skill_key = skill.value if hasattr(skill, 'value') else (skill or '')
        loc_key = location.name if hasattr(location, 'name') else (location or '')

        combined: Dict[str, float] = {}

        for sk in (skill_key, 'global'):
            skill_data = self._stats.get(sk, {})
            for lk in ('global', loc_key):
                for stat, val in skill_data.get(lk, {}).items():
                    combined[stat] = combined.get(stat, 0.0) + val

        return combined

    def is_unlocked(self, character=None, gearset=None) -> bool:
        """Generic services have no unlock requirements."""
        return True

    def is_valid_for_recipe(self, recipe) -> bool:
        """Generic services are valid for any recipe."""
        return True

    def calculate_stats(self, reputation=None) -> Dict[str, float]:
        """Return flat stats (no reputation gating for generic services)."""
        return self.get_stats_for_skill()


def _deep_merge(base: dict, overlay: dict) -> dict:
    """Deep-merge two nested stat dicts, summing leaf values.

    Both dicts use the nested stats format ``{skill: {location: {stat: value}}}``.
    Returns a new dict without mutating either input.

    Args:
        base: Base stats dict.
        overlay: Stats to merge on top of base.

    Returns:
        New dict with merged stats.
    """
    result = copy.deepcopy(base)
    for key, value in overlay.items():
        if key in result and isinstance(result[key], dict) and isinstance(value, dict):
            result[key] = _deep_merge(result[key], value)
        else:
            result[key] = copy.deepcopy(value)
    return result


class GenericItemInstance(StatsMixin):
    """ItemInstance-compatible object for generic items.

    Inherits from StatsMixin to get get_stats_for_skill(), attr(),
    _location_matches(), _convert_percentages(), and caching for free.

    StatsMixin requires: self._stats, self.name, self.gated_stats, self.requirements
    """

    def __init__(self, name, uuid, slot, keywords, rarity,
                 _stats, icon='⚡', icon_color=None, requirements=None):
        self.name = name
        self.uuid = uuid          # 'generic::item::<db_id>'
        self.slot = slot
        self.keywords = keywords   # list of strings
        self.rarity = rarity
        self._stats = _stats       # nested: {skill: {location: {stat: value}}}
        self.icon = icon
        self.icon_color = icon_color
        self.gated_stats = {}      # no gated stats for generic items
        self.requirements = requirements or []
        self.value = 0
        self.location_requirements = []


class GenericCraftedItem:
    """CraftedItem-compatible object for crafted generic items.

    Provides NORMAL, GOOD, GREAT, EXCELLENT, PERFECT, ETERNAL
    property accessors, each returning a GenericItemInstance with
    quality-specific stats deep-merged with base stats.
    """

    QUALITY_NAMES = ['Normal', 'Good', 'Great', 'Excellent', 'Perfect', 'Eternal']

    def __init__(self, name, uuid, slot, keywords,
                 base_stats, quality_stats, icon='⚡', icon_color=None, requirements=None):
        self.name = name
        self.uuid = uuid
        self.slot = slot
        self.keywords = keywords
        self._base_stats = base_stats       # nested stats format
        self._quality_stats = quality_stats  # {quality_name: nested_stats}
        self.icon = icon
        self.icon_color = icon_color
        self.requirements = requirements or []
        self.value = 0

    def _make_variant(self, quality_name: str) -> GenericItemInstance:
        """Build a GenericItemInstance for a specific quality tier.

        Args:
            quality_name: One of 'Normal', 'Good', 'Great', 'Excellent',
                          'Perfect', 'Eternal'.

        Returns:
            GenericItemInstance with deep-merged base + quality stats.
        """
        merged = _deep_merge(self._base_stats, self._quality_stats.get(quality_name, {}))
        # Map quality name to rarity for proper CSS coloring
        quality_to_rarity = {
            'Normal': 'common', 'Good': 'uncommon', 'Great': 'rare',
            'Excellent': 'epic', 'Perfect': 'legendary', 'Eternal': 'ethereal',
        }
        rarity = quality_to_rarity.get(quality_name, 'common')
        return GenericItemInstance(
            name=f"{self.name} ({quality_name})",
            uuid=self.uuid,
            slot=self.slot,
            keywords=self.keywords,
            rarity=rarity,
            _stats=merged,
            icon=self.icon,
            icon_color=self.icon_color,
            requirements=self.requirements,
        )

    @property
    def NORMAL(self) -> GenericItemInstance:
        return self._make_variant('Normal')

    @property
    def GOOD(self) -> GenericItemInstance:
        return self._make_variant('Good')

    @property
    def GREAT(self) -> GenericItemInstance:
        return self._make_variant('Great')

    @property
    def EXCELLENT(self) -> GenericItemInstance:
        return self._make_variant('Excellent')

    @property
    def PERFECT(self) -> GenericItemInstance:
        return self._make_variant('Perfect')

    @property
    def ETERNAL(self) -> GenericItemInstance:
        return self._make_variant('Eternal')



