@dataclass
class GenericActivityInfo:
    """ActivityInfo-compatible object for generic activities.

    Matches the interface of ``util.autogenerated.activities.ActivityInfo``
    so the optimizer, calculator, and combined-stats sections can consume it
    without modification.  Includes a minimal ``get_expected_drop_rate``
    implementation that computes step/XP metrics (no drop table).
    """
    name: str
    primary_skill: Optional[str]
    locations: List[Any]
    skill_requirements: Dict[str, int]
    requirements: Dict[str, Any]
    drop_table: list
    secondary_drop_table: list
    base_steps: Optional[int] = None
    base_xp: Optional[float] = None
    secondary_xp: Dict[str, int] = field(default_factory=dict)
    max_efficiency: Optional[float] = None
    faction_reputation_reward: Optional[Any] = None
    description: Optional[str] = None

    # ------------------------------------------------------------------ #
    # Methods matching ActivityInfo interface
    # ------------------------------------------------------------------ #

    def get_expected_drop_rate(self, stats: Dict[str, float],
                               location=None, target_item=None,
                               verbose: bool = False, character=None,
                               consumable=None):
        """Compute step/XP metrics using the standard game formula.

        Generic activities have no drop table, so the returned results dict
        is always empty.  The *details* dict contains the same metric keys
        the optimizer expects (current_steps, expected_steps_per_action,
        steps_per_reward_roll, primary_xp_per_step, etc.).
        """
        import math

        # Skill level from character
        skill_level = 1
        if self.primary_skill and character:
            skill_level = character.get_skill_level(self.primary_skill.lower())

        activity_level = self.skill_requirements.get(self.primary_skill, 1)
        levels_above = max(0, skill_level - activity_level)
        level_bonus_we = min(levels_above, 20) * 0.0125

        # Collectible stats
        collectible_stats: Dict[str, float] = {}
        if character and self.primary_skill:
            try:
                for coll in character.collectibles:
                    for k, v in coll.get_stats_for_skill(self.primary_skill, location=location).items():
                        collectible_stats[k] = collectible_stats.get(k, 0.0) + v
            except Exception:
                pass

        # Consumable stats
        consumable_stats: Dict[str, float] = {}
        if consumable and self.primary_skill:
            try:
                for k, v in consumable.get_stats_for_skill(self.primary_skill, location=location).items():
                    consumable_stats[k] = consumable_stats.get(k, 0.0) + v
            except Exception:
                pass

        we = stats.get('work_efficiency', 0.0) + level_bonus_we + collectible_stats.get('work_efficiency', 0.0) + consumable_stats.get('work_efficiency', 0.0)
        da = stats.get('double_action', 0.0) + collectible_stats.get('double_action', 0.0) + consumable_stats.get('double_action', 0.0)
        dr = stats.get('double_rewards', 0.0) + collectible_stats.get('double_rewards', 0.0) + consumable_stats.get('double_rewards', 0.0)
        flat = stats.get('steps_add', 0) + int(collectible_stats.get('steps_add', 0.0)) + int(consumable_stats.get('steps_add', 0.0))
        pct = stats.get('steps_percent', 0.0) + collectible_stats.get('steps_percent', 0.0) + consumable_stats.get('steps_percent', 0.0)
        bonus_xp_add = stats.get('bonus_xp_add', 0.0) + collectible_stats.get('bonus_xp_add', 0.0) + consumable_stats.get('bonus_xp_add', 0.0)
        bonus_xp_pct = stats.get('bonus_xp_percent', 0.0) + collectible_stats.get('bonus_xp_percent', 0.0) + consumable_stats.get('bonus_xp_percent', 0.0)

        # Match the UI display formula in
        # ui/static/js/components/activity-info-section.js: SINGLE ceil at
        # the END of the chain (per KamiTzayig reference). Intermediate
        # ceils introduce off-by-one errors that desync the optimizer's
        # metric from column-3 display. Mirrors the fix applied to
        # util/autogenerated/activities.py for the same bug.
        total_efficiency = 1.0 + we
        steps_with_efficiency = self.base_steps / total_efficiency
        min_steps = self.base_steps / (1 + self.max_efficiency)
        steps_after_min = max(steps_with_efficiency, min_steps)
        steps_with_pct = steps_after_min * (1 + pct)
        steps_with_flat = steps_with_pct + flat
        steps_per_single_action = max(math.ceil(steps_with_flat), 10)

        expected_paid_actions = 1.0 / (1 + da)
        expected_steps_per_action = expected_paid_actions * steps_per_single_action
        rewards_per_completion = (1 + dr) * (1 + da)
        steps_per_reward_roll = steps_per_single_action / rewards_per_completion

        primary_xp_per_action = (self.base_xp * (1.0 + bonus_xp_pct)) + bonus_xp_add
        primary_xp_per_step = primary_xp_per_action / expected_steps_per_action if expected_steps_per_action else 0

        # Compute secondary XP
        secondary_xp_per_step = {}
        secondary_xp_per_action = {}
        total_xp_per_step = primary_xp_per_step
        total_xp_for_action = primary_xp_per_action
        for sec_skill, sec_base_xp in self.secondary_xp.items():
            sec_xp_per_action = (sec_base_xp * (1.0 + bonus_xp_pct)) + bonus_xp_add
            sec_xp_per_step = sec_xp_per_action / expected_steps_per_action if expected_steps_per_action else 0
            secondary_xp_per_step[sec_skill] = sec_xp_per_step
            secondary_xp_per_action[sec_skill] = sec_xp_per_action
            total_xp_per_step += sec_xp_per_step
            total_xp_for_action += sec_xp_per_action

        details = {
            'primary_skill': self.primary_skill,
            'skill_level': skill_level,
            'base_steps': self.base_steps,
            'base_xp': self.base_xp,
            'min_steps': min_steps,
            'level_bonus_we_pct': level_bonus_we * 100,
            'work_efficiency_before_max_pct': we * 100,
            'work_efficiency_pct': total_efficiency * 100,
            'work_efficiency_max_pct': self.max_efficiency * 100,
            'double_action_pct': da * 100,
            'double_rewards_pct': dr * 100,
            'flat_steps': flat,
            'pct_steps_reduction': pct * 100,
            'find_collectibles_pct': 0.0,
            'find_gems_pct': 0.0,
            'find_bird_nests_pct': 0.0,
            'fine_material_finding_pct': 0.0,
            'current_efficiency': total_efficiency,
            'current_steps': steps_per_single_action,
            'expected_steps_per_action': expected_steps_per_action,
            'steps_with_efficiency': steps_with_efficiency,
            'steps_after_min': steps_after_min,
            'steps_with_pct': steps_with_pct,
            'steps_with_flat': steps_with_flat,
            'expected_paid_actions': expected_paid_actions,
            'steps_per_reward_roll': steps_per_reward_roll,
            'rewards_per_completion': rewards_per_completion,
            'primary_xp_per_action': primary_xp_per_action,
            'primary_xp_per_step': primary_xp_per_step,
            'secondary_xp_per_step': secondary_xp_per_step,
            'secondary_xp_per_action': secondary_xp_per_action,
            'total_xp_per_step': total_xp_per_step,
            'total_xp_for_action': total_xp_for_action,
            'steps_for_chest': float('inf'),
            'steps_for_fine_material': float('inf'),
            'steps_for_collectible': float('inf'),
            'chest_finding_pct': 0.0,
        }

        # Add collectible stats to details
        for stat_name, stat_value in collectible_stats.items():
            details[f'collectible_{stat_name}_pct'] = stat_value * 100

        results = {}  # No drops for generic activities
        if verbose:
            return results, details
        return results

    def get_all_drops(self, include_nothing: bool = False) -> list:
        """Generic activities have no drops."""
        return []

    def has_requirement(self, keyword: str) -> bool:
        """Check if activity has a keyword requirement."""
        return self.requirements.get('keyword_counts', {}).get(keyword.lower(), 0) > 0

    def get_keyword_count(self, keyword: str) -> int:
        """Get required count for a keyword."""
        return self.requirements.get('keyword_counts', {}).get(keyword.lower(), 0)

    def is_unlocked(self, gearset_export=None, gearset=None, character=None) -> bool:
        """Check if activity requirements are met (keyword counts, skill level, etc.)."""
        # Check skill level requirements
        if character and self.skill_requirements:
            for skill, required_level in self.skill_requirements.items():
                char_level = character.get_skill_level(skill.lower())
                if char_level < required_level:
                    return False

        # Check keyword requirements from gearset
        keyword_counts = self.requirements.get('keyword_counts', {})
        if keyword_counts and (gearset or gearset_export):
            if not gearset and gearset_export:
                from util.gearset_utils import Gearset
                gearset = Gearset(gearset_export)
            if gearset:
                try:
                    for keyword, required_count in keyword_counts.items():
                        if required_count <= 0:
                            continue
                        count = sum(
                            1 for slot, item in gearset.get_all_items()
                            if item and hasattr(item, 'keywords') and
                            any(keyword.lower() == kw.lower() for kw in item.keywords)
                        )
                        if count < required_count:
                            return False
                except Exception:
                    pass

        return True


