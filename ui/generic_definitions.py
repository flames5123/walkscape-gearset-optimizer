    @staticmethod
    def _resolve_location(location_str: str):
        """Resolve a location name string to a LocationInfo object.

        Tries Location.by_name() first, then matches by enum attribute name
        (slug form, e.g. 'halfmaw_hideout'), then case-insensitive display name.
        Falls back to a minimal LocationInfo with the string as a region tag.
        """
        if not location_str:
            return None
        try:
            from util.walkscape_constants import Location, LocationInfo
            loc = Location.by_name(location_str)
            if loc:
                return loc
            # Try matching by enum attribute name (slug: 'halfmaw_hideout')
            # and by display name (case-insensitive: 'Halfmaw Hideout')
            location_slug = location_str.upper()
            location_lower = location_str.lower()
            for attr_name in dir(Location):
                if attr_name.startswith('_'):
                    continue
                attr = getattr(Location, attr_name)
                if not isinstance(attr, LocationInfo):
                    continue
                # Match by slug (DB stores 'halfmaw_hideout', enum attr is 'HALFMAW_HIDEOUT')
                if attr_name == location_slug:
                    return attr
                # Match by display name (case-insensitive)
                if attr.name.lower() == location_lower:
                    return attr
            # Not a known location — create a minimal LocationInfo with the
            # string as a region tag (handles region names like "Jarvonia")
            return LocationInfo(location_str, [location_lower])
        except Exception:
            try:
                from util.walkscape_constants import LocationInfo
                return LocationInfo(location_str, [location_str.lower()])
            except Exception:
                return None

    @staticmethod
    def to_activity_info(generic_activity: dict) -> 'GenericActivityInfo':
        """Convert a generic activity dict (from DB) to an ActivityInfo-compatible object.

        Args:
            generic_activity: Dict with keys from the ``generic_activities`` table
                (name, skill, location, base_steps, base_xp, max_efficiency,
                required_level).

        Returns:
            A ``GenericActivityInfo`` instance consumable by the optimizer.
        """
        skill = generic_activity['skill']
        required_level = generic_activity.get('required_level', 1)
        skill_requirements = {skill: required_level} if required_level > 1 else {}

        # Parse requirements from DB
        raw_reqs = generic_activity.get('requirements_json', '{}')
        if isinstance(raw_reqs, str):
            reqs = json.loads(raw_reqs) if raw_reqs else {}
        else:
            reqs = raw_reqs or {}

        # Build requirements dict matching wiki format
        requirements = {
            'keyword_counts': reqs.get('keyword_counts', {}),
            'reputation': reqs.get('reputation', {}),
            'achievement_points': reqs.get('achievement_points', 0),
            'activity_completions': reqs.get('activity_completions', {}),
        }

        # Parse secondary XP from DB
        raw_sec_xp = generic_activity.get('secondary_xp_json', '{}')
        if isinstance(raw_sec_xp, str):
            secondary_xp = json.loads(raw_sec_xp) if raw_sec_xp else {}
        else:
            secondary_xp = raw_sec_xp or {}

        return GenericActivityInfo(
            name=generic_activity['name'],
            primary_skill=skill,
            locations=[GenericDefinitionManager._resolve_location(generic_activity['location'])],
            base_steps=int(generic_activity['base_steps']),
            base_xp=float(generic_activity.get('base_xp', 0)),
            secondary_xp=secondary_xp,
            max_efficiency=float(generic_activity['max_efficiency']),
            skill_requirements=skill_requirements,
            requirements=requirements,
            drop_table=[],
            secondary_drop_table=[],
        )

