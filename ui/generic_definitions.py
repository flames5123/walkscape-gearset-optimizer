class GenericDefinitionManager:
    """Business logic layer for generic activity/recipe/service definitions.

    Wraps ``DatabaseManager`` CRUD calls with UUID generation, timestamps,
    community sharing, and cloning.

    Args:
        db: A ``DatabaseManager`` instance.
    """

    def __init__(self, db):
        self.db = db

    # ------------------------------------------------------------------ #
    # SAVE
    # ------------------------------------------------------------------ #

    def save_activity(self, session_uuid: str, data: dict) -> dict:
        """Save a new generic activity.

        Args:
            session_uuid: Owner session UUID.
            data: Dict with keys: name, skill, location, base_steps, base_xp,
                  max_efficiency, required_level (optional, default 1),
                  is_public (optional, default True).

        Returns:
            Saved activity dict with generated id and timestamps.
        """
        return self.db.save_generic_activity(
            session_uuid=session_uuid,
            name=data['name'],
            skill=data['skill'],
            location=data['location'],
            base_steps=data['base_steps'],
            base_xp=data.get('base_xp', 0),
            max_efficiency=data['max_efficiency'],
            required_level=data.get('required_level', 1),
            is_public=data.get('is_public', True),
            source=data.get('source'),
            icon=data.get('icon', '⚡'),
            contributed_by=data.get('contributed_by'),
            requirements_json=data.get('requirements_json', '{}'),
            icon_color=data.get('icon_color'),
            secondary_xp_json=data.get('secondary_xp_json', '{}'),
        )

    def save_recipe(self, session_uuid: str, data: dict) -> dict:
        """Save a new generic recipe.

        Args:
            session_uuid: Owner session UUID.
            data: Dict with keys: name, skill, base_steps, base_xp,
                  max_efficiency, required_level, service_id (optional),
                  is_public (optional, default True),
                  is_quality_item (optional, default False).

        Returns:
            Saved recipe dict with generated id and timestamps.
        """
        return self.db.save_generic_recipe(
            session_uuid=session_uuid,
            name=data['name'],
            skill=data['skill'],
            base_steps=data['base_steps'],
            base_xp=data.get('base_xp', 0),
            max_efficiency=data['max_efficiency'],
            required_level=data.get('required_level', 1),
            service_id=data.get('service_id'),
            is_public=data.get('is_public', True),
            source=data.get('source'),
            icon=data.get('icon', '⚡'),
            contributed_by=data.get('contributed_by'),
            is_quality_item=data.get('is_quality_item', False),
            requirements_json=data.get('requirements_json', '{}'),
            icon_color=data.get('icon_color'),
        )

    def save_service(self, session_uuid: str, data: dict) -> dict:
        """Save a new generic service.

        Args:
            session_uuid: Owner session UUID.
            data: Dict with keys: name, skill, location,
                  stats (dict of stat_type→value, optional),
                  is_public (optional, default True).

        Returns:
            Saved service dict with generated id and timestamps.
        """
        stats = data.get('stats', {})
        stats_json = json.dumps(stats) if isinstance(stats, dict) else stats
        # stats_json might already be a string from the frontend
        if isinstance(data.get('stats_json'), str):
            stats_json = data['stats_json']
        return self.db.save_generic_service(
            session_uuid=session_uuid,
            name=data['name'],
            skill=data['skill'],
            location=data['location'],
            stats_json=stats_json,
            is_public=data.get('is_public', True),
            source=data.get('source'),
            icon=data.get('icon', '⚡'),
            contributed_by=data.get('contributed_by'),
            tier=data.get('tier', 'basic'),
            icon_color=data.get('icon_color'),
        )

    def save_item(self, session_uuid: str, data: dict) -> dict:
        """Save a new generic item.

        Args:
            session_uuid: Owner session UUID.
            data: Dict with keys: name, slot (required), icon, icon_color,
                  keywords, stats, quality_stats, rarity, is_crafted,
                  is_public, source, contributed_by.

        Returns:
            Saved item dict with generated id and timestamps.

        Raises:
            ValueError: If name or slot is missing.
        """
        name = data.get('name', '').strip()
        slot = data.get('slot', '').strip()
        if not name:
            raise ValueError('name is required')
        if not slot:
            raise ValueError('slot is required')

        stats = data.get('stats', {})
        stats_json = json.dumps(stats) if isinstance(stats, dict) else stats
        if isinstance(data.get('stats_json'), str):
            stats_json = data['stats_json']

        quality_stats = data.get('quality_stats')
        quality_stats_json = None
        if quality_stats is not None:
            quality_stats_json = json.dumps(quality_stats) if isinstance(quality_stats, dict) else quality_stats
        if isinstance(data.get('quality_stats_json'), str):
            quality_stats_json = data['quality_stats_json']

        keywords = data.get('keywords', [])
        keywords_json = json.dumps(keywords) if isinstance(keywords, list) else keywords

        return self.db.save_generic_item(
            session_uuid=session_uuid,
            name=name,
            icon=data.get('icon', '⚡'),
            icon_color=data.get('icon_color'),
            slot=slot,
            keywords=keywords_json,
            stats_json=stats_json,
            quality_stats_json=quality_stats_json,
            rarity=data.get('rarity', 'common'),
            is_crafted=data.get('is_crafted', False),
            is_public=data.get('is_public', True),
            source=data.get('source'),
            contributed_by=data.get('contributed_by'),
            export_item_name=data.get('export_item_name') or None,
            gear_set_export=data.get('gear_set_export') or None,
            duration=int(data.get('duration', 1000) or 1000),
            value=int(data.get('value', 0) or 0),
            quality_values_json=json.dumps(data['quality_values']) if isinstance(data.get('quality_values'), dict) else data.get('quality_values_json'),
            gated_stats_json=json.dumps(data['gated_stats']) if isinstance(data.get('gated_stats'), dict) else data.get('gated_stats_json', '{}'),
        )

    # ------------------------------------------------------------------ #
    # READ
    # ------------------------------------------------------------------ #

    def get_user_definitions(self, session_uuid: str) -> dict:
        """Get all generic definitions owned by a session, plus sheet-sourced items.

        Sheet-sourced items take priority over user items with the same name,
        since the sheet is the source of truth once an item is synced there.

        Returns:
            Dict with keys 'activities', 'recipes', 'services', 'items', each a list
            of definition dicts.
        """
        from ui.sheets_sync import SHEET_SESSION_UUID
        user_defs = {
            'activities': self.db.get_generic_activities_by_session(session_uuid),
            'recipes': self.db.get_generic_recipes_by_session(session_uuid),
            'services': self.db.get_generic_services_by_session(session_uuid),
            'items': self.db.get_generic_items_by_session(session_uuid),
        }
        # Also include sheet-sourced definitions (shared data from Google Sheets)
        if session_uuid != SHEET_SESSION_UUID:
            sheet_defs = {
                'activities': self.db.get_generic_activities_by_session(SHEET_SESSION_UUID),
                'recipes': self.db.get_generic_recipes_by_session(SHEET_SESSION_UUID),
                'services': self.db.get_generic_services_by_session(SHEET_SESSION_UUID),
                'items': self.db.get_generic_items_by_session(SHEET_SESSION_UUID),
            }
            # Merge: sheet items replace user items with the same name (sheet is source of truth)
            for key in user_defs:
                sheet_names = {d.get('name', '').lower(): d for d in sheet_defs[key]}
                user_names = {d.get('name', '').lower() for d in user_defs[key]}
                # Replace user items that have a sheet version, keep user-only items
                merged = []
                seen = set()
                for d in user_defs[key]:
                    name_lower = d.get('name', '').lower()
                    if name_lower in sheet_names:
                        merged.append(sheet_names[name_lower])
                    else:
                        merged.append(d)
                    seen.add(name_lower)
                # Add sheet-only items (not in user's list) — mark as community
                # so the frontend defaults them to has=false
                for d in sheet_defs[key]:
                    if d.get('name', '').lower() not in seen:
                        d['_community'] = True
                        merged.append(d)
                user_defs[key] = merged
        return user_defs

    def get_community_definitions(self) -> dict:
        """Get all public definitions for the community list.

        Returns dicts with session_uuid stripped for anonymous sharing.
        Deduplicates by lowercase name within each type, keeping the most
        recently updated entry.

        Returns:
            Dict with keys 'activities', 'recipes', 'services', 'items'.
        """
        def _dedup_by_name(defs):
            seen = {}
            for d in defs:
                key = d.get('name', '').lower()
                if key not in seen:
                    seen[key] = d
            return list(seen.values())

        return {
            'activities': _dedup_by_name(self.db.get_public_generic_activities()),
            'recipes': _dedup_by_name(self.db.get_public_generic_recipes()),
            'services': _dedup_by_name(self.db.get_public_generic_services()),
            'items': _dedup_by_name(self.db.get_public_generic_items()),
        }

