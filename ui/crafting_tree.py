def _count_character_slots(session_data: Optional[dict]) -> Tuple[int, int, int, set, set, set]:
    """Returns (light, advanced_diving, expert_diving, their slot sets too).

    Walks character owned_items, resolves each via export_names, and tallies
    how many distinct equipment-slot positions the character can fill with
    items carrying each keyword. Mirrors the logic in
    `detect_locked_locations` (optimize_travel_gearsets.py) so tooltip
    text and the lock check stay in sync.

    Special handling for the ring slot: in WalkScape the player has TWO ring
    slot positions (ring1 + ring2), so an owned ring with quantity 2 (or two
    different rings carrying the same keyword) fills BOTH ring positions and
    contributes 2 to the count. For non-ring slots each unique item still
    contributes 1 (you can only equip one helmet at a time).
    """
    light_slots: set = set()
    advanced_diving_slots: set = set()
    expert_diving_slots: set = set()
    if not session_data:
        return (0, 0, 0, light_slots, advanced_diving_slots, expert_diving_slots)
    owned = session_data.get('owned_items', []) or []
    item_qualities = session_data.get('item_qualities', {}) or {}
    item_quantities = session_data.get('item_quantities', {}) or {}

    # Ring quantities — track total owned (across all qualities) per keyword so
    # 2x Gold Sun Stone Ring fills both ring1 and ring2 (cap at 2).
    light_ring_qty = 0
    adv_div_ring_qty = 0
    exp_div_ring_qty = 0
    seen_ring_uuids: set = set()  # avoid double-counting the same ring

    try:
        from util.autogenerated.export_names import get_item_from_export_name
        seen_non_ring_uuids: set = set()
        for export_name in owned:
            base = export_name
            for suffix in ['_common', '_uncommon', '_rare', '_epic', '_legendary', '_ethereal']:
                if export_name.endswith(suffix):
                    base = export_name[:-len(suffix)]
                    break
            # item_type='equipment' avoids the circular import between
            # equipment.py and walkscape_constants.py — only equipment items
            # carry slot/keywords anyway.
            item = get_item_from_export_name(base, item_type='equipment')
            if not item or not hasattr(item, 'keywords') or not hasattr(item, 'slot'):
                continue
            kws = [k.lower() for k in (item.keywords or [])]
            slot = (item.slot or 'unknown').lower()
            is_light = any('light source' in k for k in kws)
            is_exp_div = any('expert diving gear' in k for k in kws)
            is_adv_div = any('advanced diving gear' in k for k in kws) or is_exp_div

            if slot == 'ring':
                # Each ring (uuid) is counted once with its full owned quantity,
                # even if owned_items lists multiple quality variants of the same
                # ring (we only want to look up the total quantity once).
                uuid = getattr(item, 'uuid', None) or base
                if uuid in seen_ring_uuids:
                    continue
                seen_ring_uuids.add(uuid)
                # Resolve total quantity owned across all qualities. Rings are
                # crafted, so they live in item_qualities (item_id -> {quality: qty}).
                # Fall back to item_quantities for non-crafted rings (rare).
                item_id = item.name.lower().replace(' ', '_').replace('(', '').replace(')', '').replace('-', '_').replace("'", '')
                qty = 0
                qmap = item_qualities.get(item_id)
                if isinstance(qmap, dict):
                    for v in qmap.values():
                        if isinstance(v, (int, float)):
                            qty += int(v)
                if qty == 0:
                    fallback = item_quantities.get(item_id, 0)
                    if isinstance(fallback, (int, float)):
                        qty = int(fallback)
                # If we still didn't find a quantity but the ring is in owned_items,
                # assume at least 1 so the player gets credit for owning it.
                if qty == 0:
                    qty = 1
                if is_light:
                    light_ring_qty += qty
                if is_exp_div:
                    exp_div_ring_qty += qty
                if is_adv_div:
                    adv_div_ring_qty += qty
            else:
                # Non-ring slots: each unique uuid fills one slot occupation
                # (you can't equip two helmets at once).
                uuid = getattr(item, 'uuid', None) or base
                if uuid in seen_non_ring_uuids:
                    continue
                seen_non_ring_uuids.add(uuid)
                if is_light:
                    light_slots.add(slot)
                if is_exp_div:
                    expert_diving_slots.add(slot)
                    advanced_diving_slots.add(slot)
                elif is_adv_div:
                    advanced_diving_slots.add(slot)
    except Exception:
        pass

    # Ring slot has capacity 2 (ring1 + ring2). Cap the ring contribution at 2.
    light_count = len(light_slots) + min(light_ring_qty, 2)
    adv_div_count = len(advanced_diving_slots) + min(adv_div_ring_qty, 2)
    exp_div_count = len(expert_diving_slots) + min(exp_div_ring_qty, 2)
    return (light_count, adv_div_count, exp_div_count,
            light_slots, advanced_diving_slots, expert_diving_slots)


def _compute_location_lock_detail(
    location_name: Optional[str],
    session_data: Optional[dict],
) -> Optional[str]:
    """Character-aware location lock reason — lists only the unmet gates.

    Returns:
        None when location isn't in LOCATION_LOCK_REQUIREMENTS.
        "" (empty) when every gate is already satisfied (caller shouldn't
            show a tooltip in that case — lock shouldn't be active either).
        A human-readable string listing the MISSING requirements when the
        location is locked. Previously the tooltip just listed every gate
        from LOCATION_LOCK_REQUIREMENTS regardless of what the character
        already had, which read as "requires A + B" even when the user
        had B. User bug: Halfling Campgrounds tooltip listed both light
        sources AND Essence of the Swamp; character had the essence but
        only 2 unique-slot light sources, and interpreted the tooltip
        as "you're missing the collectible".
    """
    if not location_name or location_name not in LOCATION_LOCK_REQUIREMENTS:
        return None
    # Gather character state
    collectibles = set()
    raw_c = (session_data or {}).get('collectibles', []) if session_data else []
    for c in raw_c:
        if isinstance(c, str):
            collectibles.add(c.lower().replace(' ', '_').replace("'", ''))
        elif isinstance(c, dict):
            nm = c.get('name') or c.get('id') or c.get('export_name') or ''
            if nm:
                collectibles.add(nm.lower().replace(' ', '_').replace("'", ''))
    has_northern_map = 'mysterious_northern_map' in collectibles
    has_wilderness_permit = 'black_eye_peak_wilderness_permit' in collectibles
    has_swamp = 'essence_of_the_swamp' in collectibles
    lc, adc, edc, _ls, _ads, _eds = _count_character_slots(session_data)

    def fmt_slot_gate(need: int, have: int, what: str) -> str:
        """Format a slot-count gate with the have/need delta so the user
        sees why they're short — e.g. '3 light sources in 3 different
        slots (you have 2)'."""
        return f"{need} {what} in {need} different slots (you have {have})"

    missing = []
    if location_name == 'Winter Waves Glacier':
        if not has_northern_map:
            missing.append('Mysterious Northern Map collectible')
    elif location_name in ("Winter's End", 'Black Eye Peak'):
        if not has_wilderness_permit:
            missing.append('Black Eye Peak Wilderness Permit collectible')
    elif location_name == 'Underwater Cave':
        if adc < 3:
            missing.append(fmt_slot_gate(3, adc, 'advanced diving gear items'))
    elif location_name == 'Darktide Trench':
        if edc < 3:
            missing.append(fmt_slot_gate(3, edc, 'expert diving gear items'))
    elif location_name == 'Halfling Campgrounds':
        if lc < 3:
            missing.append(fmt_slot_gate(3, lc, 'light sources'))
        if not has_swamp:
            missing.append('Essence of the Swamp collectible')
    elif location_name == 'Bog Bottom':
        if lc < 2:
            missing.append(fmt_slot_gate(2, lc, 'light sources'))
        if adc < 3:
            missing.append(fmt_slot_gate(3, adc, 'advanced diving gear items'))
        if not has_swamp:
            missing.append('Essence of the Swamp collectible')
    elif location_name in ('Bog Top', 'Witched Woods', 'Halfmaw Hideout'):
        if lc < 2:
            missing.append(fmt_slot_gate(2, lc, 'light sources'))
        if not has_swamp:
            missing.append('Essence of the Swamp collectible')

    if not missing:
        # Every gate satisfied — caller shouldn't be here, but return
        # empty so the caller can fall back to the flat requirements
        # string if it still wants to show something.
        return ''
    return ' + '.join(missing)

# Some locations in the autogenerated data have `regions` entries that reflect
# game-world taxonomy but don't match the actual in-game unlock gate. For
# example, Wraithwater is tagged as ['wallisia', 'ghostly', 'spectral'] in the
# data dump, which would imply it needs Charter of the Drowned, but players
# can actually reach Wraithwater and Tendon Wet Fields with just the
# Jarvonian Letter of Passage (same gate as GDTE). Only Stalking Yew Woods
# and deeper areas require the Charter.
#
# Override the effective unlock regions here when the data's regions list is
# too restrictive. The override REPLACES the data's regions for unlock-check
# purposes (tooltip text, spoiler hiding, etc.). The location still shows up
# with its original regions elsewhere in the UI.
LOCATION_REGION_OVERRIDES: dict = {
    'Wraithwater': ['gdte'],
    'Tendon Wet Fields': ['gdte'],
}


def _get_effective_regions(location_obj) -> list:
    """Return the regions that gate this location for unlock purposes.

    Honors LOCATION_REGION_OVERRIDES — when a location has an override, the
    override replaces the data's region list. Otherwise returns the data's
    regions (or falls back to primary_region).
    """
    if not location_obj:
        return []
    name = getattr(location_obj, 'name', None)
    if name and name in LOCATION_REGION_OVERRIDES:
        return list(LOCATION_REGION_OVERRIDES[name])
    if hasattr(location_obj, 'regions') and location_obj.regions:
        return list(location_obj.regions)
    if hasattr(location_obj, 'primary_region') and location_obj.primary_region:
        return [location_obj.primary_region]
    return []


def _get_spoiler_reason_for_location(
    location_obj,
    location_name: Optional[str],
    is_region_locked: bool,
    is_loc_locked: bool,
    session_data: Optional[dict] = None,
) -> Optional[str]:
    """Build a human-readable 'why is this locked' string for a location.

    Returns None when nothing is locked. The output is designed to be shown as
    an HTML `title=` tooltip on the locked dropdown item.
    """
    if not (is_region_locked or is_loc_locked):
        return None

    parts = []

    if is_region_locked:
        # Use the effective regions (honoring LOCATION_REGION_OVERRIDES) so
        # the tooltip surfaces the actual in-game unlock gate rather than the
        # raw data regions — e.g. Wraithwater's override reads 'gdte' and the
        # user sees "Jarvonian Letter of Passage" instead of "Charter of the
        # Drowned".
        regions = _get_effective_regions(location_obj)

        if regions:
            # Group regions by their requirement text so we don't repeat the
            # same unlock condition multiple times when a location belongs to
            # several regions that share the same gate (e.g. Wraithwater is in
            # wallisia + ghostly + spectral and all three gate on the same
            # charter collectible).
            seen_keys = set()
            by_req = {}  # requirement_text -> [region_label, ...]
            order = []   # preserve first-seen order of requirement texts
            for r in regions:
                key = r.lower()
                if key in seen_keys:
                    continue
                seen_keys.add(key)
                req = REGION_UNLOCK_REQUIREMENTS.get(key, '')
                # Collapse the "sub-region shares the Wallisia gate" phrasing
                # down to just "Charter of the Drowned collectible" so the
                # tooltip reads cleanly. If any region in this location uses
                # the canonical requirement, that dominates the group.
                canonical = req
                if req.startswith('Wallisia access'):
                    canonical = REGION_UNLOCK_REQUIREMENTS.get('wallisia', req)
                if canonical not in by_req:
                    by_req[canonical] = []
                    order.append(canonical)
                by_req[canonical].append(r.title())

            req_parts = []
            for canonical in order:
                labels = by_req[canonical]
                joined_labels = ' / '.join(labels)
                if canonical:
                    req_parts.append(f"{joined_labels}: {canonical}")
                else:
                    req_parts.append(joined_labels)
            if req_parts:
                parts.append(f"Region locked — requires {' OR '.join(req_parts)}")
            else:
                parts.append("Region not unlocked on this character")
        else:
            parts.append("Region not unlocked on this character")

    if is_loc_locked and location_name:
        # Prefer character-aware detail (lists only what's missing) when
        # session_data is available. Falls back to the flat static
        # requirements text when either the helper returns None (unknown
        # location) or '' (everything satisfied but caller still marked
        # this locked for some other reason). The flat text remains a
        # safe default.
        detail = (_compute_location_lock_detail(location_name, session_data)
                  if session_data is not None else None)
        if detail:
            parts.append(f"{location_name} requires: {detail}")
        else:
            req = LOCATION_LOCK_REQUIREMENTS.get(location_name)
            if req:
                parts.append(f"{location_name} requires: {req}")
            else:
                parts.append(f"{location_name} is locked for this character")

    if not parts:
        return 'Locked on this character'
    return ' · '.join(parts)


def _get_spoiler_reason_for_recipe(recipe, services_dict: dict, unlocked_regions: set) -> Optional[str]:
    """Reason string for a recipe when all its matching services live in locked regions.

    Returns None when the recipe is reachable (at least one unlocked service).
    """
    if not unlocked_regions or not recipe or not recipe.service:
        return None
    matching_regions = []
    for svc_id, svc in services_dict.items():
        if _service_valid_for_recipe(svc, recipe):
            if hasattr(svc, 'location') and svc.location:
                region = _get_region_for_location(svc.location)
                if region:
                    matching_regions.append(region.lower())
    if not matching_regions:
        return None
    unlocked_lower = {r.lower() for r in unlocked_regions}
    if any(r in unlocked_lower for r in matching_regions):
        return None  # recipe reachable via at least one unlocked service
    # All matching service regions are locked — surface the requirements
    region_keys = sorted(set(matching_regions))
    req_parts = []
    for r in region_keys:
        req = REGION_UNLOCK_REQUIREMENTS.get(r)
        if req:
            req_parts.append(f"{r.title()} ({req})")
        else:
            req_parts.append(r.title())
    return f"All services for this recipe are in locked regions — unlock {' or '.join(req_parts)}"


def _best_auto_children_ambiguous(available_sources: list) -> bool:
    """Return True when Best (auto) could pick among multiple candidate sources
    that would produce different children subtrees.

    Used to default-collapse Best(auto) nodes so the user doesn't see a
    single leaf rendered from one arbitrary candidate when the others would
    yield completely different materials (e.g. Ectoplasm: Cut→logs,
    Cook→brew, Smelt→rock, Weave→scraps).

    Considers only real candidates (excludes 'best' and 'bank'). Two or
    more distinct recipe/activity/chest/shop candidates → ambiguous.
    """
    real = [s for s in (available_sources or [])
            if s.get('type') not in ('best', 'bank')]
    return len(real) >= 2


def descendant_ids(nodes: List[dict], node_id: str) -> Set[str]:
    """Return the set of node_ids that descend from `node_id` (children,
    grandchildren, ...), excluding `node_id` itself.

    Used by the gear-aware Best(auto) route resolver to splice a winning
    subtree in/out of the flat node list.
    """
    children_map: dict = {}
    for n in nodes:
        pid = n.get('parent_id')
        if pid:
            children_map.setdefault(pid, []).append(n.get('node_id'))
    ids: Set[str] = set()
    stack = list(children_map.get(node_id, []))
    while stack:
        cur = stack.pop()
        if cur in ids or cur is None:
            continue
        ids.add(cur)
        stack.extend(children_map.get(cur, []))
    return ids


def route_candidates(available_sources: list, skip_shops: bool = True) -> list:
    """Return the distinct, user-usable sources a Best(auto) node could pick
    between, for gear-aware route resolution.

    Filtering:
      - drop 'best'/'bank' meta entries
      - drop spoiler-locked sources (user can't reach them)
      - drop 'shop' entries when skip_shops is set

    De-duplication: a multi-material-group recipe appears once per group in
    `available_sources` (plus a material_group_index == -1 "Best (auto)"
    entry). Route resolution only chooses the *source* (which subtree of
    activities/recipes to use); the per-recipe material-group Best(auto) is a
    separate, calc-time mechanism. So collapse all entries that share
    (type, source_id, parent_activity_id, chest_source) to a single
    candidate, preferring the recipe-level Best(auto) (material_group_index
    == -1) entry when present.
    """
    cands: list = []
    seen: dict = {}
    for s in (available_sources or []):
        t = s.get('type')
        if t in ('best', 'bank'):
            continue
        if s.get('is_spoiler'):
            continue
        if t == 'shop' and skip_shops:
            continue
        key = (t, s.get('source_id'), s.get('parent_activity_id'), s.get('chest_source'))
        if key not in seen:
            seen[key] = len(cands)
            cands.append(s)
        elif s.get('material_group_index') == -1:
            # Prefer the recipe-level "Best (auto)" group entry.
            cands[seen[key]] = s
    return cands


def _refresh_spoiler_reasons(tree_nodes: List[dict], game_data: dict, session_data: Optional[dict]) -> None:
    """Recompute `spoiler_reason` on every source/service in saved tree state.

    Trees saved before the spoiler_reason feature landed carry `is_spoiler`
    booleans but no reason strings, so the frontend title= tooltip renders
    empty. This walks every node's `available_sources` and `available_services`
    and backfills the reason using the current session's unlock state.

    Idempotent: skips entries that already have a non-empty `spoiler_reason`.
    """
    if not tree_nodes:
        return
    unlocked_regions = set()
    if session_data:
        unlocked_regions = set(session_data.get('region_unlocks', []) or [])
    recipes_dict = game_data.get('recipes', {}) if game_data else {}
    services_dict = game_data.get('services', {}) if game_data else {}

    for node in tree_nodes:
        for src in (node.get('available_sources') or []):
            if not src.get('is_spoiler'):
                continue
            if src.get('spoiler_reason'):
                continue
            stype = src.get('type')
            reason = None
            if stype == 'recipe':
                recipe = recipes_dict.get(src.get('source_id'))
                if recipe is not None:
                    reason = _get_spoiler_reason_for_recipe(recipe, services_dict, unlocked_regions)
            else:
                # Activity / chest / shop — resolve via the location object.
                loc_obj = None
                loc_name = src.get('location')
                if stype == 'activity':
                    act = game_data.get('activities', {}).get(src.get('source_id')) if game_data else None
                    if act and getattr(act, 'locations', None):
                        for loc in act.locations:
                            name = loc.name if hasattr(loc, 'name') else str(loc)
                            if not loc_name or name == loc_name:
                                loc_obj = loc
                                if loc_name:
                                    break
                elif stype == 'chest':
                    parent_act_id = src.get('parent_activity_id')
                    parent_recipe_id = src.get('parent_recipe_id')
                    if parent_act_id:
                        act = game_data.get('activities', {}).get(parent_act_id) if game_data else None
                        if act and getattr(act, 'locations', None):
                            loc_obj = act.locations[0]
                            loc_name = loc_obj.name if hasattr(loc_obj, 'name') else str(loc_obj)
                    elif parent_recipe_id:
                        # chest-from-recipe: treat like recipe spoiler
                        recipe = recipes_dict.get(parent_recipe_id)
                        if recipe is not None:
                            reason = _get_spoiler_reason_for_recipe(recipe, services_dict, unlocked_regions)
                elif stype == 'shop':
                    # Synthesize a minimal location-like shim out of the stored region.
                    region = src.get('region')
                    loc_name = src.get('location')
                    if region:
                        class _Shim:
                            __slots__ = ('regions', 'primary_region')
                            def __init__(self, r):
                                self.regions = [r]
                                self.primary_region = r
                        loc_obj = _Shim(region)
                if reason is None and (loc_obj is not None or loc_name):
                    is_region_locked = False
                    if loc_obj is not None and unlocked_regions:
                        is_region_locked = not _is_location_in_unlocked_region(loc_obj, unlocked_regions)
                    is_loc_locked = _is_location_locked(loc_name, session_data, True)
                    if is_region_locked or is_loc_locked:
                        reason = _get_spoiler_reason_for_location(
                            loc_obj, loc_name, bool(is_region_locked), bool(is_loc_locked),
                            session_data=session_data,
                        )
            if reason:
                src['spoiler_reason'] = reason

        for svc in (node.get('available_services') or []):
            if not svc.get('is_spoiler'):
                continue
            if svc.get('spoiler_reason'):
                continue
            # service label format: "Service Name (Location Name)"
            label = svc.get('label') or ''
            loc_name = None
            if '(' in label and label.rstrip().endswith(')'):
                loc_name = label[label.rfind('(') + 1:-1].strip()
            # Try to find the matching service instance to resolve its location.
            svc_inst = services_dict.get(svc.get('id')) if services_dict else None
            loc_obj = getattr(svc_inst, 'location', None) if svc_inst else None
            is_region_locked = False
            if loc_obj is not None and unlocked_regions:
                is_region_locked = not _is_location_in_unlocked_region(loc_obj, unlocked_regions)
            is_loc_locked = _is_location_locked(loc_name, session_data, True)
            if is_region_locked or is_loc_locked:
                reason = _get_spoiler_reason_for_location(
                    loc_obj, loc_name, bool(is_region_locked), bool(is_loc_locked),
                    session_data=session_data,
                )
                if reason:
                    svc['spoiler_reason'] = reason



