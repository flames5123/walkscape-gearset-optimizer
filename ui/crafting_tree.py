def _estimate_item_base_cost(
    item_ref: str,
    game_data: dict,
    visited: Optional[Set[str]] = None,
    max_depth: int = 5,
) -> float:
    """Rough gear-independent "steps to produce one unit" estimate.

    Used by `on_source_change` to resolve a 'Best (auto)' pick to a concrete
    underlying recipe so the tree shows the children of the branch that is
    likely to win at LP calc time. Uses:
      - recipe.base_steps / quantity + sum(mat_qty * recursive_cost / qty)
      - activity.base_steps / (chance * avg_drop_qty)
    taking the minimum over all sources. Ignores gear, fine materials,
    services, and multi-group material alternatives (uses the first group).
    Returns inf when no non-bank source can be estimated within max_depth.
    """
    if visited is None:
        visited = set()
    if item_ref in visited or max_depth <= 0:
        return float('inf')
    visited = visited | {item_ref}

    best_cost = float('inf')

    # Try recipes — iterate over ALL material groups (not just materials[0])
    # so multi-input recipes like Birch Plank (from birch_log OR birch_scrap)
    # get their cheapest input evaluated.
    for recipe in game_data.get('recipes', {}).values():
        if getattr(recipe, 'output_item', None) != item_ref:
            continue
        qty = recipe.quantity or 1
        base = recipe.base_steps or 0
        if not base or not qty:
            continue
        groups = recipe.materials or [[]]
        for mats in groups:
            cost = base / qty
            for mat_qty, mat in mats:
                mat_ref = _get_item_ref_string(mat)
                if not mat_ref:
                    continue
                mat_cost = _estimate_item_base_cost(mat_ref, game_data, visited, max_depth - 1)
                if mat_cost == float('inf'):
                    # Can't resolve this material — skip it so we still return
                    # something instead of inf. Prevents one bad material from
                    # disqualifying a whole recipe.
                    continue
                cost += (mat_cost * mat_qty) / qty
            if cost < best_cost:
                best_cost = cost

    # Try activities (main + secondary drop tables)
    for activity in game_data.get('activities', {}).values():
        base = getattr(activity, 'base_steps', 0) or 0
        if not base:
            continue
        for drop in (getattr(activity, 'drop_table', None) or []):
            drop_ref = getattr(drop, 'item_ref', None)
            if not _match_item_ref(drop_ref, item_ref):
                continue
            chance = (getattr(drop, 'chance_percent', 0) or 0) / 100.0
            avg_qty = drop.quantity.average if getattr(drop, 'quantity', None) else 1.0
            if chance > 0 and avg_qty > 0:
                cost = base / (chance * avg_qty)
                if cost < best_cost:
                    best_cost = cost

    return best_cost


def _compute_material_group_labels(groups) -> List[str]:
    """Compute descriptive labels for each material group of a recipe by
    finding the materials that DIFFER between groups.

    For each group, the label is the name(s) of materials NOT shared with
    every other group. Used by the Material Options row + source dropdown
    expansion (Boxtrap pattern: "Craft a boxtrap - Birch plank" vs
    "Craft a boxtrap - Pine plank") to surface the differentiating
    material between candidate variants of the same recipe.

    Mirrors the column-3 logic in recipe-info-section.js
    _getMaterialGroupLabels(). Returns one label per group; an empty
    string when the recipe only has one group (no differentiation
    needed).

    Args:
        groups: recipe.materials — outer list = groups, inner list =
            (qty, material) tuples.

    Returns:
        List[str] — one label per group. Empty list when groups <= 1.
    """
    if not groups or len(groups) <= 1:
        return []
    # Build a "<name>:<qty>" key set per group so we compare materials
    # by name + quantity (not object identity).
    group_keys = []
    for g in groups:
        keys = set()
        for qty, mat in g or []:
            mat_name = getattr(mat, 'name', None) or str(mat)
            keys.add(f"{mat_name}:{qty}")
        group_keys.append(keys)
    # Find keys present in EVERY group — those are the "common"
    # materials that don't differentiate variants.
    if not group_keys:
        return []
    common = set(group_keys[0])
    for gk in group_keys[1:]:
        common &= gk
    labels = []
    for g in groups:
        diff_names = []
        for qty, mat in g or []:
            mat_name = getattr(mat, 'name', None) or str(mat)
            if f"{mat_name}:{qty}" not in common:
                diff_names.append(mat_name)
        if diff_names:
            labels.append(' + '.join(diff_names))
        else:
            # Edge case: all materials shared (shouldn't happen if
            # groups truly differ, but be defensive). Fallback: list
            # all materials so the label isn't empty.
            labels.append(' + '.join(
                getattr(mat, 'name', None) or str(mat)
                for _, mat in g or []
            ))
    return labels


def _build_leaf_materials(
    available_sources: list,
    game_data: dict,
    underlying_source_type: Optional[str] = None,
    underlying_source_id: Optional[str] = None,
    underlying_material_group_index: Optional[int] = None,
) -> List[dict]:
    """Aggregate every input-material option across all candidate sources.

    For Best(auto) nodes, the UI shows these as a unified "Materials" button
    row so the user sees every possible leaf they could feed into this node:
    - Recipe candidate with N material groups → one option per group, labeled
      by the materials in that group (e.g. "1× Birch log", "2× Birch scrap").
      Click switches to that recipe + group.
    - Activity candidate (direct drop, e.g. Ghost Tag) → one option labeled
      by the activity name. Click switches to that activity.

    Returns a list of option dicts:
        {
          'kind': 'recipe_group' | 'activity',
          'label': str,          # button text
          'icon': Optional[str], # icon path
          'source_type': 'recipe' | 'activity',
          'source_id': str,
          'material_group_index': Optional[int],  # only for 'recipe_group'
          'is_best_pick': bool,  # matches the Best(auto) winner
        }

    The caller decides how to render (selected/dimmed) based on is_best_pick
    and the node's own source_type / selected_material_group_index.
    """
    options: List[dict] = []
    seen_recipe_ids: Set[str] = set()
    for s in available_sources or []:
        if not s or s.get('is_spoiler'):
            continue
        stype = s.get('type')
        if stype in ('bank', 'best', 'shop', 'chest'):
            continue
        # Skip activity sources — Material Options is RECIPE-ONLY.
        # Activities that drop the target item belong in the Source
        # dropdown, not in this row. User spec (re-stated 2026-05-15):
        # "It shouldn't list activities that drop the item. That's
        # what the source dropdown is for."
        if stype == 'activity':
            continue
        sid = s.get('source_id')
        icon = s.get('icon')
        if stype == 'recipe':
            # De-duplicate by recipe source_id. The Boxtrap-pattern
            # source dropdown expansion (added 2026-05-15) emits one
            # available_sources entry per material group, so a recipe
            # with N groups appears N times. Without this guard,
            # _build_leaf_materials iterates each one and re-emits
            # all N group options for that recipe → N² chips
            # (e.g. Boxtrap renders 49 chips for 7 plank types).
            # We only need to walk the recipe's groups ONCE per
            # unique recipe to surface every chip option.
            if sid in seen_recipe_ids:
                continue
            seen_recipe_ids.add(sid)
            recipe = game_data.get('recipes', {}).get(sid)
            if not recipe or not recipe.materials:
                continue
            # Per-recipe differing-material labels for multi-group
            # recipes (e.g. "Craft a boxtrap - Birch plank" vs
            # "Craft a boxtrap - Pine plank"). Mirrors the column-3
            # naming logic in recipe-info-section.js
            # _getMaterialGroupLabels(). Single-group recipes get an
            # empty string here (recipe_label falls back to
            # recipe.name in that case).
            group_diff_labels = _compute_material_group_labels(recipe.materials)
            for group_idx, group in enumerate(recipe.materials):
                if not group:
                    continue
                parts = []
                first_mat_icon = icon
                for qty, mat in group:
                    mat_name = getattr(mat, 'name', None) or str(mat)
                    parts.append(f"{qty}× {mat_name}")
                    if first_mat_icon == icon:
                        mat_ref = _get_item_ref_string(mat)
                        if mat_ref:
                            first_mat_icon = _get_icon_path_for_ref(mat_ref, mat) or icon
                label = ' + '.join(parts) if parts else (s.get('label') or sid)
                # recipe_label = the source-dropdown name the commit
                # would land on. For multi-group recipes this is
                # "<Recipe.name> - <differing material(s)>"; for
                # single-group it's just "<Recipe.name>". Frontend
                # uses this as the "Preview: <link>" text.
                diff_label = group_diff_labels[group_idx] if group_idx < len(group_diff_labels) else ''
                if diff_label:
                    recipe_label = f"{recipe.name} - {diff_label}"
                else:
                    recipe_label = recipe.name
                is_best = (
                    underlying_source_type == 'recipe'
                    and underlying_source_id == sid
                    and (underlying_material_group_index or 0) == group_idx
                )
                options.append({
                    'kind': 'recipe_group',
                    'label': label,
                    'icon': first_mat_icon,
                    'source_type': 'recipe',
                    'source_id': sid,
                    'material_group_index': group_idx,
                    'recipe_name': recipe.name,
                    'recipe_label': recipe_label,
                    'is_best_pick': is_best,
                })
    return options


def _pick_best_underlying_source(
    available_sources: list,
    game_data: dict,
    target_item_ref: Optional[str] = None,
) -> Optional[dict]:
    """Pick the cheapest recipe/activity/chest entry from `available_sources`
    using the `_estimate_item_base_cost` heuristic.

    This is the gear-independent "Best (auto)" tiebreaker used at source-change
    time so the tree displays the children of the likely-winning branch. The
    LP solver re-evaluates with full gear/skill context at calc time and may
    still swap to a different candidate.

    Priority fallback: if no recipe/activity can be scored, picks the first
    non-best/non-bank entry (preserves prior 'first in list' behavior).
    """
    scored = []
    for s in available_sources:
        src_type = s.get('type')
        if src_type in ('best', 'bank'):
            continue
        if src_type == 'recipe':
            recipe = game_data.get('recipes', {}).get(s.get('source_id'))
            if not recipe or not recipe.base_steps:
                continue
            qty = recipe.quantity or 1
            # Evaluate ALL material groups and take the cheapest — matches the
            # behavior of _estimate_item_base_cost so Best(auto) picks the
            # right recipe when one material group is much cheaper than
            # another (e.g. Birch Plank from scraps vs logs).
            best_group_score = float('inf')
            groups = recipe.materials or [[]]
            for mats in groups:
                score = recipe.base_steps / qty
                for mat_qty, mat in mats:
                    mat_ref = _get_item_ref_string(mat)
                    if not mat_ref:
                        continue
                    mat_cost = _estimate_item_base_cost(mat_ref, game_data)
                    if mat_cost != float('inf'):
                        score += (mat_cost * mat_qty) / qty
                if score < best_group_score:
                    best_group_score = score
            if best_group_score < float('inf'):
                scored.append((best_group_score, s))
        elif src_type == 'activity':
            activity = game_data.get('activities', {}).get(s.get('source_id'))
            if not activity:
                continue
            base = getattr(activity, 'base_steps', 0) or 0
            if not base:
                continue
            # Score = steps per unit of THIS item dropped. Walk drop tables
            # to find the relevant drop and factor in chance × avg_qty so
            # low-frequency drops don't falsely look cheaper than recipes.
            # Matches the activity arm of _estimate_item_base_cost.
            #
            # Bug note: this used to initialize best_act_score = float(base)
            # (raw steps-per-ACTION) and only replace it with the drop-
            # adjusted score (steps-per-TARGET-ITEM) when that was lower.
            # Those are different metrics: steps-per-action is always
            # smaller than steps-per-item unless the drop is ~100%. The
            # conditional was silently keeping the raw base_steps for
            # every activity whose drop was below 100%, so the picker
            # ranked by base_steps alone — an activity with faster
            # actions but a terrible drop rate (Kayaking: 68 base, 6%
            # drop) beat a slower activity with a great drop rate
            # (Butterfly catching: 115 base, 25% drop × 3 qty). Fix:
            # start at inf and use the drop-adjusted cost. If no drop
            # matches target_ref, skip this activity entirely (score=inf
            # means it never wins the min, preserving prior behavior for
            # activities that don't produce the item).
            target_ref = s.get('target_item_ref') or s.get('item_ref') or target_item_ref
            best_act_score = float('inf')
            if target_ref:
                all_drops = list(getattr(activity, 'drop_table', None) or [])
                all_drops += list(getattr(activity, 'secondary_drop_table', None) or [])
                for drop in all_drops:
                    drop_ref = getattr(drop, 'item_ref', None)
                    if not _match_item_ref(drop_ref, target_ref):
                        continue
                    chance = (getattr(drop, 'chance_percent', 0) or 0) / 100.0
                    avg_qty = drop.quantity.average if getattr(drop, 'quantity', None) else 1.0
                    if chance > 0 and avg_qty > 0:
                        cand = base / (chance * avg_qty)
                        if cand < best_act_score:
                            best_act_score = cand
            scored.append((float(best_act_score), s))
        elif src_type == 'chest':
            # Chests are hard to score cleanly without the container drop
            # table; give them a high default so they only win when nothing
            # else is available. (First-in-list fallback still handles this.)
            scored.append((float('inf'), s))
    if scored:
        scored.sort(key=lambda pair: pair[0])
        return scored[0][1]
    # Fallback: first in priority order.
    for priority_type in ('recipe', 'activity', 'chest'):
        for s in available_sources:
            if s.get('type') != priority_type:
                continue
            if priority_type == 'chest' and s.get('chest_source') != 'best':
                continue
            return s
    return None


def _populate_source_metadata(
    node: dict,
    game_data: dict,
    session_data: Optional[dict] = None,
    spoiler_protection: bool = True,
    unlocked_regions: Optional[Set[str]] = None,
) -> None:
    """Populate/refresh `available_services` and `available_locations` on a node
    based on its current `(underlying_)source_type/source_id`.

    Called from `_build_recursive` (initial tree build) and from
    `on_source_change` (after the user picks a different recipe/activity), so
    the lists stay in sync with the selected source. Without this, switching
    e.g. from "Cut into ectoplasm" (Carpentry) to "Cook into ectoplasm"
    (Cooking) would leave sawmill services on the node and mislead the user
    into thinking the recipe hadn't changed.

    Operates in-place on `node`.
    """
    if unlocked_regions is None:
        unlocked_regions = set()
        if session_data and spoiler_protection:
            unlocked_regions = set(session_data.get('region_unlocks', []))

    # Use underlying_source_* (which tracks the concrete source when source_type
    # is 'best') so 'best' nodes still get the right service/location list.
    effective_source_type = node.get('underlying_source_type', node.get('source_type'))
    effective_source_id = node.get('underlying_source_id', node.get('source_id'))

    # Default: clear both so stale values from a previous source don't leak
    # through. Only the matching branch below re-populates.
    node['available_services'] = []
    node['available_locations'] = None
    # Activity-only field: input_items meta. Cleared here so a node that
    # switches from an activity to a recipe drops the old keyword icon.
    node['activity_input_items'] = []

    if effective_source_type == 'recipe' and effective_source_id:
        recipe = game_data['recipes'].get(effective_source_id)
        if recipe:
            if not recipe.service or recipe.service.lower() == 'none':
                # No-service recipe: populate available_locations so user picks
                # which region's gear bonuses to optimize for.
                avail_locs = [{'id': '__best__', 'label': 'Best (auto)'}]
                for loc_name, loc_obj in game_data.get('locations', {}).items():
                    if not hasattr(loc_obj, 'name'):
                        continue
                    if getattr(loc_obj, 'is_underwater', False):
                        continue
                    if spoiler_protection and unlocked_regions:
                        if not _is_location_in_unlocked_region(loc_obj, unlocked_regions):
                            continue
                    if _is_location_locked(loc_obj.name, session_data, spoiler_protection):
                        continue
                    avail_locs.append({'id': loc_obj.name, 'label': loc_obj.name})
                avail_locs[1:] = sorted(avail_locs[1:], key=lambda l: l['label'])
                node['available_locations'] = avail_locs
            else:
                avail_svcs = [{'id': '__best__', 'label': 'Best (auto)', 'icon': '/assets/icons/attributes/work_efficiency.svg'}]
                matched_services = []
                for svc_id, svc in game_data.get('services', {}).items():
                    if _service_valid_for_recipe(svc, recipe):
                        matched_services.append((svc_id, svc))
                if not matched_services:
                    recipe_skill = (recipe.skill or '').lower()
                    for svc_id, svc in game_data.get('services', {}).items():
                        svc_cat = svc.category.value.lower() if hasattr(svc.category, 'value') else str(svc.category).lower()
                        if svc_cat == recipe_skill:
                            matched_services.append((svc_id, svc))
                for svc_id, svc in matched_services:
                    loc_name = svc.location.name if hasattr(svc.location, 'name') else str(svc.location)
                    is_region_locked = False
                    if spoiler_protection and hasattr(svc, 'location') and unlocked_regions:
                        is_region_locked = not _is_location_in_unlocked_region(svc.location, unlocked_regions)
                    is_loc_locked = _is_location_locked(loc_name, session_data, spoiler_protection)
                    # Service-intrinsic requirements (faction reputation, skill
                    # level). Without this, a service like Saw-in-Half Mill at
                    # Halfling Campgrounds (requires halfling_rebels: 5) shows
                    # as available the moment the location is unlocked, even
                    # when the character doesn't have the rep yet — and
                    # likewise stays flagged as locked when the user does
                    # have the rep but only the location-lock check ran.
                    is_req_locked, req_reason = _check_service_requirements(svc, session_data) if spoiler_protection else (False, None)
                    # User spec 2026-05-15: when a service has REPUTATION
                    # requirements and the user MEETS them, suppress the
                    # location/region locks for that service. Reputation
                    # is gained AT the location, so meeting the rep
                    # requirement proves the user has already been there
                    # — the location's gear-based visibility check
                    # (3 light sources for Halfling Campgrounds, etc.)
                    # is irrelevant. Without this, Saw-in-Half Mill
                    # showed "needs 3 light sources" even though the
                    # user's 5 halfling_rebels rep made the location
                    # visit-history unlocked.
                    svc_rep_reqs = (getattr(svc, 'requirements', {}) or {}).get('reputation', {}) or {}
                    if svc_rep_reqs and not is_req_locked:
                        is_region_locked = False
                        is_loc_locked = False
                    is_spoiler = is_region_locked or is_loc_locked or is_req_locked
                    spoiler_reason = None
                    if is_spoiler:
                        if is_region_locked or is_loc_locked:
                            spoiler_reason = _get_spoiler_reason_for_location(
                                svc.location, loc_name, bool(is_region_locked), bool(is_loc_locked),
                                session_data=session_data,
                            )
                        if is_req_locked and req_reason:
                            # Append the requirement reason after any
                            # location/region reason so all blockers surface
                            # in the tooltip.
                            spoiler_reason = (
                                f"{spoiler_reason} · Service requires {req_reason}"
                                if spoiler_reason else f"Service requires {req_reason}"
                            )
                    avail_svcs.append({
                        'id': svc_id,
                        'label': f"{svc.name} ({loc_name})",
                        'icon': _get_service_icon_path(svc),
                        'is_spoiler': is_spoiler,
                        'spoiler_reason': spoiler_reason,
                    })
                node['available_services'] = avail_svcs

    elif effective_source_type == 'activity' and effective_source_id:
        activity = game_data['activities'].get(effective_source_id)
        if activity and hasattr(activity, 'locations') and len(activity.locations) > 1:
            avail_locs = [{'id': '__best__', 'label': 'Best (auto)'}]
            for loc in activity.locations:
                loc_name = loc.name if hasattr(loc, 'name') else str(loc)
                avail_locs.append({'id': loc_name, 'label': loc_name})
            node['available_locations'] = avail_locs
        # Surface input_items meta on activity nodes so the frontend can
        # render the input-item slot tile (next to consumable+pet) with
        # the keyword icon (arrows/plant/fabric/etc) BEFORE optimization
        # runs, and pass filterKeyword + filterLevel into the popup when
        # the user clicks the slot to pick an item. Schema mirrors what
        # /api/activities returns for the column-3 inputs section.
        if activity and getattr(activity, 'input_items', None):
            node['activity_input_items'] = [
                {
                    k: v for k, v in {
                        'name': ii.name,
                        'type': ii.type,
                        'reference': ii.reference,
                        'quantity': ii.quantity,
                        'level': getattr(ii, 'level', None),
                        'optional': bool(getattr(ii, 'optional', False)) or None,
                    }.items() if v is not None
                }
                for ii in activity.input_items
                if ii and getattr(ii, 'name', None)
            ]
        else:
            # Clear stale meta when the source switches away from an
            # input-requiring activity (e.g. Best→ chose a recipe).
            node['activity_input_items'] = []


def build_crafting_tree(
    target_item_id: str,
    game_data: Optional[dict] = None,
    session_data: Optional[dict] = None,
    spoiler_protection: bool = True,
) -> List[dict]:
    """Build a default crafting tree as a flat node list.

    Resolution priority for each material:
    1. Recipe (if a recipe outputs this item) — pick first matching recipe
    2. Activity (if an activity drops this item) — pick first matching activity
    3. Chest (if a chest/container contains this item) — pick first matching chest
    4. Bank (fallback — zero steps, added to shopping list)

    When spoiler_protection is True and character data includes region unlocks,
    sources from locked regions are excluded from default selection (but still
    listed in available_sources with a spoiler flag).

    Cycle detection: if item_id already in ancestor path, set to bank.
    Depth cap: nodes at depth >= MAX_TREE_DEPTH default to bank.

    Args:
        target_item_id: Item reference string (e.g. "Material.IRON_BAR")
        game_data: Dict with recipes, activities, services, containers, etc.
        session_data: Character config for skill levels, owned items, region unlocks
        spoiler_protection: Whether to hide sources from locked regions

    Returns:
        Flat list of node dicts, each with parent_id reference.
    """
    if game_data is None:
        game_data = _load_game_data()

    flat_nodes = []

    # Compute unlocked regions for spoiler protection
    unlocked_regions = set()
    if session_data and spoiler_protection:
        unlocked_regions = set(session_data.get('region_unlocks', []))

    def _build_recursive(
        item_ref: str,
        parent_id: Optional[str],
        depth: int,
        base_requirement_amount: int,
        ancestor_items: Set[str],
        material_group_index: Optional[int] = None,
        material_alternatives: Optional[List[dict]] = None,
    ):
        node = _create_node(item_ref, parent_id, depth, base_requirement_amount)
        if material_group_index is not None:
            node['material_group_index'] = material_group_index
        if material_alternatives:
            node['material_alternatives'] = material_alternatives

        # Cycle detection
        if item_ref in ancestor_items:
            node['source_type'] = 'bank'
            node['available_sources'] = [{'type': 'bank', 'source_id': None, 'label': 'Bank (cycle detected)'}]
            flat_nodes.append(node)
            return node['node_id']

        # Depth cap
        if depth >= MAX_TREE_DEPTH:
            node['source_type'] = 'bank'
            node['available_sources'] = [{'type': 'bank', 'source_id': None, 'label': 'Bank (max depth)'}]
            flat_nodes.append(node)
            return node['node_id']

        # Get all available sources
        sources = get_available_sources(item_ref, game_data, session_data, spoiler_protection)
        node['available_sources'] = sources

        # Pick default source: recipe > activity > chest > bank
        # Skip spoiler sources when spoiler protection is on
        non_spoiler = [s for s in sources if not s.get('is_spoiler', False)]
        candidates = non_spoiler if non_spoiler else sources

        best_source = None
        # If "Best (auto)" exists, use it as the display source
        best_auto = next((s for s in candidates if s.get('type') == 'best'), None)
        if best_auto:
            best_source = best_auto
        else:
            for priority_type in ['recipe', 'activity', 'chest', 'shop', 'bank']:
                for s in candidates:
                    if s['type'] == priority_type:
                        # For chest, prefer the 'best' option if available
                        if priority_type == 'chest' and s.get('chest_source') != 'best':
                            continue
                        best_source = s
                        break
                if best_source:
                    break
            # Fallback: pick first chest if no 'best' chest found
            if not best_source:
                for priority_type in ['recipe', 'activity', 'chest', 'shop', 'bank']:
                    for s in candidates:
                        if s['type'] == priority_type:
                            best_source = s
                            break
                    if best_source:
                        break

        if not best_source:
            best_source = {'type': 'bank', 'source_id': None, 'label': 'Bank (no source)'}

        # For "Best (auto)", also determine the underlying source for building children.
        # Uses a base-steps cost heuristic so the displayed branch matches the
        # likely LP winner, not just the first recipe in the list.
        underlying_source = best_source
        if best_source.get('type') == 'best':
            picked = _pick_best_underlying_source(candidates, game_data, target_item_ref=item_ref)
            if picked is not None:
                underlying_source = picked

        node['source_type'] = best_source['type']
        node['source_id'] = best_source.get('source_id')
        # Store the underlying source info for children building and metrics
        node['underlying_source_type'] = underlying_source['type']
        node['underlying_source_id'] = underlying_source.get('source_id')
        node['parent_activity_id'] = underlying_source.get('parent_activity_id') or best_source.get('parent_activity_id')
        node['chest_source'] = underlying_source.get('chest_source', best_source.get('chest_source', 'activity'))
        node['parent_recipe_id'] = underlying_source.get('parent_recipe_id') or best_source.get('parent_recipe_id')

        # "Best (auto)" ambiguity — when this node has multiple viable underlying
        # sources whose children would differ (e.g. Ectoplasm can be Cut/Cook/
        # Smelt/Weave with 4 different raw materials), default-collapse the node
        # so the user doesn't see a misleading single leaf. Frontend reads
        # `auto_collapsed_best` and treats it as `collapsed=true` unless the
        # user has explicitly toggled it open (`node.collapsed === false`).
        node['auto_collapsed_best'] = (
            best_source.get('type') == 'best'
            and _best_auto_children_ambiguous(node.get('available_sources') or [])
        )

        # For service/location population, use the underlying source type
        effective_source_type = node.get('underlying_source_type', node['source_type'])
        effective_source_id = node.get('underlying_source_id', node['source_id'])

        # Populate available_services / available_locations for this source.
        # Centralized in _populate_source_metadata so on_source_change can
        # reuse the same logic and keep these lists in sync with the chosen
        # recipe/activity.
        _populate_source_metadata(
            node, game_data, session_data, spoiler_protection, unlocked_regions
        )

        # Compute the unified "Materials" button options — every input-material
        # alternative across all candidate sources (recipes' material groups
        # + direct-drop activities). Frontend renders these under the
        # Hide/Show children button when the node has 2+ options.
        node['leaf_materials'] = _build_leaf_materials(
            node.get('available_sources') or [],
            game_data,
            underlying_source_type=node.get('underlying_source_type'),
            underlying_source_id=node.get('underlying_source_id'),
            underlying_material_group_index=node.get('selected_material_group_index'),
        )
        # Fresh tree: the Best pick hasn't been computed yet (build time
        # picks a deterministic winner for children, but the UI should
        # show all material options equally until calculate_tree actually
        # evaluates them). Frontend gates .is-best-pick and the (best)
        # label on this flag.
        node['best_pick_computed'] = False

        # When the unified Materials selector is visible (2+ options), don't
        # auto-collapse Best(auto) nodes — the user should see the buttons.
        if node.get('leaf_materials') and len(node['leaf_materials']) >= 2:
            node['auto_collapsed_best'] = False

        flat_nodes.append(node)
        new_ancestors = ancestor_items | {item_ref}

        # Recursively build children for recipe nodes.
        #
        # Recipe materials structure:
        #   outer list = alternative groups (pick ONE group)
        #   inner list = all materials required within that group
        #
        # Example: [[(1, chef_hat), (2, ironweed), (3, cloth)], [(1, other_mat)]]
        #   means: use (chef_hat + ironweed + cloth) OR use (other_mat)
        #
        # We default to the first group and build child nodes for each item in it.
        # The node gets material_group_alternatives listing all outer groups so the
        # user can switch to a different combo.
        if underlying_source['type'] == 'recipe' and underlying_source.get('source_id'):
            recipe = game_data['recipes'].get(underlying_source['source_id'])
            if recipe and recipe.materials:
                # Build the list of alternative groups for the parent node
                alt_groups = []
                for group in recipe.materials:
                    if not group:
                        continue
                    group_label_parts = []
                    for qty, mat in group:
                        mat_name = mat.name if hasattr(mat, 'name') else str(mat)
                        group_label_parts.append(f"{qty}× {mat_name}")
                    alt_groups.append({
                        'label': ' + '.join(group_label_parts),
                        'materials': [
                            {
                                'item_id': _get_item_ref_string(mat),
                                'name': mat.name if hasattr(mat, 'name') else str(mat),
                                'quantity': qty,
                                'icon': _get_icon_path_for_ref(_get_item_ref_string(mat) or '', mat),
                            }
                            for qty, mat in group
                            if _get_item_ref_string(mat)
                        ],
                    })

                # Store alternative groups on the node (for UI group-switcher)
                # Prepend "Best (auto)" when there are multiple groups
                if len(alt_groups) > 1:
                    node['material_group_alternatives'] = [
                        {'label': 'Best (auto)', 'is_best': True}
                    ] + alt_groups
                    # Default to "Best (auto)" (index -1 means auto)
                    node['selected_material_group_index'] = -1
                else:
                    node['material_group_alternatives'] = []
                    node['selected_material_group_index'] = 0

                # Build children from the first (default) group
                default_group = recipe.materials[0] if recipe.materials else []
                for mat_idx, (req_qty, req_mat) in enumerate(default_group):
                    mat_ref = _get_item_ref_string(req_mat)
                    if not mat_ref:
                        continue
                    _build_recursive(
                        item_ref=mat_ref,
                        parent_id=node['node_id'],
                        depth=depth + 1,
                        base_requirement_amount=req_qty,
                        ancestor_items=new_ancestors,
                        material_group_index=mat_idx,
                        material_alternatives=[],  # no per-slot alternatives; groups are on parent
                    )

        # Activity and chest nodes are leaf nodes (no children)
        # Bank nodes are also leaf nodes

        return node['node_id']

    _build_recursive(
        item_ref=target_item_id,
        parent_id=None,
        depth=0,
        base_requirement_amount=1,
        ancestor_items=set(),
    )

    return flat_nodes


