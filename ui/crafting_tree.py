def _compute_activity_drop_yields_per_action(
    activity,
    stats: Dict[str, float],
    skill_level: int,
) -> Dict[str, float]:
    """Return `{item_ref: expected_qty_per_action}` for every drop in an activity.

    Iterates the full drop table (main + secondary) and computes the expected
    quantity per action for each drop entry, accounting for:
      - drop chance (static or level-based)
      - average quantity per drop
      - multi-roll mechanics
      - Double Action (DA) and Double Rewards (DR) stacking: rewards_per_completion = (1+DA)*(1+DR)
      - Find bonuses (collectible finding, chest finding) — applied per-item-type

    Keys are `item_ref` strings (e.g. 'Material.COAL', 'Container.HUNTING_CHEST').
    Drops without an `item_ref` (e.g. 'Nothing') and "Nothing" entries are skipped.
    """
    yields: Dict[str, float] = {}
    if not activity:
        return yields

    all_drops = list(getattr(activity, 'drop_table', []) or []) + \
        list(getattr(activity, 'secondary_drop_table', []) or [])
    if not all_drops:
        return yields

    da = stats.get('double_action', 0.0)
    dr = stats.get('double_rewards', 0.0)
    rewards_per_completion = (1.0 + da) * (1.0 + dr)

    # Find bonuses (applied per drop category)
    find_collectibles = stats.get('find_collectibles', 0.0)
    chest_finding = stats.get('chest_finding', 0.0)
    find_gems = stats.get('find_gems', 0.0)
    find_bird_nests = stats.get('find_bird_nests', 0.0)
    fine_material_finding = stats.get('fine_material_finding', 0.0)
    # Base fine chance for materials: 1% of the normal drop rate, multiplied
    # by (1 + FMF). Matches ActivityInfo.get_expected_drop_rate's fine model.
    fine_chance_multiplier = 0.01 * (1.0 + fine_material_finding)

    # Level-based drop weights (match ActivityInfo.get_expected_drop_rate logic)
    has_level_based = any(d.is_level_based for d in all_drops)
    total_weight = 0.0
    non_level_weighted_percent = 10.0
    if has_level_based:
        for d in activity.drop_table:
            if d.is_level_based:
                total_weight += d.calculate_weight(skill_level)
        total_final_chance = sum(
            d.final_chance for d in activity.drop_table if d.final_chance
        )
        non_level_weighted_percent = 100.0 - total_final_chance

    for drop in all_drops:
        if not drop.item_ref:
            # Activities (e.g. Tinkering) drop a 'Coins' line with no
            # item_ref. Synthesize 'Currency.COINS' so the side_drops
            # aggregator can value them. Same fix as the chest path.
            if (drop.item_name or '').strip().lower() != 'coins':
                continue
        if drop.item_name == 'Nothing':
            continue

        # Resolve the effective ref ONCE so the yield/fine paths below
        # use the synthetic 'Currency.COINS' when item_ref is missing.
        effective_ref = drop.item_ref or 'Currency.COINS'

        # Average quantity per drop roll
        if drop.quantity is None or drop.quantity.is_na:
            avg_qty = 0.0
        elif drop.quantity.is_static:
            avg_qty = float(drop.quantity.min_qty or 0)
        else:
            avg_qty = (float(drop.quantity.min_qty or 0) + float(drop.quantity.max_qty or 0)) / 2.0
        if avg_qty <= 0:
            continue

        # Drop chance (static or level-based)
        if drop.is_level_based:
            drop_chance_percent = drop.get_chance_at_level(
                skill_level, total_weight, non_level_weighted_percent
            )
        else:
            drop_chance_percent = drop.chance_percent or 0.0
        if not drop_chance_percent or drop_chance_percent <= 0:
            continue

        # Per-item find bonus (applied as multiplier on drop chance)
        find_bonus = 0.0
        try:
            if drop.item_object:
                from util.autogenerated.collectibles import CollectibleInstance
                if isinstance(drop.item_object, CollectibleInstance):
                    find_bonus = find_collectibles
                elif drop.item_ref and 'Container.' in drop.item_ref and 'BIRD_NEST' not in drop.item_ref:
                    find_bonus = chest_finding
                elif hasattr(drop.item_object, 'keywords') and any(
                    kw.lower() in ('gem', 'rough gem') for kw in drop.item_object.keywords
                ):
                    find_bonus = find_gems
                elif 'bird nest' in drop.item_name.lower() or 'nest' in drop.item_name.lower():
                    find_bonus = find_bird_nests
        except Exception:
            if drop.item_ref and 'Collectible.' in drop.item_ref:
                find_bonus = find_collectibles
            elif drop.item_ref and 'Container.' in drop.item_ref and 'BIRD_NEST' not in drop.item_ref:
                find_bonus = chest_finding

        if drop.is_multi_roll:
            # Per-roll chance * N rolls * (1 + find_bonus) * avg_qty * rewards_per_completion
            per_roll = drop.base_roll_chance or 0.0
            yield_per_action = (
                drop.multi_roll_count
                * per_roll
                * (1.0 + find_bonus)
                * avg_qty
                * rewards_per_completion
            )
        else:
            base_chance = drop_chance_percent / 100.0
            yield_per_action = (
                base_chance
                * (1.0 + find_bonus)
                * avg_qty
                * rewards_per_completion
            )

        if yield_per_action > 0:
            yields[effective_ref] = yields.get(effective_ref, 0.0) + yield_per_action

            # If this material has a fine variant, emit it too at the
            # FMF-adjusted rate (1% × (1 + FMF) of the normal drop).
            # Only materials have fine variants in practice — guard on prefix.
            # Coin drops are not Material.* so the guard naturally skips
            # them.
            if effective_ref.startswith('Material.') and not effective_ref.endswith('_FINE'):
                fine_ref = effective_ref + '_FINE'
                if _resolve_item_ref(fine_ref) is not None:
                    fine_yield = yield_per_action * fine_chance_multiplier
                    if fine_yield > 0:
                        yields[fine_ref] = yields.get(fine_ref, 0.0) + fine_yield

    # Item-Finding category drops (bug 79ec57d9 / 2026-05-31). The
    # activity engine's `get_expected_drop_rate` already expands every
    # `ItemFindingCategory.X` stat into additional drops (ECTOPLASM,
    # AGT, BIRD_NEST, ...), but this side-drops yield iterator was
    # iterating only `drop_table + secondary_drop_table` so spectral
    # gear at a `ghostly` location never showed Ectoplasm in the
    # crafting tree's side-drops summary. Per IF stat we add
    # `(stat/100) * (chance%/100) * avg_qty * (1+DA) * (1+DR)` directly
    # to yields — IF drops are NOT eligible for find-bonus stacking and
    # are always single-roll, so this matches the activity engine's
    # behaviour exactly.
    try:
        from util.item_utils import iter_if_drops_per_roll as _iter_if_drops
    except ImportError:
        _iter_if_drops = None
    if _iter_if_drops is not None:
        for if_ref, qty_per_roll in _iter_if_drops(stats):
            if not if_ref or qty_per_roll <= 0:
                continue
            if_yield = qty_per_roll * rewards_per_completion
            if if_yield <= 0:
                continue
            yields[if_ref] = yields.get(if_ref, 0.0) + if_yield

    return yields


def _compute_container_drop_yields_per_opening(container) -> Dict[str, float]:
    """Return `{item_ref: expected_qty_per_chest_opening}` for a container.

    Each chest opens `ROLLS_PER_CHEST` times; each roll draws independently from
    the container's drop table. Expected yield per opening for a given drop is
    `chance * avg_qty * ROLLS_PER_CHEST`.
    """
    yields: Dict[str, float] = {}
    if not container:
        return yields
    try:
        from util.autogenerated.containers import ROLLS_PER_CHEST
    except ImportError:
        return yields

    for drop in container.get_all_drops():
        if not drop.item_ref:
            # Some chest drop entries have no item_ref but ARE meaningful
            # — chests routinely roll a 'Coins' line (e.g. Mining chest:
            # 20.586% chance, 10-100 coins) and dropping them silently
            # under-counts side-drop value + net profit. Emit a synthetic
            # 'Currency.COINS' ref so the side_drops aggregator can pick
            # them up. User-reported 2026-05-16: "Coins as a side drop
            # don't account for the coins in the full side drops/net
            # profit value."
            if (drop.item_name or '').strip().lower() == 'coins':
                pass  # fall through with synthetic ref below
            else:
                continue
        if drop.item_name == 'Nothing':
            continue
        chance = (drop.chance_percent or 0.0) / 100.0
        if chance <= 0:
            continue
        if drop.quantity is None or drop.quantity.is_na:
            avg_qty = 0.0
        elif drop.quantity.is_static:
            avg_qty = float(drop.quantity.min_qty or 0)
        else:
            avg_qty = (float(drop.quantity.min_qty or 0) + float(drop.quantity.max_qty or 0)) / 2.0
        if avg_qty <= 0:
            continue
        per_opening = chance * avg_qty * ROLLS_PER_CHEST
        if per_opening > 0:
            ref = drop.item_ref or 'Currency.COINS'
            yields[ref] = yields.get(ref, 0.0) + per_opening
    return yields


def _split_target_yield_by_quality(
    total_qty: float,
    target_item_ref: str,
    recipe,
    QO: float,
    use_fine: bool,
    has_equipment_input: bool,
    target_quality: str,
    activity_level: int,
) -> List[dict]:
    """Split a total produced quantity across quality tiers ≥ target_quality.

    Args:
        total_qty: The total quantity produced (after DA/DR/p_valid_quality).
                   This is `output_qty * (1+DA) * (1+DR) * p_valid_quality` per
                   action × total_actions, or equivalently the expected count
                   of units clearing the target-quality bar.
        target_item_ref: Item ref string for the target (e.g. 'Item.IRON_SICKLE').
        recipe: The Recipe object (or None if the target is not a recipe output).
        QO: Total quality_outcome stat (gear + service + collectibles, etc.).
        use_fine: Whether fine materials are being used.
        has_equipment_input: Whether the recipe has an equipment material input.
        target_quality: The user-selected target quality threshold.
        activity_level: The recipe's base level (used by calculate_quality_weights).

    Returns:
        A list of `{item, item_id, quantity, value}` dicts, one per quality tier
        at or above `target_quality`. If the target is not equipment or
        target_quality == 'Normal', returns a single-entry list with the target
        item at `total_qty`.
    """
    # Resolve the target so we can read its name/value (per-quality for
    # CraftedItems).
    target_obj = _resolve_item_ref(target_item_ref)
    target_name = (target_obj.name if target_obj and hasattr(target_obj, 'name')
                   else target_item_ref.split('.')[-1].replace('_', ' ').title())

    # Single-tier case: not an equipment target, or zero production.
    # NOTE: for equipment targets we always do the multi-tier split (even
    # when target_quality == 'Normal'), because Normal-target means "any
    # quality counts" -- the user crafts get distributed across ALL tiers
    # by QO%, and the breakdown is what they want to see in the Target
    # Yield section of the summary. Showing a single "Hydrilium sickle x
    # 3000" row hides the per-tier expected count and per-tier coin
    # values (Eternal sickles are worth 21x a Normal). It also leaves the
    # popover with no quality tag, so hovering a row showed the BASE
    # item's stats (which are empty for crafted items -- all stats live
    # under stats_by_quality keyed by tier name) instead of the matching
    # tier's stats. Bug 04a95d91 follow-up (2026-05-20).
    item_is_equipment = target_item_ref.startswith('Item.')
    if not item_is_equipment or total_qty <= 0:
        value = 0
        if target_obj is not None and hasattr(target_obj, 'value') and target_obj.value:
            value = float(target_obj.value)
        return [{
            'item': target_name,
            'item_id': target_item_ref,
            'quantity': total_qty,
            'value': total_qty * value,
            'icon_path': _get_icon_path_for_ref(target_item_ref, target_obj),
        }]

    # Multi-tier split using calculate_quality_weights.
    try:
        from util.quality_outcome import calculate_quality_weights
        qw = calculate_quality_weights(
            activity_level, QO, use_fine=use_fine, has_equipment_input=has_equipment_input
        )
    except Exception:
        # Fall back to single-tier on any error — don't crash the summary.
        value = 0
        if target_obj is not None and hasattr(target_obj, 'value') and target_obj.value:
            value = float(target_obj.value)
        return [{
            'item': target_name,
            'item_id': target_item_ref,
            'quantity': total_qty,
            'value': total_qty * value,
            'icon_path': _get_icon_path_for_ref(target_item_ref, target_obj),
        }]

    percentages = qw.get('percentages', {})
    # We only redistribute the units that already cleared the target-quality
    # threshold — i.e. the caller's `total_qty` equals the sum of probabilities
    # from target_quality upward. Renormalize over that range so the split
    # sums exactly to total_qty.
    target_idx = QUALITY_TIERS.index(target_quality) if target_quality in QUALITY_TIERS else 0
    applicable = QUALITY_TIERS[target_idx:]
    total_pct = sum(percentages.get(q, 0.0) for q in applicable)

    results = []
    # If total_pct == 0 (shouldn't happen if caller computed quality_prob > 0)
    # we fall back to a single Normal row.
    if total_pct <= 1e-9:
        value = 0
        if target_obj is not None and hasattr(target_obj, 'value') and target_obj.value:
            value = float(target_obj.value)
        return [{
            'item': target_name,
            'item_id': target_item_ref,
            'quantity': total_qty,
            'value': total_qty * value,
            'icon_path': _get_icon_path_for_ref(target_item_ref, target_obj),
        }]

    # Per-quality object resolution: for CraftedItems we have per-quality value.
    # The object returned by _resolve_item_ref may be a CraftedItem (has .GOOD,
    # .PERFECT, etc.) or a plain ItemInstance (no per-quality variants).
    def _quality_variant(tier: str):
        if target_obj is None:
            return None
        variant_attr = tier.upper()  # 'Good' -> 'GOOD'
        if hasattr(target_obj, variant_attr):
            return getattr(target_obj, variant_attr)
        return target_obj  # plain item — same variant for every tier

    for tier in applicable:
        tier_pct = percentages.get(tier, 0.0)
        if tier_pct <= 0:
            continue
        tier_qty = total_qty * (tier_pct / total_pct)
        variant = _quality_variant(tier)
        variant_name = variant.name if variant and hasattr(variant, 'name') else f"{target_name} ({tier})"
        variant_value = 0
        if variant is not None and hasattr(variant, 'value') and variant.value:
            variant_value = float(variant.value)
        results.append({
            'item': variant_name,
            'item_id': target_item_ref,
            'quality': tier,
            'quantity': tier_qty,
            'value': tier_qty * variant_value,
            # Per-quality variant uses the same icon as the base item.
            'icon_path': _get_icon_path_for_ref(target_item_ref, target_obj),
        })
    return results


def _compute_craft_sub_quality_drops(
    total_at_or_above_target: float,
    target_item_ref: str,
    recipe,
    QO: float,
    use_fine: bool,
    has_equipment_input: bool,
    target_quality: str,
    activity_level: int,
) -> Tuple[List[dict], Dict[str, float]]:
    """Returns (sub_target_side_drops, full_tier_counts) for a craft node.

    When the root crafts equipment with target_quality above 'Normal',
    the optimizer surfaces only at-or-above-target yields via
    `_split_target_yield_by_quality`. But crafts that FAILED the
    target-quality roll still produced real items at lower tiers —
    those go in side_drops with per-quality coin values so the summary
    shows the full picture (e.g. Perfect Iron sickle run also yields
    N Normal / M Good / K Great sickles).

    full_tier_counts covers EVERY tier (incl. target+above) — used by
    the Holistic Solver Insight on the root node to render a "Quality
    breakdown" list.

    Returns empty list + empty dict when item isn't equipment, target
    is Normal, or the per-tier math fails.
    """
    item_is_equipment = target_item_ref.startswith('Item.')
    if (not item_is_equipment
            or target_quality == 'Normal'
            or total_at_or_above_target <= 0):
        return ([], {})

    target_obj = _resolve_item_ref(target_item_ref)
    target_name = (target_obj.name if target_obj and hasattr(target_obj, 'name')
                   else target_item_ref.split('.')[-1].replace('_', ' ').title())

    try:
        from util.quality_outcome import calculate_quality_weights
        qw = calculate_quality_weights(
            activity_level, QO, use_fine=use_fine, has_equipment_input=has_equipment_input
        )
    except Exception:
        return ([], {})
    percentages = qw.get('percentages', {}) or {}

    target_idx = QUALITY_TIERS.index(target_quality) if target_quality in QUALITY_TIERS else 0
    at_or_above = QUALITY_TIERS[target_idx:]

    sum_at_or_above = sum(percentages.get(q, 0.0) for q in at_or_above)
    if sum_at_or_above <= 1e-9:
        return ([], {})

    # Un-filter the at-or-above count back to the total crafts so we
    # can project below-target counts from the same % distribution.
    # Percentages in `qw` are in percent (0..100), not fraction.
    total_crafts = total_at_or_above_target / (sum_at_or_above / 100.0)

    def _quality_variant(tier: str):
        if target_obj is None:
            return None
        variant_attr = tier.upper()
        if hasattr(target_obj, variant_attr):
            return getattr(target_obj, variant_attr)
        return target_obj

    full_counts: Dict[str, float] = {}
    sub_drops: List[dict] = []
    for tier in QUALITY_TIERS:
        pct = percentages.get(tier, 0.0)
        count = total_crafts * (pct / 100.0)
        if count > 0:
            full_counts[tier] = count
        if tier in at_or_above:
            continue
        if count <= 1e-9:
            continue
        variant = _quality_variant(tier)
        unit_value = 0.0
        if variant is not None and hasattr(variant, 'value') and variant.value:
            try:
                unit_value = float(variant.value)
            except (TypeError, ValueError):
                unit_value = 0.0
        display_name = (variant.name if variant and hasattr(variant, 'name')
                        else f"{target_name} ({tier})")
        sub_drops.append({
            'item': display_name,
            'item_id': target_item_ref,
            'quantity': count,
            'unit_value': unit_value,
            'total_value': count * unit_value,
            'quality': tier,
            # 16x16 icon for the side-drops summary table — sub-target
            # quality crafts share the base item's icon.
            'icon_path': _get_icon_path_for_ref(target_item_ref, target_obj),
        })

    return (sub_drops, full_counts)


def extract_node_action_vector(
    node: dict,
    game_data: dict,
    session_data: Optional[dict],
    global_settings: dict,
) -> dict:
    """Pure function: return the LP-ready action vector for a single node.

    Mirrors `calculate_node_metrics()` for stat resolution but produces a
    flat per-action view used by `solve_crafting_tree_lp()`:

        {
          'node_id': str,
          'cost': float,            # steps per single action (0 for bank/shop)
          'yields': {ref: float},   # net per-action yield (+produced / -consumed)
          'raw_produced': {ref: float},
          'raw_consumed': {ref: float},
          'target_item_id': str,    # Possibly fine-rewritten
          'source_name': str,
          'skill_name': Optional[str],
          'xp_yield': {skill_lower: float},
          'stats_used': {...},      # DA, DR, NMC, WE, p_valid_quality, base_steps, ...
          'source_type': str,       # 'bank' | 'shop' | 'recipe' | 'activity' | 'chest'
        }

    Does NOT mutate `node`. Reads node state after Pass-1 completes so any
    auto-gear selection or Pass-1 mutations flow through (Requirement 2.10).
    """
    use_fine = global_settings.get('use_fine', False)

    # Work on a shallow copy of the node for any tweaks we need to make
    # without mutating the original (chest 'best' unwrap, etc.).
    raw_item_ref = node.get('item_id', '') or ''
    item_ref = _rewrite_to_fine(raw_item_ref, use_fine)
    source_type = node.get('source_type', 'bank') or 'bank'

    # Resolve 'best' to its underlying source at the vector level.
    #
    # Strategy: enumerate non-bank/non-best/non-shop candidates, compute
    # each one's per-unit cost, and pick the minimum. This matches Pass-1's
    # `calculate_node_metrics` 'best' handler (which also ranks by steps).
    #
    # We EXCLUDE chest sources from the ranking because their cost is 0
    # (opening a chest is free) but they consume a `Container.*` item that
    # nothing else in the tree produces — the LP would pick them greedily
    # and then be infeasible on the chest demand row. If `build_crafting_tree`
    # built out an actual chest child, it's still part of the tree and the
    # LP will see it; we just don't pick it as the top-level "best".
    if source_type == 'best':
        skip_shops = global_settings.get('skip_shops', True)
        best_vec = None
        best_per_unit = float('inf')
        for src in node.get('available_sources', []) or []:
            st = src.get('type')
            if st in (None, 'bank', 'best', 'chest'):
                continue
            if st == 'shop' and skip_shops:
                continue
            resolved_node = dict(node)
            resolved_node['source_type'] = st
            resolved_node['source_id'] = src.get('source_id')
            resolved_node['parent_activity_id'] = src.get('parent_activity_id')
            resolved_node['parent_recipe_id'] = src.get('parent_recipe_id')
            resolved_node['chest_source'] = src.get('chest_source', 'activity')
            resolved_node['selected_location_id'] = src.get('location') or node.get('selected_location_id')
            try:
                candidate = extract_node_action_vector(
                    resolved_node, game_data, session_data, global_settings
                )
            except Exception:
                continue
            target_yield = candidate['yields'].get(item_ref, 0.0)
            if target_yield <= 0:
                continue
            # Per-unit cost; cost=0 candidates (shop when allowed) rank equal
            # to each other but chest is already excluded above.
            per_unit = candidate['cost'] / target_yield
            if per_unit < best_per_unit:
                best_per_unit = per_unit
                best_vec = candidate
        if best_vec is not None:
            best_vec['node_id'] = node.get('node_id', best_vec['node_id'])
            return best_vec
        # No viable non-bank/non-chest candidate — fall back to whatever
        # build_crafting_tree pre-selected (may be a chest, recipe, or
        # activity). This preserves behavior for trees rooted at chest-only
        # items.
        underlying_type = node.get('underlying_source_type')
        underlying_id = node.get('underlying_source_id')
        if underlying_type and underlying_id:
            resolved_node = dict(node)
            resolved_node['source_type'] = underlying_type
            resolved_node['source_id'] = underlying_id
            return extract_node_action_vector(resolved_node, game_data, session_data, global_settings)
        # Give up: treat as bank-like
        source_type = 'bank'

    result = {
        'node_id': node.get('node_id', ''),
        'cost': 0.0,
        'yields': {},
        'raw_produced': {},
        'raw_consumed': {},
        'target_item_id': item_ref,
        'source_name': '',
        'skill_name': None,
        'xp_yield': {},
        'stats_used': {},
        'source_type': source_type,
    }

    # --- Bank -------------------------------------------------------------
    if source_type == 'bank':
        result['cost'] = 0.0
        result['yields'] = {item_ref: 1.0}
        result['raw_produced'] = {item_ref: 1.0}
        result['source_name'] = f'Bank: {item_ref}'
        result['source_icon'] = '/assets/icons/items/coins.svg'
        return result

    # --- Shop -------------------------------------------------------------
    if source_type == 'shop':
        # Pull shop price/currency from available_sources (same logic as
        # calculate_node_metrics).
        shop_src = next(
            (s for s in node.get('available_sources', []) or []
             if s.get('type') == 'shop' and s.get('source_id') == node.get('source_id')),
            None,
        )
        price = float(shop_src.get('price', 0.0) or 0.0) if shop_src else 0.0
        currency = shop_src.get('currency', 'coins') if shop_src else 'coins'
        # Bug a8b48d9a: shops only stock the NORMAL (non-fine) variant of a
        # material. When fine-mode rewrote this node's demand to a _FINE ref,
        # the shop cannot supply it — it physically sells the normal item.
        # Yield the normal ref the shop actually stocks (raw_item_ref, the
        # un-rewritten node item) instead of the fine ref. This makes the
        # 'best' resolver above skip the shop for fine demand (its yield won't
        # match the fine target) and forces fine demand to route to an activity
        # that can drop the fine variant, rather than "buying" a fine item the
        # shop never carries.
        shop_item_ref = raw_item_ref
        result['cost'] = 0.0
        result['yields'] = {shop_item_ref: 1.0}
        result['raw_produced'] = {shop_item_ref: 1.0}
        result['target_item_id'] = shop_item_ref
        result['source_name'] = f'Shop: {node.get("source_id", "")}'
        result['source_icon'] = '/assets/icons/items/coins.svg'
        result['stats_used'] = {
            'shop_price': price,
            'shop_currency': currency,
            'shop_name': node.get('source_id', ''),
        }
        return result

    # --- Stats resolution (for recipe / activity / chest) -----------------
    gear_stats = _get_gear_stats(node, session_data, game_data)
    skill_name = None
    activity_level = 1
    base_steps = 0
    base_xp = 0.0
    max_efficiency = 0.6
    recipe = None
    activity = None

    if source_type == 'recipe':
        recipe = game_data['recipes'].get(node.get('source_id'))
        if recipe:
            skill_name = recipe.skill
            activity_level = recipe.level or 1
            base_steps = recipe.base_steps or 0
            base_xp = recipe.base_xp or 0.0
            max_efficiency = recipe.max_efficiency or 0.6
    elif source_type in ('activity', 'chest'):
        act_id = (node.get('source_id') if source_type == 'activity'
                  else node.get('parent_activity_id'))
        activity = game_data['activities'].get(act_id) if act_id else None
        if activity:
            skill_name = activity.primary_skill
            if activity.skill_requirements:
                activity_level = list(activity.skill_requirements.values())[0]
            base_steps = activity.base_steps or 318
            base_xp = activity.base_xp or 0.0
            max_efficiency = activity.max_efficiency or 0.6

    skill_level = _get_skill_level(skill_name, session_data)
    # Evaluate collectible bonuses at the node's stat-context location so the
    # LP's steps coefficients stay consistent with the displayed node stats
    # (bug 4e840909).
    _stat_location = _resolve_node_stat_location(node, game_data, session_data)
    collectible_stats = _get_collectible_stats(session_data, skill_name, location=_stat_location)

    stats = dict(gear_stats)
    for k, v in collectible_stats.items():
        stats[k] = stats.get(k, 0.0) + v

    # Service stats for recipe nodes
    selected_service_name = None
    if source_type == 'recipe' and recipe and skill_name:
        service_stats, svc_name = _get_best_service_stats(
            recipe, skill_name, game_data, session_data,
            node.get('selected_service_id'),
            node.get('selected_location_id'),
        )
        for k, v in service_stats.items():
            stats[k] = stats.get(k, 0.0) + v
        selected_service_name = svc_name

    DA = min(1.0, stats.get('double_action', 0.0))
    DR = min(1.0, stats.get('double_rewards', 0.0))
    NMC = min(0.99, stats.get('no_materials_consumed', 0.0))
    WE = stats.get('work_efficiency', 0.0)
    QO = stats.get('quality_outcome', 0.0)
    flat = int(stats.get('steps_add', 0))
    pct = stats.get('steps_percent', 0.0)
    bxp_pct = stats.get('bonus_xp_percent', 0.0)
    bxp_add = stats.get('bonus_xp_add', 0.0)

    # p_valid_quality: only at root when target_quality != 'Normal' AND
    # target is equipment. The LP caller passes target_quality via global
    # settings; to keep this function pure we treat "root" as "is the target
    # quality constraint expected to apply". Here we compute it unconditionally
    # and the LP caller decides whether to use it.
    p_valid_quality = 1.0
    target_quality = global_settings.get('target_quality', 'Normal')
    is_root = bool(node.get('_lp_is_root', False))
    has_equipment_input = False
    if recipe and recipe.materials:
        for group in recipe.materials:
            for _qty, mat in group:
                mat_ref = _get_item_ref_string(mat)
                if mat_ref and mat_ref.startswith('Item.'):
                    has_equipment_input = True
                    break
            if has_equipment_input:
                break
    # QO from `stats` is gear + collectibles + service only. Add the skill-level
    # bonus here so downstream quality-weight math matches the in-game value
    # and is consistent with Column 2's recipe-info-section calculation.
    level_bonus_qo = max(0, skill_level - activity_level)
    QO_effective = QO + level_bonus_qo
    if is_root and target_quality != 'Normal' and item_ref.startswith('Item.'):
        try:
            from util.quality_outcome import calculate_quality_weights
            qw = calculate_quality_weights(activity_level, QO_effective, use_fine=use_fine,
                                            has_equipment_input=has_equipment_input)
            percentages = qw.get('percentages', {})
            target_idx = QUALITY_TIERS.index(target_quality) if target_quality in QUALITY_TIERS else 0
            p_valid_quality = sum(
                percentages.get(q, 0.0) / 100.0
                for q in QUALITY_TIERS[target_idx:]
            )
            if p_valid_quality <= 1e-5:
                p_valid_quality = 1e-5
        except Exception:
            p_valid_quality = 1.0

    steps_per_action = _calculate_steps_per_action(
        base_steps, max_efficiency, skill_level, activity_level, WE, flat, pct
    )

    result['stats_used'] = {
        'DA': DA, 'DR': DR, 'NMC': NMC, 'WE': WE,
        'quality_outcome': QO_effective, 'p_valid_quality': p_valid_quality,
        'flat': flat, 'pct': pct,
        'base_steps': base_steps,
        'service_name': selected_service_name,
    }
    result['skill_name'] = skill_name.lower() if skill_name else None

    # --- Recipe -----------------------------------------------------------
    if source_type == 'recipe' and recipe:
        result['cost'] = steps_per_action
        result['source_name'] = f'Recipe: {recipe.name}'
        # Source icon for the steps-breakdown summary table — user
        # spec (2026-05-15): "show the item icon for recipes". The
        # recipe's output_item ref maps to the item's icon path; fall
        # back to the recipe's skill icon if the item ref doesn't
        # resolve.
        try:
            output_ref = getattr(recipe, 'output_item', '') or ''
            if output_ref:
                result['source_icon'] = _get_icon_path_for_ref(output_ref) or _get_recipe_icon_path(recipe)
            else:
                result['source_icon'] = _get_recipe_icon_path(recipe)
        except Exception:
            result['source_icon'] = _get_recipe_icon_path(recipe)
        output_qty = recipe.quantity or 1
        # Target yield per action
        target_yield_per_action = output_qty * (1.0 + DA) * (1.0 + DR) * p_valid_quality
        if target_yield_per_action > 0:
            result['yields'][item_ref] = result['yields'].get(item_ref, 0.0) + target_yield_per_action
            result['raw_produced'][item_ref] = result['raw_produced'].get(item_ref, 0.0) + target_yield_per_action

        # Item-Finding category drops (bug af9d3e86 / 79ec57d9 / 2026-05-31).
        # When the recipe is run with gear that grants `ItemFindingCategory.X`
        # at a matching location (e.g. Ghost trap pack /
        # `ItemFindingCategory.ECTOPLASM` at Wraithwater), each reward roll
        # has a chance to drop the IF target. The LP solver minimises
        # Σ cost_i × x_i subject to demand — without these IF yields, the
        # solver couldn't see the bonus output that justified the
        # gearset-optimizer's IF-credit pick. Result: the optimizer would
        # pick Ghost trap, but the displayed total_steps wouldn't go down
        # because the LP didn't know IF.ECTOPLASM produces extra Ectoplasm
        # per craft. Now they agree.
        try:
            from util.item_utils import iter_if_drops_per_roll as _iter_if_drops_lp
        except ImportError:
            _iter_if_drops_lp = None
        if _iter_if_drops_lp is not None:
            _rewards_per_completion_lp = (1.0 + DA) * (1.0 + DR)
            for _if_ref, _if_qty_per_roll in _iter_if_drops_lp(stats):
                if not _if_ref or _if_qty_per_roll <= 0:
                    continue
                _if_per_action = _if_qty_per_roll * _rewards_per_completion_lp
                if _if_per_action <= 0:
                    continue
                _if_ref_rewritten = _rewrite_to_fine(_if_ref, use_fine)
                # IF drops aren't quality-bearing; only apply p_valid_quality
                # to the recipe's primary output. IF target drops still count
                # toward demand for the (non-quality) base item ref — same as
                # how the activity path treats IF drops.
                result['yields'][_if_ref_rewritten] = (
                    result['yields'].get(_if_ref_rewritten, 0.0) + _if_per_action
                )
                result['raw_produced'][_if_ref_rewritten] = (
                    result['raw_produced'].get(_if_ref_rewritten, 0.0) + _if_per_action
                )

        # Input consumption — mirror input_ratio math but as a per-action quantity.
        # In calculate_node_metrics the parent pays `req_qty * (1-NMC)` per unit
        # of its own output. Per-action equivalent:
        #   consumed_per_action = req_qty * (1+DA) * (1-NMC)
        # (because DA gives bonus actions that share the same material batch
        # but NMC reduces consumption overall.)
        default_group_idx = node.get('selected_material_group_index', 0)
        if default_group_idx is None or default_group_idx < 0:
            default_group_idx = 0
        if recipe.materials and default_group_idx < len(recipe.materials):
            mat_group = recipe.materials[default_group_idx]
        else:
            mat_group = recipe.materials[0] if recipe.materials else []
        for req_qty, mat in mat_group:
            mat_ref = _get_item_ref_string(mat)
            if not mat_ref:
                continue
            mat_ref = _rewrite_to_fine(mat_ref, use_fine)
            consumed = float(req_qty) * (1.0 + DA) * (1.0 - NMC)
            result['yields'][mat_ref] = result['yields'].get(mat_ref, 0.0) - consumed
            result['raw_consumed'][mat_ref] = result['raw_consumed'].get(mat_ref, 0.0) + consumed

        # Secondary recipe drop table (pet eggs, Silver nugget on bar recipes, etc.)
        recipe_drops = getattr(recipe, 'drop_table', None) or []
        for entry in recipe_drops:
            drop_ref = None
            drop_chance = 0.0
            drop_avg_qty = 1.0
            roll_count = 1
            if isinstance(entry, dict):
                drop_ref = entry.get('item_ref') or entry.get('item_id')
                drop_chance = float(entry.get('chance_percent', 0) or 0) / 100.0
                qty = entry.get('quantity')
                if isinstance(qty, (int, float)):
                    drop_avg_qty = float(qty)
                elif hasattr(qty, 'average'):
                    drop_avg_qty = float(qty.average)
                mrc = entry.get('multi_roll_count')
                if mrc and int(mrc) > 1:
                    roll_count = int(mrc)
            elif hasattr(entry, 'item_ref'):
                drop_ref = entry.item_ref
                drop_chance = float(entry.chance_percent or 0) / 100.0
                drop_avg_qty = entry.quantity.average if entry.quantity else 1.0
                mrc = getattr(entry, 'multi_roll_count', None)
                if mrc and int(mrc) > 1:
                    roll_count = int(mrc)
            if not drop_ref or drop_chance <= 0 or drop_avg_qty <= 0:
                continue
            drop_ref = _rewrite_to_fine(drop_ref, use_fine)
            # chance_percent is per-roll when multi_roll_count > 1
            per_action = roll_count * drop_chance * drop_avg_qty * (1.0 + DA) * (1.0 + DR)
            result['yields'][drop_ref] = result['yields'].get(drop_ref, 0.0) + per_action
            result['raw_produced'][drop_ref] = result['raw_produced'].get(drop_ref, 0.0) + per_action

        # XP per action
        xp_per_action = (base_xp * (1.0 + bxp_pct)) + bxp_add
        if skill_name and xp_per_action > 0:
            result['xp_yield'][skill_name.lower()] = xp_per_action

        return result

    # --- Activity ---------------------------------------------------------
    if source_type == 'activity' and activity:
        result['cost'] = steps_per_action
        result['source_name'] = f'Activity: {activity.name}'
        # Source icon for the steps-breakdown summary — user spec:
        # "the activity icon for activities". Construct the path from
        # the activity's primary skill + activity name slug, mirroring
        # get_available_sources(). Fall back to the work-efficiency
        # default if any field is missing.
        try:
            skill_slug = (getattr(activity, 'primary_skill', '') or '').lower().replace(' ', '_')
            act_slug = (getattr(activity, 'name', '') or '').lower().replace(' ', '_').replace("'", '').replace('-', '_')
            if skill_slug and act_slug:
                result['source_icon'] = f"/assets/icons/activities/{skill_slug}/{act_slug}.svg"
            else:
                result['source_icon'] = '/assets/icons/attributes/work_efficiency.svg'
        except Exception:
            result['source_icon'] = '/assets/icons/attributes/work_efficiency.svg'
        # Drops: full drop table scaled by DA/DR/find bonuses. Fine variants
        # are emitted by _compute_activity_drop_yields_per_action at their
        # actual FMF-adjusted rate — do NOT rewrite the ref here.
        drop_yields = _compute_activity_drop_yields_per_action(activity, stats, skill_level)
        # Apply p_valid_quality ONLY to the target item (quality filter
        # applies to the thing we're aiming for, not incidental drops).
        for drop_ref, yield_per_action in drop_yields.items():
            effective = yield_per_action
            if drop_ref == item_ref and is_root:
                effective = yield_per_action * p_valid_quality
            if effective <= 0:
                continue
            result['yields'][drop_ref] = result['yields'].get(drop_ref, 0.0) + effective
            result['raw_produced'][drop_ref] = result['raw_produced'].get(drop_ref, 0.0) + effective

        # XP per action — activities have no DR-dependence for XP per action
        xp_per_action = (base_xp * (1.0 + bxp_pct)) + bxp_add
        if skill_name and xp_per_action > 0:
            result['xp_yield'][skill_name.lower()] = xp_per_action

        return result

    # --- Chest ------------------------------------------------------------
    if source_type == 'chest':
        container = game_data.get('containers', {}).get(node.get('source_id'))
        result['source_name'] = f'Chest: {container.name if container else node.get("source_id", "")}'
        result['source_icon'] = '/assets/icons/items/containers/treasure_chest.svg'
        result['cost'] = 0.0  # opening a chest costs nothing (chest is consumed)
        if container is not None:
            yields = _compute_container_drop_yields_per_opening(container)
            for dref, per_open in yields.items():
                rewritten = _rewrite_to_fine(dref, use_fine)
                effective = per_open
                if rewritten == item_ref and is_root:
                    effective = per_open * p_valid_quality
                if effective <= 0:
                    continue
                result['yields'][rewritten] = result['yields'].get(rewritten, 0.0) + effective
                result['raw_produced'][rewritten] = result['raw_produced'].get(rewritten, 0.0) + effective
            # One chest is consumed per opening
            chest_ref = f"Container.{node.get('source_id')}" if node.get('source_id') else None
            if chest_ref and _resolve_item_ref(chest_ref) is not None:
                result['yields'][chest_ref] = result['yields'].get(chest_ref, 0.0) - 1.0
                result['raw_consumed'][chest_ref] = result['raw_consumed'].get(chest_ref, 0.0) + 1.0
        return result

    # Fallback: unknown source type → bank-like behavior
    result['yields'] = {item_ref: 1.0}
    result['raw_produced'] = {item_ref: 1.0}
    result['source_name'] = f'Unknown: {source_type}'
    return result


def _bounds_for_node(node: dict) -> Tuple[float, Optional[float]]:
    """Return the LP variable bounds for a node: (lo, hi).

    - Bank with banked_quantity > 0 → (0, banked_quantity)
    - Everyone else → (0, None)   (unbounded above)
    """
    if node.get('source_type') == 'bank':
        cap = node.get('banked_quantity', 0) or 0
        if cap and cap > 0:
            return (0.0, float(cap))
    return (0.0, None)


def _lp_enabled(session_data: Optional[dict]) -> bool:
    """Return True when the caller has indicated the LP flag is on."""
    if not session_data:
        return False
    return bool(session_data.get('_lp_enabled', False))


def solve_crafting_tree_lp(
    tree_nodes: List[dict],
    root_target_amount: float,
    game_data: dict,
    session_data: Optional[dict],
    global_settings: dict,
    root_node_id: Optional[str] = None,
    root_self_target_amount: Optional[float] = None,
) -> Tuple[bool, str, dict]:
    """Solve the whole-tree LP: minimize Σ cost_i × x_i subject to demand.

    Args:
        root_target_amount: total demand for the root item, INCLUDING buffer
            (e.g. target_quantity × (1 + buffer_percentage)). The LP solves
            for this much production at the root.
        root_self_target_amount: optional, the un-buffered target_quantity.
            When provided, every non-root node's contribution to the master
            summary (total_steps, actions, steps_breakdown, xp_by_skill,
            side_drops, shopping_list, etc.) is scaled by
            (root_self_target_amount / root_target_amount). This implements
            "buffer at root only" semantics (bug 15110e01) so children's
            material requirements reflect the integer target_quantity even
            though the LP itself solves at the buffered demand.

    Returns:
        (success, message, master_metrics)

        On failure:
            success=False, message = error string, master_metrics = {}
        On success:
            success=True, message='', master_metrics has the same shape as
            calculate_tree()'s summary (total_steps, xp_by_skill,
            shopping_list, cost_breakdown, steps_breakdown, target_yield,
            side_drops, material_cost, net_profit, etc.) PLUS per-node
            `lp_data` attached directly to each node's `metrics` dict.
    """
    try:
        from scipy.optimize import linprog  # noqa: F401 — lazy import
    except ImportError:
        return (False, 'scipy not installed', {})
    except Exception as e:
        return (False, f'scipy import error: {e}', {})

    if not tree_nodes:
        return (False, 'empty tree', {})

    # Identify root
    root_node = None
    if root_node_id:
        root_node = next((n for n in tree_nodes if n.get('node_id') == root_node_id), None)
    if not root_node:
        root_node = next((n for n in tree_nodes if n.get('parent_id') is None), None)
    if not root_node:
        return (False, 'no root node', {})

    use_fine = global_settings.get('use_fine', False)
    root_target_ref = _rewrite_to_fine(root_node.get('item_id', ''), use_fine)

    # Build action vectors. Mark the root so quality scaling applies.
    vectors = []
    for n in tree_nodes:
        # Mark root transiently for extract_node_action_vector
        if n.get('node_id') == root_node.get('node_id'):
            n['_lp_is_root'] = True
        try:
            v = extract_node_action_vector(n, game_data, session_data, global_settings)
        except Exception as e:
            n.pop('_lp_is_root', None)
            return (False, f'action vector error: {e}', {})
        finally:
            n.pop('_lp_is_root', None)
        vectors.append(v)

    # Pre-check: all bank nodes AND no pseudo-shop overflow (checked below)
    # → nothing to solve. We defer this check until after we've built the
    # pseudo-shop list so we can still solve cases where bank caps are too
    # low and pseudo-shops fill the gap.
    all_bank = all(v['source_type'] == 'bank' for v in vectors)

    # Collect all items referenced in any yield dict.
    all_items: Set[str] = set()
    for v in vectors:
        all_items.update(v['yields'].keys())
    all_items.add(root_target_ref)

    # Pseudo-shop overflow variables: for each bank node with a finite cap,
    # if the item has a shop value, add an unbounded pseudo-shop at that price.
    pseudo_shops = []  # list of (item_ref, cost) tuples
    seen_pseudo_items: Set[str] = set()
    for n, v in zip(tree_nodes, vectors):
        if v['source_type'] != 'bank':
            continue
        cap = n.get('banked_quantity', 0) or 0
        if not cap or cap <= 0:
            continue
        item_ref = v['target_item_id']
        if item_ref in seen_pseudo_items:
            continue
        obj = _resolve_item_ref(item_ref)
        shop_price = None
        if obj is not None and hasattr(obj, 'value') and obj.value:
            try:
                shop_price = float(obj.value)
            except (TypeError, ValueError):
                shop_price = None
        if shop_price is None or shop_price <= 0:
            # No fallback supply; leave as infeasible if demand exceeds cap.
            continue
        pseudo_shops.append((item_ref, shop_price))
        seen_pseudo_items.add(item_ref)
        all_items.add(item_ref)

    # Now apply the all-bank pre-check: skip LP only when there's nothing
    # the solver could ever do (no action nodes AND no pseudo-shops).
    if all_bank and not pseudo_shops:
        return (False, 'no action nodes (all bank)', {})

    # Total variables: tree_nodes + pseudo_shops
    N_tree = len(vectors)
    N_pseudo = len(pseudo_shops)
    N_total = N_tree + N_pseudo

    # Objective (costs): to minimize total steps. Pseudo-shops contribute
    # shop_price per unit as a coin cost; we add them into the objective too
    # so the LP picks the cheapest path. Mixing units of steps and coins is
    # intentional — the reference implementation does the same thing — with
    # the understanding that our "total_steps" reported downstream subtracts
    # the pseudo-shop contribution and reports them separately as shopping
    # costs.
    c = [v['cost'] for v in vectors] + [price for _ref, price in pseudo_shops]

    # Constraints: Σ yields_i(k) × x_i >= demand(k), for each item k.
    # In linprog form: A_ub @ x <= b_ub. Negate both sides.
    item_list = sorted(all_items)
    A_ub = []
    b_ub = []
    for k in item_list:
        row = [-(v['yields'].get(k, 0.0)) for v in vectors]
        # Pseudo-shops yield +1 of their item per unit
        for p_ref, _ in pseudo_shops:
            row.append(-1.0 if p_ref == k else 0.0)
        A_ub.append(row)
        demand = root_target_amount if k == root_target_ref else 0.0
        b_ub.append(-demand)

    # Bounds: tree nodes use _bounds_for_node; pseudo-shops are unbounded.
    bounds = [_bounds_for_node(n) for n in tree_nodes] + [(0.0, None)] * N_pseudo

    try:
        res = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
    except Exception as e:
        return (False, f'linprog error: {e}', {})

    if not res.success:
        return (False, res.message or 'linprog failed', {})

    x = res.x
    if x is None:
        return (False, 'linprog returned no solution', {})

    # Post-solve sanity: reject NaN/Inf
    for val in x:
        if val != val or val == float('inf') or val == float('-inf'):
            return (False, 'numerical instability (nan/inf)', {})

    # ---------------------------------------------------------------------
    # Build master_metrics from the solution.
    # ---------------------------------------------------------------------
    total_steps = 0.0
    total_actions = 0.0
    xp_by_skill: Dict[str, float] = {}
    steps_breakdown_dict: Dict[str, float] = {}
    # Per-source icon for the steps-breakdown summary table (user spec
    # 2026-05-15). Keyed by source_name (same as the steps dict);
    # first-write-wins so duplicate entries don't override.
    steps_breakdown_icons: Dict[str, str] = {}
    steps_by_skill: Dict[str, float] = {}
    shopping_list_dict: Dict[str, float] = {}
    side_drops_raw: Dict[str, float] = {}

    # Helper: resolve an item ref (e.g. "Material.TWINE") to its display name
    # (e.g. "Twine") so the frontend doesn't have to show raw enum strings.
    # Falls back to the raw ref when resolution fails.
    def _lp_item_name(ref):
        try:
            obj = _resolve_item_ref(ref)
            if obj is not None and hasattr(obj, 'name') and obj.name:
                return obj.name
        except Exception:
            pass
        return ref

    # Tree nodes
    # Bug 15110e01: buffer-at-root scaling. The LP itself solves with
    # demand = root_target_amount (= effective_qty when called from
    # calculate_tree), so the root's allocated actions ≈ effective_qty
    # and children's actions reflect "buffered" material flow. To make
    # the master summary report "buffer at root only" totals, we scale
    # each non-root node's contribution by
    # root_self_target_amount / root_target_amount (= target_qty/eff_qty,
    # typically 1/1.05 ≈ 0.952). The root's contribution is unscaled —
    # its allocated actions × cost already represents the buffered work
    # the user asked for. Falls back to no scaling when caller doesn't
    # supply root_self_target_amount (back-compat).
    if (root_self_target_amount is not None
            and root_target_amount > 0
            and root_node_id is not None):
        _child_scale = float(root_self_target_amount) / float(root_target_amount)
    else:
        _child_scale = 1.0
    for i, (n, v) in enumerate(zip(tree_nodes, vectors)):
        raw_actions = float(x[i])
        is_root = (root_node_id is not None and n.get('node_id') == root_node_id)
        node_scale = 1.0 if is_root else _child_scale
        actions = raw_actions * node_scale
        steps = actions * v['cost']

        if v['source_type'] == 'bank':
            # Bank consumption counts toward shopping list
            item = v['target_item_id']
            if actions > 0:
                shopping_list_dict[item] = shopping_list_dict.get(item, 0.0) + actions
            lp_data = {
                'actions': actions,
                'steps': 0.0,
                'source_name': v['source_name'],
                'contributions': [{'item_id': item, 'item_name': _lp_item_name(item), 'amount': actions, 'percent': 0.0}] if actions > 0 else [],
                'consumptions': [],
            }
        elif v['source_type'] == 'shop':
            item = v['target_item_id']
            if actions > 0:
                shopping_list_dict[item] = shopping_list_dict.get(item, 0.0) + actions
            lp_data = {
                'actions': actions,
                'steps': 0.0,
                'source_name': v['source_name'],
                'contributions': [{'item_id': item, 'item_name': _lp_item_name(item), 'amount': actions, 'percent': 0.0}] if actions > 0 else [],
                'consumptions': [],
            }
        else:
            # Activity / recipe / chest contributions & consumptions
            total_steps += steps
            total_actions += actions
            steps_breakdown_dict[v['source_name']] = (
                steps_breakdown_dict.get(v['source_name'], 0.0) + steps
            )
            # Track per-source icon so the steps-breakdown summary
            # table can render a 16x16 icon next to each row (item
            # icon for recipes, activity icon for activities, etc.).
            # First-write-wins per source name — mirrors how the
            # steps_breakdown_dict aggregates duplicate entries.
            if v.get('source_icon') and v['source_name'] not in steps_breakdown_icons:
                steps_breakdown_icons[v['source_name']] = v['source_icon']
            sk = v.get('skill_name')
            if sk:
                steps_by_skill[sk] = steps_by_skill.get(sk, 0.0) + steps
                xp_by_skill[sk] = xp_by_skill.get(sk, 0.0) + actions * v['xp_yield'].get(sk, 0.0)
            # Produced items → side_drops pool
            for ref, per_action in v['raw_produced'].items():
                side_drops_raw[ref] = side_drops_raw.get(ref, 0.0) + actions * per_action
            for ref, per_action in v['raw_consumed'].items():
                side_drops_raw[ref] = side_drops_raw.get(ref, 0.0) - actions * per_action

            # Build lp_data
            contributions = []
            for ref, per_action in v['raw_produced'].items():
                if actions * per_action > 0:
                    contributions.append({'item_id': ref, 'item_name': _lp_item_name(ref), 'amount': actions * per_action, 'percent': 0.0})
            consumptions = []
            for ref, per_action in v['raw_consumed'].items():
                if actions * per_action > 0:
                    consumptions.append({'item_id': ref, 'item_name': _lp_item_name(ref), 'amount': actions * per_action})
            lp_data = {
                'actions': actions,
                'steps': steps,
                'source_name': v['source_name'],
                'contributions': contributions,
                'consumptions': consumptions,
            }

        # Attach to the original node's metrics dict
        if 'metrics' not in n or n['metrics'] is None:
            n['metrics'] = {}
        n['metrics']['lp_data'] = lp_data

    # Pseudo-shops. Bug 15110e01: pseudo-shops fulfil children's
    # material demand, so they scale by _child_scale (target_qty/eff_qty)
    # to match the rest of children's "buffer at root only" treatment.
    pseudo_cost_total = 0.0
    for j, (p_ref, price) in enumerate(pseudo_shops):
        units = float(x[N_tree + j]) * _child_scale
        if units > 0:
            shopping_list_dict[p_ref] = shopping_list_dict.get(p_ref, 0.0) + units
            pseudo_cost_total += units * price

    # Build shopping_list and cost_breakdown
    shopping_list = []
    for ref, qty in shopping_list_dict.items():
        if qty <= 0:
            continue
        obj = _resolve_item_ref(ref)
        name = obj.name if obj and hasattr(obj, 'name') else ref
        rarity = None
        try:
            if obj is not None:
                rarity = getattr(obj, 'rarity', None) or None
        except Exception:
            rarity = None
        shopping_list.append({
            'item_id': ref,
            'name': name,
            'quantity': qty,
            # 16x16 item icon path for the summary table — user spec
            # 2026-05-15.
            'icon_path': _get_icon_path_for_ref(ref, obj),
            # Rarity for the row icon's drop-shadow filter (matches
            # the .item-icon.rarity-* pattern used in the main UI).
            'rarity': rarity,
        })

    cost_breakdown = []
    material_cost = 0.0
    shop_price_map = _build_shop_price_map(tree_nodes)
    for entry in shopping_list:
        obj = _resolve_item_ref(entry['item_id'])
        # Bug 4a16affa: prefer the shop's listed price for materials the tree
        # sources from a shop; fall back to the item's sell value otherwise.
        unit_value = shop_price_map.get(entry['item_id'], 0.0)
        if unit_value <= 0:
            unit_value = 0.0
            if obj and hasattr(obj, 'value') and obj.value:
                try:
                    unit_value = float(obj.value)
                except (TypeError, ValueError):
                    unit_value = 0.0
        total_cost = entry['quantity'] * unit_value
        cost_breakdown.append({
            'item': entry['name'],
            'quantity': entry['quantity'],
            'unit_value': unit_value,
            'total_cost': total_cost,
        })
        material_cost += total_cost

    # steps_breakdown list form
    steps_breakdown = [
        {
            'source': src,
            'steps': stp,
            'source_icon': steps_breakdown_icons.get(src),
        }
        for src, stp in steps_breakdown_dict.items()
        if stp > 0
    ]

    # Target yield: apply the quality split to the root target production.
    root_target_production = side_drops_raw.get(root_target_ref, 0.0)
    root_recipe = game_data['recipes'].get(root_node.get('source_id')) if root_node.get('source_type') == 'recipe' else None
    root_activity_level = 1
    if root_recipe:
        root_activity_level = root_recipe.level or 1
    root_QO = 0.0
    # Try to pull QO from the root's action vector
    for v in vectors:
        if v['node_id'] == root_node.get('node_id'):
            root_QO = float(v['stats_used'].get('quality_outcome', 0.0) or 0.0)
            break
    has_eq_input = False
    if root_recipe and root_recipe.materials:
        for group in root_recipe.materials:
            for _qty, mat in group:
                mref = _get_item_ref_string(mat)
                if mref and mref.startswith('Item.'):
                    has_eq_input = True
                    break
            if has_eq_input:
                break
    target_yield = _split_target_yield_by_quality(
        total_qty=root_target_production,
        target_item_ref=root_target_ref,
        recipe=root_recipe, QO=root_QO,
        use_fine=use_fine, has_equipment_input=has_eq_input,
        target_quality=global_settings.get('target_quality', 'Normal'),
        activity_level=root_activity_level,
    )
    target_value = sum(e.get('value', 0.0) or 0.0 for e in target_yield)

    # Sub-target quality crafts of the root item. sub_drops are appended
    # to side_drops below; full_counts get stashed on root_node.metrics
    # for the Holistic Solver Insight.
    craft_sub_drops, full_craft_counts = _compute_craft_sub_quality_drops(
        total_at_or_above_target=root_target_production,
        target_item_ref=root_target_ref,
        recipe=root_recipe, QO=root_QO,
        use_fine=use_fine, has_equipment_input=has_eq_input,
        target_quality=global_settings.get('target_quality', 'Normal'),
        activity_level=root_activity_level,
    )
    if full_craft_counts:
        try:
            if isinstance(root_node.get('metrics'), dict):
                root_node['metrics'].setdefault('craft_quality_counts', {}).update(full_craft_counts)
        except Exception:
            pass

    # Side drops = all positive production entries except root target
    side_drops = []
    side_drops_value = 0.0
    # Sell-value lookup for chests (Container.*). Chest objects don't
    # carry a .value attr — the wiki source-of-truth lives in
    # util/coin_value.CHEST_COIN_VALUES. Without this, every chest in
    # side_drops priced at 0 coins and never contributed to net profit.
    try:
        from util.coin_value import CHEST_COIN_VALUES as _CHEST_COIN_VALUES
    except Exception:
        _CHEST_COIN_VALUES = {}
    for ref, amt in side_drops_raw.items():
        if ref == root_target_ref:
            continue
        if amt <= 1e-9:
            continue
        # Coins side drop: chests synthesize 'Currency.COINS' (no ref
        # in the drop data), activities use 'Currency.COIN' (singular,
        # set in the autogen drop table). Normalize both into the same
        # row so the user sees one "Coins" line and the value flows
        # into net profit. Each coin is worth 1 coin, so unit_value=1.
        if ref in ('Currency.COINS', 'Currency.COIN'):
            unit_value = 1.0
            total_value = amt * unit_value
            side_drops.append({
                'item': 'Coins', 'item_id': 'Currency.COINS',
                'quantity': amt,
                'unit_value': unit_value, 'total_value': total_value,
                'icon_path': '/assets/icons/items/coins.svg',
                'is_fine': False,
            })
            side_drops_value += total_value
            continue
        obj = _resolve_item_ref(ref)
        name = obj.name if obj and hasattr(obj, 'name') else ref.split('.')[-1].replace('_', ' ').title()
        unit_value = 0.0
        if obj is not None and hasattr(obj, 'value') and obj.value:
            try:
                unit_value = float(obj.value)
            except (TypeError, ValueError):
                unit_value = 0.0
        # Containers (Container.CRAFTING_CHEST, etc.) don't have a
        # .value attribute — pull their wiki sell-value out of
        # CHEST_COIN_VALUES so chests counted in side_drops actually
        # contribute to net profit.
        if unit_value <= 0 and ref.startswith('Container.'):
            try:
                unit_value = float(_CHEST_COIN_VALUES.get(ref, 0) or 0)
            except (TypeError, ValueError):
                unit_value = 0.0
        total_value = amt * unit_value
        # Rarity for the drop-shadow filter on the row icon. Crafted
        # items carry their tier in obj.rarity; raw materials default
        # to common. Quality is meaningful only for equipment side-
        # drops (sub-target craft tiers) — those are appended below
        # via craft_sub_drops which already carries `quality`.
        rarity = None
        try:
            if obj is not None:
                rarity = getattr(obj, 'rarity', None) or None
        except Exception:
            rarity = None
        side_drops.append({
            'item': name, 'item_id': ref, 'quantity': amt,
            'unit_value': unit_value, 'total_value': total_value,
            # 16x16 item icon for the summary table.
            'icon_path': _get_icon_path_for_ref(ref, obj),
            # Mark fine variants so the frontend can apply the
            # cyan glow drop-shadow to the icon (matches the
            # .item-icon.fine pattern in styles.css).
            'is_fine': '_FINE' in (ref or '').upper() or '(Fine)' in (name or ''),
            'rarity': rarity,
        })
        side_drops_value += total_value
    # Append sub-target quality crafts of the root item last, so they
    # sort alongside real side drops by total_value.
    for entry in craft_sub_drops:
        side_drops.append(entry)
        side_drops_value += entry.get('total_value', 0.0)
    side_drops.sort(key=lambda e: e.get('total_value', 0.0), reverse=True)

    daily_steps = global_settings.get('daily_steps', 30000)
    time_days = total_steps / daily_steps if daily_steps > 0 else 0.0
    net_profit = target_value + side_drops_value - material_cost

    # Skill progression: for each skill gaining XP, look up the
    # character's current total XP (session skills_xp) and project the
    # level before/after the crafting run. Frontend uses these for the
    # "52 → 54" cell in the XP by Skill table — so the user can see
    # whether the run levels them up. Skills not present in session
    # skills_xp fall back to level_before=None (frontend shows only the
    # projected level then). Keys use the lowercased skill names so they
    # line up 1:1 with xp_by_skill.
    skill_progression: Dict[str, dict] = {}
    try:
        from util.walkscape_constants import xp_to_level
        session_skills_xp = (session_data or {}).get('skills_xp', {}) or {}
        # Normalize session keys — character data often stores them
        # TitleCase (Woodcutting) but xp_by_skill uses lowercase.
        norm_session_xp = {}
        for k, v in session_skills_xp.items():
            try:
                norm_session_xp[str(k).lower()] = float(v)
            except (TypeError, ValueError):
                continue
        for skill, xp_gain in xp_by_skill.items():
            if not xp_gain or xp_gain <= 0:
                continue
            skill_lc = str(skill).lower()
            cur_xp = norm_session_xp.get(skill_lc)
            if cur_xp is None:
                skill_progression[skill_lc] = {
                    'xp': float(xp_gain),
                    'level_before': None,
                    'level_after': None,
                }
                continue
            level_before = xp_to_level(int(cur_xp))
            level_after = xp_to_level(int(cur_xp + xp_gain))
            skill_progression[skill_lc] = {
                'xp': float(xp_gain),
                'level_before': int(level_before),
                'level_after': int(level_after),
            }
    except Exception as e:
        print(f"[ct-summary] skill_progression build failed: {e}", flush=True)
        skill_progression = {}

    master = {
        'total_steps': total_steps,
        'total_actions': total_actions,
        'time_days': time_days,
        'xp_by_skill': xp_by_skill,
        'skill_progression': skill_progression,
        'shopping_list': shopping_list,
        'cost_breakdown': cost_breakdown,
        'steps_breakdown': steps_breakdown,
        'steps_by_skill': steps_by_skill,
        'target_yield': target_yield,
        'target_value': target_value,
        'side_drops': side_drops,
        'side_drops_value': side_drops_value,
        'material_cost': material_cost,
        'net_profit': net_profit,
    }
    return (True, '', master)


def calculate_node_metrics(
    node: dict,
    children_nodes: List[dict],
    children_metrics: List[dict],
    game_data: dict,
    session_data: Optional[dict],
    global_settings: dict,
    is_root: bool = False,
) -> dict:
    """Calculate metrics for a single node given its children's metrics.

    Formulas by source_type:

    Recipe:
        steps_per_item = steps_per_action / (output_qty × (1+DA) × (1+DR) × quality_prob)
        input_ratio = (required_amount × (1-NMC)) / (output_qty × (1+DR) × quality_prob)

    Activity:
        steps_per_item = steps_from_drop_table / quality_prob

    Chest:
        steps_per_item = (steps_per_chest / expected_items) / quality_prob

    Bank:
        Subtract banked_quantity from total needed.

    Returns dict with steps_per_item, total_steps, total_actions, xp, shopping_list, etc.
    """
    result = {
        'steps_per_item': float('inf'),
        'total_steps': 0.0,
        'total_actions': 0.0,
        # Per-node-only work (excludes children rolled up in the recipe
        # branch). Defaults match total_*, which is correct for leaves
        # (bank/shop/activity/chest) — they have no children to roll up.
        # The recipe branch explicitly snapshots these before the child
        # loop so total_* can accumulate without touching self_*.
        'self_steps': 0.0,
        'self_actions': 0.0,
        # Per-node-only xp + steps_breakdown contribution (just this node's
        # own work, no children rolled up). Used by calculate_tree's
        # "buffer at root only" summary scaling — only the ROOT node's
        # self_* portion is multiplied by effective_qty (target × (1+buffer));
        # children cascade with target_quantity. Bug 15110e01.
        'self_xp': {},
        'self_steps_breakdown': {},
        'xp': {},
        'shopping_list': {},
        'raw_materials': {},
        'drops_gained': {},
        # Per-node-only drops_gained snapshot (just this node's own drops,
        # set before children roll up). Used by calculate_tree's
        # "buffer at root only" scaling for side_drops (bug 15110e01).
        'self_drops_gained': {},
        'steps_breakdown': {},
        # Parallel dict mapping each steps_breakdown source_name to its
        # 16x16 icon path (item icon for recipes, activity icon for
        # activities). Frontend renders this next to the source name
        # in the summary's Steps Breakdown table. Populated alongside
        # steps_breakdown anywhere in this function that writes the
        # source_name → steps mapping.
        'steps_breakdown_icons': {},
        'stats_used': {},
        'input_ratios': {},
    }

    source_type = node.get('source_type', 'bank')
    item_ref = node.get('item_id', '')
    # Normal (non-fine) ref the node actually represents in the tree. Shops only
    # ever stock this variant (bug a8b48d9a) — never the _FINE rewrite below.
    raw_item_ref = item_ref

    # Global fine materials setting — switch material refs to fine versions
    use_fine = global_settings.get('use_fine', False)
    item_ref = _rewrite_to_fine(item_ref, use_fine)

    # Populate available_locations for no-service recipe nodes (handles both
    # 'recipe' and 'best' -> recipe cases). This runs before the 'best' branch
    # because the 'best' handler recurses with a temp node and wouldn't update
    # the real node.
    effective_src_type = node.get('underlying_source_type') if source_type == 'best' else source_type
    effective_src_id = node.get('underlying_source_id') if source_type == 'best' else node.get('source_id')
    # Debug: log for any recipe node to understand what's happening on Twine etc.
    if effective_src_type == 'recipe':
        _dbg_existing = node.get('available_locations')
        _dbg_recipe = game_data.get('recipes', {}).get(effective_src_id) if effective_src_id else None
        _dbg_svc = _dbg_recipe.service if _dbg_recipe else None
        print(f"[crafting_tree] Recipe node check: node_id={node.get('node_id')} "
              f"item={node.get('item_id')} source_type={source_type} "
              f"effective_src_id={effective_src_id!r} recipe_found={_dbg_recipe is not None} "
              f"service={_dbg_svc!r} existing_avail_locs_truthy={bool(_dbg_existing)}")
    # For no-service recipe nodes, always refresh available_locations.
    # (Unconditional so stale saved-state values get replaced.)
    if (effective_src_type == 'recipe' and effective_src_id
            and game_data.get('locations')):
        _eff_recipe = game_data['recipes'].get(effective_src_id)
        if _eff_recipe and (not _eff_recipe.service or _eff_recipe.service.lower() == 'none'):
            _unlocked = set(session_data.get('region_unlocks', [])) if session_data else set()
            _avail_locs = [{'id': '__best__', 'label': 'Best (auto)'}]
            for _loc_name, _loc_obj in game_data['locations'].items():
                if not hasattr(_loc_obj, 'name'):
                    continue
                if getattr(_loc_obj, 'is_underwater', False):
                    continue
                if _unlocked and not _is_location_in_unlocked_region(_loc_obj, _unlocked):
                    continue
                if _is_location_locked(_loc_obj.name, session_data):
                    continue
                _avail_locs.append({'id': _loc_obj.name, 'label': _loc_obj.name})
            _avail_locs[1:] = sorted(_avail_locs[1:], key=lambda l: l['label'])
            node['available_locations'] = _avail_locs
            print(f"[crafting_tree] Populated available_locations for no-service recipe "
                  f"node_id={node.get('node_id')} item={node.get('item_id')} "
                  f"count={len(_avail_locs)}")

    # Clear stale __none__ service for no-service recipes (handles saved trees
    # that have the old [{'id': '__none__', 'label': 'No service'}] placeholder).
    if effective_src_type == 'recipe' and effective_src_id:
        _eff_recipe2 = game_data['recipes'].get(effective_src_id)
        if _eff_recipe2 and (not _eff_recipe2.service or _eff_recipe2.service.lower() == 'none'):
            _svcs = node.get('available_services')
            if _svcs and any(s.get('id') == '__none__' for s in _svcs):
                node['available_services'] = []

    # "Best (auto)" — try all non-bank sources and pick lowest steps/item
    if source_type == 'best':
        skip_shops = global_settings.get('skip_shops', True)
        best_result = None
        best_steps = float('inf')
        best_label = None
        best_icon = ''
        best_src_type = None
        best_src_id = None
        # The children_nodes/children_metrics passed into this function were
        # built for node['underlying_source_id'] — the source picked by
        # _pick_best_underlying_source at tree-build time (which already
        # does a global min-steps search across all candidates + material
        # groups). Restrict Pass-1 to ONLY evaluate that same source so the
        # children stay consistent with the trial. Without this filter,
        # Pass-1 would try e.g. "Cut into ectoplasm" using children that
        # were actually built for "Smelt into ectoplasm" (Ectoplasm rock),
        # producing bogus numbers and picking the wrong source as winner —
        # showing "Best → Cut" while the optimizer still runs Smelt (rocks
        # + smithing gear).
        effective_underlying_type = node.get('underlying_source_type')
        effective_underlying_id = node.get('underlying_source_id')
        for src in node.get('available_sources', []):
            if src['type'] in ('bank', 'best'):
                continue
            if src['type'] == 'shop' and skip_shops:
                continue
            # Only evaluate the source matching the built children. Any other
            # candidate's trial would be computed with mismatched child data.
            if effective_underlying_type and effective_underlying_id:
                if src.get('type') != effective_underlying_type:
                    continue
                if src.get('source_id') != effective_underlying_id:
                    continue
            # Temporarily set the node to this source
            saved = {k: node.get(k) for k in ('source_type', 'source_id', 'parent_activity_id',
                                                'chest_source', 'parent_recipe_id')}
            saved_avail_locs = node.pop('available_locations', None)
            node['source_type'] = src['type']
            node['source_id'] = src.get('source_id')
            node['parent_activity_id'] = src.get('parent_activity_id')
            node['chest_source'] = src.get('chest_source', 'activity')
            node['parent_recipe_id'] = src.get('parent_recipe_id')
            try:
                trial = calculate_node_metrics(
                    node=node, children_nodes=children_nodes, children_metrics=children_metrics,
                    game_data=game_data, session_data=session_data,
                    global_settings=global_settings, is_root=is_root,
                )
                spi = trial.get('steps_per_item')
                if spi is not None and spi < best_steps:
                    best_steps = spi
                    best_result = trial
                    best_label = src.get('label', str(src.get('source_id', '')))
                    best_icon = src.get('icon', '')
                    best_src_type = src.get('type')
                    best_src_id = src.get('source_id')
            except Exception:
                pass
            # Restore
            for k, v in saved.items():
                node[k] = v
            if saved_avail_locs is not None:
                node['available_locations'] = saved_avail_locs
            elif 'available_locations' in node:
                del node['available_locations']

        if best_result:
            best_result['stats_used']['best_source_label'] = best_label
            best_result['stats_used']['best_source_icon'] = best_icon
            # Record the effective underlying source that Pass-1 actually picked.
            # This can differ from `underlying_source_*` set by build_crafting_tree
            # (which uses priority-order, not steps-per-item). Downstream code
            # (LP solver, UI) can compare this to the gear's skill context to
            # detect stale gear.
            best_result['stats_used']['effective_source_type'] = best_src_type
            best_result['stats_used']['effective_source_id'] = best_src_id
            # Restore node to 'best' type
            node['source_type'] = 'best'
            node['source_id'] = '__best__'
            return best_result
        # Fallback: no valid source found
        node['source_type'] = 'best'
        node['source_id'] = '__best__'
        return result

    # Bank nodes
    if source_type == 'bank':
        result['steps_per_item'] = 0.0
        result['total_steps'] = 0.0
        result['total_actions'] = 0.0
        banked = node.get('banked_quantity', 0)
        # Shopping list will be computed in calculate_tree based on effective quantity
        result['shopping_list'] = {item_ref: 1.0}  # Per-unit: 1 item needed
        result['raw_materials'] = {item_ref: 1.0}
        return result

    # Shop nodes — zero steps, costs coins, leaf node
    if source_type == 'shop':
        result['steps_per_item'] = 0.0
        result['total_steps'] = 0.0
        result['total_actions'] = 0.0
        # Bug a8b48d9a: shops stock only the normal (non-fine) variant. Use the
        # un-rewritten ref so a shop is never reported as a source for a fine
        # material it doesn't actually carry.
        result['shopping_list'] = {raw_item_ref: 1.0}
        result['raw_materials'] = {raw_item_ref: 1.0}
        # Find the price from available_sources
        shop_src = next(
            (s for s in node.get('available_sources', [])
             if s.get('type') == 'shop' and s.get('source_id') == node.get('source_id')),
            None
        )
        price = shop_src.get('price', 0) if shop_src else 0
        currency = shop_src.get('currency', 'coins') if shop_src else 'coins'
        result['stats_used'] = {'shop_price': price, 'shop_currency': currency,
                                'shop_name': node.get('source_id', '')}
        return result

    # Resolve gear stats
    gear_stats = _get_gear_stats(node, session_data, game_data)

    # Resolve collectible stats
    skill_name = None
    activity_level = 1
    base_steps = 0
    base_xp = 0.0
    max_efficiency = 0.6
    recipe = None
    activity = None

    if source_type == 'recipe':
        recipe = game_data['recipes'].get(node.get('source_id'))
        if recipe:
            skill_name = recipe.skill
            activity_level = recipe.level
            base_steps = recipe.base_steps
            base_xp = recipe.base_xp
            max_efficiency = recipe.max_efficiency

    elif source_type in ('activity', 'chest'):
        act_id = node.get('source_id') if source_type == 'activity' else node.get('parent_activity_id')
        activity = game_data['activities'].get(act_id)
        if activity:
            skill_name = activity.primary_skill
            if activity.skill_requirements:
                activity_level = list(activity.skill_requirements.values())[0]
            base_steps = activity.base_steps or 318
            base_xp = activity.base_xp or 0
            max_efficiency = activity.max_efficiency or 0.6

    skill_level = _get_skill_level(skill_name, session_data)
    # Resolve the node's stat-context location so collectible bonuses are
    # evaluated at the SAME location as gear/service stats. Without this,
    # location-gated collectible stats (e.g. underwater double_rewards) were
    # dropped from the displayed node stats (bug 4e840909).
    _stat_location = _resolve_node_stat_location(node, game_data, session_data)
    collectible_stats = _get_collectible_stats(session_data, skill_name, location=_stat_location)

    # Combine all stats
    stats = dict(gear_stats)
    for k, v in collectible_stats.items():
        stats[k] = stats.get(k, 0.0) + v

    # Activity-node input items: merge their stats into the stats dict so DR/DA
    # from arrows (or other input items) are reflected in the drops calculation.
    # Input item selection lives in node.gear_config.selected_input_items, populated
    # by the optimization worker when an activity has `input_items` declared.
    if source_type in ('activity', 'chest') and activity and skill_name:
        _sii = (node.get('gear_config') or {}).get('selected_input_items') or {}
        if _sii:
            _input_loc = None
            if getattr(activity, 'locations', None):
                _first_loc = activity.locations[0]
                _input_loc = _first_loc.name if hasattr(_first_loc, 'name') else str(_first_loc)
            for _idx_key, _ii in _sii.items():
                if not _ii:
                    continue
                _input_obj = _resolve_input_item_ref(_ii)
                if _input_obj is None:
                    continue
                try:
                    _ii_stats = _input_obj.get_stats_for_skill(skill_name, location=_input_loc) \
                        if hasattr(_input_obj, 'get_stats_for_skill') else {}
                except Exception:
                    _ii_stats = {}
                for _k, _v in (_ii_stats or {}).items():
                    try:
                        stats[_k] = stats.get(_k, 0.0) + float(_v)
                    except (TypeError, ValueError):
                        continue

    # Add service stats for recipe nodes
    selected_service_name = None
    selected_service_id = node.get('selected_service_id')
    if source_type == 'recipe' and recipe and skill_name:
        service_stats, svc_name = _get_best_service_stats(
            recipe, skill_name, game_data, session_data, selected_service_id,
            node.get('selected_location_id'),
        )
        for k, v in service_stats.items():
            stats[k] = stats.get(k, 0.0) + v
        selected_service_name = svc_name

        # Populate available_services on the node for frontend dropdown
        if 'available_services' not in node or not any(s.get('icon') for s in node.get('available_services', []) if s.get('id') != '__best__'):
            # Recipe doesn't require a service — no service row, use location dropdown instead
            if not recipe.service or recipe.service.lower() == 'none':
                node['available_services'] = []
            else:
                avail = []
                avail.append({'id': '__best__', 'label': 'Best (auto)', 'icon': '/assets/icons/attributes/work_efficiency.svg'})
                matched = []
                for svc_id, svc in game_data.get('services', {}).items():
                    if _service_valid_for_recipe(svc, recipe):
                        matched.append((svc_id, svc))
                if not matched:
                    recipe_skill = (recipe.skill or '').lower()
                    for svc_id, svc in game_data.get('services', {}).items():
                        svc_cat = svc.category.value.lower() if hasattr(svc.category, 'value') else str(svc.category).lower()
                        if svc_cat == recipe_skill:
                            matched.append((svc_id, svc))
                for svc_id, svc in matched:
                    loc_name = svc.location.name if hasattr(svc.location, 'name') else str(svc.location)
                    # Check spoiler status — region-level and location-level
                    region_unlocks = set(session_data.get('region_unlocks', [])) if session_data else set()
                    if not region_unlocks and session_data:
                        region_unlocks = {'jarvonia'}
                    is_region_locked = not _is_location_in_unlocked_region(svc.location, region_unlocks) if hasattr(svc, 'location') else False
                    is_loc_locked = _is_location_locked(loc_name, session_data)
                    is_spoiler = is_region_locked or is_loc_locked
                    spoiler_reason = _get_spoiler_reason_for_location(
                        getattr(svc, 'location', None), loc_name,
                        bool(is_region_locked), bool(is_loc_locked),
                        session_data=session_data,
                    ) if is_spoiler else None
                    avail.append({
                        'id': svc_id,
                        'label': f"{svc.name} ({loc_name})",
                        'icon': _get_service_icon_path(svc),
                        'is_spoiler': is_spoiler,
                        'spoiler_reason': spoiler_reason,
                    })
                node['available_services'] = avail

    # For activity nodes, resolve location for stat context
    activity_location = None
    if source_type in ('activity', 'chest') and activity and activity.locations:
        sel_loc = node.get('selected_location_id')
        if sel_loc:
            for loc in activity.locations:
                loc_name = loc.name if hasattr(loc, 'name') else str(loc)
                if loc_name.lower() == sel_loc.lower():
                    activity_location = loc_name
                    break
        if not activity_location:
            activity_location = activity.locations[0].name if hasattr(activity.locations[0], 'name') else str(activity.locations[0])

        # Populate available_locations on the node for frontend dropdown
        if 'available_locations' not in node and len(activity.locations) > 1:
            avail_locs = []
            avail_locs.append({'id': '__best__', 'label': 'Best (auto)'})
            for loc in activity.locations:
                loc_name = loc.name if hasattr(loc, 'name') else str(loc)
                avail_locs.append({'id': loc_name, 'label': loc_name})
            node['available_locations'] = avail_locs

    # For no-service recipe nodes, use selected_location_id for gear stat context
    elif source_type == 'recipe' and recipe and (not recipe.service or recipe.service.lower() == 'none'):
        sel_loc = node.get('selected_location_id')
        if sel_loc and sel_loc != '__best__':
            activity_location = sel_loc
        # available_locations is populated at the top of this function
        # (before the 'best' branch) to handle both 'recipe' and 'best' source types.
        # Even with no explicit selection, surface the last auto-resolved
        # location on `stats_used.location` so the frontend can render
        # "Best → <region>" in the location dropdown (via the bestResolvedName
        # fallback in _wireFullLocationDropdown). Without this, picking "Best
        # (auto)" leaves the button saying "Best (auto)" forever even after
        # the worker has picked a winner.
        if not activity_location:
            last_auto = node.get('last_auto_resolved_location')
            if last_auto:
                activity_location = last_auto

    # Extract key stats
    DA = min(1.0, stats.get('double_action', 0.0))
    DR = min(1.0, stats.get('double_rewards', 0.0))
    NMC = min(0.99, stats.get('no_materials_consumed', 0.0))
    WE = stats.get('work_efficiency', 0.0)
    QO = stats.get('quality_outcome', 0.0)
    flat = int(stats.get('steps_add', 0))
    pct = stats.get('steps_percent', 0.0)
    bxp_pct = stats.get('bonus_xp_percent', 0.0)
    bxp_add = stats.get('bonus_xp_add', 0.0)

    # Quality probability — only at root when target_quality != Normal
    # Only apply quality for equipment items (Item.*), not materials/consumables
    quality_prob = 1.0
    target_quality = global_settings.get('target_quality', 'Normal')
    item_is_equipment = item_ref.startswith('Item.')
    # QO from `stats` is gear + collectibles + service only. Add the skill-level
    # bonus here so downstream quality-weight math matches the in-game value
    # and is consistent with Column 2's recipe-info-section calculation.
    level_bonus_qo = max(0, skill_level - activity_level)
    QO_effective = QO + level_bonus_qo
    if is_root and target_quality != 'Normal' and item_is_equipment:
        try:
            from util.quality_outcome import calculate_quality_weights
            # Check if recipe has equipment inputs (for fine material 70/30 blend)
            has_equipment_input = False
            if recipe and recipe.materials:
                for group in recipe.materials:
                    for qty, mat in group:
                        mat_ref = _get_item_ref_string(mat)
                        if mat_ref and mat_ref.startswith('Item.'):
                            has_equipment_input = True
                            break
                    if has_equipment_input:
                        break
            qw = calculate_quality_weights(activity_level, QO_effective, use_fine=use_fine, has_equipment_input=has_equipment_input)
            percentages = qw.get('percentages', {})
            # Sum probabilities for target quality and above
            target_idx = QUALITY_TIERS.index(target_quality) if target_quality in QUALITY_TIERS else 0
            quality_prob = sum(
                percentages.get(q, 0.0) / 100.0
                for q in QUALITY_TIERS[target_idx:]
            )
            if quality_prob <= 0.00001:
                quality_prob = 0.00001
        except Exception:
            quality_prob = 1.0

    # Level-based WE bonus (same as in _calculate_steps_per_action)
    levels_above = max(0, skill_level - activity_level)
    level_bonus_we = min(levels_above, 20) * 0.0125
    total_we_with_level = WE + level_bonus_we
    # Display the full effective WE (gear + collectibles + service + level
    # bonus). The activity-output / "equip" screen shows this uncapped value;
    # the max_efficiency cap only limits the steps benefit (applied inside
    # _calculate_steps_per_action), NOT the displayed stat. Capping the
    # displayed WE here made the crafting-tree node read lower than the
    # activity screen for high-level / high-WE setups (bug 4e840909).

    result['stats_used'] = {
        'DA': DA, 'DR': DR, 'NMC': NMC, 'WE': total_we_with_level,
        'quality_outcome': QO_effective, 'quality_prob': quality_prob,
        'level_bonus_we': level_bonus_we,
        'skill_level': skill_level,
        'flat': flat, 'pct': pct,
        'fine_material_finding': stats.get('fine_material_finding', 0.0),
        'service_name': selected_service_name,
        'location': activity_location,
    }

    # Calculate steps per action
    steps_per_action = _calculate_steps_per_action(
        base_steps, max_efficiency, skill_level, activity_level, WE, flat, pct
    )

    # ==========================================
    # RECIPE
    # ==========================================
    if source_type == 'recipe' and recipe:
        output_qty = recipe.quantity or 1

        # Bug af9d3e86 / 79ec57d9 (2026-05-31): credit IF target bonus on
        # recipe output. When `recipe.output_item` is dropped by an
        # `ItemFindingCategory.X` stat the player has (e.g. Spectral gear's
        # `ItemFindingCategory.ECTOPLASM` while crafting at Wraithwater /
        # Cursed Loom), the IF stat acts as bonus drops of the target item,
        # cutting required crafts/steps. Activity engine already does this
        # in `get_expected_drop_rate`; recipes need parity.
        try:
            from util.item_utils import if_target_bonus_per_roll as _if_bonus_for_target
            _if_target_bonus_per_roll_value = _if_bonus_for_target(
                stats, getattr(recipe, 'output_item', '') or ''
            )
        except ImportError:
            _if_target_bonus_per_roll_value = 0.0

        # Steps per item for this node alone
        # target_yield_per_action = (output_qty + IF_bonus) * (1+DA) * (1+DR) * quality_prob
        # IF bonus drops aren't quality-bearing, but for non-quality recipes
        # quality_prob == 1.0 anyway. For quality recipes, IF still
        # contributes Normal-quality copies — only count the IF bonus
        # against the same quality_prob denominator so we don't over-credit
        # gear when scoring a Perfect-quality target.
        _if_target_yield_per_action = _if_target_bonus_per_roll_value * (1.0 + DA) * (1.0 + DR)
        _primary_yield_per_action = output_qty * (1.0 + DA) * (1.0 + DR) * quality_prob
        _effective_yield_per_action = _primary_yield_per_action + _if_target_yield_per_action
        if _effective_yield_per_action > 0:
            steps_per_item = steps_per_action / _effective_yield_per_action
        else:
            steps_per_item = float('inf')
        result['steps_per_item'] = steps_per_item
        result['total_steps'] = steps_per_item
        result['steps_breakdown'][f"Recipe: {recipe.name}"] = steps_per_item
        # Snapshot the per-node-only steps_breakdown contribution. Used
        # by calculate_tree's "buffer at root only" scaling — bug
        # 15110e01 — and never overwritten by the children rollup loop.
        result['self_steps_breakdown'][f"Recipe: {recipe.name}"] = steps_per_item
        # Recipe source icon = the recipe's output item icon (user
        # spec 2026-05-15). Falls back to the recipe's skill icon if
        # the output item ref doesn't resolve.
        try:
            output_ref = getattr(recipe, 'output_item', '') or ''
            if output_ref:
                result['steps_breakdown_icons'][f"Recipe: {recipe.name}"] = (
                    _get_icon_path_for_ref(output_ref) or _get_recipe_icon_path(recipe)
                )
            else:
                result['steps_breakdown_icons'][f"Recipe: {recipe.name}"] = _get_recipe_icon_path(recipe)
        except Exception:
            result['steps_breakdown_icons'][f"Recipe: {recipe.name}"] = _get_recipe_icon_path(recipe)

        # Targeted logging for tree-vs-info-section steps/item divergence
        # investigations (e.g. Iron sickle showing 8110 in the tree node
        # header but 8273 in the recipe-info "Perfect" row after equip).
        # Emits the full set of inputs that feed the formula so we can
        # compare against the equivalent logs in calculator-section.js
        # ([CT-STEPS-INFO]) to spot the divergence source. Most likely
        # suspects: target_quality differs (tree uses global_settings.target_quality,
        # info section may render per-tier rows), or DA/DR/NMC/WE differ
        # between the optimizer-picked gearset and the equipped gearset.
        print(f"[CT-STEPS-TREE] recipe={recipe.name} output_qty={output_qty} "
              f"steps_per_action={steps_per_action:.4f} DA={DA:.4f} DR={DR:.4f} "
              f"NMC={NMC:.4f} WE={total_we_with_level:.4f} QO_effective={QO_effective} "
              f"target_quality={target_quality} quality_prob={quality_prob:.6f} "
              f"skill_level={skill_level} activity_level={activity_level} "
              f"base_steps={base_steps} max_eff={max_efficiency:.4f} "
              f"flat={flat} pct={pct:.4f} "
              f"=> steps_per_item={steps_per_item:.4f}",
              flush=True)

        # XP per item
        xp_per_item = ((base_xp * (1.0 + bxp_pct)) + bxp_add) / (output_qty * (1.0 + DR) * quality_prob)
        if skill_name:
            result['xp'][skill_name.lower()] = xp_per_item
            result['self_xp'][skill_name.lower()] = xp_per_item

        # Total actions for this node
        # Effective per-action yield includes IF target bonus (see
        # steps_per_item derivation above) so total_actions reflects the
        # actual number of crafts you'd run to satisfy the parent's
        # `input_ratio * target_qty` consumption.
        if _effective_yield_per_action > 0:
            result['total_actions'] = 1.0 / _effective_yield_per_action
        else:
            result['total_actions'] = float('inf')

        # Snapshot the per-recipe-only work BEFORE children roll in. The
        # frontend uses these to render per-node totals (e.g. twine recipe
        # at x1 shows "1 action" for the spin itself, not 6 that would
        # include the flax gathering below). Children's work gets added
        # to total_steps / total_actions in the loop below, leaving
        # self_steps / self_actions untouched.
        result['self_steps'] = steps_per_item
        result['self_actions'] = result['total_actions']

        # ------------------------------------------------------------------
        # drops_gained — per unit of node output (this recipe produces 1 target
        # per unit of itself, plus any service-provided secondary drops).
        # Requirement 1.9: only activity/recipe/chest nodes contribute.
        # ------------------------------------------------------------------
        # Per-action output of the target — quality-adjusted, INCLUDING the
        # IF target-bonus contribution (bug af9d3e86 / 79ec57d9). The
        # primary recipe output and any IF.X drop whose ref matches the
        # recipe's output_item both surface as the same item_ref, so they
        # combine here. drops_gained[item_ref] still ends up at 1.0 per
        # node output unit because total_actions = 1 / effective_yield.
        if _effective_yield_per_action > 0:
            result['drops_gained'][item_ref] = (
                result['drops_gained'].get(item_ref, 0.0)
                + _effective_yield_per_action * result['total_actions']
            )
        # IF expansion drops that DON'T match the recipe target get
        # surfaced as separate side drops (e.g. Adventurers' guild
        # tokens via Adventuring amulet on a non-AGT recipe). Each IF
        # drop is single-roll and gets `(1+DA)*(1+DR)` reward rolls.
        try:
            from util.item_utils import iter_if_drops_per_roll as _iter_if_drops_recipe
        except ImportError:
            _iter_if_drops_recipe = None
        if _iter_if_drops_recipe is not None:
            _rewards_per_completion_recipe = (1.0 + DA) * (1.0 + DR)
            for _if_ref, _if_qty_per_roll in _iter_if_drops_recipe(stats):
                if not _if_ref or _if_ref == item_ref:
                    # Already counted in the effective yield above
                    continue
                _if_yield_per_action = _if_qty_per_roll * _rewards_per_completion_recipe
                if _if_yield_per_action <= 0:
                    continue
                result['drops_gained'][_if_ref] = (
                    result['drops_gained'].get(_if_ref, 0.0)
                    + _if_yield_per_action * result['total_actions']
                )
        # Secondary recipe drop table (e.g. pet eggs, Silver nugget on bar recipes) — service-provided
        recipe_drop_table = getattr(recipe, 'drop_table', None) or []
        for entry in recipe_drop_table:
            # Recipe drop entries may be dicts or DropEntry instances
            drop_ref = None
            drop_chance = 0.0
            drop_avg_qty = 1.0
            roll_count = 1
            if isinstance(entry, dict):
                drop_ref = entry.get('item_ref') or entry.get('item_id')
                drop_chance = float(entry.get('chance_percent', 0) or 0) / 100.0
                qty = entry.get('quantity')
                if isinstance(qty, (int, float)):
                    drop_avg_qty = float(qty)
                elif hasattr(qty, 'average'):
                    drop_avg_qty = float(qty.average)
                mrc = entry.get('multi_roll_count')
                if mrc and int(mrc) > 1:
                    roll_count = int(mrc)
            elif hasattr(entry, 'item_ref'):
                drop_ref = entry.item_ref
                drop_chance = float(entry.chance_percent or 0) / 100.0
                drop_avg_qty = entry.quantity.average if entry.quantity else 1.0
                mrc = getattr(entry, 'multi_roll_count', None)
                if mrc and int(mrc) > 1:
                    roll_count = int(mrc)
            if not drop_ref or drop_chance <= 0 or drop_avg_qty <= 0:
                continue
            # Secondary drop yield per action — DA/DR still apply; rolls multiply linearly.
            secondary_per_action = roll_count * drop_chance * drop_avg_qty * (1.0 + DA) * (1.0 + DR)
            result['drops_gained'][drop_ref] = (
                result['drops_gained'].get(drop_ref, 0.0)
                + secondary_per_action * result['total_actions']
            )

        # Snapshot the per-node-only drops_gained contribution BEFORE
        # children roll up. Used by calculate_tree's "buffer at root only"
        # scaling for side_drops (bug 15110e01).
        result['self_drops_gained'] = dict(result['drops_gained'])

        # Aggregate children
        # First, detect co-dropped siblings: children sharing the same activity source
        # get their steps reduced because you gather both items simultaneously
        co_drop_groups = {}  # activity_source_id -> list of child indices
        for i, child_node in enumerate(children_nodes):
            child_source = child_node.get('source_type', '')
            if child_source in ('activity', 'best'):
                effective_source = child_node.get('source_id', '')
                if child_source == 'best':
                    effective_source = child_node.get('underlying_source_id', '') or effective_source
                if effective_source:
                    co_drop_groups.setdefault(effective_source, []).append(i)

        # For co-drop groups with 2+ siblings, the activity steps are shared:
        # instead of each child paying full steps, the group pays max(steps) once
        # and each child's contribution is scaled by 1/group_size
        co_drop_scale = {}  # child index -> scale factor (1.0 = no sharing)
        for source_id, indices in co_drop_groups.items():
            if len(indices) > 1:
                for idx in indices:
                    co_drop_scale[idx] = 1.0 / len(indices)

        for i, (child_node, child_metrics) in enumerate(zip(children_nodes, children_metrics)):
            req_amount = child_node.get('base_requirement_amount', 1)
            input_ratio = (req_amount * (1.0 - NMC)) / (output_qty * (1.0 + DR) * quality_prob)

            # Apply co-drop scaling: if this child shares an activity with siblings,
            # reduce its step contribution (you get both drops from the same actions)
            scale = co_drop_scale.get(i, 1.0)
            scaled_steps = input_ratio * child_metrics.get('total_steps', 0.0) * scale

            result['input_ratios'][child_node['node_id']] = input_ratio

            result['total_steps'] += scaled_steps
            result['total_actions'] += input_ratio * child_metrics.get('total_actions', 0.0) * scale

            for sk, xpv in child_metrics.get('xp', {}).items():
                result['xp'][sk] = result['xp'].get(sk, 0.0) + input_ratio * xpv * scale
            for item_k, amt in child_metrics.get('shopping_list', {}).items():
                result['shopping_list'][item_k] = result['shopping_list'].get(item_k, 0.0) + input_ratio * amt  # no scale — still need the materials
            for item_k, amt in child_metrics.get('raw_materials', {}).items():
                result['raw_materials'][item_k] = result['raw_materials'].get(item_k, 0.0) + input_ratio * amt  # no scale
            for item_k, amt in child_metrics.get('drops_gained', {}).items():
                # Drops roll up scaled by input_ratio only — NOT by co_drop_scale.
                # The co_drop_scale factor already lives in each child's total_steps
                # (via scaled_steps = input_ratio * total_steps * scale), so applying
                # it to drop quantities would double-count. See design.md
                # "Co-drop rollup vs drops_gained".
                result['drops_gained'][item_k] = result['drops_gained'].get(item_k, 0.0) + input_ratio * amt
            for src, stp in child_metrics.get('steps_breakdown', {}).items():
                result['steps_breakdown'][src] = result['steps_breakdown'].get(src, 0.0) + input_ratio * stp * scale  # scaled — shared steps
            # Roll the child's source-icon mapping up too so the
            # summary builder in calculate_tree can resolve every
            # source_name back to an icon. First-write wins for a
            # given source_name (consistent with how steps_breakdown
            # aggregates duplicate source entries).
            for src_name, icon in child_metrics.get('steps_breakdown_icons', {}).items():
                if src_name not in result['steps_breakdown_icons']:
                    result['steps_breakdown_icons'][src_name] = icon

    # ==========================================
    # ACTIVITY
    # ==========================================
    elif source_type == 'activity' and activity:
        steps_from_drops = _get_activity_drop_steps(activity, item_ref, stats, skill_level)
        if steps_from_drops and steps_from_drops > 0:
            steps_per_item = steps_from_drops / quality_prob
            result['steps_per_item'] = steps_per_item
            result['total_steps'] = steps_per_item
            result['steps_breakdown'][f"Activity: {activity.name}"] = steps_per_item
            # Snapshot per-node-only steps_breakdown contribution (bug 15110e01).
            result['self_steps_breakdown'][f"Activity: {activity.name}"] = steps_per_item
            # Activity source icon = activity icon constructed from
            # primary_skill + name slug (mirrors get_available_sources).
            try:
                skill_slug = (getattr(activity, 'primary_skill', '') or '').lower().replace(' ', '_')
                act_slug = (getattr(activity, 'name', '') or '').lower().replace(' ', '_').replace("'", '').replace('-', '_')
                if skill_slug and act_slug:
                    result['steps_breakdown_icons'][f"Activity: {activity.name}"] = f"/assets/icons/activities/{skill_slug}/{act_slug}.svg"
                else:
                    result['steps_breakdown_icons'][f"Activity: {activity.name}"] = '/assets/icons/attributes/work_efficiency.svg'
            except Exception:
                result['steps_breakdown_icons'][f"Activity: {activity.name}"] = '/assets/icons/attributes/work_efficiency.svg'
            result['total_actions'] = steps_per_item / steps_per_action if steps_per_action > 0 else 0
            result['raw_materials'][item_ref] = 1.0
            # Activities are leaves — no children to roll up. self == total.
            # Still set these so the frontend can use a uniform field and
            # not have to branch on node type.
            result['self_steps'] = steps_per_item
            result['self_actions'] = result['total_actions']

            # XP per item
            # p_drop_q_drop = steps_per_action / (steps_from_drops * (1+DA) * (1+DR))
            # xp_per_item = ((base_xp * (1+bxp_pct)) + bxp_add) / ((1+DR) * p_drop_q_drop * quality_prob)
            if steps_from_drops > 0:
                p_drop_q_drop = steps_per_action / (steps_from_drops * (1.0 + DA) * (1.0 + DR))
                if p_drop_q_drop > 0:
                    xp_per_item = ((base_xp * (1.0 + bxp_pct)) + bxp_add) / ((1.0 + DR) * p_drop_q_drop * quality_prob)
                    if skill_name:
                        result['xp'][skill_name.lower()] = xp_per_item
                        result['self_xp'][skill_name.lower()] = xp_per_item

            # ------------------------------------------------------------------
            # drops_gained — iterate the full drop table (not just the target).
            # Each yield_per_action is multiplied by total_actions of this node
            # to express the result per unit of node output (consistent with
            # total_steps and raw_materials).
            # ------------------------------------------------------------------
            drop_yields = _compute_activity_drop_yields_per_action(activity, stats, skill_level)
            actions_per_unit = result['total_actions']
            for drop_ref, yield_per_action in drop_yields.items():
                result['drops_gained'][drop_ref] = (
                    result['drops_gained'].get(drop_ref, 0.0)
                    + yield_per_action * actions_per_unit
                )
            # Activities are leaves — self == total for drops too (bug 15110e01).
            result['self_drops_gained'] = dict(result['drops_gained'])
        else:
            result['steps_per_item'] = float('inf')
            result['total_steps'] = float('inf')

    # ==========================================
    # CHEST
    # ==========================================
    elif source_type == 'chest':
        container = game_data.get('containers', {}).get(node.get('source_id'))
        chest_source = node.get('chest_source', 'activity')

        if chest_source == 'best':
            # Try all available chest sources and pick the best (lowest steps/item)
            best_steps = None
            best_label = 'Chest'
            # Try activity source
            parent_act_id = node.get('parent_activity_id')
            if not parent_act_id:
                # Find it from available_sources
                for s in node.get('available_sources', []):
                    if s.get('chest_source') == 'activity' and s.get('parent_activity_id'):
                        parent_act_id = s['parent_activity_id']
                        break
            if parent_act_id:
                parent_activity = game_data['activities'].get(parent_act_id)
                act_steps = _get_chest_steps_per_item(container, parent_activity, item_ref, stats, skill_level)
                if act_steps and act_steps > 0 and (best_steps is None or act_steps < best_steps):
                    best_steps = act_steps
                    best_label = f"Activity: {parent_activity.name}" if parent_activity else "Activity"
            # Try all recipe sources
            for s in node.get('available_sources', []):
                if s.get('chest_source') == 'recipe' and s.get('parent_recipe_id'):
                    parent_recipe = game_data['recipes'].get(s['parent_recipe_id'])
                    r_steps = _get_chest_steps_per_item_via_recipe(container, parent_recipe, item_ref, stats, skill_level)
                    if r_steps and r_steps > 0 and (best_steps is None or r_steps < best_steps):
                        best_steps = r_steps
                        best_label = f"Recipe: {parent_recipe.name}" if parent_recipe else "Recipe"
            chest_steps = best_steps
            label_prefix = f"Best → {best_label}"

        elif chest_source == 'recipe':
            parent_recipe_id = node.get('parent_recipe_id')
            parent_recipe = game_data['recipes'].get(parent_recipe_id) if parent_recipe_id else None
            chest_steps = _get_chest_steps_per_item_via_recipe(container, parent_recipe, item_ref, stats, skill_level)
            label_prefix = f"Recipe: {parent_recipe.name}" if parent_recipe else "Recipe chest"
        else:
            parent_act_id = node.get('parent_activity_id')
            parent_activity = game_data['activities'].get(parent_act_id) if parent_act_id else None
            chest_steps = _get_chest_steps_per_item(container, parent_activity, item_ref, stats, skill_level)
            label_prefix = f"Activity: {parent_activity.name}" if parent_activity else "Activity chest"

        if chest_steps and chest_steps > 0:
            steps_per_item = chest_steps / quality_prob
            result['steps_per_item'] = steps_per_item
            result['total_steps'] = steps_per_item
            result['total_actions'] = steps_per_item / steps_per_action if steps_per_action > 0 else 0
            # Chest nodes are leaves — no children to roll up. Same
            # defaulting rationale as activities above.
            result['self_steps'] = steps_per_item
            result['self_actions'] = result['total_actions']
            chest_name = container.name if container else node.get('source_id', 'Unknown Chest')
            result['steps_breakdown'][f"Chest ({label_prefix}): {chest_name}"] = steps_per_item
            # Snapshot per-node-only steps_breakdown contribution (bug 15110e01).
            result['self_steps_breakdown'][f"Chest ({label_prefix}): {chest_name}"] = steps_per_item
            # Chest source icon — the universal treasure-chest icon.
            result['steps_breakdown_icons'][f"Chest ({label_prefix}): {chest_name}"] = '/assets/icons/items/containers/treasure_chest.svg'
            result['raw_materials'][item_ref] = 1.0

            # ------------------------------------------------------------------
            # drops_gained — every drop from the chest plus the chest itself as
            # a consumed input (subtract 1 chest per opening). Quantities are
            # expressed per unit of node output: openings_per_unit times the
            # per-opening yield of each drop.
            # ------------------------------------------------------------------
            container_yields = _compute_container_drop_yields_per_opening(container)
            target_per_opening = container_yields.get(item_ref, 0.0)
            # Also match via _match_item_ref to handle fine-rewritten targets
            if target_per_opening <= 0:
                for dref, per_open in container_yields.items():
                    if _match_item_ref(dref, item_ref):
                        target_per_opening = per_open
                        break
            if target_per_opening > 0:
                # openings_per_unit satisfies: openings_per_unit * target_per_opening == 1
                openings_per_unit = 1.0 / target_per_opening
                for dref, per_open in container_yields.items():
                    result['drops_gained'][dref] = (
                        result['drops_gained'].get(dref, 0.0)
                        + per_open * openings_per_unit
                    )
                # Consume one chest per opening (net subtraction from the pool)
                chest_ref = f"Container.{node.get('source_id')}" if node.get('source_id') else None
                if chest_ref and _resolve_item_ref(chest_ref) is not None:
                    result['drops_gained'][chest_ref] = (
                        result['drops_gained'].get(chest_ref, 0.0) - openings_per_unit
                    )
                # Chest nodes are leaves — self == total for drops too (bug 15110e01).
                result['self_drops_gained'] = dict(result['drops_gained'])
        else:
            result['steps_per_item'] = float('inf')
            result['total_steps'] = float('inf')

    return result


def calculate_tree(
    tree_nodes: List[dict],
    global_settings: dict,
    game_data: Optional[dict] = None,
    session_data: Optional[dict] = None,
    skip_recompute: bool = False,
) -> dict:
    """Calculate metrics for the entire tree bottom-up.

    Applies buffer_percentage from global_settings to the root node's quantity
    before cascading down.

    If ``skip_recompute=True``, the bottom-up traversal is SKIPPED and each
    node's existing ``metrics`` field is reused as-is. Use this for the
    "Rerun Summary" button — pure aggregation of the values already on
    the nodes, no per-node optimizer / LP / spoiler work. Result is
    deterministic for a fixed tree state. The node mutation passes that
    require fresh metrics (best_pick refresh, lock-warning recompute,
    spoiler refresh, LP solver) are also skipped in this mode.

    Args:
        tree_nodes: Flat node list with gear configs
        global_settings: {target_quantity, daily_steps, target_quality, buffer_percentage}
        game_data: Recipes, activities, services, containers, materials
        session_data: Character skills, collectibles, owned items

    Returns:
        {
            "nodes": [...],  # Each node enriched with metrics
            "summary": {
                "total_steps": float,
                "time_days": float,
                "xp_by_skill": {skill: xp},
                "shopping_list": [{item_id, name, quantity}],
                "cost_breakdown": [{item, quantity, unit_value, total_cost}],
                "steps_breakdown": [{source, steps}]
            }
        }
    """
    if game_data is None:
        game_data = _load_game_data()

    # Backfill spoiler_reason on saved available_sources. Sources are persisted
    # as-is in the tree's saved state. Trees saved before the spoiler_reason
    # feature landed only carry is_spoiler booleans and would otherwise render
    # no hover tooltip on the locked 🔒 entries. Recompute the reason strings
    # so the frontend title= attributes are always populated.
    if not skip_recompute:
        _refresh_spoiler_reasons(tree_nodes, game_data, session_data)

    target_quantity = global_settings.get('target_quantity', 1)
    daily_steps = global_settings.get('daily_steps', 30000)
    buffer_percentage = global_settings.get('buffer_percentage', 0.05)

    # Effective quantity at root
    effective_qty = target_quantity * (1.0 + buffer_percentage)

    # Build parent->children mapping
    children_map = defaultdict(list)
    node_map = {}
    for n in tree_nodes:
        node_map[n['node_id']] = n
        if n['parent_id']:
            children_map[n['parent_id']].append(n)

    # Find root (node with no parent)
    root_node = None
    for n in tree_nodes:
        if n['parent_id'] is None:
            root_node = n
            break
    if not root_node:
        return {'nodes': tree_nodes, 'summary': _empty_summary()}

    # Bottom-up traversal using topological sort
    # Process leaves first, then parents
    metrics_cache = {}

    def _calc_recursive(node_id: str, is_root: bool = False):
        node = node_map[node_id]
        children = children_map.get(node_id, [])

        # Calculate children first
        child_metrics_list = []
        child_nodes_list = []
        for child in children:
            _calc_recursive(child['node_id'], is_root=False)
            child_metrics_list.append(metrics_cache[child['node_id']])
            child_nodes_list.append(child)

        try:
            metrics = calculate_node_metrics(
                node=node,
                children_nodes=child_nodes_list,
                children_metrics=child_metrics_list,
                game_data=game_data,
                session_data=session_data,
                global_settings=global_settings,
                is_root=is_root,
            )
        except Exception as e:
            import traceback
            print(f"[crafting_tree] ERROR in calculate_node_metrics for node "
                  f"{node_id!r} item={node.get('item_id')!r} "
                  f"source_type={node.get('source_type')!r} "
                  f"source_id={node.get('source_id')!r}: {e}")
            traceback.print_exc()
            # Return a safe empty metrics so the rest of the tree still calculates
            metrics = {
                'steps_per_item': None,
                'total_steps': None,
                'total_actions': 0.0,
                'xp': {},
                'shopping_list': {},
                'raw_materials': {},
                'drops_gained': {},
                'steps_breakdown': {},
                'stats_used': {},
                'input_ratios': {},
                'error': str(e),
            }
        metrics_cache[node_id] = metrics
        node['metrics'] = metrics

    if skip_recompute:
        # "Rerun Summary" path. The bottom-up _calc_recursive is the
        # heavy / non-deterministic step (per-node best-source picks
        # for Best(auto), gear_config recompute, etc.). For pure
        # aggregation we just reuse whatever metrics each node already
        # carries from its last full optimize / calculate pass and
        # feed metrics_cache so the downstream effective_quantity
        # walk and summary build see the same numbers.
        for _n in tree_nodes:
            metrics_cache[_n['node_id']] = _n.get('metrics') or {}
    else:
        _calc_recursive(root_node['node_id'], is_root=True)

        # Mark best_pick_computed on every node with leaf_materials so the UI
        # can show '(best)' / reorder / dim losers. Before this pass runs the
        # flag is False from build_crafting_tree, which causes the frontend to
        # render all material options neutrally ("fresh tree" state).
        for _n in tree_nodes:
            if _n.get('leaf_materials'):
                _n['best_pick_computed'] = True
                # Refresh is_best_pick so it reflects the final underlying source
                # picked after metrics were recomputed.
                _n['leaf_materials'] = _build_leaf_materials(
                    _n.get('available_sources') or [],
                    game_data,
                    underlying_source_type=_n.get('underlying_source_type'),
                    underlying_source_id=_n.get('underlying_source_id'),
                    underlying_material_group_index=_n.get('selected_material_group_index'),
                )

    # Top-down propagate effective quantity so each node knows how many of
    # that item the user actually needs. Starts with the effective_qty at
    # root (target * buffer) and multiplies down by each metrics.input_ratios
    # edge. Stored as node['effective_quantity'] for the frontend.
    #
    # Buffer scope (bug 15110e01): only the ROOT node carries the buffer
    # (effective_qty = target × (1+buffer)). Children cascade from
    # target_quantity (whole-number demand), per user spec — "only the
    # parent node should be 1.05x (and then cascade down with whole
    # numbers)". The buffer represents statistical safety on the target
    # craft itself; child material requirements are computed against the
    # actual count of targets the user wants (target_quantity), not the
    # buffered count.
    #
    # Child demand is then ceiled UP to the next multiple of the child's
    # base_requirement_amount (the amount the parent recipe consumes per
    # craft). Rationale: if a twine recipe needs 2 flax and the expected
    # demand lands at 7.35 flax (NMC reduces avg consumption), the player
    # can't run half a craft — some crafts consume 2, some consume 0, and
    # the expected-value math says we'll use ~7.35 over enough runs. But
    # you need to stockpile a whole-craft quantity to actually complete
    # the next craft, which means rounding up to 8 (4 full crafts' worth).
    # Users reported 7 flax for 5 twine feeling wrong — 8 reads as "4
    # complete 2-flax crafts" and is the stockpile they actually need.
    root_node['effective_quantity'] = effective_qty
    # Children cascade from target_quantity (integer), NOT effective_qty.
    _stack = [(root_node['node_id'], target_quantity)]
    while _stack:
        _nid, _eff = _stack.pop()
        _m = metrics_cache.get(_nid) or {}
        _ratios = _m.get('input_ratios', {}) or {}
        for _child in children_map.get(_nid, []):
            _ratio = _ratios.get(_child['node_id'], 0.0) or 0.0
            _child_eff = _eff * _ratio
            # Ceil to the next multiple of base_requirement_amount so the
            # number represents a whole-craft stockpile. For req_amount=1
            # (activity leaves, 1-for-1 recipes) this is plain ceil(x)
            # which matches the old display behavior. For req_amount>=2
            # (e.g. twine recipe: 2 flax per craft) it bumps up to the
            # nearest craftable quantity.
            _req = _child.get('base_requirement_amount', 1) or 1
            if _req > 0 and _child_eff > 0 and _child_eff != float('inf'):
                _child_eff = math.ceil(_child_eff / _req) * _req
            _child['effective_quantity'] = _child_eff
            _stack.append((_child['node_id'], _child_eff))

    # Build summary by scaling root metrics. Bug 15110e01:
    # buffer (target × (1+buffer)) applies to ROOT's own contribution only,
    # children cascade with target_quantity. Equivalently:
    #   total_M = root.total_M × target_quantity + root.self_M × buffer_overhead
    # where buffer_overhead = effective_qty - target_quantity (= target × buffer%).
    # For target=1, buffer=5%: buffer_overhead = 0.05.
    # For target=N, buffer=0%: buffer_overhead = 0, falls back to × target_quantity.
    root_metrics = metrics_cache.get(root_node['node_id'], {})
    buffer_overhead = effective_qty - target_quantity

    # Handle bank nodes with banked_quantity
    # Walk the tree and adjust shopping list for banked quantities
    # (banked_quantity reduces the effective need at that node)

    root_self_steps = root_metrics.get('self_steps', 0.0) or 0.0
    root_self_actions = root_metrics.get('self_actions', 0.0) or 0.0
    total_steps = (
        root_metrics.get('total_steps', 0.0) * target_quantity
        + root_self_steps * buffer_overhead
    )
    total_actions = (
        root_metrics.get('total_actions', 0.0) * target_quantity
        + root_self_actions * buffer_overhead
    )

    # XP per skill: split via root's self_xp (only the root's own skill
    # contribution gets the buffer; descendant xp scales with target_qty).
    root_self_xp = root_metrics.get('self_xp', {}) or {}
    xp_by_skill = {}
    for sk, xpv in root_metrics.get('xp', {}).items():
        xp_by_skill[sk] = (
            xpv * target_quantity
            + root_self_xp.get(sk, 0.0) * buffer_overhead
        )

    # Shopping list: at root, this is purely children-contributed (the
    # root recipe's materials are added via children's input_ratios).
    # The root has no "self" shopping list, so children scale with
    # target_quantity entirely.
    shopping_list_raw = {}
    for item_ref, amt in root_metrics.get('shopping_list', {}).items():
        shopping_list_raw[item_ref] = amt * target_quantity

    # Subtract banked quantities from shopping list
    for n in tree_nodes:
        if n.get('source_type') == 'bank' and n.get('banked_quantity', 0) > 0:
            item_ref = n['item_id']
            if item_ref in shopping_list_raw:
                # Calculate effective quantity at this node
                # For simplicity, subtract banked from total needed
                banked = n['banked_quantity']
                shopping_list_raw[item_ref] = max(0, shopping_list_raw[item_ref] - banked)

    shopping_list = []
    for item_ref, qty in shopping_list_raw.items():
        if qty > 0:
            item_obj = _resolve_item_ref(item_ref)
            name = item_obj.name if item_obj and hasattr(item_obj, 'name') else item_ref
            rarity = None
            try:
                if item_obj is not None:
                    rarity = getattr(item_obj, 'rarity', None) or None
            except Exception:
                rarity = None
            shopping_list.append({
                'item_id': item_ref,
                'name': name,
                'quantity': qty,
                # 16x16 item icon for the summary table (user spec
                # 2026-05-15). Mirrors the equivalent enrichment in
                # the LP-master summary builder.
                'icon_path': _get_icon_path_for_ref(item_ref, item_obj),
                # Rarity for the icon's drop-shadow filter.
                'rarity': rarity,
            })

    # Cost breakdown
    cost_breakdown = []
    shop_price_map = _build_shop_price_map(tree_nodes)
    for item in shopping_list:
        item_obj = _resolve_item_ref(item['item_id'])
        # Bug 4a16affa: shop-sourced materials cost the shop's listed price,
        # not the item's sell value.
        unit_value = shop_price_map.get(item['item_id'], 0.0)
        if unit_value <= 0:
            unit_value = 0.0
            if item_obj and hasattr(item_obj, 'value'):
                unit_value = float(item_obj.value or 0)
        cost_breakdown.append({
            'item': item['name'],
            'quantity': item['quantity'],
            'unit_value': unit_value,
            'total_cost': item['quantity'] * unit_value,
        })

    # Steps breakdown. Bug 15110e01: root's own row scales by
    # effective_qty (carries the buffer), every other row scales by
    # target_quantity (integer cascade). Identify root's row(s) via
    # root_metrics['self_steps_breakdown'] which holds JUST the root's
    # own contribution (set in the recipe/activity/chest branch before
    # children roll up).
    steps_breakdown = []
    sb_icons = root_metrics.get('steps_breakdown_icons', {}) or {}
    root_self_sb = root_metrics.get('self_steps_breakdown', {}) or {}
    for src, stp in root_metrics.get('steps_breakdown', {}).items():
        # If src appears in the root's self breakdown, it accumulates
        # (root_self_portion × effective_qty) + (any descendant_portion × target_qty).
        # Otherwise it's purely descendant-contributed.
        self_portion = root_self_sb.get(src, 0.0) or 0.0
        scaled = (
            (stp - self_portion) * target_quantity
            + self_portion * effective_qty
        )
        steps_breakdown.append({
            'source': src,
            'steps': scaled,
            'source_icon': sb_icons.get(src),
        })

    time_days = total_steps / daily_steps if daily_steps > 0 else 0.0

    # ------------------------------------------------------------------
    # Side drops, target yield, net profit (Requirement 1)
    # ------------------------------------------------------------------
    target_item_ref = root_node.get('item_id', '')
    # Fine-rewrite root target ref if use_fine is on (mirrors calculate_node_metrics)
    use_fine = global_settings.get('use_fine', False)
    target_quality = global_settings.get('target_quality', 'Normal')
    target_item_ref = _rewrite_to_fine(target_item_ref, use_fine)

    # target_yield: single-tier for non-equipment targets or Normal quality;
    # per-quality breakdown otherwise using the helper.
    root_stats = root_metrics.get('stats_used', {}) or {}
    root_QO = float(root_stats.get('quality_outcome', 0.0) or 0.0)
    root_source_type = root_node.get('source_type', '')
    root_recipe = None
    root_activity_level = 1
    if root_source_type == 'recipe':
        root_recipe = game_data['recipes'].get(root_node.get('source_id'))
        if root_recipe:
            root_activity_level = root_recipe.level
    elif root_source_type in ('activity', 'chest'):
        act_id = (root_node.get('source_id') if root_source_type == 'activity'
                  else root_node.get('parent_activity_id'))
        activity = game_data['activities'].get(act_id) if act_id else None
        if activity and activity.skill_requirements:
            root_activity_level = list(activity.skill_requirements.values())[0]

    # Detect has_equipment_input for the fine-blend math
    has_equipment_input = False
    if root_recipe and root_recipe.materials:
        for group in root_recipe.materials:
            for _qty, mat in group:
                mat_ref = _get_item_ref_string(mat)
                if mat_ref and mat_ref.startswith('Item.'):
                    has_equipment_input = True
                    break
            if has_equipment_input:
                break

    target_yield = _split_target_yield_by_quality(
        total_qty=effective_qty,
        target_item_ref=target_item_ref,
        recipe=root_recipe,
        QO=root_QO,
        use_fine=use_fine,
        has_equipment_input=has_equipment_input,
        target_quality=target_quality,
        activity_level=root_activity_level,
    )
    target_value = sum(e.get('value', 0.0) or 0.0 for e in target_yield)

    # Sub-target quality crafts of the root item — projected from the
    # same quality_weights distribution used by _split_target_yield_by_quality.
    # sub_drops get appended to side_drops below; full_counts is stashed
    # on root_metrics for the Holistic Solver Insight.
    craft_sub_drops, full_craft_counts = _compute_craft_sub_quality_drops(
        total_at_or_above_target=effective_qty,
        target_item_ref=target_item_ref,
        recipe=root_recipe,
        QO=root_QO,
        use_fine=use_fine,
        has_equipment_input=has_equipment_input,
        target_quality=target_quality,
        activity_level=root_activity_level,
    )
    if full_craft_counts:
        try:
            root_metrics.setdefault('craft_quality_counts', {}).update(full_craft_counts)
        except Exception:
            pass

    # side_drops: every entry in root drops_gained except the root target.
    # Bug 15110e01: split scaling — root's own drop_table contributions
    # scale with effective_qty, descendant contributions with target_qty.
    # root_self_drops_gained holds just the root recipe's drop-table
    # entries (target item + secondary recipe drops); anything else came
    # from children rolled up via input_ratios.
    side_drops = []
    side_drops_value = 0.0
    root_self_drops = root_metrics.get('self_drops_gained', {}) or {}
    # Bug 2026-06-01 (Jimmy): a recipe's input materials were leaking
    # into side_drops because drops_gained sums the children's
    # production via input_ratio rollup, but never subtracts what the
    # parent recipe consumes. For Weave into ectoplasm, slime hunting's
    # scrap production rolled up to the root as ~1.66 scraps per
    # ectoplasm produced — but those same scraps are consumed by the
    # recipe (5 per craft × NMC adjustment). Net: zero excess scraps,
    # but naive side_drops showed 8141 of them. The LP-balanced view
    # already nets them out via constraint solving; the naive view
    # needs the explicit subtraction.
    root_raw_consumed = root_metrics.get('raw_materials', {}) or {}
    # Sell-value lookup for chests (Container.*) — same fix as the LP
    # path above. See _CHEST_COIN_VALUES rationale there.
    try:
        from util.coin_value import CHEST_COIN_VALUES as _CHEST_COIN_VALUES
    except Exception:
        _CHEST_COIN_VALUES = {}
    for drop_ref, amt in root_metrics.get('drops_gained', {}).items():
        if drop_ref == target_item_ref:
            continue
        self_portion = root_self_drops.get(drop_ref, 0.0) or 0.0
        scaled_qty = (
            (amt - self_portion) * target_quantity
            + self_portion * effective_qty
        )
        # Subtract whatever the recipe tree consumes of this same item
        # at the same scaling. raw_materials is per node output unit,
        # so it scales with target_quantity (consumption is part of the
        # tree's downstream cost, not the root's self drops).
        consumed = float(root_raw_consumed.get(drop_ref, 0.0) or 0.0)
        if consumed > 0:
            scaled_qty -= consumed * target_quantity
        if scaled_qty <= 0:
            continue
        # Coins (chests synthesize 'Currency.COINS', activities use the
        # singular 'Currency.COIN' from the drop table). Normalize both
        # into a single "Coins" row so net profit gets the full credit.
        if drop_ref in ('Currency.COINS', 'Currency.COIN'):
            unit_value = 1.0
            total_value = scaled_qty * unit_value
            side_drops.append({
                'item': 'Coins', 'item_id': 'Currency.COINS',
                'quantity': scaled_qty,
                'unit_value': unit_value, 'total_value': total_value,
                'icon_path': '/assets/icons/items/coins.svg',
                'is_fine': False,
            })
            side_drops_value += total_value
            continue
        obj = _resolve_item_ref(drop_ref)
        name = obj.name if obj and hasattr(obj, 'name') else drop_ref.split('.')[-1].replace('_', ' ').title()
        unit_value = 0.0
        if obj is not None and hasattr(obj, 'value') and obj.value:
            try:
                unit_value = float(obj.value)
            except (TypeError, ValueError):
                unit_value = 0.0
        # Containers (chests) — pull from the wiki sell-value map.
        if unit_value <= 0 and drop_ref.startswith('Container.'):
            try:
                unit_value = float(_CHEST_COIN_VALUES.get(drop_ref, 0) or 0)
            except (TypeError, ValueError):
                unit_value = 0.0
        total_value = scaled_qty * unit_value
        rarity = None
        try:
            if obj is not None:
                rarity = getattr(obj, 'rarity', None) or None
        except Exception:
            rarity = None
        side_drops.append({
            'item': name,
            'item_id': drop_ref,
            'quantity': scaled_qty,
            'unit_value': unit_value,
            'total_value': total_value,
            # 16x16 item icon for the side-drops summary table.
            'icon_path': _get_icon_path_for_ref(drop_ref, obj),
            # Fine flag drives the cyan glow drop-shadow on the
            # icon (mirrors the existing .item-icon.fine pattern).
            'is_fine': '_FINE' in (drop_ref or '').upper() or '(Fine)' in (name or ''),
            'rarity': rarity,
        })
        side_drops_value += total_value

    # Append sub-target quality crafts of the root item, so they sort
    # alongside real side drops by total_value below.
    for entry in craft_sub_drops:
        side_drops.append(entry)
        side_drops_value += entry.get('total_value', 0.0)

    # Sort side drops by total_value desc for cleaner display downstream
    side_drops.sort(key=lambda e: e.get('total_value', 0.0), reverse=True)

    material_cost = sum(c.get('total_cost', 0.0) or 0.0 for c in cost_breakdown)
    net_profit = target_value + side_drops_value - material_cost

    # Skill progression for the XP-by-skill table. Same shape as the
    # LP-path master dict above — frontend treats them interchangeably.
    skill_progression: Dict[str, dict] = {}
    try:
        from util.walkscape_constants import xp_to_level
        session_skills_xp = (session_data or {}).get('skills_xp', {}) or {}
        norm_session_xp = {}
        for k, v in session_skills_xp.items():
            try:
                norm_session_xp[str(k).lower()] = float(v)
            except (TypeError, ValueError):
                continue
        for skill, xp_gain in xp_by_skill.items():
            if not xp_gain or xp_gain <= 0:
                continue
            skill_lc = str(skill).lower()
            cur_xp = norm_session_xp.get(skill_lc)
            if cur_xp is None:
                skill_progression[skill_lc] = {
                    'xp': float(xp_gain),
                    'level_before': None,
                    'level_after': None,
                }
                continue
            level_before = xp_to_level(int(cur_xp))
            level_after = xp_to_level(int(cur_xp + xp_gain))
            skill_progression[skill_lc] = {
                'xp': float(xp_gain),
                'level_before': int(level_before),
                'level_after': int(level_after),
            }
    except Exception as e:
        print(f"[ct-summary] skill_progression build failed (naive): {e}", flush=True)
        skill_progression = {}

    summary = {
        'total_steps': total_steps,
        'total_actions': total_actions,
        'time_days': time_days,
        'xp_by_skill': xp_by_skill,
        'skill_progression': skill_progression,
        'shopping_list': shopping_list,
        'cost_breakdown': cost_breakdown,
        'steps_breakdown': steps_breakdown,
        'effective_quantity': effective_qty,
        # New fields from Requirement 1
        'target_yield': target_yield,
        'target_value': target_value,
        'side_drops': side_drops,
        'side_drops_value': side_drops_value,
        'material_cost': material_cost,
        'net_profit': net_profit,
        # lp_mode is set later by Task 8; default here for back-compat clients.
        'lp_mode': 'off',
    }

    # ------------------------------------------------------------------
    # Pass 2: LP solver (feature-flagged)
    # ------------------------------------------------------------------
    if _lp_enabled(session_data) and not skip_recompute:
        # Pre-check: all bank nodes → nothing to solve.
        all_bank = all(n.get('source_type') == 'bank' for n in tree_nodes)
        if all_bank:
            summary['lp_mode'] = 'off'
        else:
            try:
                lp_demand = effective_qty
                success, msg, master = solve_crafting_tree_lp(
                    tree_nodes=tree_nodes,
                    root_target_amount=lp_demand,
                    game_data=game_data,
                    session_data=session_data,
                    global_settings=global_settings,
                    root_node_id=root_node.get('node_id'),
                    # Bug 15110e01: buffer applies to root only. LP scales
                    # non-root contributions by target_qty/effective_qty.
                    root_self_target_amount=target_quantity,
                )
                if success:
                    # Snapshot the naive (non-LP) totals onto the summary
                    # BEFORE merging LP values over the top. The frontend
                    # uses these when the "Show Holistic Mode details"
                    # toggle is off, so the displayed summary stays
                    # consistent with the naive per-card math. When the
                    # toggle is on the frontend picks the LP totals.
                    # Without this, toggling the UI reveals a card/summary
                    # mismatch because cards are naive and summary is LP
                    # (e.g. flax->twine: cards sum to ~207 but LP summary
                    # is 124 because LP re-routed flax through butterfly
                    # catching — bug 379d0724, 2026-05-09).
                    summary['naive_total_steps'] = summary['total_steps']
                    summary['naive_total_actions'] = summary['total_actions']
                    summary['naive_time_days'] = summary['time_days']
                    summary['naive_xp_by_skill'] = summary['xp_by_skill']
                    summary['naive_shopping_list'] = summary['shopping_list']
                    summary['naive_cost_breakdown'] = summary['cost_breakdown']
                    summary['naive_steps_breakdown'] = summary['steps_breakdown']
                    summary['naive_target_yield'] = summary['target_yield']
                    summary['naive_target_value'] = summary['target_value']
                    summary['naive_side_drops'] = summary['side_drops']
                    summary['naive_side_drops_value'] = summary['side_drops_value']
                    summary['naive_material_cost'] = summary['material_cost']
                    summary['naive_net_profit'] = summary['net_profit']

                    # Merge LP totals into summary per design's Merge Table
                    summary.update({
                        'total_steps': master.get('total_steps', summary['total_steps']),
                        'total_actions': master.get('total_actions', summary['total_actions']),
                        'time_days': master.get('time_days', summary['time_days']),
                        'xp_by_skill': master.get('xp_by_skill', summary['xp_by_skill']),
                        'skill_progression': master.get('skill_progression', summary.get('skill_progression', {})),
                        'shopping_list': master.get('shopping_list', summary['shopping_list']),
                        'cost_breakdown': master.get('cost_breakdown', summary['cost_breakdown']),
                        'steps_breakdown': master.get('steps_breakdown', summary['steps_breakdown']),
                        'steps_by_skill': master.get('steps_by_skill', {}),
                        'target_yield': master.get('target_yield', summary['target_yield']),
                        'target_value': master.get('target_value', summary['target_value']),
                        'side_drops': master.get('side_drops', summary['side_drops']),
                        'side_drops_value': master.get('side_drops_value', summary['side_drops_value']),
                        'material_cost': master.get('material_cost', summary['material_cost']),
                        'net_profit': master.get('net_profit', summary['net_profit']),
                        'lp_mode': 'on',
                    })
                else:
                    summary['lp_mode'] = 'fallback'
                    summary['lp_error'] = msg
                    # Log LP fallbacks for observability (Task 12)
                    try:
                        import logging
                        logger = logging.getLogger(__name__)
                        session_uuid = (session_data or {}).get('uuid', 'unknown')
                        logger.warning(
                            f"LP fallback: session={session_uuid} "
                            f"tree_size={len(tree_nodes)} error={msg}"
                        )
                    except Exception:
                        pass
            except Exception as e:
                import traceback
                summary['lp_mode'] = 'fallback'
                summary['lp_error'] = str(e)
                try:
                    import logging
                    logger = logging.getLogger(__name__)
                    session_uuid = (session_data or {}).get('uuid', 'unknown')
                    logger.warning(
                        f"LP exception: session={session_uuid} "
                        f"tree_size={len(tree_nodes)} error={e}"
                    )
                    logger.debug(traceback.format_exc())
                except Exception:
                    pass

    # Recompute lock_warning per node based on the CURRENT locked_slots
    # and the optimizer's last gearset_export. Lock changes go through
    # _calculateOnly (preserveUI) and don't trigger a fresh optimize, so
    # without this pass the lock_warning field stays at its old value —
    # users who lock conflicting items after the last Optimize never
    # see the warning until they re-optimize. Recomputed here so the
    # ⚠️ badge reflects the live lock state on every recalc.
    #
    # Skipped in skip_recompute mode — the rerun-summary path does not
    # mutate node state, only aggregates existing values.
    if not skip_recompute:
        for n in tree_nodes:
            gc = n.get('gear_config') or {}
            node_locks = n.get('locked_slots') or {}
            # Always start from a clean slate so unlocking the conflicting
            # item clears the warning even when the optimizer hasn't run
            # since the lock was originally set.
            if 'lock_warning' in gc:
                gc['lock_warning'] = None
            if not node_locks:
                continue
            export = gc.get('optimized_export')
            if not export:
                continue
            src_type = n.get('source_type')
            src_id = n.get('source_id')
            # Best(auto) nodes pick a concrete underlying source; that's
            # what carries the keyword_counts requirement, so dispatch
            # against it.
            if src_type == 'best':
                src_type = n.get('underlying_source_type')
                src_id = n.get('underlying_source_id')
            req_obj = None
            try:
                if src_type == 'activity' and src_id:
                    req_obj = (game_data or {}).get('activities', {}).get(src_id)
                elif src_type == 'recipe' and src_id:
                    req_obj = (game_data or {}).get('recipes', {}).get(src_id)
            except Exception:
                req_obj = None
            if req_obj is None:
                continue
            try:
                # Pass the node's selected/user input items so the keyword
                # check counts arrows/plant/fabric/etc as satisfying the
                # input-driven keyword requirement (see helper docstring).
                sii = (gc.get('user_input_items') or {}) or (gc.get('selected_input_items') or {})
                warning = _check_locked_gearset_conflicts(req_obj, export, node_locks, sii)
            except Exception:
                warning = None
            if warning:
                n['gear_config']['lock_warning'] = warning

    # Aggregate per-node lock_warning strings into summary.lock_warnings
    # so the summary dashboard can show a banner ("3 nodes have locked
    # gear that doesn't meet activity requirements") and link to each
    # affected card. Non-conflicting nodes contribute nothing.
    lock_warnings = []
    for n in tree_nodes:
        gc = n.get('gear_config') or {}
        warn = gc.get('lock_warning')
        if warn:
            lock_warnings.append({
                'node_id': n.get('node_id'),
                'item_name': n.get('item_name'),
                'message': warn,
            })
    if lock_warnings:
        summary['lock_warnings'] = lock_warnings

    # ------------------------------------------------------------------
    # Aggregate non-owned/locked upgrades across the whole tree so the
    # summary can render a "Non-owned/Locked Upgrades" section that
    # collapses per-item with a per-node breakdown of where each
    # upgrade applies and the total step savings across the tree.
    # ------------------------------------------------------------------
    try:
        summary['tree_upgrades'] = _aggregate_tree_upgrades(
            tree_nodes, effective_qty=effective_qty)
    except Exception as _agg_err:
        print(f"[ct-upgrades] aggregation failed: {_agg_err!r}", flush=True)
        summary['tree_upgrades'] = []

    # ------------------------------------------------------------------
    # [SUMMARY-DEBUG] User report 948d02f1: "the base node says it
    # 37359 total steps for perfect+. This is what should be in the
    # summary node, not 74,643 steps." Print every candidate value so
    # we can correlate which one the user means and decide what the
    # summary should display. Always logged (no debug gate) so we
    # don't have to ask the user to flip a flag mid-debug.
    # ------------------------------------------------------------------
    try:
        _root = root_node or next(
            (n for n in tree_nodes if n.get('parent_id') is None), None
        )
        _root_metrics = (_root or {}).get('metrics') or {}
        import math as _math
        _eff_qty = summary.get('effective_quantity') or 0.0
        _eff_qty_ceil = int(_math.ceil(_eff_qty)) if _eff_qty else 0
        _root_total = _root_metrics.get('total_steps') or 0.0
        _root_steps_per_item = _root_metrics.get('steps_per_item') or 0.0
        _root_self_steps = _root_metrics.get('self_steps') or 0.0
        # _displayed_cumulative_steps is set by the frontend annotator,
        # so on the backend it's typically not present yet. Log if so.
        _root_disp_cum = _root.get('_displayed_cumulative_steps') if _root else None
        _root_disp_self = _root.get('_displayed_self_steps') if _root else None
        print(
            f"[SUMMARY-DEBUG] "
            f"summary.total_steps={summary.get('total_steps')} "
            f"summary.naive_total_steps={summary.get('naive_total_steps')} "
            f"summary.effective_quantity={_eff_qty} "
            f"effective_quantity_ceil={_eff_qty_ceil} "
            f"root.total_steps={_root_total} "
            f"root.steps_per_item={_root_steps_per_item} "
            f"root.self_steps={_root_self_steps} "
            f"root._displayed_cumulative_steps={_root_disp_cum} "
            f"root._displayed_self_steps={_root_disp_self} "
            f"root.steps_per_item_ceil_qty={_root_steps_per_item * _eff_qty_ceil} "
            f"lp_mode={summary.get('lp_mode')}",
            flush=True,
        )
    except Exception as _summary_dbg_err:
        print(f"[SUMMARY-DEBUG] failed: {_summary_dbg_err!r}", flush=True)

    return {
        'nodes': _sanitize_for_json(tree_nodes),
        'summary': _sanitize_for_json(summary),
    }


def _sanitize_for_json(obj):
    """Recursively replace float inf/nan with None for JSON serialization."""
    if isinstance(obj, float):
        if obj != obj or obj == float('inf') or obj == float('-inf'):  # nan or inf
            return None
        return obj
    if isinstance(obj, dict):
        return {k: _sanitize_for_json(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_sanitize_for_json(v) for v in obj]
    return obj


