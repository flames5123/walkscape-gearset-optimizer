def on_source_change(
    nodes: List[dict],
    node_id: str,
    new_source: dict,
    game_data: Optional[dict] = None,
    session_data: Optional[dict] = None,
    spoiler_protection: bool = True,
) -> List[dict]:
    """Update a node's source, preserving children whose item_id exists in new source's materials.

    Args:
        nodes: Flat node list (will be modified in place and returned)
        node_id: ID of the node to update
        new_source: Source dict with type, source_id, parent_activity_id, etc.
        game_data: Game data dict
        session_data: Session data for spoiler protection
        spoiler_protection: Whether to apply spoiler protection

    Returns:
        Updated flat node list
    """
    if game_data is None:
        game_data = _load_game_data()

    # Find the target node
    target_node = None
    for n in nodes:
        if n['node_id'] == node_id:
            target_node = n
            break
    if not target_node:
        return nodes

    # Update source
    old_source_type = target_node.get('source_type')
    old_source_id = target_node.get('source_id')
    target_node['source_type'] = new_source['type']
    target_node['source_id'] = new_source.get('source_id')
    target_node['parent_activity_id'] = new_source.get('parent_activity_id')
    target_node['chest_source'] = new_source.get('chest_source', 'activity')
    target_node['parent_recipe_id'] = new_source.get('parent_recipe_id')
    # Multi-material-group source dropdown entries (Boxtrap pattern)
    # carry their material_group_index inline. When the user picks
    # such an entry directly (not via the Material Options chip flow,
    # which still passes mgi via a separate craftingTreeMaterialGroupChange
    # call), apply the group index here so the children get rebuilt
    # against the correct group below.
    inline_mgi = new_source.get('material_group_index')
    if inline_mgi is not None:
        target_node['selected_material_group_index'] = inline_mgi
    # Store location for activity sources with specific locations
    if new_source.get('location'):
        target_node['selected_location_id'] = new_source['location']

    # Best (auto) ambiguity flag — mirror the _build_recursive branch. True
    # when Best covers multiple distinct candidates whose subtrees differ;
    # frontend uses this as the default-collapsed signal.
    target_node['auto_collapsed_best'] = (
        new_source['type'] == 'best'
        and _best_auto_children_ambiguous(target_node.get('available_sources') or [])
    )
    # When the user explicitly picks a concrete source (leaves Best mode),
    # also clear any user-set `collapsed: true` stuck from the old Best
    # default so the chosen subtree renders open.
    if new_source['type'] != 'best' and target_node.get('collapsed') is True:
        target_node['collapsed'] = False

    # Keep underlying_source_* in sync with the new selection. When the user
    # explicitly picks a concrete source (recipe/activity/chest/etc.), the
    # underlying is that same source. For 'best', resolve to the cheapest
    # recipe/activity using a gear-independent base-steps heuristic so the
    # displayed tree matches the likely LP winner instead of always showing
    # the first recipe in the list.
    if new_source['type'] != 'best':
        target_node['underlying_source_type'] = new_source['type']
        target_node['underlying_source_id'] = new_source.get('source_id')
    else:
        available_sources = target_node.get('available_sources', [])
        target_item_ref = target_node.get('item_id') or ''
        resolved = _pick_best_underlying_source(
            available_sources, game_data, target_item_ref=target_item_ref
        )
        if resolved is not None:
            target_node['underlying_source_type'] = resolved.get('type')
            target_node['underlying_source_id'] = resolved.get('source_id')
            # Also sync parent_activity_id / chest_source / parent_recipe_id
            # from the resolved source so child-building and metric calc see
            # the right context.
            if resolved.get('parent_activity_id'):
                target_node['parent_activity_id'] = resolved['parent_activity_id']
            if resolved.get('chest_source'):
                target_node['chest_source'] = resolved['chest_source']
            if resolved.get('parent_recipe_id'):
                target_node['parent_recipe_id'] = resolved['parent_recipe_id']

    # Refresh available_services / available_locations to match the new
    # source. Without this the node keeps the old recipe's service list
    # (e.g. sawmills after switching from "Cut into ectoplasm" to
    # "Cook into ectoplasm"), which makes the tree look like the source
    # selection didn't take effect.
    _populate_source_metadata(target_node, game_data, session_data, spoiler_protection)

    # Refresh the unified Materials button list so is_best_pick tracks the
    # new underlying source (winner button highlights correctly after a swap).
    target_node['leaf_materials'] = _build_leaf_materials(
        target_node.get('available_sources') or [],
        game_data,
        underlying_source_type=target_node.get('underlying_source_type'),
        underlying_source_id=target_node.get('underlying_source_id'),
        underlying_material_group_index=target_node.get('selected_material_group_index'),
    )

    # When the source type or source id changes, previously-optimized gear
    # is no longer valid — it was optimized for a different activity/recipe
    # (different skill, different stat priorities). Clear it so the user
    # sees empty gear and re-optimizes for the new source. Without this,
    # e.g. switching from a Foraging source to an Agility source keeps the
    # foraging gearset in place and nothing visible happens when the user
    # changes the dropdown.
    source_changed = (
        old_source_type != target_node['source_type']
        or old_source_id != target_node['source_id']
    )
    if source_changed:
        # User spec 2026-05-15: KEEP the optimized gearset across
        # source changes. The gearset is the user's optimizer choice
        # and they want to see what stats it would produce against
        # the new source — not start from zero. The next
        # calculate_tree() pass will re-apply the gearset's stats
        # against the new source's context (location/service) and
        # the displayed WE/DA/DR/NMC/QO will reflect the new total.
        # Old behavior cleared optimized_export here, which the user
        # explicitly flagged as wrong.
        gc = target_node.setdefault('gear_config', {})
        # Don't reset mode — user's auto/manual preference persists.
        # Clear the location if the new source doesn't specify one
        # (otherwise the dropdown shows a stale location from the old source).
        if not new_source.get('location'):
            target_node['selected_location_id'] = None
        # Clear stale metrics from the previous source. Without this,
        # fields like stats_used.best_source_label / best_source_icon
        # persist from the old calc and the source dropdown renders
        # "Best → <old source>" right after switching to Best(auto),
        # making it look like the selection didn't take. Same issue for
        # steps_per_item displayed on the node header. The next
        # calculate_tree() pass will repopulate metrics fresh — and
        # since we kept gearset_export above, those fresh metrics
        # include the gear stats applied against the new source.
        target_node['metrics'] = None
        # Drop the cached optimized_stats too — they were computed
        # for the OLD source's location/service context. Keeping the
        # export string lets calculate_tree decode and re-apply the
        # gearset against the new source on the next pass.
        gc['optimized_stats'] = None
        # Reset best_pick_computed so the Material Options row reappears
        # when the user switches a node back to Best(auto) via the source
        # dropdown after a previous Calculate. The frontend's
        # _getDisplayedLeafMaterials() gates the chip row on
        # `isBest && !bestComputed` (or _mo_preview_chip). Without this
        # reset, switching from a manually-picked recipe back to Best
        # leaves bestComputed=True from the prior Calculate and the
        # chips stay hidden, even though the user is asking to re-pick
        # via Best(auto). Clearing it returns the node to the "fresh
        # tree" state until the next Calculate re-populates the winner.
        target_node['best_pick_computed'] = False

    # Get current children
    old_children = [n for n in nodes if n['parent_id'] == node_id]
    old_children_by_item = {n['item_id']: n for n in old_children}

    # Remove all descendants of this node
    def _get_descendant_ids(parent_id):
        ids = set()
        for n in nodes:
            if n['parent_id'] == parent_id:
                ids.add(n['node_id'])
                ids |= _get_descendant_ids(n['node_id'])
        return ids

    descendant_ids = _get_descendant_ids(node_id)
    nodes = [n for n in nodes if n['node_id'] not in descendant_ids]

    # For recipe sources (including 'best' that resolved to a recipe above),
    # build new children preserving existing where possible.
    effective_recipe_id = None
    if new_source['type'] == 'recipe' and new_source.get('source_id'):
        effective_recipe_id = new_source.get('source_id')
    elif new_source['type'] == 'best' and target_node.get('underlying_source_type') == 'recipe':
        effective_recipe_id = target_node.get('underlying_source_id')

    if effective_recipe_id:
        recipe = game_data['recipes'].get(effective_recipe_id)
        if recipe and recipe.materials:
            # Collect ancestor items for cycle detection
            ancestor_items = set()
            current = target_node
            while current:
                ancestor_items.add(current['item_id'])
                parent = None
                for n in nodes:
                    if n['node_id'] == current.get('parent_id'):
                        parent = n
                        break
                current = parent

            # Build alternative groups list for the parent node
            alt_groups = []
            for group in recipe.materials:
                if not group:
                    continue
                group_label_parts = []
                for qty, mat in group:
                    mat_name = mat.name if hasattr(mat, 'name') else str(mat)
                    group_label_parts.append(f"{qty}× {mat_name}")
                alt_groups.append({
                    'label': ' + '.join(group_label_parts),
                    'materials': [
                        {
                            'item_id': _get_item_ref_string(mat),
                            'name': mat.name if hasattr(mat, 'name') else str(mat),
                            'quantity': qty,
                            'icon': _get_icon_path_for_ref(_get_item_ref_string(mat) or '', mat),
                        }
                        for qty, mat in group
                        if _get_item_ref_string(mat)
                    ],
                })
            if len(alt_groups) > 1:
                target_node['material_group_alternatives'] = [
                    {'label': 'Best (auto)', 'is_best': True}
                ] + alt_groups
                # Bug 015ac89c: don't clobber inline_mgi here. When the user
                # picks a specific material group from the source dropdown
                # (e.g. "Smelt a silver bar - Silver ore"), the entry carries
                # `material_group_index: 1` and the top of this function
                # already wrote it to `selected_material_group_index`. Resetting
                # to -1 unconditionally throws away that pick, so the child
                # rebuild below falls back to group 0 (Silver nugget) and the
                # user never sees the Silver ore branch (where Mine silver ore
                # would appear as a source). Only default to -1 (Best auto)
                # when the source change did NOT specify an explicit group.
                if inline_mgi is None:
                    target_node['selected_material_group_index'] = -1
            else:
                target_node['material_group_alternatives'] = []
                target_node['selected_material_group_index'] = 0
            # Resolve the default material group to build children for.
            # When alternatives exist, index -1 means "Best (auto)" — use
            # the first group as default; otherwise honor the stored index.
            sel_idx = target_node.get('selected_material_group_index', 0) or 0
            if sel_idx < 0 or sel_idx >= len(recipe.materials):
                sel_idx = 0
            default_group = recipe.materials[sel_idx] if recipe.materials else []
            for mat_idx, (req_qty, req_mat) in enumerate(default_group):
                mat_ref = _get_item_ref_string(req_mat)
                if not mat_ref:
                    continue

                if mat_ref in old_children_by_item:
                    # Preserve existing child, update quantity
                    preserved = old_children_by_item[mat_ref]
                    preserved['base_requirement_amount'] = req_qty
                    preserved['parent_id'] = node_id
                    preserved['material_group_index'] = mat_idx
                    preserved['material_alternatives'] = []
                    nodes.append(preserved)
                    # Rebuild subtree for preserved child
                    sub_nodes = build_crafting_tree(
                        mat_ref, game_data, session_data, spoiler_protection
                    )
                    if sub_nodes:
                        sub_root_id = sub_nodes[0]['node_id']
                        for sn in sub_nodes[1:]:
                            if sn['parent_id'] == sub_root_id:
                                sn['parent_id'] = preserved['node_id']
                            sn['depth'] = preserved['depth'] + (sn['depth'] - sub_nodes[0]['depth'])
                        nodes.extend(sub_nodes[1:])
                else:
                    # Create new subtree
                    sub_nodes = build_crafting_tree(
                        mat_ref, game_data, session_data, spoiler_protection
                    )
                    if sub_nodes:
                        sub_nodes[0]['parent_id'] = node_id
                        sub_nodes[0]['base_requirement_amount'] = req_qty
                        sub_nodes[0]['material_group_index'] = mat_idx
                        sub_nodes[0]['material_alternatives'] = []
                        depth_offset = target_node['depth'] + 1 - sub_nodes[0]['depth']
                        for sn in sub_nodes:
                            sn['depth'] += depth_offset
                        nodes.extend(sub_nodes)

    # For activity/bank sources, no children (leaf nodes).
    # For chest sources with a recipe, build the recipe's material sub-tree as children.
    # Children were already removed above.
    if new_source['type'] == 'chest' and new_source.get('chest_source') == 'recipe':
        parent_recipe_id = new_source.get('parent_recipe_id')
        recipe = game_data['recipes'].get(parent_recipe_id) if parent_recipe_id else None
        if recipe and recipe.materials:
            # Collect ancestors for cycle detection
            ancestor_items = set()
            current = target_node
            while current:
                ancestor_items.add(current['item_id'])
                parent = next((n for n in nodes if n['node_id'] == current.get('parent_id')), None)
                current = parent

            # Build alt groups for the parent node
            alt_groups = []
            for group in recipe.materials:
                if not group:
                    continue
                group_label_parts = [f"{qty}× {mat.name if hasattr(mat, 'name') else str(mat)}" for qty, mat in group]
                alt_groups.append({
                    'label': ' + '.join(group_label_parts),
                    'materials': [
                        {'item_id': _get_item_ref_string(mat), 'name': mat.name if hasattr(mat, 'name') else str(mat),
                         'quantity': qty, 'icon': _get_icon_path_for_ref(_get_item_ref_string(mat) or '', mat)}
                        for qty, mat in group if _get_item_ref_string(mat)
                    ],
                })
            if len(alt_groups) > 1:
                target_node['material_group_alternatives'] = [
                    {'label': 'Best (auto)', 'is_best': True}
                ] + alt_groups
                target_node['selected_material_group_index'] = -1
            else:
                target_node['material_group_alternatives'] = []
                target_node['selected_material_group_index'] = 0

            default_group = recipe.materials[0] if recipe.materials else []
            for mat_idx, (req_qty, req_mat) in enumerate(default_group):
                mat_ref = _get_item_ref_string(req_mat)
                if not mat_ref:
                    continue
                sub_nodes = build_crafting_tree(mat_ref, game_data, session_data, spoiler_protection)
                if sub_nodes:
                    sub_nodes[0]['parent_id'] = node_id
                    sub_nodes[0]['base_requirement_amount'] = req_qty
                    sub_nodes[0]['material_group_index'] = mat_idx
                    sub_nodes[0]['material_alternatives'] = []
                    depth_offset = target_node['depth'] + 1 - sub_nodes[0]['depth']
                    for sn in sub_nodes:
                        sn['depth'] += depth_offset
                    nodes.extend(sub_nodes)

    return nodes


