def get_craftable_items(game_data: Optional[dict] = None) -> List[dict]:
    """Return all items that appear as recipe outputs.

    Returns list of {item_id, name, output_ref} for the target item dropdown.
    """
    if game_data is None:
        game_data = _load_game_data()

    seen = set()
    items = []
    for recipe_name, recipe in game_data['recipes'].items():
        if not recipe.output_item:
            continue
        ref = recipe.output_item  # e.g. "Material.PINE_PLANK"
        if ref in seen:
            continue
        seen.add(ref)
        item_obj = recipe.get_output_item_object()
        display_name = item_obj.name if item_obj and hasattr(item_obj, 'name') else ref.split('.')[-1].replace('_', ' ').title()
        items.append({
            'item_id': ref,
            'name': display_name,
        })
    items.sort(key=lambda x: x['name'])
    return items


