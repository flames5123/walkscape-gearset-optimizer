# Metrics whose alt-entry `delta` is denominated in step units. Only
# these can be summed across nodes (other metrics like materials_for_target
# would mix step-counts with material-counts). After the worker rewrite
# (commit 1e62f8bf), all tree-node alts with children use TOTAL_TREE_STEPS,
# so this set covers the realistic cases.
#
# `steps_per_reward_roll` is the metric ACTIVITY / gathering nodes optimize
# on (see crafting_tree_optimize.py: node_source_type in activity/chest ->
# default_metric = "steps_per_reward_roll"). It IS a step-denominated metric
# (steps to obtain one target drop), so gathering-tool upgrades (a better
# sickle / pickaxe on a Mine/Forage node) belong in the summary just like
# recipe-tool upgrades. Omitting it silently dropped every gathering-step
# upgrade from the "Non-owned/Locked Upgrades" list — user report
# 15435d68 (2026-07-13): "does not show potential upgrades for gathering
# steps ... eg. how many steps would an eternal spectral sickle save".
# Cross-node summing stays sound because the aggregation rescales every
# alt's delta into whole-tree displayed-step units before summing (see the
# subtree-steps rescale below), so per-reward-roll and per-target deltas
# both land in the same units.
_TREE_UPGRADE_STEP_METRICS = frozenset({
    'total_tree_steps_for_target',
    'steps_for_target',
    'steps_per_reward_roll',
})


def _aggregate_tree_upgrades(tree_nodes, effective_qty=1.0):
    """Walk every node's gear_config.slot_alternatives and aggregate
    non-owned/locked upgrades by item identity so the summary can show
    "this ring is an upgrade everywhere — saves N steps total."

    Each tree node carries `gear_config.slot_alternatives = {alternatives,
    locked_alternatives}` after a per-node optimize run. Within those,
    each alt entry has {name, uuid, quality, slot, delta, delta_pct,
    primary_metric, ...}. We group entries by (uuid or name, quality)
    so the same item-quality variant accumulates its step savings
    across every node where it improves the gearset.

    Returns a sorted list (most savings first, i.e. most-negative
    total_delta first):

        [
            {
                'name': 'Spectral handwear (Eternal)',
                'uuid': 'a4cfc099-...',
                'quality': 'Eternal',
                'rarity': 'ethereal',
                'is_locked': False,
                'missing_requirements': [],   # set when is_locked
                'total_delta': -7388.0,       # sum of delta across nodes
                'nodes': [
                    {
                        'node_id': 'node_274492ed38b8',
                        'item_name': 'Bamboo toolbox',
                        'icon_path': '/assets/...',
                        'source_type': 'recipe',
                        'source_id': 'Woodwork a bamboo toolbox',
                        'slot': 'hands',
                        'delta': -4364.65,
                        'delta_pct': -7.15,
                        'replaces': 'Pearl bracelet',
                    },
                    ...
                ],
            },
            ...
        ]

    Skipped:
      - Alts whose primary_metric isn't in the step-units set (the deltas
        wouldn't be meaningful in step terms — see TREE_UPGRADE_STEP_METRICS).
      - Empty `slot_alternatives` (node never optimized).

    Scaling (bug 2026-06-30): every node's `delta` is rescaled into
    displayed-step units that are denominated PER ONE target item (the
    same per-one-target basis the node metrics use — node.metrics.total_steps
    is per-one-target, and calculate_tree multiplies it by `effective_qty`
    = target_quantity × (1 + buffer) to produce the headline total_steps the
    user sees). The aggregation previously returned these per-one-target
    deltas verbatim, so an upgrade on a tree making 3000 items showed
    "−2 steps total" when it actually saves −2 × effective_qty steps over the
    whole build. We multiply both `total_delta` and each per-node `delta` by
    `effective_qty` so the savings are on the same scale as the tree total.
    `delta_pct` is scale-invariant and left untouched.

    Locked alts merge with non-owned alts under the same (uuid, quality)
    key — if an item appears as locked on one node and unlocked on another,
    the entry is treated as locked overall and the union of missing
    requirements is preserved. This is unusual but possible if a
    requirement only fires for certain skill/level combos.
    """
    # ── Whole-tree subtree step totals (correct rescale base) ──────────
    # An upgrade on node N saves steps across every place the whole build
    # produces N's output AND (for recipe nodes) the inputs feeding N.
    # The right scale base is therefore the LP-allocated whole-tree step
    # total of N's SUBTREE (N + all descendants), NOT node.metrics.total_steps
    # — which is the PER-ONE-OUTPUT cost (e.g. 114.85 steps to smelt one
    # ectoplasm) and is ~Q_N times too small (the build smelts ~772). Using
    # the per-output base made a perfect Spectral hammer report "-6 steps"
    # when equipping it and re-running the tree actually saved ~-3522
    # (user report 12385108, 2026-07-13). lp_data.steps is the node's real
    # whole-tree self contribution (it sums to summary.total_steps); summing
    # it over the subtree gives the whole-tree cost the upgrade's fractional
    # improvement (delta_pct) applies to. lp_data already bakes in
    # effective_qty (target_quantity × buffer), so no separate effective_qty
    # multiply is applied on this path.
    _nodes_by_id = {}
    _children_by_parent = {}
    for _n in tree_nodes or []:
        _nid = _n.get('node_id')
        if _nid is None:
            continue
        _nodes_by_id[_nid] = _n
        _pid = _n.get('parent_id')
        _children_by_parent.setdefault(_pid, []).append(_nid)

    def _node_self_lp_steps(n):
        lp = ((n.get('metrics') or {}).get('lp_data') or {})
        try:
            return float(lp.get('steps'))
        except (TypeError, ValueError):
            return None

    _subtree_steps_cache = {}

    def _subtree_lp_steps(node_id, _seen=None):
        """Sum of lp_data.steps over node_id + all descendants. Returns
        None if NO node in the subtree carries lp_data (legacy/partial
        trees) so callers can fall back to the old per-node rescale."""
        if node_id in _subtree_steps_cache:
            return _subtree_steps_cache[node_id]
        if _seen is None:
            _seen = set()
        if node_id in _seen:
            return None
        _seen.add(node_id)
        n = _nodes_by_id.get(node_id)
        total = None
        if n is not None:
            self_steps = _node_self_lp_steps(n)
            if self_steps is not None:
                total = self_steps
        for child_id in _children_by_parent.get(node_id, []):
            child_total = _subtree_lp_steps(child_id, _seen)
            if child_total is not None:
                total = (total or 0.0) + child_total
        _subtree_steps_cache[node_id] = total
        return total

    aggregated = {}
    # Set True as soon as any alt is rescaled against whole-tree subtree
    # steps (which already bake in effective_qty). Controls whether the
    # final loop applies the legacy effective_qty multiply.
    used_whole_tree_base = False
    for node in tree_nodes or []:
        gc = node.get('gear_config') or {}
        sa = gc.get('slot_alternatives') or {}
        if not sa:
            continue
        node_id = node.get('node_id') or ''
        node_item_name = node.get('item_name') or '?'
        node_icon = node.get('icon_path') or None
        # underlying_* preferred so a "Best (auto)" wrapper resolves to
        # the concrete activity/recipe the user actually optimized for.
        source_type = (node.get('underlying_source_type')
                       or node.get('source_type')
                       or '')
        source_id = (node.get('underlying_source_id')
                     or node.get('source_id')
                     or '')

        # Scale base for converting an alt's per-node `delta` into
        # whole-tree displayed-step units. Two bases, in priority order:
        #
        #  1. node_subtree_steps (PRIMARY): the LP-allocated whole-tree
        #     step total of this node's subtree (self + descendants). This
        #     is the real number of steps the build spends producing this
        #     node's output and its inputs, so an upgrade's fractional
        #     improvement (delta_pct) maps directly onto whole-tree steps.
        #     Already includes effective_qty. Used for all live trees.
        #
        #  2. node_disp_steps (LEGACY fallback, no lp_data): node.metrics
        #     .total_steps — the PER-ONE-OUTPUT cost. Only correct for the
        #     root (whose one output IS the build target); for child nodes
        #     it is ~Q_N times too small, which is exactly the 12385108 bug.
        #     Kept only so legacy/partial trees without lp_data don't crash.
        #     This path still applies the effective_qty multiply at the end.
        #
        # The alt `delta` values are denominated in the per-node optimizer's
        # INTERNAL metric units (total_tree_steps_for_target / steps_for_target
        # / steps_per_reward_roll), whose baseline (`old_value`) can be far
        # larger than the user-facing displayed step total. Rescaling via
        # delta * (base / old_value)  ==  (delta_pct/100) * base keeps the
        # aggregated savings in the same units as the headline total_steps.
        _node_metrics = node.get('metrics') or {}
        try:
            node_disp_steps = float(_node_metrics.get('total_steps'))
        except (TypeError, ValueError):
            node_disp_steps = None
        node_subtree_steps = _subtree_lp_steps(node_id)

        # First pass: collect candidate alts per (key, node, slot) raw,
        # then dedupe per (key, node) keeping only the best slot. This
        # is necessary because compute_slot_alternatives runs ONE pass
        # per slot and reports the same item once per slot it improves
        # (e.g. Spectral saw can be an upgrade in tool0, tool1, tool2
        # all at once for the same node — but you can only equip ONE
        # saw per activity, so summing all three slots triple-counts
        # the savings). Same item appearing in BOTH `alternatives` and
        # `locked_alternatives` dicts (locked-but-not-owned items get
        # tested in both passes) also needs dedupe to avoid 2x-count.
        # See user feedback 2026-05-19 for both regressions.
        candidates = {}  # (key, node_id) -> best alt entry candidate
        for group_kind, group in (
            ('nonowned', sa.get('alternatives') or {}),
            ('locked', sa.get('locked_alternatives') or {}),
        ):
            if not isinstance(group, dict):
                continue
            for slot, alts in group.items():
                if not isinstance(alts, list):
                    continue
                for alt in alts:
                    if not isinstance(alt, dict):
                        continue
                    primary_metric = alt.get('primary_metric') or ''
                    base_metric = (
                        primary_metric.split('::', 1)[0]
                        if '::' in primary_metric
                        else primary_metric
                    )
                    if base_metric not in _TREE_UPGRADE_STEP_METRICS:
                        continue
                    name = alt.get('name')
                    if not name:
                        continue
                    quality = alt.get('quality')
                    uuid = alt.get('uuid')
                    rarity = alt.get('rarity')
                    delta = alt.get('delta')
                    if delta is None:
                        continue
                    try:
                        delta = float(delta)
                    except (TypeError, ValueError):
                        continue
                    delta_pct = alt.get('delta_pct')
                    try:
                        delta_pct = (float(delta_pct)
                                     if delta_pct is not None else 0.0)
                    except (TypeError, ValueError):
                        delta_pct = 0.0

                    # Rescale `delta` into whole-tree displayed-step units.
                    # `old_value` is the internal baseline the delta was
                    # measured against; delta/old_value == delta_pct/100 is
                    # the scale-invariant fractional improvement. Multiplying
                    # that fraction by the correct step base yields the
                    # user-facing saving.
                    #
                    #  PRIMARY: node_subtree_steps (whole-tree LP steps of
                    #    the node's subtree). This already includes
                    #    effective_qty, so NO further effective_qty multiply
                    #    is applied to this path (see final loop).
                    #  LEGACY:  node_disp_steps (per-one-output) only when
                    #    lp_data is absent; the effective_qty multiply at the
                    #    end still applies to keep old behaviour.
                    old_value = alt.get('old_value')
                    try:
                        old_value = (float(old_value)
                                     if old_value is not None else None)
                    except (TypeError, ValueError):
                        old_value = None
                    if node_subtree_steps is not None and node_subtree_steps > 0:
                        if old_value and old_value > 0:
                            delta = delta * (node_subtree_steps / old_value)
                        elif delta_pct:
                            delta = (delta_pct / 100.0) * node_subtree_steps
                        # subtree steps already include effective_qty, so the
                        # final loop must NOT multiply again.
                        used_whole_tree_base = True
                    elif node_disp_steps is not None and node_disp_steps > 0:
                        if old_value and old_value > 0:
                            delta = delta * (node_disp_steps / old_value)
                        elif delta_pct:
                            delta = (delta_pct / 100.0) * node_disp_steps

                    replaces = alt.get('replaces')

                    # Group key: prefer uuid+quality so the same crafted
                    # item at different qualities aggregates separately
                    # (Spectral handwear (Perfect) vs (Eternal) are
                    # distinct upgrades). Fall back to name when uuid is
                    # missing (e.g. non-crafted items the worker didn't
                    # decorate with one).
                    key = (uuid or name, quality or '')
                    cand_key = (key, node_id)
                    cand_payload = {
                        'name': name, 'uuid': uuid, 'quality': quality,
                        'rarity': rarity, 'group_kind': group_kind,
                        'missing_requirements': alt.get('missing_requirements') or [],
                        'node_row': {
                            'node_id': node_id,
                            'item_name': node_item_name,
                            'icon_path': node_icon,
                            'source_type': source_type,
                            'source_id': source_id,
                            'slot': slot,
                            'delta': delta,
                            'delta_pct': delta_pct,
                            'replaces': replaces,
                        },
                    }
                    existing = candidates.get(cand_key)
                    # Keep the slot with the BEST (most-negative) delta
                    # for this (item, node). For ring slots only — both
                    # ring1 and ring2 are physically separate slots and
                    # the user CAN equip the same ring in both if they
                    # own two — we keep both rows under separate keys
                    # by appending the slot to the dedupe key. (Today
                    # compute_slot_alternatives' "RING EXCEPTION" only
                    # suggests a 2nd copy via ring2 slot anyway, so
                    # this is a defensive carve-out, not a hot path.)
                    is_ring = isinstance(slot, str) and slot.startswith('ring')
                    if is_ring:
                        cand_key = (key, node_id, slot)
                        existing = candidates.get(cand_key)
                    if existing is None or delta < existing['node_row']['delta']:
                        # Locked-sticky: if EITHER pass saw it locked,
                        # the entry counts as locked.
                        if existing is not None and existing.get('group_kind') == 'locked':
                            cand_payload['group_kind'] = 'locked'
                        candidates[cand_key] = cand_payload
                    else:
                        # Existing entry wins on delta, but if THIS pass
                        # is locked we still need to mark the keeper as
                        # locked + union missing_requirements.
                        if group_kind == 'locked':
                            existing['group_kind'] = 'locked'
                            for req in cand_payload['missing_requirements']:
                                if req and req not in existing['missing_requirements']:
                                    existing['missing_requirements'].append(req)

        # Second pass: roll deduped candidates into per-(uuid,quality)
        # aggregate entries. Each candidate contributes EXACTLY ONE
        # node-row to the entry — no per-slot duplication, no
        # locked/non-owned double-counting.
        for cand in candidates.values():
            name = cand['name']
            quality = cand['quality']
            uuid = cand['uuid']
            rarity = cand['rarity']
            key = (uuid or name, quality or '')
            entry = aggregated.get(key)
            if entry is None:
                entry = {
                    'name': name,
                    'uuid': uuid,
                    'quality': quality,
                    'rarity': rarity,
                    'is_locked': cand['group_kind'] == 'locked',
                    'missing_requirements': set(),
                    'total_delta': 0.0,
                    'nodes': [],
                }
                aggregated[key] = entry
            if cand['group_kind'] == 'locked':
                entry['is_locked'] = True
                for req in cand['missing_requirements']:
                    if req:
                        entry['missing_requirements'].add(str(req))
            entry['total_delta'] += cand['node_row']['delta']
            entry['nodes'].append(cand['node_row'])

    # Legacy per-one-target deltas need scaling up to whole-build totals to
    # match the headline total_steps. But when the whole-tree subtree base
    # was used (the normal path — lp_data present), the deltas are ALREADY
    # whole-tree (effective_qty baked into lp_data.steps), so scaling again
    # would double-count. Only apply effective_qty on the legacy fallback.
    if used_whole_tree_base:
        scale = 1.0
    else:
        try:
            scale = float(effective_qty)
        except (TypeError, ValueError):
            scale = 1.0
        if not (scale > 0):
            scale = 1.0

    result = []
    for entry in aggregated.values():
        if scale != 1.0:
            entry['total_delta'] *= scale
            for n in entry['nodes']:
                if n.get('delta') is not None:
                    n['delta'] *= scale
        # Stable order for missing_reqs so JSON diffs don't churn.
        entry['missing_requirements'] = sorted(entry['missing_requirements'])
        # Sort per-entry node breakdown by biggest savings first within
        # this item (matches the popup's per-slot ordering convention).
        entry['nodes'].sort(key=lambda n: n.get('delta', 0))
        result.append(entry)
    # Top-level sort: REVERSED to put smallest savings first (the worst
    # upgrades). Per user 2026-05-19: "the worst is the most achievable,"
    # so the most-attainable upgrades surface first; the user can scroll
    # down to see the bigger savings if they want a hard goal. delta is
    # NEGATIVE for step improvements, so descending = least-negative
    # (smallest savings) first.
    result.sort(key=lambda e: e.get('total_delta', 0), reverse=True)
    return result


