def on_material_group_change(
    nodes: List[dict],
    node_id: str,
    group_index: int,
    game_data: Optional[dict] = None,
    session_data: Optional[dict] = None,
    spoiler_protection: bool = True,
    global_settings: Optional[dict] = None,
) -> List[dict]:
    """Switch a recipe node to a different material group (alternative combo).

    The outer array of recipe.materials is the list of alternative combos.
    Each combo is a list of (qty, mat) tuples — all required within that combo.

    group_index == -1 means "Best (auto)": try all groups, pick the one with
    lowest total_steps for the whole tree.

    Args:
        nodes: Flat node list
        node_id: ID of the recipe node to update
        group_index: Index into recipe.materials to select, or -1 for Best (auto)
        game_data: Game data dict
        session_data: Session data
        spoiler_protection: Spoiler protection flag
        global_settings: Settings for calculate_tree (needed for Best auto)

    Returns:
        Updated flat node list
    """
    if game_data is None:
        game_data = _load_game_data()

    target_node = next((n for n in nodes if n['node_id'] == node_id), None)
    if not target_node:
        return nodes

    recipe = game_data['recipes'].get(target_node.get('source_id'))
    if not recipe or not recipe.materials:
        return nodes

    num_groups = len(recipe.materials)

    # "Best (auto)" — try every group, pick lowest total_steps
    if group_index == -1:
        if num_groups <= 1:
            # Nothing to compare, just use group 0
            group_index = 0
        else:
            best_idx = 0
            best_steps = float('inf')
            for try_idx in range(num_groups):
                trial_nodes = copy.deepcopy(nodes)
                trial_nodes = on_material_group_change(
                    trial_nodes, node_id, try_idx,
                    game_data, session_data, spoiler_protection,
                    global_settings=global_settings,
                )
                gs = global_settings or {'target_quantity': 1, 'daily_steps': 10000,
                                         'target_quality': 'Normal', 'buffer_percentage': 0.05}
                try:
                    result = calculate_tree(trial_nodes, gs, game_data, session_data)
                    total = result.get('summary', {}).get('total_steps') or float('inf')
                    if total is None:
                        total = float('inf')
                except Exception:
                    total = float('inf')
                if total < best_steps:
                    best_steps = total
                    best_idx = try_idx

            # Apply the winning group, then mark as "best" selection
            nodes = on_material_group_change(
                nodes, node_id, best_idx,
                game_data, session_data, spoiler_protection,
                global_settings=global_settings,
            )
            # Re-find target node (list was mutated)
            target_node = next((n for n in nodes if n['node_id'] == node_id), None)
            if target_node:
                target_node['selected_material_group_index'] = -1
                target_node['best_material_group_index'] = best_idx
            return nodes

    if group_index < 0 or group_index >= num_groups:
        return nodes

    target_node['selected_material_group_index'] = group_index
    # Clear best_material_group_index when manually selecting
    target_node.pop('best_material_group_index', None)

    # Remove all current children of this node
    def _get_descendant_ids(parent_id):
        ids = set()
        for n in nodes:
            if n['parent_id'] == parent_id:
                ids.add(n['node_id'])
                ids |= _get_descendant_ids(n['node_id'])
        return ids

    descendant_ids = _get_descendant_ids(node_id)
    nodes[:] = [n for n in nodes if n['node_id'] not in descendant_ids]

    # Collect ancestors for cycle detection
    ancestor_items = set()
    current = target_node
    while current:
        ancestor_items.add(current['item_id'])
        parent = next((n for n in nodes if n['node_id'] == current.get('parent_id')), None)
        current = parent

    # Build children from the selected group
    selected_group = recipe.materials[group_index]
    for mat_idx, (req_qty, req_mat) in enumerate(selected_group):
        mat_ref = _get_item_ref_string(req_mat)
        if not mat_ref:
            continue
        sub_nodes = build_crafting_tree(mat_ref, game_data, session_data, spoiler_protection)
        if sub_nodes:
            sub_nodes[0]['parent_id'] = node_id
            sub_nodes[0]['base_requirement_amount'] = req_qty
            sub_nodes[0]['material_group_index'] = mat_idx
            sub_nodes[0]['material_alternatives'] = []
            depth_offset = target_node['depth'] + 1 - sub_nodes[0]['depth']
            for sn in sub_nodes:
                sn['depth'] += depth_offset
            nodes.extend(sub_nodes)

    # Refresh leaf_materials so is_best_pick reflects the newly-selected group.
    if game_data:
        target_node['leaf_materials'] = _build_leaf_materials(
            target_node.get('available_sources') or [],
            game_data,
            underlying_source_type=target_node.get('underlying_source_type'),
            underlying_source_id=target_node.get('underlying_source_id'),
            underlying_material_group_index=target_node.get('selected_material_group_index'),
        )

    return nodes


def _get_skill_level(skill_name: str, session_data: Optional[dict] = None) -> int:
    """Get character skill level, defaulting to 99 if no character data."""
    if not session_data or not skill_name:
        return DEFAULT_SKILL_LEVEL
    skills = session_data.get('skills', {})
    # Try exact match first, then case-insensitive
    level = skills.get(skill_name)
    if level is None:
        level = skills.get(skill_name.lower())
    if level is None:
        level = skills.get(skill_name.capitalize())
    return level if level is not None else DEFAULT_SKILL_LEVEL


def _get_collectible_stats(session_data: Optional[dict], skill: Optional[str] = None,
                           location=None) -> Dict[str, float]:
    """Get collectible passive stat bonuses from character data.

    session_data stores collectibles as raw export-name strings (e.g.
    'mark_of_the_trident'), but calculate_collectible_stats() needs
    CollectibleInstance objects exposing get_stats_for_skill(). Passing the raw
    strings straight through raised AttributeError on every entry, and the bare
    except below then silently returned {} — so collectible bonuses (notably
    location-gated double_rewards) never reached the displayed crafting-tree
    node stats, diverging from the activity-output screen (bug 4e840909).
    Resolve any string entries via the registry; pass objects through unchanged.
    """
    if not session_data:
        return {}
    collectibles = session_data.get('collectibles', [])
    if not collectibles:
        return {}
    try:
        from util.walkscape_constants import collectible_by_export_name
    except Exception:
        collectible_by_export_name = None
    resolved = []
    for c in collectibles:
        if isinstance(c, str):
            if collectible_by_export_name is not None:
                obj = collectible_by_export_name(c)
                if obj is not None:
                    resolved.append(obj)
        elif c is not None:
            resolved.append(c)
    if not resolved:
        return {}
    try:
        from util.collectibles_utils import calculate_collectible_stats
        return calculate_collectible_stats(resolved, skill=skill, location=location)
    except Exception:
        return {}


def _calculate_steps_per_action(
    base_steps: int,
    max_efficiency: float,
    skill_level: int,
    activity_level: int,
    we: float,
    flat: int,
    pct: float,
) -> float:
    """Calculate steps per single action using the standard formula.

    Returns the raw steps per single action (before DA).
    """
    # Level-based WE bonus: levels above activity requirement * 1.25%, capped at 20 levels (25% max)
    levels_above = max(0, skill_level - activity_level)
    level_bonus_we = min(levels_above, 20) * 0.0125

    total_we = we + level_bonus_we
    capped_we = min(total_we, max_efficiency)
    total_efficiency = 1.0 + capped_we

    # Match the game's formula (per KamiTzayig reference): single ceil at the END
    # of the chain. Applying ceil before the pct multiplier introduces off-by-one
    # errors when a pct modifier is present (e.g. Flowing pocketwatch -5%).
    base_over_eff = base_steps / total_efficiency
    min_steps = base_steps / (1.0 + max_efficiency)   # safety net (float, pre-ceil)
    steps_after_min = max(base_over_eff, min_steps)

    steps_with_pct = steps_after_min * (1.0 + pct)
    steps_with_flat = steps_with_pct + flat
    # Single ceil at the end, with the 10-step floor applied before the ceil.
    return float(max(math.ceil(steps_with_flat), 10))


def _resolve_best_service_for_recipe(
    recipe, skill_name: str, game_data: dict,
    session_data: Optional[dict] = None,
    selected_service_id: Optional[str] = None,
    selected_location_id: Optional[str] = None,
):
    """Return the Service object the node will actually use for `recipe`, or None.

    Single source of truth for "which service does this recipe node use?".
    Both the service-stat row (`_get_best_service_stats`) and the gear-stat
    location context (`_get_gear_stats`) call this so they never diverge.

    Selection rules (mirrors the service-stat display):
      - `'__none__'` or a no-service recipe -> None (no service applied)
      - an explicit `selected_service_id` -> that service (if it exists)
      - otherwise ('__best__' / unset) -> the highest-WE compatible service,
        with region/location locks filtered out, tie-broken by total stat sum.

    Bug fix (report 613a1e83, 2026-06-16): `_get_gear_stats` previously
    resolved the gear-stat location by scanning for the FIRST compatible
    service in dict order, while the service row picked the BEST-by-WE
    service. For "Make an elderhide tunic" the first compatible loom is the
    Cursed Loom (Wraithwater, ghostly) but the best-WE loom is Marked
    Textiles (Myriadian Arc, non-ghostly). That mismatch made the tree
    aggregate gear stats at a ghostly location — wrongly applying the
    Spectral needle's +2.5% ghostly double_rewards — while labelling the
    node Myriadian Arc. Routing both through this helper keeps the gear-stat
    location consistent with the displayed/scored service.
    """
    services = game_data.get('services', {})

    if selected_service_id == '__none__':
        return None
    if not recipe.service or recipe.service.lower() == 'none':
        return None
    if not services:
        return None

    # Explicit pick wins (fall through to best-WE if the id is unknown).
    if selected_service_id and selected_service_id != '__best__':
        svc = services.get(selected_service_id)
        if svc is not None:
            return svc

    # First try services that match the recipe's service requirement.
    matched = [(sid, s) for sid, s in services.items() if _service_valid_for_recipe(s, recipe)]
    # Fallback: if no match (recipe.service is 'None'), try all services of the same skill.
    if not matched:
        recipe_skill = (recipe.skill or '').lower()
        matched = [(sid, s) for sid, s in services.items()
                   if (s.category.value.lower() if hasattr(s.category, 'value') else str(s.category).lower()) == recipe_skill]

    # Honor the worker's jointly-optimized choice. When the service is auto
    # ('__best__'/unset) but the node already has a worker-resolved location
    # (selected_location_id, written from the optimize result's best_location),
    # restrict candidates to services AT that location so the displayed service
    # row + its stats agree with the gearset the worker actually optimized —
    # which was scoped to that location. Without this the row would re-resolve
    # by best-WE and could name a different service than the one the gear was
    # built for (report df39440d: gear jointly optimized at the winning
    # service's location, service row independently showed the best-WE one).
    # Falls back to the unfiltered set if nothing matches the location.
    if selected_location_id:
        want = str(selected_location_id).lower().replace(' ', '_').replace("'", '')
        loc_matched = []
        for sid, s in matched:
            loc = getattr(s, 'location', None)
            loc_name = loc.name if hasattr(loc, 'name') else (str(loc) if loc else '')
            if loc_name.lower().replace(' ', '_').replace("'", '') == want:
                loc_matched.append((sid, s))
        if loc_matched:
            matched = loc_matched

    best_svc = None
    best_we = -1.0
    best_total = -1.0
    for svc_id, svc in matched:
        # Skip services in locked regions or locked locations.
        if session_data:
            region_unlocks = set(session_data.get('region_unlocks', []))
            if not region_unlocks:
                region_unlocks = {'jarvonia'}
            if hasattr(svc, 'location') and not _is_location_in_unlocked_region(svc.location, region_unlocks):
                continue
            loc_name = svc.location.name if hasattr(svc.location, 'name') else str(svc.location) if hasattr(svc, 'location') else None
            if _is_location_locked(loc_name, session_data):
                continue
        svc_stats = _resolve_service_stats(svc, skill_name, session_data)
        svc_we = svc_stats.get('work_efficiency', 0.0)
        total = sum(abs(v) for v in svc_stats.values())
        # Pick highest WE, break ties by total stat sum.
        if svc_we > best_we or (svc_we == best_we and total > best_total):
            best_we = svc_we
            best_total = total
            best_svc = svc

    return best_svc


def _get_best_service_stats(
    recipe, skill_name: str, game_data: dict,
    session_data: Optional[dict] = None,
    selected_service_id: Optional[str] = None,
    selected_location_id: Optional[str] = None,
) -> Tuple[Dict[str, float], Optional[str]]:
    """Find the best compatible service for a recipe and return its stats.

    If selected_service_id is set, use that specific service.
    Otherwise, try all compatible services and pick the one that gives the
    most work_efficiency (the most impactful crafting stat).

    Returns:
        (stats_dict, service_display_name) — stats as {stat_name: value}, and
        the display name of the selected service (or None if no service found).
    """
    services = game_data.get('services', {})

    # "No service" explicitly selected
    if selected_service_id == '__none__':
        return {}, 'No service'

    # Recipe doesn't require a service — never apply service bonuses
    if not recipe.service or recipe.service.lower() == 'none':
        return {}, 'No service'

    if not services:
        return {}, None

    svc = _resolve_best_service_for_recipe(
        recipe, skill_name, game_data, session_data, selected_service_id,
        selected_location_id,
    )
    if svc is None:
        return {}, None

    svc_stats = _resolve_service_stats(svc, skill_name, session_data)
    loc_name = svc.location.name if hasattr(svc.location, 'name') else str(svc.location)
    return svc_stats, f"{svc.name} ({loc_name})"


def _resolve_service_stats(svc, skill_name: str, session_data: Optional[dict] = None) -> Dict[str, float]:
    """Get stats from a service for a given skill, including reputation-gated bonuses."""
    try:
        svc_stats = svc.get_stats_for_skill(skill_name, location=None)
        result = dict(svc_stats) if svc_stats else {}

        # Add reputation-gated bonuses if character data available
        if session_data and hasattr(svc, 'gated_stats') and svc.gated_stats:
            reputation = session_data.get('reputation', {})
            rep_gates = svc.gated_stats.get('reputation', {})
            for faction, thresholds in rep_gates.items():
                char_rep = reputation.get(faction, 0)
                for threshold_str, stat_block in thresholds.items():
                    threshold = int(threshold_str) if isinstance(threshold_str, str) else threshold_str
                    if char_rep >= threshold:
                        # stat_block is {skill: {location: {stat: value}}}
                        for sk, locs in stat_block.items():
                            if sk.lower() == skill_name.lower() or sk.lower() == 'global':
                                for loc, stat_vals in locs.items():
                                    for stat_name, stat_val in stat_vals.items():
                                        result[stat_name] = result.get(stat_name, 0.0) + (stat_val / 100.0)

        return result
    except Exception:
        return {}


def _resolve_node_stat_location(node: dict, game_data: Optional[dict] = None,
                                session_data: Optional[dict] = None) -> Optional[str]:
    """Resolve the location name used for location-aware stat lookups on a node.

    This MUST mirror the location resolution inside _decode_gearset_stats so
    that gear, collectible, and service stats are all evaluated at the SAME
    location. Recipe nodes use the explicitly selected location, falling back
    to the best-matching service's location; activity/chest nodes use the
    activity's first location. Returns None when no location context applies.

    Before bug 4e840909, collectible stats were aggregated with location=None,
    which silently dropped location-gated bonuses (e.g. underwater
    double_rewards) that the gear path and the activity-output screen DID apply.
    """
    if not game_data:
        return None
    source_type = node.get('source_type', '')
    if source_type == 'recipe':
        recipe = game_data.get('recipes', {}).get(node.get('source_id'))
        if not recipe:
            return None
        location = node.get('selected_location_id') or None
        if location is None and recipe.service and recipe.service.lower() != 'none':
            try:
                svc = _resolve_best_service_for_recipe(
                    recipe, recipe.skill, game_data, session_data,
                    node.get('selected_service_id'),
                )
                if svc is not None and getattr(svc, 'location', None) is not None:
                    svc_loc = svc.location
                    location = svc_loc.name if hasattr(svc_loc, 'name') else str(svc_loc)
            except Exception:
                pass
        return location
    elif source_type in ('activity', 'chest'):
        act_id = (node.get('source_id') if source_type == 'activity'
                  else node.get('parent_activity_id'))
        activity = game_data.get('activities', {}).get(act_id)
        if activity and getattr(activity, 'locations', None):
            loc = activity.locations[0]
            return loc.name if hasattr(loc, 'name') else str(loc)
    return None


def _get_gear_stats(node: dict, session_data: Optional[dict] = None,
                    game_data: Optional[dict] = None) -> Dict[str, float]:
    """Resolve gear stats for a node based on its gear_config.

    For auto-optimize nodes with optimized_stats, use those.
    For nodes with optimized_export, decode gearset and calculate stats.
    For default/no gear, return zeros.
    """
    gear_config = node.get('gear_config', {})
    locked_slots = node.get('locked_slots') or {}

    # Cached stats short-circuit ONLY when the user has not pinned any
    # slots. As soon as locked_slots is non-empty, we MUST re-decode
    # because the cached optimized_stats reflect the OPTIMIZER's choice,
    # not the user's pin. Without this, the per-slot lock never moves
    # the displayed WE/DR/DA values until the user clicks Optimize.
    if gear_config.get('optimized_stats') and not locked_slots:
        return dict(gear_config['optimized_stats'])

    # If we have an optimized export string, decode it and calculate stats
    if gear_config.get('optimized_export'):
        try:
            # Merge in the optimizer's persisted pet/consumable picks
            # whenever the user hasn't explicitly locked those slots.
            # encode_gearset() can't serialize 'pet'/'consumable' (Gearset
            # has no _pet/_consumable attrs), so without this merge the
            # optimizer's pick was silently dropped on every re-decode
            # (location/service change, page reload). User bug d3ce19e5.
            #
            # Locks always win — they're the user's explicit pin. We only
            # overlay the optimizer's pick into slots the user hasn't
            # touched. The result is fed through the same `extra_locked_
            # items` path _decode_gearset_stats already uses for
            # pet/consumable locks, so the stats aggregation is identical.
            effective_locked = dict(locked_slots) if locked_slots else {}
            opt_pet = gear_config.get('optimized_pet')
            opt_cons = gear_config.get('optimized_consumable')
            if opt_pet and 'pet' not in effective_locked:
                effective_locked['pet'] = opt_pet
            if opt_cons and 'consumable' not in effective_locked:
                effective_locked['consumable'] = opt_cons
            return _decode_gearset_stats(
                gear_config['optimized_export'],
                node, game_data,
                locked_slots=effective_locked if effective_locked else None,
                session_data=session_data,
            )
        except Exception:
            pass

    return {}


def _decode_gearset_stats(export_string: str, node: dict,
                          game_data: Optional[dict] = None,
                          locked_slots: Optional[dict] = None,
                          session_data: Optional[dict] = None) -> Dict[str, float]:
    """Decode a gearset export string and calculate stats for the node's context.

    When `locked_slots` is provided ({slot: {itemId, quality, level?}}),
    the decoded gearset is patched with the locked items BEFORE stat
    aggregation. This is the path the per-slot popup uses to surface
    new effective stats without re-running the per-node optimizer."""
    from util.gearset_utils import Gearset

    gearset = Gearset(export_string)

    # Apply lock overrides — replaces the optimizer's pick for the
    # specified slot with the user's pin so the resulting stats
    # reflect what would be equipped after this lock applies.
    #
    # Consumable + pet locks are tracked separately because the
    # Gearset class only has slot attrs for gear/tools/rings/neck.
    # Without this list, setattr(gearset, '_consumable', ...) was a
    # silent no-op (hasattr returns False) and the consumable's
    # stats never made it into the aggregated total — user picked
    # jerky, DR stayed at the optimizer's pre-lock value.
    extra_locked_items = []
    if locked_slots:
        try:
            from util.autogenerated.equipment import Item
            for slot_name, slot_info in locked_slots.items():
                if not slot_info:
                    continue
                item_id = slot_info.get('itemId') if isinstance(slot_info, dict) else None
                quality = slot_info.get('quality') if isinstance(slot_info, dict) else None
                if not item_id:
                    continue
                # Skip generic items here — they're not in the Item registry.
                # Real coverage requires plumbing GenericDefinitionManager;
                # for now, locked generics fall back to the optimizer's pick.
                if str(item_id).startswith('generic::'):
                    continue
                # Pet slot resolves through the Pet registry, not Item.
                # locked_slots[pet] carries level + name; look up the
                # PetLevelInfo so its stats actually flow into the
                # decoded gearset. Without this branch, pet picks were
                # silently dropped at overlay time and stats stayed
                # the same as before the swap.
                locked_item = None
                if slot_name == 'pet':
                    try:
                        from util.autogenerated.pets import PETS_BY_NAME
                        species = (slot_info.get('name') or '').strip()
                        # itemId for pets is the lowercased name
                        # (e.g. 'dog', 'camel'); fall back to that
                        # when the explicit name field is missing.
                        if not species:
                            species = str(item_id).replace('_', ' ').title()
                        species_cap = species.capitalize()
                        level = int(slot_info.get('level') or 0)
                        pet_levels = PETS_BY_NAME.get(species_cap)
                        if pet_levels and level > 0:
                            locked_item = pet_levels.get_level(level)
                    except Exception:
                        locked_item = None
                # Consumable resolves through the Consumable registry.
                elif slot_name == 'consumable':
                    try:
                        from util.autogenerated.consumables import Consumable
                        locked_item = Consumable.by_export_name(item_id)
                        if not locked_item:
                            for _attr in dir(Consumable):
                                if _attr.startswith('_'):
                                    continue
                                cons = getattr(Consumable, _attr)
                                if hasattr(cons, 'name'):
                                    cid = cons.name.lower().replace(' ', '_').replace("'", '')
                                    if cid == item_id:
                                        locked_item = cons
                                        break
                    except Exception:
                        locked_item = None
                else:
                    try:
                        locked_item = Item.by_uuid(item_id, (quality or 'common').lower())
                    except Exception:
                        locked_item = None
                if not locked_item:
                    continue
                slot_attr = f'_{slot_name}'
                # Consumable and pet are NOT returned by
                # gearset.get_all_items(), even though the Gearset class now
                # exposes _consumable/_pet attributes. Routing them through
                # setattr would silently drop their stats from the aggregation
                # below (bug 4e840909: the locked Fruit cake's +18%
                # double_rewards vanished, so the crafting-tree node read
                # ~0.18 lower DR than the activity-output screen). Always fold
                # these via extra_locked_items so the loop picks them up.
                if slot_name in ('consumable', 'pet'):
                    extra_locked_items.append(locked_item)
                elif hasattr(gearset, slot_attr):
                    setattr(gearset, slot_attr, locked_item)
                else:
                    # Gearset class doesn't track this slot natively —
                    # collect it so the aggregation below can fold its
                    # stats in alongside the gearset items.
                    extra_locked_items.append(locked_item)
        except Exception:
            # Defensive: any failure in the override path falls back to
            # the un-overridden gearset stats — better stale than 500.
            pass

    items = [item for _, item in gearset.get_all_items() if item is not None]
    # Fold in any locked consumable / pet items the Gearset class
    # can't track natively. They have get_stats_for_skill via
    # StatsMixin so the aggregation loop below picks them up.
    if extra_locked_items:
        items.extend(extra_locked_items)

    if not items:
        return {}

    # Determine skill and location for stat context
    skill_name = None
    location = None

    source_type = node.get('source_type', '')
    if source_type == 'recipe' and game_data:
        recipe = game_data.get('recipes', {}).get(node.get('source_id'))
        if recipe:
            skill_name = recipe.skill
            # Use selected location for no-service recipes (location-specific gear bonuses)
            location = node.get('selected_location_id') or None
            # Bug af9d3e86 / 79ec57d9 follow-up (2026-05-31): when the
            # recipe is bound to a location-specific service (e.g.
            # Cursed Loom Wraithwater) but the user never picked a
            # location on the node, fall back to the service's
            # location. Otherwise ghostly-gated gear stats (Spectral
            # needle's IFC.ECTOPLASM, Ghost trap pack's IFC.ECTOPLASM,
            # etc.) silently drop out of the aggregated total because
            # `aggregate_gearset_stats(location=None)` filters them.
            # The internal scorer DID see them via service.location and
            # picked the IF gear, but the LP path then couldn't credit
            # the bonus drops, making the displayed total worse than
            # the no-IF baseline.
            #
            # Bug 613a1e83 (2026-06-16): this used to scan for the FIRST
            # compatible service in dict order, which diverged from the
            # best-by-WE service the rest of the node uses (service row,
            # location label). For "Make an elderhide tunic" the first
            # compatible loom is the Cursed Loom (Wraithwater, ghostly)
            # but the best-WE loom is Marked Textiles (Myriadian Arc,
            # non-ghostly). Aggregating gear stats at the ghostly location
            # wrongly applied the Spectral needle's +2.5% ghostly
            # double_rewards while the node was labelled Myriadian Arc.
            # Now we resolve the SAME service via the shared helper so the
            # gear-stat location always matches the displayed/scored service.
            if location is None and recipe.service and recipe.service.lower() != 'none':
                try:
                    svc = _resolve_best_service_for_recipe(
                        recipe, skill_name, game_data, session_data,
                        node.get('selected_service_id'),
                    )
                    if svc is not None and getattr(svc, 'location', None) is not None:
                        svc_loc = svc.location
                        location = svc_loc.name if hasattr(svc_loc, 'name') else str(svc_loc)
                except Exception:
                    pass
    elif source_type in ('activity', 'chest') and game_data:
        act_id = node.get('source_id') if source_type == 'activity' else node.get('parent_activity_id')
        activity = game_data.get('activities', {}).get(act_id)
        if activity:
            skill_name = activity.primary_skill
            if activity.locations:
                loc = activity.locations[0]
                location = loc.name if hasattr(loc, 'name') else str(loc)

    if not skill_name:
        return {}

    # Manually aggregate stats from items (avoid needing character object)
    total_stats = {}
    for item in items:
        try:
            item_stats = item.get_stats_for_skill(skill_name, location=location)
            for stat_name, stat_value in item_stats.items():
                total_stats[stat_name] = total_stats.get(stat_name, 0.0) + stat_value
        except Exception:
            continue

    return total_stats


def _resolve_input_item_ref(input_item_meta: dict):
    """Resolve a serialized input-item dict (shape from selected_input_items)
    back into a live Item/Material instance so we can call get_stats_for_skill.

    `input_item_meta` comes from app.py's _auto_pick_input_items_for_activity
    and carries: {itemId, uuid, name, input_type, input_reference, ...}.
    Returns None if nothing resolves.
    """
    if not input_item_meta:
        return None
    try:
        from util.autogenerated.equipment import Item as _ItemMod
    except Exception:
        _ItemMod = None
    try:
        from util.autogenerated.materials import Material as _MatMod, MaterialInstance as _MatInst
    except Exception:
        _MatMod = None
        _MatInst = None

    # Try Item by UUID
    uuid = input_item_meta.get('uuid')
    if uuid and _ItemMod is not None and hasattr(_ItemMod, 'by_uuid'):
        try:
            obj = _ItemMod.by_uuid(uuid)
            if obj is not None:
                return obj
        except Exception:
            pass
    # Try Material by export name / short id
    ename = input_item_meta.get('itemId') or input_item_meta.get('export_name')
    if ename and _MatMod is not None and hasattr(_MatMod, 'by_export_name'):
        try:
            obj = _MatMod.by_export_name(ename)
            if obj is not None:
                return obj
        except Exception:
            pass
    # Try Material by attribute name or display-name match
    name = input_item_meta.get('name')
    if _MatMod is not None and _MatInst is not None and name:
        for attr_name in dir(_MatMod):
            if attr_name.startswith('_'):
                continue
            mat = getattr(_MatMod, attr_name)
            if isinstance(mat, _MatInst) and getattr(mat, 'name', None) == name:
                return mat
    return None


def _get_activity_drop_steps(activity, item_ref: str, stats: Dict[str, float],
                             skill_level: int) -> Optional[float]:
    """Calculate steps per item from an activity's drop table.

    Uses the activity's get_expected_drop_rate method if available,
    otherwise falls back to manual calculation from drop table.
    """
    if not activity or not activity.drop_table:
        return None

    item_obj = _resolve_item_ref(item_ref)
    if not item_obj:
        return None

    # Try using the activity's built-in method
    try:
        drop_rates = activity.get_expected_drop_rate(
            stats=stats,
            target_item=item_obj,
            character=None,  # Will use default
        )
        item_name = item_obj.name if hasattr(item_obj, 'name') else item_ref
        steps = drop_rates.get(item_name)
        if steps and steps > 0:
            return steps
    except Exception:
        pass

    # Fallback: manual calculation from drop table
    for drop in activity.drop_table:
        if _match_item_ref(drop.item_ref, item_ref):
            if drop.chance_percent and drop.chance_percent > 0:
                avg_qty = drop.quantity.average if drop.quantity else 1.0
                if avg_qty <= 0:
                    avg_qty = 1.0
                # Steps per item = steps_per_action / (chance * avg_qty * (1+DA) * (1+DR))
                # But we want steps_from_drop_table which is steps_per_action / (chance * avg_qty)
                # The DA/DR are applied separately
                base_steps = activity.base_steps or 318
                max_eff = activity.max_efficiency or 0.6
                activity_level = 1
                if activity.skill_requirements:
                    activity_level = list(activity.skill_requirements.values())[0]

                we = stats.get('work_efficiency', 0.0)
                flat = int(stats.get('steps_add', 0))
                pct = stats.get('steps_percent', 0.0)

                steps_per_action = _calculate_steps_per_action(
                    base_steps, max_eff, skill_level, activity_level, we, flat, pct
                )
                da = stats.get('double_action', 0.0)
                dr = stats.get('double_rewards', 0.0)

                chance = drop.chance_percent / 100.0
                steps_per_item = steps_per_action / (chance * avg_qty * (1.0 + da) * (1.0 + dr))
                return steps_per_item
    return None


def _get_chest_steps_per_item(
    container, parent_activity, item_ref: str,
    stats: Dict[str, float], skill_level: int
) -> Optional[float]:
    """Calculate steps per item from a chest/container."""
    if not container or not parent_activity:
        return None

    item_obj = _resolve_item_ref(item_ref)
    if not item_obj:
        return None

    # Calculate steps per chest (how many steps to get one chest)
    # First find the chest drop rate in the parent activity
    chest_steps = None
    try:
        drop_rates = parent_activity.get_expected_drop_rate(
            stats=stats,
            target_item=container.name,
            character=None,
        )
        chest_steps = drop_rates.get(container.name)
    except Exception:
        pass

    if not chest_steps:
        # Fallback: look in secondary drop table for chest
        for drop in getattr(parent_activity, 'secondary_drop_table', []) or []:
            if drop.item_name and drop.item_name.lower() == container.name.lower():
                if drop.chance_percent and drop.chance_percent > 0:
                    base_steps = parent_activity.base_steps or 318
                    max_eff = parent_activity.max_efficiency or 0.6
                    activity_level = 1
                    if parent_activity.skill_requirements:
                        activity_level = list(parent_activity.skill_requirements.values())[0]
                    we = stats.get('work_efficiency', 0.0)
                    flat = int(stats.get('steps_add', 0))
                    pct = stats.get('steps_percent', 0.0)
                    da = stats.get('double_action', 0.0)
                    dr = stats.get('double_rewards', 0.0)

                    steps_per_action = _calculate_steps_per_action(
                        base_steps, max_eff, skill_level, activity_level, we, flat, pct
                    )
                    chance = drop.chance_percent / 100.0
                    chest_steps = steps_per_action / (chance * (1.0 + da) * (1.0 + dr))
                break

    if not chest_steps or chest_steps <= 0:
        return None

    # Calculate expected items per chest
    expected_items = 0.0
    for drop in container.get_all_drops():
        if _match_item_ref(drop.item_ref, item_ref):
            chance = (drop.chance_percent or 0.0) / 100.0
            avg_qty = drop.quantity.average if drop.quantity else 1.0
            # Per chest = chance_per_roll * avg_qty * ROLLS_PER_CHEST
            from util.autogenerated.containers import ROLLS_PER_CHEST
            expected_items += chance * avg_qty * ROLLS_PER_CHEST

    if expected_items <= 0:
        return None

    return chest_steps / expected_items


def _get_chest_steps_per_item_via_recipe(
    container, parent_recipe, item_ref: str,
    stats: Dict[str, float], skill_level: int
) -> Optional[float]:
    """Calculate steps per item from a chest obtained via recipe secondary drop (0.4% base rate)."""
    if not container or not parent_recipe:
        return None

    item_obj = _resolve_item_ref(item_ref)
    if not item_obj:
        return None

    BASE_CHEST_RATE = 0.004  # 0.4% per reward roll

    we = stats.get('work_efficiency', 0.0)
    flat = int(stats.get('steps_add', 0))
    pct = stats.get('steps_percent', 0.0)
    da = stats.get('double_action', 0.0)
    dr = stats.get('double_rewards', 0.0)
    cf = stats.get('chest_finding', 0.0)

    steps_per_action = _calculate_steps_per_action(
        parent_recipe.base_steps, parent_recipe.max_efficiency,
        skill_level, parent_recipe.level, we, flat, pct
    )

    # Steps per reward roll (already accounts for DA and DR)
    steps_per_reward_roll = steps_per_action / ((1.0 + da) * (1.0 + dr))

    # Effective chest rate per reward roll — ONLY CF boosts the rate.
    # DR already increases reward rolls per step (via steps_per_reward_roll),
    # so multiplying the rate by (1+DR) again would double-count it.
    # This matches drops-section.js (see CRAFTING_BUGS.md Bug 2 fix) and the
    # reference implementation in KamiTzayig/walkscape_auto_gearset.
    effective_chest_rate = BASE_CHEST_RATE * (1.0 + cf)
    if effective_chest_rate <= 0:
        return None

    # Steps to get one chest
    chest_steps = steps_per_reward_roll / effective_chest_rate

    # Expected items per chest opening
    expected_items = 0.0
    from util.autogenerated.containers import ROLLS_PER_CHEST
    for drop in container.get_all_drops():
        if _match_item_ref(drop.item_ref, item_ref):
            chance = (drop.chance_percent or 0.0) / 100.0
            avg_qty = drop.quantity.average if drop.quantity else 1.0
            expected_items += chance * avg_qty * ROLLS_PER_CHEST

    if expected_items <= 0:
        return None

    return chest_steps / expected_items


