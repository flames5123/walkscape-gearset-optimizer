# DEPTH OPTIMIZER (Task 2.1)
# ============================================================================

def depth_optimize_node(
    node: dict,
    game_data: dict,
    session_data: Optional[dict],
    global_settings: dict,
) -> dict:
    """Test all alternative sources for a node and return ranked results.

    For activity nodes: tests all alternative locations.
    For recipe nodes: tests all alternative recipes that produce the same item,
    and all compatible services for each recipe.

    Returns:
        {
            "best": {source_id, location_id, steps_per_item, gearset_export},
            "alternatives": [
                {source_id, location_id, label, steps_per_item, gearset_export},
                ...
            ]
        }
    """
    alternatives = []
    item_ref = node.get('item_id', '')

    if node.get('source_type') == 'activity':
        act_id = node.get('source_id')
        activity = game_data['activities'].get(act_id)
        if activity and activity.locations:
            skill_name = activity.primary_skill
            skill_level = _get_skill_level(skill_name, session_data)
            collectible_stats = _get_collectible_stats(session_data, skill_name)

            for location in activity.locations:
                # For each location, calculate steps with default stats
                stats = dict(collectible_stats)
                location_name = location.name if hasattr(location, 'name') else str(location)

                steps = _get_activity_drop_steps(activity, item_ref, stats, skill_level)
                if steps and steps > 0 and steps != float('inf'):
                    alternatives.append({
                        'source_id': act_id,
                        'location_id': location_name,
                        'label': f"{activity.name} ({location_name})",
                        'steps_per_item': steps,
                        'gearset_export': None,
                    })

    elif node.get('source_type') == 'recipe':
        # Test all recipes that produce this item
        for recipe_name, recipe in game_data['recipes'].items():
            if recipe.output_item != item_ref:
                continue

            skill_name = recipe.skill
            skill_level = _get_skill_level(skill_name, session_data)
            collectible_stats = _get_collectible_stats(session_data, skill_name)

            # Find compatible services
            compatible_services = []
            for svc_id, svc in game_data.get('services', {}).items():
                if _service_valid_for_recipe(svc, recipe):
                    compatible_services.append((svc_id, svc))

            if not compatible_services:
                # Calculate without service
                stats = dict(collectible_stats)
                output_qty = recipe.quantity or 1
                DA = stats.get('double_action', 0.0)
                DR = stats.get('double_rewards', 0.0)
                WE = stats.get('work_efficiency', 0.0)
                flat = int(stats.get('steps_add', 0))
                pct = stats.get('steps_percent', 0.0)

                spa = _calculate_steps_per_action(
                    recipe.base_steps, recipe.max_efficiency,
                    skill_level, recipe.level, WE, flat, pct
                )
                steps_per_item = spa / (output_qty * (1.0 + DA) * (1.0 + DR))
                alternatives.append({
                    'source_id': recipe_name,
                    'service_id': None,
                    'label': f"{recipe.name} (no service)",
                    'steps_per_item': steps_per_item,
                    'gearset_export': None,
                })
            else:
                for svc_id, svc in compatible_services:
                    # Get service stats and add to collectible stats
                    stats = dict(collectible_stats)
                    svc_stats = _resolve_service_stats(svc, skill_name, session_data)
                    for k, v in svc_stats.items():
                        stats[k] = stats.get(k, 0.0) + v
                    output_qty = recipe.quantity or 1
                    DA = stats.get('double_action', 0.0)
                    DR = stats.get('double_rewards', 0.0)
                    WE = stats.get('work_efficiency', 0.0)
                    flat = int(stats.get('steps_add', 0))
                    pct = stats.get('steps_percent', 0.0)

                    spa = _calculate_steps_per_action(
                        recipe.base_steps, recipe.max_efficiency,
                        skill_level, recipe.level, WE, flat, pct
                    )
                    steps_per_item = spa / (output_qty * (1.0 + DA) * (1.0 + DR))
                    location_name = svc.location.name if hasattr(svc.location, 'name') else str(svc.location)
                    alternatives.append({
                        'source_id': recipe_name,
                        'service_id': svc_id,
                        'label': f"{recipe.name} at {svc.name} ({location_name})",
                        'steps_per_item': steps_per_item,
                        'gearset_export': None,
                    })

    # Sort by steps_per_item ascending
    alternatives.sort(key=lambda a: a.get('steps_per_item', float('inf')))

    if not alternatives:
        return {
            'best': None,
            'alternatives': [],
        }

    best = alternatives[0]
    return {
        'best': best,
        'alternatives': alternatives,
    }
