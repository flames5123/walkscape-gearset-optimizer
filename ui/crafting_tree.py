def _load_game_data() -> dict:
    """Load all game data modules into a single dict.

    Uses `from util.walkscape_constants import *` to avoid circular imports
    (equipment.py <-> walkscape_constants.py cycle).

    Returns dict with keys: recipes, activities, services, containers, materials,
    locations.
    """
    # CRITICAL: use walkscape_constants re-export to avoid circular import
    from util.walkscape_constants import (
        Recipe, Material, Item, Consumable, Collectible,
    )
    from util.autogenerated.recipes import RECIPES_BY_NAME, RecipeInstance
    from util.autogenerated.activities import ACTIVITIES_BY_NAME, ActivityInfo
    from util.autogenerated.services import Service, ServiceInstance
    from util.autogenerated.containers import Container, ContainerInfo
    from util.autogenerated.materials import MaterialInstance
    from util.autogenerated.locations import Location, LocationInfo

    # Recipes keyed by recipe name
    recipes = dict(RECIPES_BY_NAME)

    # Activities keyed by activity name
    activities = dict(ACTIVITIES_BY_NAME)

    # Services keyed by enum attr name
    services = {}
    for attr_name in dir(Service):
        if attr_name.startswith('_'):
            continue
        svc = getattr(Service, attr_name)
        if isinstance(svc, ServiceInstance):
            services[attr_name] = svc

    # Containers keyed by enum attr name
    containers = {}
    for attr_name in dir(Container):
        if attr_name.startswith('_'):
            continue
        cont = getattr(Container, attr_name)
        if isinstance(cont, ContainerInfo):
            containers[attr_name] = cont

    # Materials keyed by enum attr name
    materials = {}
    for attr_name in dir(Material):
        if attr_name.startswith('_'):
            continue
        mat = getattr(Material, attr_name)
        if isinstance(mat, MaterialInstance):
            materials[attr_name] = mat

    # Locations keyed by enum attr name
    locations = {}
    for attr_name in dir(Location):
        if attr_name.startswith('_') or attr_name == 'by_name':
            continue
        loc = getattr(Location, attr_name)
        if isinstance(loc, LocationInfo):
            locations[attr_name] = loc

    # Shops list
    from util.autogenerated.shops import ALL_SHOPS

    return {
        'recipes': recipes,
        'activities': activities,
        'services': services,
        'containers': containers,
        'materials': materials,
        'locations': locations,
        'shops': ALL_SHOPS,
    }


def _get_item_ref_string(item_obj) -> Optional[str]:
    """Get the string reference for an item object (e.g. 'Material.COPPER_ORE')."""
    from util.autogenerated.materials import MaterialInstance

    if isinstance(item_obj, MaterialInstance):
        # Lazy import Material enum via walkscape_constants to avoid circular import
        from util.walkscape_constants import Material
        for attr_name in dir(Material):
            if attr_name.startswith('_'):
                continue
            if getattr(Material, attr_name) is item_obj:
                return f"Material.{attr_name}"
    # Check if it's an equipment item
    if hasattr(item_obj, 'uuid'):
        from util.walkscape_constants import Item
        for attr_name in dir(Item):
            if attr_name.startswith('_'):
                continue
            if getattr(Item, attr_name) is item_obj:
                return f"Item.{attr_name}"
    # Check consumable
    if hasattr(item_obj, 'name'):
        from util.walkscape_constants import Consumable
        for attr_name in dir(Consumable):
            if attr_name.startswith('_'):
                continue
            if getattr(Consumable, attr_name) is item_obj:
                return f"Consumable.{attr_name}"
    return None


def _resolve_item_ref(ref_str: str):
    """Resolve a string reference like 'Material.COPPER_ORE' to the actual object."""
    if not ref_str or '.' not in ref_str:
        return None
    class_name, attr_name = ref_str.split('.', 1)
    # Use walkscape_constants re-exports to avoid circular imports
    from util.walkscape_constants import Material, Item, Consumable, Collectible
    if class_name == 'Material':
        return getattr(Material, attr_name, None)
    elif class_name == 'Item':
        return getattr(Item, attr_name, None)
    elif class_name == 'Consumable':
        return getattr(Consumable, attr_name, None)
    elif class_name == 'Collectible':
        return getattr(Collectible, attr_name, None)
    elif class_name == 'Currency':
        from util.autogenerated.currency import Currency
        return getattr(Currency, attr_name, None)
    elif class_name == 'Container':
        from util.autogenerated.containers import Container
        return getattr(Container, attr_name, None)
    return None


def _build_shop_price_map(tree_nodes: Optional[List[dict]]) -> Dict[str, float]:
    """Map produced-item-ref -> shop unit price for shop-sourced nodes.

    Bug 4a16affa: materials the tree tells you to *buy from a shop* cost the
    shop's listed price (e.g. Mahogany plank = 200 coins at Southern Gem), not
    the item's sell/base value (10). The cost-breakdown builders default to
    obj.value for every shopping-list entry, which understated material cost
    for any shop-sourced material. This helper lets those builders prefer the
    real shop price when a material is sourced from a shop node.

    Keyed by node['item_id'] which is the ref the shopping list uses for
    shop-sourced materials (shops only stock the normal, non-fine variant).
    """
    price_map: Dict[str, float] = {}
    for n in tree_nodes or []:
        if not isinstance(n, dict) or n.get('source_type') != 'shop':
            continue
        shop_src = next(
            (s for s in (n.get('available_sources') or [])
             if s.get('type') == 'shop' and s.get('source_id') == n.get('source_id')),
            None,
        )
        if not shop_src:
            continue
        try:
            price = float(shop_src.get('price', 0.0) or 0.0)
        except (TypeError, ValueError):
            price = 0.0
        if price <= 0:
            continue
        ref = n.get('item_id')
        if ref:
            # Defensive: if the same material is bought from more than one
            # shop node in the tree, keep the higher price.
            price_map[ref] = max(price_map.get(ref, 0.0), price)
    return price_map


def _match_item_ref(drop_ref: Optional[str], target_ref: str) -> bool:
    """Check if a drop's item_ref matches a target item reference string."""
    if not drop_ref:
        return False
    return drop_ref == target_ref


def _rewrite_to_fine(item_ref: str, use_fine: bool) -> str:
    """Rewrite a Material.X ref to Material.X_FINE when fine mode is on and a
    fine variant exists. Otherwise return the ref unchanged.

    Used by both Pass-1 (calculate_node_metrics) and Pass-2 (LP solver /
    extract_node_action_vector) so the fine-rewrite logic lives in one place.

    Args:
        item_ref: Item reference string (e.g. 'Material.IRON_ORE').
        use_fine: Global fine-materials flag from global_settings.

    Returns:
        Either the fine variant (e.g. 'Material.IRON_ORE_FINE') or the input
        unchanged.
    """
    if not use_fine or not item_ref:
        return item_ref
    if not item_ref.startswith('Material.') or item_ref.endswith('_FINE'):
        return item_ref
    fine_ref = item_ref + '_FINE'
    if _resolve_item_ref(fine_ref) is not None:
        return fine_ref
    return item_ref


def _get_region_for_location(location_obj) -> Optional[str]:
    """Get the primary region for a location object.

    Honors LOCATION_REGION_OVERRIDES — returns the override's first region
    when present so callers downstream see the effective gating region.
    """
    if location_obj is None:
        return None
    name = getattr(location_obj, 'name', None)
    if name and name in LOCATION_REGION_OVERRIDES:
        override = LOCATION_REGION_OVERRIDES[name]
        if override:
            return override[0]
    if hasattr(location_obj, 'primary_region'):
        return location_obj.primary_region
    if hasattr(location_obj, 'regions') and location_obj.regions:
        return location_obj.regions[0]
    return None


def _is_location_in_unlocked_region(location_obj, unlocked_regions: set) -> bool:
    """Check if a location is in any unlocked region.

    A location can belong to multiple regions (e.g. Bilgemont Port is in
    both 'gdte' and 'erdwise'). It's accessible if ANY of its effective
    regions is unlocked. Respects LOCATION_REGION_OVERRIDES.
    """
    if not unlocked_regions:
        return False
    unlocked_lower = {r.lower() for r in unlocked_regions}
    effective = _get_effective_regions(location_obj)
    if effective:
        return any(r.lower() in unlocked_lower for r in effective)
    return True  # No region info — assume accessible


def _service_valid_for_recipe(svc, recipe) -> bool:
    """Recipe↔service match that respects "specific-service" requirements
    (e.g. 'Advanced Cursed Forge' only matches services named 'Cursed Forge',
    not plain 'Forge'). Mirrors the logic the recipe-info endpoint uses so
    the crafting tree's service dropdown shows the same filtered list as
    the recipe info section.

    The autogenerated Service.is_valid_for_recipe() strips 'basic '/'advanced '
    from both sides and compares the remaining word — but for 'Advanced
    Cursed Forge' that leaves 'cursed forge' vs 'forge', which never matches.
    This helper handles that case by requiring the service's NAME to equal
    the recipe's detailed service type when the recipe is asking for a
    specific specialization.
    """
    recipe_service = (getattr(recipe, 'service', None) or '')
    if not recipe_service or recipe_service.lower() == 'none':
        return True  # caller decides fallback
    # Strip tier tokens off both sides.
    recipe_without_tier = recipe_service
    for prefix in ('Basic ', 'Advanced '):
        if recipe_without_tier.startswith(prefix):
            recipe_without_tier = recipe_without_tier[len(prefix):]
    recipe_without_tier_lower = recipe_without_tier.lower()
    svc_tier = getattr(svc, 'tier', '') or ''
    svc_base_type = svc_tier
    for prefix in ('Basic ', 'Advanced '):
        if svc_base_type.startswith(prefix):
            svc_base_type = svc_base_type[len(prefix):]
    svc_base_type_lower = svc_base_type.lower()
    recipe_tier_level = 'basic' if 'basic' in recipe_service.lower() else 'advanced'
    svc_tier_level = 'basic' if 'basic' in svc_tier.lower() else 'advanced'
    is_specific_service = recipe_without_tier_lower != svc_base_type_lower

    svc_name = (getattr(svc, 'name', '') or '')
    if is_specific_service:
        # Recipe asks for a specialization (e.g. 'Cursed Forge', 'Runic Sawmill').
        # Only services whose NAME exactly matches the recipe's specialization
        # are valid. Filters out plain-base services.
        if svc_name.lower() != recipe_without_tier_lower:
            return False
        if recipe_tier_level != svc_tier_level:
            return False
        return True
    # Generic base-type match: service base must equal recipe base and a
    # basic service can't satisfy an advanced recipe.
    if recipe_without_tier_lower != svc_base_type_lower:
        return False
    if recipe_tier_level == 'advanced' and svc_tier_level == 'basic':
        return False
    return True


def _get_region_for_recipe(recipe, services_dict: dict) -> Optional[str]:
    """Get the region for a recipe based on its service requirement.

    Returns the region of the first matching service, used only as a fallback.
    For spoiler checking, use _is_recipe_spoiler instead.
    """
    if not recipe.service:
        return None
    for svc_id, svc in services_dict.items():
        if _service_valid_for_recipe(svc, recipe):
            if hasattr(svc, 'location') and svc.location:
                return _get_region_for_location(svc.location)
    return None


def _is_location_locked(location_name: Optional[str], session_data: Optional[dict], spoiler_protection: bool = True) -> bool:
    """Check if a specific location is locked (per-location lock, not region-level).

    Respects `spoiler_protection`: when False, returns False so the user sees
    everything. When True (default), returns True if the location is in the
    character's `locked_locations` (e.g. Underwater Cave requires diving
    gear that isn't equipped).
    """
    if not location_name or not session_data:
        return False
    if not spoiler_protection:
        return False
    locked_locations = set(session_data.get('locked_locations', []))
    if not locked_locations:
        return False
    return location_name in locked_locations


def _check_service_requirements(svc, session_data: Optional[dict]) -> Tuple[bool, Optional[str]]:
    """Return (locked: bool, reason: Optional[str]) for a service's intrinsic
    requirements (skill level + faction reputation + coin access).

    This complements the region/location lock checks. The autogenerated
    `ServiceInstance.is_unlocked()` does the same check but expects a
    Character object — here we work directly off the session_data dict so
    we can use it from the spoiler-tagging path.

    Returns (False, None) if the user meets all requirements OR session_data
    is missing (no character context → don't gate).

    Specifically gates the Saw-in-Half Mill at Halfling Campgrounds on
    `halfling_rebels: 5`, the Erdwiss Trinketry Factory on 77,777 coins
    (`access: [{'type': 'coins', 'coins': 77777}]`), plus any other
    reputation-, skill-, or coin-gated services.
    """
    if not session_data or not svc:
        return False, None
    reqs = getattr(svc, 'requirements', {}) or {}
    skill_reqs = reqs.get('skill', {}) or {}
    rep_reqs = reqs.get('reputation', {}) or {}
    access_reqs = reqs.get('access', []) or []
    char_rep = session_data.get('reputation', {}) or {}
    char_coins = int(session_data.get('coins', 0) or 0)
    missing_parts = []
    # Skill check — character.skills exposes XP, but we want LEVEL. The
    # session_data shape varies; if the value looks like XP (large int),
    # we'd need a converter. For now, best-effort: also check if there's a
    # 'skill_levels' dict, fall back to skipping if neither is available.
    char_levels = session_data.get('skill_levels') or {}
    for skill_name, required_level in skill_reqs.items():
        key = skill_name.lower()
        actual = char_levels.get(key)
        if actual is None:
            # Some session shapes only carry XP; without a level converter
            # here, skip this skill gate rather than false-positive.
            continue
        if actual < required_level:
            missing_parts.append(f"{skill_name.title()} Lv. {required_level} (you have {actual})")
    # Reputation check — char_rep is a dict like {'halfling_rebels': 5}.
    for faction, required_amount in rep_reqs.items():
        key = faction.lower()
        actual = int(char_rep.get(key, 0) or 0)
        if actual < required_amount:
            faction_label = faction.replace('_', ' ').title()
            missing_parts.append(
                f"{required_amount} {faction_label} faction reputation (you have {actual})"
            )
    # Access check — coin gates (e.g. Erdwiss Trinketry Factory: 77,777
    # coins). Other access shapes (items, legacy "Region Access" strings)
    # are skipped here since region/location locks handle those upstream.
    for access in access_reqs:
        if not isinstance(access, dict):
            continue
        if access.get('type') != 'coins':
            continue
        required_coins = int(access.get('coins', 0) or 0)
        if required_coins <= 0:
            continue
        if char_coins < required_coins:
            missing_parts.append(
                f"{required_coins:,} coins (you have {char_coins:,})"
            )
    if not missing_parts:
        return False, None
    return True, " · ".join(missing_parts)


def _check_locked_gearset_conflicts(
    activity_or_recipe,
    gearset_export: Optional[str],
    locked_slots: Optional[dict],
    selected_input_items: Optional[dict] = None,
) -> Optional[str]:
    """Return a human-readable warning when the locked gearset can't satisfy
    activity/recipe keyword requirements; None when feasible.

    Activities (and some recipes) require specific gear keywords —
    e.g. Cut Birch needs ≥1 hatchet. When the user pins specific items to
    specific slots via node.locked_slots, the per-node optimizer is forced
    to keep those items even if they prevent the keyword requirement from
    being met. We surface that to the user as a yellow ⚠️ on the card +
    in the summary so they can unlock or swap before retrying.

    `selected_input_items` is the node's resolved input picks (shape
    matches `gear_config.selected_input_items` / `user_input_items`):
    {idx: {keywords, input_reference, ...}}. Activities like hunting
    consume an input item that ALSO satisfies a keyword requirement
    (e.g. arrows). Without counting these, locking gear that doesn't
    have a 'hunting_bow' keyword would fire a false 'Arrows missing'
    warning even though the input slot has arrows. Mirrors the
    optimizer's pre-satisfy logic in optimize_worker.py
    (`input_item_keywords`).

    Returns:
        None when the gearset satisfies all keyword counts, OR when there's
        no gearset to validate, OR when locked_slots is empty (nothing
        user-pinned, so any optimizer-only failure isn't a 'lock' conflict).
        Otherwise: a short string like 'Locked gear missing keyword: hatchet
        (need 1, have 0)'.
    """
    if not gearset_export or not locked_slots or not activity_or_recipe:
        return None
    requirements = getattr(activity_or_recipe, 'requirements', None) or {}
    keyword_counts = requirements.get('keyword_counts', {}) or {}
    if not keyword_counts:
        return None
    try:
        from util.gearset_utils import Gearset
        gearset = Gearset(gearset_export)
    except Exception:
        # Couldn't decode — don't false-positive a warning; the popup
        # would already be showing other errors.
        return None
    # Overlay the user's locks on top of the optimizer's pick BEFORE
    # counting keywords. Without this, locking all 5 tools to non-bow
    # items on a hunting activity wouldn't trigger a warning when the
    # original optimizer pick had a bow — we'd be counting the bow
    # from the stale export. Mirrors the overlay used in
    # `_decode_gearset_stats` (the lock-aware stats path) so the
    # warning matches what the user actually sees on the tile.
    try:
        from util.autogenerated.equipment import Item
        for slot_name, slot_info in locked_slots.items():
            if not slot_info:
                continue
            item_id = slot_info.get('itemId') if isinstance(slot_info, dict) else None
            quality = slot_info.get('quality') if isinstance(slot_info, dict) else None
            if not item_id:
                continue
            if str(item_id).startswith('generic::'):
                # Generic items aren't in the Item registry; skip
                # overlay (the optimizer's pick stays in place for
                # this slot in the keyword count, which is the
                # closest approximation we can make).
                continue
            try:
                locked_item = Item.by_uuid(item_id, (quality or 'common').lower())
            except Exception:
                locked_item = None
            if not locked_item:
                continue
            slot_attr = f'_{slot_name}'
            if hasattr(gearset, slot_attr):
                setattr(gearset, slot_attr, locked_item)
    except Exception:
        # Defensive: any failure in overlay falls back to the
        # un-overridden gearset — better stale than a 500.
        pass
    # Build the set of keywords satisfied by input items (arrows /
    # plants / fabric / etc.) so they count toward the requirement
    # alongside equipped gear. Mirrors the optimizer's
    # `input_item_keywords` set in optimize_worker.py — without this
    # the warning fires "Arrows missing" even when the input slot
    # has arrows. Two paths:
    #   1. selected_input_items[idx] has resolved keywords/keywords
    #      list (always when user picked or auto-pick ran).
    #   2. Fallback to activity.input_items[idx].reference (the
    #      keyword name) when nothing resolved yet — the optimizer
    #      still pre-satisfies via the activity definition.
    input_kw_set = set()
    try:
        if selected_input_items:
            for _idx, info in selected_input_items.items():
                if not info:
                    continue
                kws = info.get('keywords') if isinstance(info, dict) else None
                if kws:
                    for kw in kws:
                        if kw:
                            input_kw_set.add(str(kw).lower())
                ref = info.get('input_reference') if isinstance(info, dict) else None
                if ref:
                    input_kw_set.add(str(ref).lower())
        # Activity-level fallback: definitions even if no input picked yet.
        if hasattr(activity_or_recipe, 'input_items') and activity_or_recipe.input_items:
            for ii in activity_or_recipe.input_items:
                if getattr(ii, 'type', '') == 'keyword':
                    ref = (getattr(ii, 'reference', '') or '').lower()
                    if ref:
                        input_kw_set.add(ref)
    except Exception:
        # Non-fatal — fall through to the gearset-only count.
        pass
    missing_parts = []
    for keyword, required_count in keyword_counts.items():
        if not required_count or required_count <= 0:
            continue
        try:
            count = sum(
                1 for _slot, item in gearset.get_all_items()
                if item and hasattr(item, 'keywords')
                and any(keyword.lower() == kw.lower() for kw in (item.keywords or []))
            )
        except Exception:
            count = 0
        # Input items (arrows / plant / fabric) can satisfy a keyword
        # requirement directly. Cap the contribution at required_count
        # so a single "arrows" input doesn't claim N satisfactions.
        if keyword.lower() in input_kw_set and count < required_count:
            count += 1
        if count < required_count:
            missing_parts.append(
                f"{keyword.replace('_', ' ').title()} "
                f"(need {required_count}, have {count})"
            )
    if not missing_parts:
        return None
    return "Locked gear missing keyword: " + ", ".join(missing_parts)


def _is_recipe_spoiler(recipe, services_dict: dict, unlocked_regions: set) -> bool:
    """Return True only if ALL matching services are in locked regions.

    A recipe is accessible (not a spoiler) if at least one service that can
    fulfill it is in an unlocked region.
    """
    if not unlocked_regions:
        return False
    if not recipe.service:
        return False
    matching_regions = []
    for svc_id, svc in services_dict.items():
        if _service_valid_for_recipe(svc, recipe):
            if hasattr(svc, 'location') and svc.location:
                region = _get_region_for_location(svc.location)
                if region:
                    matching_regions.append(region.lower())
    if not matching_regions:
        return False
    # Spoiler only if NO matching service is in an unlocked region
    unlocked_lower = {r.lower() for r in unlocked_regions}
    return not any(r in unlocked_lower for r in matching_regions)


