def get_available_sources(
    item_ref: str,
    game_data: dict,
    session_data: Optional[dict] = None,
    spoiler_protection: bool = True
) -> List[dict]:
    """Find all possible sources for an item.

    Args:
        item_ref: Item reference string like "Material.COPPER_ORE"
        game_data: Dict with recipes, activities, containers, services, etc.
        session_data: Character config for region unlocks
        spoiler_protection: Whether to hide sources from locked regions

    Returns:
        List of source dicts with type, source_id, label, region, is_spoiler, etc.
    """
    sources = []
    unlocked_regions = set()
    if session_data and spoiler_protection:
        unlocked_regions = set(session_data.get('region_unlocks', []))

    item_obj = _resolve_item_ref(item_ref)
    item_name = item_obj.name if item_obj and hasattr(item_obj, 'name') else item_ref.split('.')[-1].replace('_', ' ').title()

    # 1. Check recipes that output this item
    for recipe_name, recipe in game_data['recipes'].items():
        if recipe.output_item == item_ref:
            region = _get_region_for_recipe(recipe, game_data.get('services', {}))
            is_spoiler = (spoiler_protection and unlocked_regions and
                          _is_recipe_spoiler(recipe, game_data.get('services', {}), unlocked_regions))
            spoiler_reason = None
            if is_spoiler:
                spoiler_reason = _get_spoiler_reason_for_recipe(
                    recipe, game_data.get('services', {}), unlocked_regions
                )
            recipe_icon = _get_recipe_icon_path(recipe)
            # Multi-material-group expansion (Boxtrap pattern, user
            # spec 2026-05-15): when a recipe has 2+ material groups
            # (different ways to source the same craft), expand it
            # into one source dropdown entry per group, named by the
            # differing material — exactly like column 3 does it.
            # E.g. "Craft a boxtrap - Birch plank" vs "Craft a boxtrap
            # - Pine plank". Single-group recipes still get a single
            # entry with the bare recipe name (no expansion).
            mat_groups = recipe.materials or []
            group_diff_labels = _compute_material_group_labels(mat_groups)
            if len(mat_groups) >= 2 and any(group_diff_labels):
                # Per-recipe "Best (auto)" entry (user spec 2026-05-15:
                # "Same for our new 'craft a boxtrap - Birch plank' and
                # all the other planks below"). material_group_index=-1
                # signals "auto" — the LP optimizer picks the cheapest
                # group at calc time. Pre-Calculate this falls back to
                # group 0 in build_crafting_tree's default-group logic.
                sources.append({
                    'type': 'recipe',
                    'source_id': recipe_name,
                    'material_group_index': -1,
                    'label': f"{recipe.name} - Best (auto) ({recipe.skill} Lv.{recipe.level})",
                    'region': region,
                    'is_spoiler': bool(is_spoiler),
                    'spoiler_reason': spoiler_reason,
                    'icon': recipe_icon,
                })
                for group_idx, diff_label in enumerate(group_diff_labels):
                    label_main = f"{recipe.name}"
                    if diff_label:
                        label_main = f"{label_main} - {diff_label}"
                    sources.append({
                        'type': 'recipe',
                        'source_id': recipe_name,
                        'material_group_index': group_idx,
                        'label': f"{label_main} ({recipe.skill} Lv.{recipe.level})",
                        'region': region,
                        'is_spoiler': bool(is_spoiler),
                        'spoiler_reason': spoiler_reason,
                        'icon': recipe_icon,
                    })
            else:
                sources.append({
                    'type': 'recipe',
                    'source_id': recipe_name,
                    'label': f"{recipe.name} ({recipe.skill} Lv.{recipe.level})",
                    'region': region,
                    'is_spoiler': bool(is_spoiler),
                    'spoiler_reason': spoiler_reason,
                    'icon': recipe_icon,
                })

    # 2. Check activities that drop this item
    for act_name, activity in game_data['activities'].items():
        found = False
        for drop in activity.drop_table:
            if _match_item_ref(drop.item_ref, item_ref):
                found = True
                break
        if not found:
            # Also check secondary drop table
            for drop in getattr(activity, 'secondary_drop_table', []) or []:
                if _match_item_ref(drop.item_ref, item_ref):
                    found = True
                    break
        if found:
            skill_name = (activity.primary_skill or '').lower().replace(' ', '_')
            act_name_slug = (activity.name or '').lower().replace(' ', '_').replace("'", '').replace('-', '_')
            act_icon = f"/assets/icons/activities/{skill_name}/{act_name_slug}.svg" if skill_name else '/assets/icons/attributes/work_efficiency.svg'
            # Create one entry per location for multi-location activities
            locations = activity.locations if activity.locations else [None]
            for loc in locations:
                location_name = loc.name if loc and hasattr(loc, 'name') else (str(loc) if loc else None)
                region = _get_region_for_location(loc) if loc else None
                is_region_spoiler = (spoiler_protection and loc and unlocked_regions
                              and not _is_location_in_unlocked_region(loc, unlocked_regions))
                is_loc_locked = _is_location_locked(location_name, session_data, spoiler_protection)
                is_spoiler = bool(is_region_spoiler) or is_loc_locked
                if is_loc_locked:
                    is_spoiler = True
                spoiler_reason = _get_spoiler_reason_for_location(
                    loc, location_name, bool(is_region_spoiler), bool(is_loc_locked),
                    session_data=session_data,
                ) if is_spoiler else None
                sources.append({
                    'type': 'activity',
                    'source_id': act_name,
                    'label': f"{activity.name}" + (f" ({location_name})" if location_name else ""),
                    'location': location_name,
                    'region': region,
                    'is_spoiler': is_spoiler,
                    'spoiler_reason': spoiler_reason,
                    'icon': act_icon,
                })

    # 3. Check containers/chests that contain this item
    for cont_name, container in game_data.get('containers', {}).items():
        all_drops = container.get_all_drops()
        found = False
        for drop in all_drops:
            if _match_item_ref(drop.item_ref, item_ref):
                found = True
                break
        if found:
            # Find ALL parent activities that drop this chest
            parent_activities = []
            for act_name, activity in game_data['activities'].items():
                drops_chest = False
                for adrop in activity.drop_table:
                    if adrop.item_name and adrop.item_name.lower() == container.name.lower():
                        drops_chest = True
                        break
                if not drops_chest:
                    for adrop in getattr(activity, 'secondary_drop_table', []) or []:
                        if adrop.item_name and adrop.item_name.lower() == container.name.lower():
                            drops_chest = True
                            break
                if drops_chest:
                    parent_region = None
                    parent_loc = None
                    if activity.locations:
                        parent_loc = activity.locations[0]
                        parent_region = _get_region_for_location(parent_loc)
                    parent_activities.append((act_name, activity.name, parent_region, parent_loc))

            # Add one chest-from-activity source per parent activity
            for parent_act_id, parent_act_name, parent_region, parent_loc in parent_activities:
                is_region_spoiler = (spoiler_protection and parent_loc and unlocked_regions
                              and not _is_location_in_unlocked_region(parent_loc, unlocked_regions))
                loc_name = parent_loc.name if parent_loc and hasattr(parent_loc, 'name') else None
                is_loc_locked = _is_location_locked(loc_name, session_data, spoiler_protection)
                is_spoiler = bool(is_region_spoiler) or is_loc_locked
                spoiler_reason = _get_spoiler_reason_for_location(
                    parent_loc, loc_name, bool(is_region_spoiler), bool(is_loc_locked),
                    session_data=session_data,
                ) if is_spoiler else None
                sources.append({
                    'type': 'chest',
                    'source_id': cont_name,
                    'parent_activity_id': parent_act_id,
                    'chest_source': 'activity',
                    'label': f"{container.name} from {parent_act_name}",
                    'region': parent_region,
                    'is_spoiler': is_spoiler,
                    'spoiler_reason': spoiler_reason,
                    'icon': '/assets/icons/items/containers/treasure_chest.svg',
                })

            # Chest from Recipe sources — skill chests drop at 0.4% from any recipe of that skill
            # Derive the skill from the chest name (e.g. "Trinketry chest" → "Trinketry")
            recipe_sources_for_chest = []
            if container.container_type == 'skill_chest':
                chest_skill = container.name.replace(' chest', '').replace(' Chest', '').strip()
                for recipe_name, recipe in game_data['recipes'].items():
                    if recipe.skill and recipe.skill.lower() == chest_skill.lower():
                        recipe_region = _get_region_for_recipe(recipe, game_data.get('services', {}))
                        recipe_is_spoiler = (spoiler_protection and recipe_region and unlocked_regions
                                             and recipe_region.lower() not in {r.lower() for r in unlocked_regions})
                        recipe_spoiler_reason = None
                        if recipe_is_spoiler and unlocked_regions:
                            recipe_spoiler_reason = _get_spoiler_reason_for_recipe(
                                recipe, game_data.get('services', {}), unlocked_regions
                            )
                        recipe_sources_for_chest.append({
                            'type': 'chest',
                            'source_id': cont_name,
                            'parent_recipe_id': recipe_name,
                            'chest_source': 'recipe',
                            'label': f"{container.name} from {recipe.name} ({recipe.skill} Lv.{recipe.level})",
                            'region': recipe_region,
                            'is_spoiler': bool(recipe_is_spoiler) if unlocked_regions else False,
                            'spoiler_reason': recipe_spoiler_reason,
                            'icon': '/assets/icons/items/containers/treasure_chest.svg',
                        })

            # Per-container "Best (auto)" entry — applies to ANY chest
            # with 2+ sources (activity OR recipe), not just skill chests.
            # User spec 2026-05-15: "I should be able to select 'Coral
            # chest -- Best (auto)' like the skill chests. Same for
            # Rusty chest and any other weird chest like this that's
            # not a skill chest." Inserted BEFORE the per-source entries
            # for this container so it reads above them in the dropdown.
            total_chest_sources_for_container = len(parent_activities) + len(recipe_sources_for_chest)
            if total_chest_sources_for_container > 1:
                sources.insert(
                    next((i for i, s in enumerate(sources)
                          if s.get('type') == 'chest' and s.get('source_id') == cont_name),
                         len(sources)),
                    {
                        'type': 'chest',
                        'source_id': cont_name,
                        'chest_source': 'best',
                        'label': f"{container.name} — Best (auto)",
                        'region': None,
                        'is_spoiler': False,
                        'icon': '/assets/icons/items/containers/treasure_chest.svg',
                    }
                )

            sources.extend(recipe_sources_for_chest)

    # 4. Check shops that sell this item
    _CURRENCY_ICONS = {
        'coins': '/assets/icons/items/coins.svg',
        'sea_shell': '/assets/icons/items/materials/sea_shell.svg',
        'ectoplasm': '/assets/icons/items/materials/ectoplasm.svg',
        'adventurers_guild_token': "/assets/icons/items/adventurers'_guild_token.svg",
    }
    for shop in game_data.get('shops', []):
        for shop_item in shop.inventory:
            if shop_item.item_ref == item_ref:
                region = shop.region or None
                is_region_spoiler = (spoiler_protection and region and unlocked_regions
                              and region.lower() not in {r.lower() for r in unlocked_regions})
                is_loc_locked = _is_location_locked(shop.location, session_data, spoiler_protection)
                is_spoiler = bool(is_region_spoiler) or is_loc_locked
                # Shops don't carry a location object, synthesize one just for the
                # regions list so the helper can name the gating region.
