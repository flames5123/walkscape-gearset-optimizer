def _get_service_icon_path(svc) -> str:
    """Get icon path for a service — matches the naming in assets/icons/services/."""
    name = (svc.name or '').lower().replace(' ', '_').replace("'", '')
    tier = (svc.tier or '').lower()
    # Services whose name starts with "basic" have files like basic_forge.svg (no suffix)
    # Others get _(basic) or _(advanced) suffix based on tier
    name_has_tier = name.startswith('basic_') or name.startswith('advanced_')
    if name_has_tier:
        return f"/assets/icons/services/{name}.svg"
    if 'advanced' in tier:
        return f"/assets/icons/services/{name}_(advanced).svg"
    if 'basic' in tier:
        return f"/assets/icons/services/{name}_(basic).svg"
    return f"/assets/icons/services/{name}.svg"


def _get_icon_path_for_ref(item_ref: str, item_obj=None) -> str:
    """Get the icon path for an item reference string."""
    if not item_ref:
        return ''
    if item_obj is None:
        item_obj = _resolve_item_ref(item_ref)
    item_name = item_obj.name if item_obj and hasattr(item_obj, 'name') else item_ref.split('.')[-1].replace('_', ' ').title()
    # Remove quality suffixes like " (Fine)" for icon lookup
    clean_name = item_name.replace(' (Fine)', '')
    filename = clean_name.replace(' ', '_').lower() + '.svg'

    if item_ref.startswith('Material.'):
        return f"/assets/icons/items/materials/{filename}"
    elif item_ref.startswith('Item.'):
        return f"/assets/icons/items/equipment/{filename}"
    elif item_ref.startswith('Consumable.'):
        return f"/assets/icons/items/consumables/{filename}"
    elif item_ref.startswith('Collectible.'):
        return f"/assets/icons/items/collectibles/{filename}"
    elif item_ref.startswith('Container.'):
        # Containers/chests live under /containers/, not /materials/.
        # User reported 2026-05-15: side-drops summary was failing to
        # resolve carpentry_chest.svg because it was being looked up
        # under /materials/ instead of /containers/.
        return f"/assets/icons/items/containers/{filename}"
    elif item_ref.startswith('Egg.'):
        # Pet eggs (e.g. Egg.MUMMY_EGG → /pet_eggs/mummy_egg.svg).
        # User reported 2026-05-15: side-drops were missing icons for
        # pet eggs because they fell into the materials catch-all.
        return f"/assets/icons/items/pet_eggs/{filename}"
    else:
        return f"/assets/icons/items/materials/{filename}"


