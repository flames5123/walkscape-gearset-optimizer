"""Trading "Upgrades for me" filter — simple static dominance.

Powers the FAC-gated (``trading_upgrades_filter``) Browse checkbox: show only
market SELL listings whose item is EXPLICITLY better than something the viewer
already owns, using character-independent static dominance.

Semantics (confirmed with the user):
  * Compare only items in the SAME equipment slot.
  * An item A is "explicitly better" than B iff A statically dominates B:
    A >= B on every (scope-qualified) stat and A > B on at least one. Sign-aware
    via the shared ``INVERTED_STATS`` set (steps_add / steps_percent are
    lower-is-better). This mirrors
    ``util.stats_report.precompute.build_dominators._statically_dominates`` but
    over the item's FULL stat tree flattened across every (skill, location)
    scope, so no activity/character context is required.
  * "after all our self dominance": the viewer's owned items are first reduced
    to the non-self-dominated FRONTIER per slot (drop any owned item that is
    already dominated by another owned item of the same slot). A listing counts
    as an upgrade iff it statically dominates at least one owned frontier item
    in its slot.

Everything here is read-only and defensive: anything that fails to resolve is
simply never flagged as an upgrade (conservative — we never over-report).
"""
from __future__ import annotations

from typing import Dict, List, Optional, Tuple, Callable

try:
    from util.stats_report.precompute.build_dominators import INVERTED_STATS
except Exception:  # pragma: no cover - fallback if import path shifts
    INVERTED_STATS = frozenset({"steps_add", "steps_percent"})

# Crafted quality tiers (lowest -> highest), matching build_item_ids.QUALITY_TIERS.
_QUALITY_TIERS = ("normal", "good", "great", "excellent", "perfect", "eternal")

_EPS = 1e-9

# ---------------------------------------------------------------------------
# Catalog resolution (cached once per process).
# ---------------------------------------------------------------------------
_CATALOG: Optional[Dict[str, dict]] = None  # slug -> {"slot": str, "qualities": {quality: flat_stats}}
_ALIAS: Optional[Dict[str, str]] = None     # alias slug -> canonical catalog slug


def _canon(name: str) -> str:
    return (name or "").lower().replace(" ", "_").replace("(", "").replace(")", "") \
        .replace("-", "_").replace("'", "")


def _flatten_stats(nested, prefix: str = "") -> Dict[str, float]:
    """Flatten a possibly-nested stat tree into {scope_qualified_key: value}.

    The LAST path component is the raw stat name, so the inverted-stat check can
    key on it. Non-numeric leaves are skipped.
    """
    out: Dict[str, float] = {}
    if not isinstance(nested, dict):
        return out
    for k, v in nested.items():
        key = f"{prefix}\x01{k}" if prefix else str(k)
        if isinstance(v, dict):
            out.update(_flatten_stats(v, key))
        elif isinstance(v, (int, float)) and not isinstance(v, bool):
            out[key] = float(v)
    return out


def _raw_stat(flat_key: str) -> str:
    return flat_key.rsplit("\x01", 1)[-1]


def _item_stats(item) -> dict:
    return getattr(item, "_stats", None) or getattr(item, "stats", None) or {}


def _build_catalog() -> Tuple[Dict[str, dict], Dict[str, str]]:
    """Build slug -> {slot, qualities:{quality: flat_stats}} and an alias map.

    Uses the same enumeration the stats-report dominators use, so crafted tiers
    and plain item instances are both covered. Aliases let a trading slug
    (game key / name-canon) resolve to the catalog slug (the attribute name).
    """
    catalog: Dict[str, dict] = {}
    alias: Dict[str, str] = {}
    try:
        from util.stats_report.precompute.build_dominators import _enumerate_all_catalog_items
        items = _enumerate_all_catalog_items()
    except Exception:
        return catalog, alias

    try:
        from util.autogenerated.item_game_keys import ITEM_GAME_KEYS
    except Exception:
        ITEM_GAME_KEYS = {}

    for slug, quality, instance in items:
        slot = getattr(instance, "slot", None)
        if not slot:
            continue
        entry = catalog.setdefault(slug, {"slot": slot, "qualities": {}})
        entry["qualities"][quality] = _flatten_stats(_item_stats(instance))
        # Aliases: by canonical display name and by game key, so a listing's
        # slug (which comes from the game export key space) still resolves.
        name = getattr(instance, "name", "") or ""
        # CraftedItem instances carry "(quality)" in the name — strip it.
        base_name = name.split(" (")[0] if " (" in name else name
        for a in (_canon(base_name),):
            if a and a not in catalog:
                alias.setdefault(a, slug)
        gk = ITEM_GAME_KEYS.get(_canon(base_name))
        if gk and gk not in catalog:
            alias.setdefault(gk, slug)
    return catalog, alias


def _catalog() -> Tuple[Dict[str, dict], Dict[str, str]]:
    global _CATALOG, _ALIAS
    if _CATALOG is None:
        _CATALOG, _ALIAS = _build_catalog()
    return _CATALOG, _ALIAS


def _resolve_slug(slug: str) -> Optional[str]:
    catalog, alias = _catalog()
    if not slug:
        return None
    if slug in catalog:
        return slug
    return alias.get(slug) or alias.get(_canon(slug))


def _map_quality(canonical_slug: str, token: str) -> str:
    """Map a trading quality token to the catalog quality key for this item."""
    catalog, _ = _catalog()
    qualities = catalog.get(canonical_slug, {}).get("qualities", {})
    tok = (token or "").lower()
    if tok in qualities:
        return tok
    if tok in _QUALITY_TIERS and tok in qualities:
        return tok
    # Base / rarity tokens / fine / anything unknown -> the item's base stats.
    if "normal" in qualities:
        return "normal"
    # Fallback to any available quality (keeps a stat set to compare on).
    return next(iter(qualities), "normal")


def resolve(slug: str, token: str) -> Optional[Tuple[str, Dict[str, float]]]:
    """Return (slot, flat_stats) for a (slug, quality-token), or None."""
    cslug = _resolve_slug(slug)
    if not cslug:
        return None
    catalog, _ = _catalog()
    entry = catalog.get(cslug)
    if not entry:
        return None
    q = _map_quality(cslug, token)
    stats = entry["qualities"].get(q)
    if stats is None:
        return None
    return entry["slot"], stats


def dominates(a: Dict[str, float], b: Dict[str, float]) -> bool:
    """True iff A statically dominates B (A>=B everywhere, A>B somewhere).

    Sign-aware via INVERTED_STATS on the raw (leaf) stat name.
    """
    if not a and not b:
        return False
    keys = set(a) | set(b)
    if not keys:
        return False
    better_anywhere = False
    for key in keys:
        av = a.get(key, 0.0)
        bv = b.get(key, 0.0)
        inverted = _raw_stat(key) in INVERTED_STATS
        if inverted:
            if av > bv + _EPS:
                return False
            if av < bv - _EPS:
                better_anywhere = True
        else:
            if av < bv - _EPS:
                return False
            if av > bv + _EPS:
                better_anywhere = True
    return better_anywhere


def owned_frontier(owned_qualities: Dict[str, Dict[str, int]]) -> Dict[str, List[Dict[str, float]]]:
    """Reduce the viewer's owned items to the non-self-dominated frontier per slot.

    ``owned_qualities`` is ``{slug: {quality_token: qty}}`` (from
    ``_trading_owned_qualities``). Returns ``{slot: [flat_stats, ...]}``.
    """
    by_slot: Dict[str, List[Dict[str, float]]] = {}
    for slug, tokens in (owned_qualities or {}).items():
        for token, qty in (tokens or {}).items():
            try:
                if int(qty) <= 0:
                    continue
            except (TypeError, ValueError):
                continue
            r = resolve(slug, token)
            if not r:
                continue
            slot, stats = r
            if not stats:
                continue
            by_slot.setdefault(slot, []).append(stats)

    frontier: Dict[str, List[Dict[str, float]]] = {}
    for slot, items in by_slot.items():
        kept: List[Dict[str, float]] = []
        for i, cand in enumerate(items):
            dominated = False
            for j, other in enumerate(items):
                if i == j:
                    continue
                # `other` strictly dominates `cand` -> drop cand. Ties (identical
                # stats) must not both be dropped, so break ties by index.
                if dominates(other, cand) and not (dominates(cand, other) and j > i):
                    dominated = True
                    break
            if not dominated:
                kept.append(cand)
        frontier[slot] = kept
    return frontier


def make_predicate(owned_qualities: Dict[str, Dict[str, int]]) -> Callable[[str, str], bool]:
    """Return ``fn(slug, token) -> bool`` : is this item an upgrade for the viewer?

    True iff the item statically dominates at least one owned frontier item in
    the same slot. Memoized per (slug, token).
    """
    frontier = owned_frontier(owned_qualities)
    cache: Dict[Tuple[str, str], bool] = {}

    def _is_upgrade(slug: str, token: str) -> bool:
        key = (slug or "", token or "")
        if key in cache:
            return cache[key]
        res = False
        r = resolve(slug, token)
        if r:
            slot, stats = r
            if stats:
                for owned in frontier.get(slot, ()):  # same slot only
                    if dominates(stats, owned):
                        res = True
                        break
        cache[key] = res
        return res

    return _is_upgrade
