#!/usr/bin/env python3
"""Termite pet "effort" -> secondary-skill XP support (informational).

The Termite pet's passive "Terminate" ability (unlocks at level 4) has a
`chance`% chance, while doing its `skill` (Woodcutting), to convert a found
`from_keywords` item (logs) from the activity loot into `to_skill` (Carpentry)
XP equal to the material's ``effort`` * ``xp_effort_modifier`` (0.5).

This module derives that as an INFORMATIONAL secondary-XP stream (it is NOT an
optimization objective). It also reflects the conversion in the drop table:
`chance`% of those logs become XP instead of items, so the displayed yield of
each logs-keyword material drops by `chance` (steps-per-material rises by
1/(1-chance)).

The ability data lives on ``Pet.TERMITE.get_level(level).abilities[].item_swap``
(hand-authored in util/scrapers/old_shape_emitters.py because the tools API
publishes the swap stat in a shape the generic emitter can't reconstruct).
"""
from __future__ import annotations

from typing import Any, Dict, Optional


def _norm_kw(keyword: Any) -> str:
    """Normalize a keyword for tolerant matching: lowercase + drop a trailing
    plural 's' so the API keyword id "logs" matches the material keyword "Log"."""
    return str(keyword).strip().lower().rstrip('s')


def _active_pet_item_swap(active_pet: Optional[Dict[str, Any]],
                          activity) -> Optional[Dict[str, Any]]:
    """Return the terminate-style item_swap dict IF the active pet is a Termite
    (level >= 4) whose ability's `skill` matches the activity's primary skill.
    Otherwise None."""
    if not isinstance(active_pet, dict):
        return None
    species = (active_pet.get('species') or active_pet.get('name') or '').lower()
    try:
        level = int(active_pet.get('level') or 0)
    except (TypeError, ValueError):
        return None
    if species != 'termite' or level < 4:
        return None
    primary_skill = (getattr(activity, 'primary_skill', '') or '').lower()
    try:
        from util.autogenerated.pets import Pet
    except Exception:
        return None
    pet_levels = getattr(Pet, 'TERMITE', None)
    if pet_levels is None or not hasattr(pet_levels, 'get_level'):
        return None
    level_info = pet_levels.get_level(level)
    for ability in (getattr(level_info, 'abilities', None) or []):
        swap = ability.get('item_swap') if isinstance(ability, dict) else None
        if not swap:
            continue
        # Ability only applies while doing its own skill (Woodcutting).
        swap_skill = (swap.get('skill') or '').lower()
        if swap_skill and swap_skill != primary_skill:
            continue
        return swap
    return None


def apply_termite_effort(activity, results: Dict[str, float],
                         details: Dict[str, Any],
                         active_pet: Optional[Dict[str, Any]]) -> Optional[Dict[str, Any]]:
    """If the Termite (lvl >= 4) is the active pet on a matching activity, MUTATE
    ``results`` to reduce each logs-keyword material's yield by the swap chance,
    and return a computed secondary-XP dict:

        {'skill': 'carpentry', 'per_step': float, 'per_action': float,
         'chance': 0.15, 'per_step_by_item': {item_name: xp_per_step}}

    Returns None (and leaves ``results`` untouched) when the ability doesn't
    apply. The XP is derived from the ORIGINAL (pre-reduction) expected log
    yield, so it already reflects double-rewards / find bonuses baked into
    ``results`` (steps_per_item). Bonus-XP gear stats are intentionally NOT
    applied — the conversion is a fixed effort * modifier, not activity XP.
    """
    swap = _active_pet_item_swap(active_pet, activity)
    if not swap:
        return None
    # The ability's from_keywords use the API keyword id ("logs"); materials
    # store the display keyword ("Log"). Normalize both (lowercase + drop a
    # trailing plural 's') so "logs" matches "Log".
    from_kws = {_norm_kw(k) for k in (swap.get('from_keywords') or [])}
    to_skill = (swap.get('to_skill') or 'carpentry').lower()
    try:
        chance = float(swap.get('chance', 0.0)) / 100.0
        modifier = float(swap.get('xp_effort_modifier', 0.0))
    except (TypeError, ValueError):
        return None
    if chance <= 0.0 or chance >= 1.0 or not from_kws:
        return None

    # Map each logs-keyword material dropped by this activity -> its effort.
    log_effort: Dict[str, int] = {}
    try:
        drops = activity.get_all_drops()
    except Exception:
        drops = []
    for drop in drops:
        try:
            item_object = drop.item_object
        except Exception:
            item_object = None
        if item_object is None:
            continue
        effort = getattr(item_object, 'effort', None)
        if effort is None:
            continue
        keywords = [str(k).lower() for k in (getattr(item_object, 'keywords', None) or [])]
        if any(_norm_kw(k) in from_kws for k in keywords):
            log_effort[drop.item_name] = effort
    if not log_effort:
        return None

    per_step_by_item: Dict[str, float] = {}
    per_step_total = 0.0
    INF = float('inf')
    for item_name, effort in log_effort.items():
        steps_per_item = results.get(item_name)
        if steps_per_item and steps_per_item != INF and steps_per_item > 0:
            per_step_total += (1.0 / steps_per_item) * chance * float(effort) * modifier
            per_step_by_item[item_name] = (1.0 / steps_per_item) * chance * float(effort) * modifier
            # Reduce the displayed yield: `chance` of these logs are converted
            # to XP, so only (1 - chance) remain as items -> steps rise.
            # NOTE: the swap only converts NON-fine logs, so the fine-variant
            # yield ("<name> (Fine)") is intentionally left unchanged.
            results[item_name] = steps_per_item / (1.0 - chance)

    if per_step_total <= 0.0:
        return None

    esa = details.get('expected_steps_per_action') if isinstance(details, dict) else None
    per_action = per_step_total * esa if esa else None
    return {
        'skill': to_skill,
        'per_step': per_step_total,
        'per_action': per_action,
        'chance': chance,
        'per_step_by_item': per_step_by_item,
    }


# ─────────────────────────────────────────────────────────────────────────
# Goals / stats-report support
#
# The interactive views (activity-info / calculator / comparison) key the
# Terminate carpentry stream off the EQUIPPED pet (store.state.gearsets.current
# .pet). The goals / stats report is different: it is informational and its
# product intent is "carpentry xp/step applies to all log-cutting activities IF
# you have the lvl 4 termite" — i.e. keyed on OWNERSHIP, not on which pet the
# per-activity optimizer happened to equip. The owned Termite (species+level) is
# already part of the stats-report staleness fingerprint (owned_pets in
# util.stats_report.metric_inputs.compute_metric_inputs_hash, and
# _pet_skill_index maps 'termite' -> {'woodcutting','carpentry'}), so a row
# recomputes when the Termite is added / removed / leveled.
# ─────────────────────────────────────────────────────────────────────────


def owned_termite_level(character) -> Optional[int]:
    """Highest level of a Termite the character OWNS, or None if it owns no
    Termite at level >= 4 (the Terminate ability unlock level). Reads
    ``character.pets`` (list of {'species','level',...} dicts). Never raises."""
    try:
        pets = getattr(character, 'pets', None) or []
        best = None
        for p in pets:
            if not isinstance(p, dict):
                continue
            species = (p.get('species') or p.get('name') or '').lower()
            if species != 'termite':
                continue
            try:
                lvl = int(p.get('level') or 0)
            except (TypeError, ValueError):
                continue
            if lvl >= 4 and (best is None or lvl > best):
                best = lvl
        return best
    except Exception:
        return None


def activity_has_logs_drop(activity) -> bool:
    """True if the activity drops at least one logs-keyword material carrying an
    ``effort`` value — i.e. a material the Terminate ability can convert to
    Carpentry XP. Gearset-independent, so it is a safe pre-filter for whether a
    Carpentry row should be emitted for a (Woodcutting) activity. Never raises."""
    try:
        drops = activity.get_all_drops()
    except Exception:
        return False
    for drop in (drops or []):
        try:
            item_object = drop.item_object
        except Exception:
            item_object = None
        if item_object is None:
            continue
        if getattr(item_object, 'effort', None) is None:
            continue
        keywords = [str(k) for k in (getattr(item_object, 'keywords', None) or [])]
        if any(_norm_kw(k) == 'log' for k in keywords):
            return True
    return False


def compute_report_termite_carpentry(activity, total_stats, location, character):
    """Informational Carpentry XP the Terminate ability adds on a Woodcutting
    activity for the goals / stats report.

    Keyed on OWNERSHIP: if the character owns a level >= 4 Termite, compute the
    Carpentry XP/step (+ XP/action) the ability grants on this activity with the
    given optimized gearset ``total_stats``. Returns the same dict shape as
    ``apply_termite_effort`` ({'skill','per_step','per_action','chance',
    'per_step_by_item'}), or None when it doesn't apply (no owned lvl>=4 Termite,
    non-Woodcutting activity, or no convertible logs-keyword drops). Never
    raises — the report row falls back to 0 Carpentry on None.

    The drop yields are recomputed here (like the interactive /api/calculate-
    activity-stats path) so the XP reflects the optimized gearset's find /
    double-reward bonuses. A COPY of ``results`` is passed so this never mutates
    the caller's drop-rate map.
    """
    try:
        lvl = owned_termite_level(character)
        if lvl is None:
            return None
        results, details = activity.get_expected_drop_rate(
            total_stats or {}, location=location, verbose=True, character=character)
        return apply_termite_effort(
            activity, dict(results), details, {'species': 'termite', 'level': lvl})
    except Exception:
        return None
