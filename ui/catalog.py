#!/usr/bin/env python3
"""
Item catalog builder for Walkscape UI.

Organizes all items into categories for UI display:
- Collectibles
- Consumables (by skill)
- Materials
- Loot (achievement rewards, activity drops, faction rewards, shop items, chests)
- Crafted (by keyword)
- Pets

Auto-generated by scrape_equipment.py, scrape_materials.py, scrape_consumables.py, etc.
"""

from typing import Dict, List, Optional, Set, Tuple
from collections import defaultdict
import re

# Import everything from walkscape_constants which handles circular imports correctly
from util.walkscape_constants import (
    Item, Material, Consumable, Container, Activity,
    Collectible, COLLECTIBLES_BY_NAME
)

# Import new data modules for categorization
from util.autogenerated.ap_rewards import AP_REWARD_ITEM_NAMES, ALL_REWARDS as AP_ALL_REWARDS
from util.autogenerated.faction_rewards import ALL_FACTION_TRACKS, get_faction_reward_item_names
from util.autogenerated.shops import ALL_SHOPS, get_shop_item_names

# Helper function to get icon path
def get_icon_path(item_name: str, item_type: str = 'equipment') -> str:
    """Get icon path for an item."""
    # Sanitize name for filename - keep hyphens and apostrophes
    filename = item_name.replace(' ', '_').lower() + '.svg'
    
    # Check if this is a pet egg (ends with " egg")
    if item_name.endswith(' egg'):
        # Check if it's actually a pet egg by trying to import
        try:
            from util.autogenerated.pets import EGGS_BY_NAME
            if item_name in EGGS_BY_NAME:
                return f"icons/items/pet_eggs/{filename}"
        except:
            pass
    
    # Determine subdirectory based on type
    if item_type == 'container':
        subdir = 'containers'
    elif item_type == 'consumable':
        subdir = 'consumables'
    elif item_type == 'collectible':
        subdir = 'collectibles'
    elif item_type == 'material':
        subdir = 'materials'
    else:
        subdir = 'equipment'
    
    # Return path - let browser handle 404s
    return f"icons/items/{subdir}/{filename}"


class ItemCatalog:
    """Organizes all items into categories for UI display"""
    
    def __init__(self):
        self._build_catalog()
    
    def _build_catalog(self):
        """Build categorized item lists from equipment, materials, etc."""
        # Pre-compute item source sets for categorization
        self._ap_reward_names = AP_REWARD_ITEM_NAMES
        self._faction_reward_names = get_faction_reward_item_names()
        self._shop_item_names = get_shop_item_names()
        self._activity_drop_names = self._compute_activity_drop_names()
        self._achievement_reward_names = self._compute_achievement_reward_names()
        self._chest_item_names = self._compute_chest_item_names()

        self.categories = {
            'collectibles': self._get_collectibles_with_subcategories(),
            'consumables': self._get_consumables_by_skill(),
            'loot': {
                'ap_rewards': self._get_loot_ap_rewards(),
                'achievement_rewards': self._get_achievement_items(),
                'activity_drops': self._get_loot_activity_drops(),
                'misc_loot': self._get_misc_loot(),
                'faction_rewards': self._get_loot_faction_rewards(),
                'shop_items': self._get_loot_shop_items(),
            },
            'crafted': self._get_crafted_by_keyword()[0],
            'crafted_unique_count': self._get_crafted_by_keyword()[1],
            'chests': self._get_chests_with_contents(),
            'pets': self._get_pets(),
            'materials': self._get_all_materials(),
            'all_equipment': self._get_all_equipment(),  # All equipment items for catalog API
        }
    
    def _get_collectibles_with_subcategories(self) -> Dict[str, List[Dict]]:
        """Get collectibles organized by source subcategory."""
        # Build a dict of all collectibles
        all_collectibles = {}
        for collectible in COLLECTIBLES_BY_NAME.values():
            item_dict = {
                'id': self._name_to_id(collectible.name),
                'name': collectible.name,
                'type': 'collectible',
                'rarity': 'common',
                'keywords': [],
                'stats': collectible._stats,
                'icon_path': f"/assets/{get_icon_path(collectible.name, 'collectible')}",
            }
            all_collectibles[collectible.name] = item_dict

        # Categorize collectibles by source
        ap_rewards = []
        activity_drops = []
        faction_rewards = {}
        shop_items = []
        uncategorized = []

        for name, item_dict in sorted(all_collectibles.items(), key=lambda x: x[0].lower()):
            categorized = False

            # Check AP rewards
            if name in self._ap_reward_names:
                ap_rewards.append(item_dict)
                categorized = True

            # Check activity drops
            if name in self._activity_drop_names:
                activity_drops.append(item_dict)
                categorized = True

            # Check faction rewards
            for faction_name, track in ALL_FACTION_TRACKS.items():
                for tier in track.tiers:
                    for reward in tier.rewards:
                        if reward.item_name.lower() == name.lower() and reward.item_type == 'Collectible':
                            if faction_name not in faction_rewards:
                                faction_rewards[faction_name] = []
                            faction_rewards[faction_name].append(item_dict)
                            categorized = True

            # Check shop items
            if name in self._shop_item_names:
                shop_items.append(item_dict)
                categorized = True

            if not categorized:
                uncategorized.append(item_dict)

        result = {}
        if ap_rewards:
            result['Achievement Point Rewards'] = ap_rewards
        if activity_drops:
            result['Activity Drops'] = activity_drops
        if faction_rewards:
            result['Faction Rewards'] = faction_rewards
        if shop_items:
            result['Shop Items'] = shop_items
        if uncategorized:
            result['Other'] = uncategorized

        return result
    
    def _get_consumables_by_skill(self) -> Dict[str, List[Dict]]:
        """Organize consumables by skill affinity, combining normal and fine versions.
        
        Skill group consumables (Artisan, Gathering, Utility) are expanded into each
        sub-skill category so they appear in every relevant skill tab. They share the
        same base ID so UI state changes (has/hide) stay linked across copies.
        """
        by_skill = defaultdict(list)
        consumables_dict = {}  # (skill, base_id) -> consumable entry
        
        # Skill group expansion: group name -> list of sub-skills.
        # Must match the canonical memberships in app.py (gathering_skills /
        # artisan_skills) and walkscape_constants. Hunting is a Gathering
        # skill and Tailoring is an Artisan skill -- omitting them hid
        # gathering/artisan consumables from the Hunting/Tailoring tabs.
        SKILL_GROUP_EXPANSION = {
            'Artisan': ['Carpentry', 'Cooking', 'Crafting', 'Smithing', 'Tailoring', 'Trinketry'],
            'Gathering': ['Fishing', 'Foraging', 'Hunting', 'Mining', 'Woodcutting'],
            'Utility': ['Agility'],
        }
        
        # Get all consumables (they are uppercase class attributes)
        for attr_name in dir(Consumable):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            consumable = getattr(Consumable, attr_name)
            # Duck typing: check if it has the attributes we need
            if not hasattr(consumable, 'name') or not hasattr(consumable, '_stats'):
                continue
            
            # Determine skill affinity from stats
            skill_affinity = self._get_consumable_skill(consumable)
            
            # Check if this is a fine version
            is_fine = consumable.name.endswith('(Fine)')
            base_name = consumable.name.replace(' (Fine)', '')
            base_id = self._name_to_id(base_name)
            
            # Expand skill groups into sub-skills, or use as-is
            target_skills = SKILL_GROUP_EXPANSION.get(skill_affinity, [skill_affinity])
            
            for target_skill in target_skills:
                key = (target_skill, base_id)
                
                # Create or update entry for this base consumable
                if key not in consumables_dict:
                    consumables_dict[key] = {
                        'id': base_id,  # Same ID across all sub-skills for state linking
                        'name': base_name,
                        'type': 'consumable',
                        'slot': 'consumable',
                        'has_fine': False,
                        'skill': target_skill,
                        'duration': consumable.duration if not is_fine else None,
                        'duration_fine': consumable.duration if is_fine else None,
                        'value': consumable.value if not is_fine else None,
                        'value_fine': consumable.value if is_fine else None,
                        'keywords': consumable.keywords,
                        'stats': consumable._stats if not is_fine else None,
                        'stats_fine': consumable._stats if is_fine else None,
                        'rarity': 'common',
                        'icon_path': f"/assets/{get_icon_path(base_name, 'consumable')}",
                    }
                
                # Update with fine info if this is the fine version
                if is_fine:
                    consumables_dict[key]['has_fine'] = True
                    consumables_dict[key]['duration_fine'] = consumable.duration
                    consumables_dict[key]['value_fine'] = consumable.value
                    consumables_dict[key]['stats_fine'] = consumable._stats
                else:
                    consumables_dict[key]['duration'] = consumable.duration
                    consumables_dict[key]['value'] = consumable.value
                    consumables_dict[key]['stats'] = consumable._stats
        
        # Group by skill
        for (skill_affinity, _), consumable_entry in consumables_dict.items():
            by_skill[skill_affinity].append(consumable_entry)
        
        # Sort items within each skill
        result = {}
        for skill, items_list in by_skill.items():
            result[skill] = sorted(items_list, key=lambda x: x['name'].lower())
        
        return result
    
    def _get_consumable_skill(self, consumable) -> str:
        """Determine skill affinity from consumable stats"""
        # Check stats structure: {skill: {location: {stat: value}}}
        if not consumable._stats:
            return 'Global'
        
        # Get all skills from stats
        skills = [skill for skill in consumable._stats.keys() if skill != 'global']
        
        if not skills:
            return 'Global'
        
        # Return first skill (most consumables have one skill)
        skill = skills[0]
        
        # Map skill names to display names (including skill groups)
        skill_map = {
            'agility': 'Agility',
            'carpentry': 'Carpentry',
            'cooking': 'Cooking',
            'crafting': 'Crafting',
            'fishing': 'Fishing',
            'foraging': 'Foraging',
            'hunting': 'Hunting',
            'mining': 'Mining',
            'smithing': 'Smithing',
            'tailoring': 'Tailoring',
            'trinketry': 'Trinketry',
            'woodcutting': 'Woodcutting',
            'traveling': 'Traveling',
            'artisan': 'Artisan',
            'gathering': 'Gathering',
            'utility': 'Utility',
        }
        
        return skill_map.get(skill.lower(), skill.capitalize())
    
    def _get_pets(self) -> List[Dict]:
        """Get all pets with level data for the UI."""
        try:
            from util.autogenerated.pets import Pet as PetClass, PETS_BY_NAME
        except Exception as e:
            print(f"⚠ Failed to import pets: {e}")
            return []
        
        pets = []
        for pet_name, pet_levels in PETS_BY_NAME.items():
            all_levels = pet_levels.get_all_levels()
            if not all_levels:
                continue
            
            pet_id = self._name_to_id(pet_name)
            egg_name = pet_levels.egg_name
            max_level = max(all_levels.keys())
            
            # Build levels dict for the catalog entry (use string keys for JSON compatibility)
            levels_dict = {}
            for level_num, pet_info in sorted(all_levels.items()):
                abilities_list = []
                if pet_info.abilities:
                    for ability in pet_info.abilities:
                        ability_entry = {
                            'name': ability.get('name'),
                            'effect': ability.get('effect'),
                            'requirements': ability.get('requirements'),
                            'cooldown': ability.get('cooldown'),
                            'charges': ability.get('charges'),
                            'icon': ability.get('icon'),
                        }
                        # Include structured ability stats if present
                        if ability.get('ability_stats'):
                            ability_entry['ability_stats'] = ability['ability_stats']
                        if ability.get('duration') is not None:
                            ability_entry['duration'] = ability['duration']
                        if ability.get('duration_unit'):
                            ability_entry['duration_unit'] = ability['duration_unit']
                        # Include instant-actions fields if present
                        if ability.get('instant_actions'):
                            ability_entry['instant_actions'] = True
                            ability_entry['instant_actions_skill'] = ability.get('instant_actions_skill')
                            ability_entry['instant_actions_count'] = ability.get('instant_actions_count')
                        abilities_list.append(ability_entry)
                
                levels_dict[str(level_num)] = {
                    'xp_required': pet_info.xp_required,
                    'requirement_to_gain_xp': pet_info.requirement_to_gain_xp,
                    'stats': pet_info._stats if hasattr(pet_info, '_stats') else {},
                    'abilities': abilities_list,
                }
            
            egg_filename = egg_name.lower().replace(' ', '_') + '.svg' if egg_name else 'unknown_egg.svg'
            
            pets.append({
                'id': pet_id,
                'name': pet_name,
                'type': 'pet',
                'slot': 'pet',
                'rarity': 'common',
                'keywords': ['pet'],
                'egg_name': egg_name,
                'max_level': max_level,
                'rare_name': pet_levels.rare_name,
                'rare_export_name': pet_levels.rare_export_name,
                'species': pet_levels.species,
                'icon_path': f"/assets/icons/items/pet_eggs/{egg_filename}",
                'levels': levels_dict,
            })
        
        return sorted(pets, key=lambda x: x['name'].lower())

    def _get_all_materials(self) -> List[Dict]:
        """Get all materials, combining normal and fine versions.
        Excludes items that are actually equipment or consumables (they're in materials.py
        only as recipe inputs but should show in their proper category)."""
        materials_dict = {}  # base_name -> material entry
        
        # Build set of names that exist in equipment.py or consumables.py
        # Use file-based lookup to avoid circular import issues
        import re as _re
        from pathlib import Path as _Path
        
        equipment_names = set()
        try:
            eq_content = _Path('util/autogenerated/equipment.py').read_text()
            for m in _re.finditer(r'name="([^"]+)"', eq_content):
                equipment_names.add(m.group(1).lower())
            for m in _re.finditer(r"name='([^']+)'", eq_content):
                equipment_names.add(m.group(1).lower())
        except Exception:
            pass
        
        consumable_names = set()
        try:
            cons_content = _Path('util/autogenerated/consumables.py').read_text()
            for m in _re.finditer(r'name="([^"]+)"', cons_content):
                consumable_names.add(m.group(1).lower())
            for m in _re.finditer(r"name='([^']+)'", cons_content):
                consumable_names.add(m.group(1).lower())
        except Exception:
            pass
        
        for attr_name in dir(Material):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            material = getattr(Material, attr_name)
            # Duck typing: check if it has the attributes we need
            if not hasattr(material, 'name') or not hasattr(material, 'value'):
                continue
            
            # Skip items that belong in equipment or consumables
            base_name_lower = material.name.replace(' (Fine)', '').lower()
            if base_name_lower in equipment_names or base_name_lower in consumable_names:
                continue
            
            # Check if this is a fine version
            is_fine = material.name.endswith('(Fine)')
            base_name = material.name.replace(' (Fine)', '')
            base_id = self._name_to_id(base_name)
            
            # Extract stats if the material has them (e.g., arrows with WE)
            mat_stats = {}
            if hasattr(material, '_stats') and material._stats:
                mat_stats = material._stats
            
            # Extract requirements if present
            mat_requirements = getattr(material, 'requirements', []) or []

            # Create or update entry for this base material
            if base_id not in materials_dict:
                materials_dict[base_id] = {
                    'id': base_id,
                    'name': base_name,
                    'type': 'material',
                    'has_fine': False,
                    'value': material.value if not is_fine else None,
                    'value_fine': material.value if is_fine else None,
                    'keywords': material.keywords,
                    'requirements': mat_requirements,
                    'rarity': 'common',
                    'icon_path': f"/assets/{get_icon_path(base_name, 'material')}",
                }
            
            # Update with fine info if this is the fine version
            if is_fine:
                materials_dict[base_id]['has_fine'] = True
                materials_dict[base_id]['value_fine'] = material.value
                if mat_stats:
                    materials_dict[base_id]['stats_fine'] = mat_stats
            else:
                materials_dict[base_id]['value'] = material.value
                if mat_stats:
                    materials_dict[base_id]['stats'] = mat_stats
        
        # Convert to list and sort
        items = list(materials_dict.values())
        return sorted(items, key=lambda x: x['name'].lower())
    
    def _compute_activity_drop_names(self) -> set:
        """Compute set of item names that drop from activities."""
        names = set()
        for attr_name in dir(Activity):
            if attr_name.startswith('_'):
                continue
            if not attr_name.isupper():
                continue
            activity = getattr(Activity, attr_name)
            if not hasattr(activity, 'drop_table'):
                continue
            for drop in activity.drop_table:
                if drop.item_ref and (drop.item_ref.startswith('Item.') or drop.item_ref.startswith('Collectible.')):
                    names.add(drop.item_name)
            if hasattr(activity, 'secondary_drop_table'):
                for drop in activity.secondary_drop_table:
                    if drop.item_ref and (drop.item_ref.startswith('Item.') or drop.item_ref.startswith('Collectible.')):
                        names.add(drop.item_name)
        return names

    def _compute_achievement_reward_names(self) -> set:
        """Compute set of item names with 'achievement reward' keyword."""
        names = set()
        for attr_name in dir(Item):
            if attr_name.startswith('_') or not attr_name.isupper():
                continue
            item = getattr(Item, attr_name)
            if not hasattr(item, 'keywords'):
                continue
            keywords = getattr(item, 'keywords', [])
            if any('achievement' in kw.lower() for kw in keywords):
                names.add(item.name)
        return names

    def _compute_chest_item_names(self) -> set:
        """Compute set of item names that drop from chests."""
        names = set()
        for attr_name in dir(Container):
            if attr_name.startswith('_') or not attr_name.isupper():
                continue
            container = getattr(Container, attr_name)
            if not hasattr(container, 'get_all_drops'):
                continue
            for drop in container.get_all_drops():
                names.add(drop.item_name)
        return names

    def _get_loot_ap_rewards(self) -> List[Dict]:
        """Get equipment items from AP reward track, sorted by rarity."""
        items = []
        for reward in AP_ALL_REWARDS:
            if reward.item_type not in ('Loot', 'Back accessories'):
                continue
            item = self._find_item_by_name(reward.item_name)
            if item:
                items.append(item)
        return self._sort_items(items)

    def _get_loot_activity_drops(self) -> List[Dict]:
        """Get equipment items that drop from activities. Excludes crafted items."""
        items = []
        seen = set()
        for attr_name in dir(Activity):
            if attr_name.startswith('_'):
                continue
            if not attr_name.isupper():
                continue
            activity = getattr(Activity, attr_name)
            if not hasattr(activity, 'drop_table'):
                continue
            for drop_list in [activity.drop_table, getattr(activity, 'secondary_drop_table', [])]:
                for drop in drop_list:
                    if not drop.item_ref or not drop.item_ref.startswith('Item.'):
                        continue
                    if drop.item_name in seen:
                        continue
                    seen.add(drop.item_name)
                    item = self._find_item_by_name(drop.item_name)
                    if item and item.get('type') not in ('crafted_item', 'material'):
                        items.append(item)
        return self._sort_items(items)

    def _get_loot_faction_rewards(self) -> Dict[str, List[Dict]]:
        """Get equipment items from faction reward tracks, grouped by faction. Excludes crafted items and materials."""
        by_faction = defaultdict(list)
        seen = set()
        for faction_name, track in ALL_FACTION_TRACKS.items():
            for tier in track.tiers:
                for reward in tier.rewards:
                    if reward.item_type != 'Loot':
                        continue
                    key = (faction_name, reward.item_name)
                    if key in seen:
                        continue
                    seen.add(key)
                    item = self._find_item_by_name(reward.item_name)
                    if item and item.get('type') not in ('crafted_item', 'material'):
                        by_faction[faction_name].append(item)
        # Sort items within each faction
        for faction in by_faction:
            by_faction[faction] = self._sort_items(by_faction[faction])
        return dict(by_faction)

    def _get_loot_shop_items(self) -> List[Dict]:
        """Get equipment items sold in shops. Excludes crafted items and materials."""
        items = []
        seen = set()
        for shop in ALL_SHOPS:
            for shop_item in shop.inventory:
                if shop_item.item_type not in ('Loot', 'Tool'):
                    continue
                if shop_item.item_name in seen:
                    continue
                seen.add(shop_item.item_name)
                item = self._find_item_by_name(shop_item.item_name)
                if item and item.get('type') not in ('crafted_item', 'material'):
                    items.append(item)
        return self._sort_items(items)

    def _get_misc_loot(self) -> List[Dict]:
        """Get non-crafted equipment items not in any other loot category."""
        # Collect all item names already categorized (lowercase for case-insensitive matching)
        categorized_names = set()
        for name in self._ap_reward_names:
            categorized_names.add(name.lower())
        for name in self._achievement_reward_names:
            categorized_names.add(name.lower())
        for name in self._activity_drop_names:
            categorized_names.add(name.lower())
        for name in self._faction_reward_names:
            categorized_names.add(name.lower())
        for name in self._shop_item_names:
            categorized_names.add(name.lower())
        for name in self._chest_item_names:
            categorized_names.add(name.lower())

        items = []
        seen_uuids = set()
        for attr_name in dir(Item):
            if attr_name.startswith('_') or not attr_name.isupper():
                continue
            item = getattr(Item, attr_name)
            # Skip crafted items
            if hasattr(item, 'NORMAL') and hasattr(item, 'GOOD'):
                continue
            if not hasattr(item, 'name') or not hasattr(item, 'uuid'):
                continue
            # Skip aliases (same UUID already seen)
            if item.uuid in seen_uuids:
                continue
            seen_uuids.add(item.uuid)
            if item.name.lower() not in categorized_names:
                items.append(self._item_to_dict(item))
        return self._sort_items(items)

    def _get_achievement_items(self) -> Dict[str, List[Dict]]:
        """Get items organized by achievement keyword.
        
        Includes all items with 'achievement reward' keyword, excluding those
        already in AP rewards (they have their own category).
        """
        by_keyword = defaultdict(list)
        
        for attr_name in dir(Item):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase) but include single-underscore prefixed (e.g. _99_YEAR_OLD_WINE)
            if not attr_name.isupper() and not (attr_name.startswith('_') and attr_name[1:].isupper()):
                continue
            
            item = getattr(Item, attr_name)
            # Duck typing: check if it has the attributes we need
            if not hasattr(item, 'name') or not hasattr(item, 'keywords'):
                continue
            
            # Check if item has "achievement reward" keyword (case-insensitive exact match)
            keywords = getattr(item, 'keywords', [])
            has_achievement_kw = any(kw.lower() == 'achievement reward' for kw in keywords)
            if not has_achievement_kw:
                continue
            
            # Skip items that are in AP rewards (they have their own category)
            if item.name in self._ap_reward_names:
                continue
            
            # Find other keywords to categorize by
            categorized = False
            for keyword in keywords:
                if keyword.lower() != 'achievement reward':
                    item_dict = self._item_to_dict(item)
                    by_keyword[keyword].append(item_dict)
                    categorized = True
            
            # If only keyword is "achievement reward", put in "Misc" group
            if not categorized:
                item_dict = self._item_to_dict(item)
                by_keyword['Misc'].append(item_dict)
        
        # Sort items within each keyword
        for keyword in by_keyword:
            by_keyword[keyword] = self._sort_items(by_keyword[keyword])
        
        return dict(by_keyword)
    
    def _get_chest_items(self) -> List[Dict]:
        """Get all containers (chests) with special ordering"""
        items = []
        
        # Special containers to put at top
        special_containers = ['Bird nest', 'Coin pouch', 'Gem pouch']
        special_items = []
        regular_items = []
        
        for attr_name in dir(Container):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            container = getattr(Container, attr_name)
            if not hasattr(container, 'name'):
                continue
            
            item_dict = {
                'id': self._name_to_id(container.name),
                'name': container.name,
                'type': 'container',
                'rarity': 'common',  # Containers don't have rarity
                'keywords': ['Container'],
                'icon_path': f"/assets/{get_icon_path(container.name, 'container')}",
            }
            
            if container.name in special_containers:
                special_items.append(item_dict)
            else:
                regular_items.append(item_dict)
        
        # Sort special items by the order in special_containers
        special_items.sort(key=lambda x: special_containers.index(x['name']) if x['name'] in special_containers else 999)
        
        # Sort regular items alphabetically
        regular_items.sort(key=lambda x: x['name'].lower())
        
        return special_items + regular_items
    
    def _get_chests_with_contents(self) -> Dict[str, Dict]:
        """Get all chests with their contents (items that can drop from them)"""
        chests = {}
        
        # Chests to exclude
        excluded_chests = ['Bird nest', 'Coin pouch', 'Gem pouch']
        
        for attr_name in dir(Container):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            container = getattr(Container, attr_name)
            if not hasattr(container, 'name'):
                continue
            
            # Skip excluded chests
            if container.name in excluded_chests:
                continue
            
            # Get all drops from this chest (excluding materials and coins)
            all_drops = container.get_all_drops()
            chest_contents = []
            
            for drop_entry in all_drops:
                # drop_entry is a DropEntry object with item_ref like "Material.BIRCH_LOGS" or "Item.TRAVELERS_KIT"
                if not hasattr(drop_entry, 'item_ref') or drop_entry.item_ref is None:
                    continue
                
                item_ref = drop_entry.item_ref
                
                # Skip materials
                if item_ref.startswith('Material.'):
                    continue
                
                # Parse item_ref to get the actual item
                # Format: "Item.TRAVELERS_KIT" or "Consumable.BEER"
                try:
                    parts = item_ref.split('.')
                    if len(parts) != 2:
                        continue
                    
                    class_name, attr_name = parts
                    
                    # Get the item from the appropriate class
                    if class_name == 'Item':
                        item = getattr(Item, attr_name, None)
                    elif class_name == 'Consumable':
                        item = getattr(Consumable, attr_name, None)
                    elif class_name == 'Container':
                        item = getattr(Container, attr_name, None)
                    else:
                        continue
                    
                    if item is None:
                        continue
                    
                    # Convert to dict
                    item_dict = self._item_to_dict(item)
                    if item_dict:  # Only add if conversion succeeded
                        chest_contents.append(item_dict)
                        
                except Exception as e:
                    print(f"Warning: Failed to parse item_ref '{item_ref}': {e}")
                    continue
            
            # Create chest entry
            chest_id = self._name_to_id(container.name)
            chests[chest_id] = {
                'id': chest_id,
                'name': container.name,
                'type': 'container',
                'icon_path': f"/assets/{get_icon_path(container.name, 'container')}",
                'contents': self._sort_items(chest_contents),
                'is_special': False  # No special chests anymore
            }
        
        return chests
    
    def _get_crafted_by_keyword(self) -> Dict[str, List[Dict]]:
        """Get crafted items organized by keyword"""
        by_keyword = defaultdict(list)
        
        # Define main crafted keywords - map singular keyword to display category
        keyword_to_category = {
            'amulet': 'Amulets',
            'chisel': 'Chisels',
            'diving gear': 'Diving Gear',
            'advanced diving gear': 'Diving Gear',
            'expert diving gear': 'Diving Gear',
            'fishing tool': 'Fishing Tools',
            'fishing net': 'Fishing Tools',
            'fishing rod': 'Fishing Tools',
            'fishing spear': 'Fishing Tools',
            'hammer': 'Hammers',
            'hatchet': 'Hatchets',
            'hunting bow': 'Hunting Bows',
            'needle': 'Needles',
            'pan': 'Pans',
            'pickaxe': 'Pickaxes',
            'ring': 'Rings',
            'saw': 'Saws',
            'shield': 'Shields',
            'sickle': 'Sickles',
            'toolbox': 'Toolboxes',
            'weapon': 'Weapons',
            'wrench': 'Wrenches',
        }
        
        # Slot-based categories: items in these slots go into these categories
        # regardless of keywords (diving gear chests/pants go here too)
        slot_to_category = {
            'chest': 'Chests',
            'legs': 'Pants',
            'hands': 'Gloves',
        }
        
        for attr_name in dir(Item):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            item = getattr(Item, attr_name)
            # Check if it's a crafted item (has NORMAL, GOOD, etc. quality attributes)
            if not (hasattr(item, 'NORMAL') and hasattr(item, 'GOOD')):
                continue
            
            keywords = getattr(item, 'keywords', [])
            
            slot = getattr(item, 'slot', '')
            
            # Find matching categories from item keywords
            matched_keywords = set()
            for keyword in keywords:
                kw_lower = keyword.lower()
                # Check exact match first
                if kw_lower in keyword_to_category:
                    matched_keywords.add(keyword_to_category[kw_lower])
                else:
                    # Check if any category key appears as a whole WORD in this
                    # keyword (e.g. 'hammer' in 'smithing hammer'). Word boundary
                    # so a single-word key does not substring-match an unrelated
                    # word -- e.g. 'ring' must NOT match 'tailoring'/'gathering',
                    # which was dumping non-ring crafted gear into the Rings group.
                    for cat_key, cat_name in keyword_to_category.items():
                        if re.search(r'\b' + re.escape(cat_key) + r'\b', kw_lower):
                            matched_keywords.add(cat_name)
                            break
            
            # Slot-based categorization (chests, pants, gloves)
            # Items can appear in multiple categories (e.g., diving gear in both
            # "Diving Gear" and "Chests") — dedup handles the total count
            if slot in slot_to_category:
                matched_keywords.add(slot_to_category[slot])
            
            # Special: crafted neck slot items go into Amulets
            if not matched_keywords and slot == 'neck':
                matched_keywords = {'Amulets'}
            
            # If no main keywords matched, put in "Misc. Crafted"
            if not matched_keywords:
                matched_keywords = {'Misc. Crafted'}
            
            # Add to each matched keyword category
            item_dict = self._item_to_dict(item)
            for keyword in matched_keywords:
                by_keyword[keyword].append(item_dict)
        
        # Sort items within each keyword
        for keyword in by_keyword:
            by_keyword[keyword] = self._sort_items(by_keyword[keyword])
        
        # Add unique count metadata (items in multiple categories counted once)
        all_ids = set()
        for items in by_keyword.values():
            for item in items:
                all_ids.add(item['id'])
        
        result = dict(by_keyword)
        return result, len(all_ids)
    
    def _item_to_dict(self, item) -> Dict:
        """Convert item object to dictionary"""
        # Handle AchievementItem (has _achievement_stats attribute)
        if hasattr(item, '_achievement_stats'):
            # Get stats for 0 AP (base stats)
            instance = item[0]
            
            # Build gated stats for achievement thresholds
            gated_stats = {}
            if hasattr(item, '_achievement_stats') and item._achievement_stats:
                gated_stats['achievement_points'] = {}
                for threshold, stats in item._achievement_stats.items():
                    if threshold > 0:  # Skip 0 AP (already in base stats)
                        gated_stats['achievement_points'][str(threshold)] = stats
                
            result = {
                'id': self._name_to_id(item.name),
                'name': item.name,
                'uuid': item.uuid,
                'type': 'achievement_item',
                'slot': item.slot,
                'value': item.value,
                'keywords': item.keywords,
                'rarity': getattr(item, 'rarity', 'legendary') or 'legendary',  # Use item's rarity if available
                'stats': instance._stats,
                'icon_path': f"/assets/{get_icon_path(item.name, 'equipment')}",
            }
            
            if gated_stats.get('achievement_points'):
                result['gated_stats'] = gated_stats
            
            return result
        
        # Handle CraftedItem (has NORMAL, GOOD quality attributes)
        if hasattr(item, 'NORMAL') and hasattr(item, 'GOOD'):
            # Get stats for each quality level
            stats_by_quality = {}
            for quality in ['NORMAL', 'GOOD', 'GREAT', 'EXCELLENT', 'PERFECT', 'ETERNAL']:
                if hasattr(item, quality):
                    quality_instance = getattr(item, quality)
                    quality_name = quality.capitalize()
                    stats_by_quality[quality_name] = quality_instance._stats
            
            # Get quality names from attributes
            qualities = list(stats_by_quality.keys())
            
            return {
                'id': self._name_to_id(item.name),
                'name': item.name,
                'uuid': item.uuid,
                'type': 'crafted_item',
                'slot': item.slot,
                'value': item.value,  # Base (Normal) coin value; per-quality in quality_values
                'quality_values': dict(getattr(item, '_quality_values', {}) or {}),  # {quality: coin_value}
                'keywords': item.keywords,
                'rarity': 'common',  # Base rarity, changes with quality
                'qualities': qualities,
                'stats_by_quality': stats_by_quality,  # Stats for each quality level
                'icon_path': f"/assets/{get_icon_path(item.name, 'equipment')}",
                'requirements': item.requirements if hasattr(item, 'requirements') else [],
            }
        
        # Handle ItemInstance (regular item)
        if hasattr(item, 'uuid') and hasattr(item, '_stats'):
            item_dict = {
                'id': self._name_to_id(item.name),
                'name': item.name,
                'uuid': item.uuid,
                'type': 'item',
                'slot': item.slot,
                'value': item.value,
                'keywords': item.keywords,
                'rarity': getattr(item, 'rarity', 'common') or 'common',
                'stats': item._stats,
                'icon_path': f"/assets/{get_icon_path(item.name, 'equipment')}",
            }
            
            # Add gated_stats if present
            if hasattr(item, 'gated_stats'):
                item_dict['gated_stats'] = item.gated_stats
            
            # Add requirements if present
            if hasattr(item, 'requirements'):
                item_dict['requirements'] = item.requirements
            
            return item_dict
        
        return {}
    
    def _find_item_by_name(self, name: str) -> Optional[Dict]:
        """Find item by name across all item types"""
        # Try equipment
        for attr_name in dir(Item):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            item = getattr(Item, attr_name)
            # Duck typing: check if it has the attributes we need
            if not hasattr(item, 'name') or not hasattr(item, 'uuid'):
                continue
            
            if item.name.lower() == name.lower():
                return self._item_to_dict(item)
        
        # Try materials
        for attr_name in dir(Material):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            material = getattr(Material, attr_name)
            # Duck typing: check if it has the attributes we need
            if not hasattr(material, 'name') or not hasattr(material, 'value'):
                continue
            
            if material.name.lower() == name.lower():
                is_fine = material.name.endswith('(Fine)')
                base_name = material.name.replace(' (Fine)', '')
                return {
                    'id': self._name_to_id(material.name),
                    'name': material.name,
                    'base_name': base_name,
                    'type': 'material',
                    'is_fine': is_fine,
                    'value': material.value,
                    'keywords': material.keywords,
                    'rarity': 'common',
                }
        
        return None
    
    def _sort_items(self, items: List[Dict]) -> List[Dict]:
        """Sort items by rarity then alphabetically"""
        rarity_order = {
            'common': 0,
            'uncommon': 1,
            'rare': 2,
            'epic': 3,
            'legendary': 4,
            'ethereal': 5,
        }
        
        return sorted(items, key=lambda x: (
            rarity_order.get(x.get('rarity', 'common').lower(), 0),
            x.get('name', '').lower()
        ))
    
    def _name_to_id(self, name: str) -> str:
        """Convert item name to ID (lowercase, underscores)"""
        return name.lower().replace(' ', '_').replace('(', '').replace(')', '').replace('-', '_').replace("'", '')
    
    def get_item_info(self, item_id: str) -> Optional[Dict]:
        """Get full item info by ID"""
        # Search through all categories
        for category_name, category_data in self.categories.items():
            if category_name == 'collectibles':
                # Collectibles is now a dict of subcategories
                for subcat_name, subcat_data in category_data.items():
                    if isinstance(subcat_data, dict):
                        # Nested dict (e.g. Faction Rewards -> {faction: [items]})
                        for group_items in subcat_data.values():
                            for item in group_items:
                                if item['id'] == item_id:
                                    return item
                    elif isinstance(subcat_data, list):
                        for item in subcat_data:
                            if item['id'] == item_id:
                                return item
            elif category_name == 'consumables':
                for skill, items in category_data.items():
                    for item in items:
                        if item['id'] == item_id:
                            return item
            elif category_name == 'loot':
                for subcategory, items in category_data.items():
                    if isinstance(items, dict):
                        for keyword, keyword_items in items.items():
                            for item in keyword_items:
                                if item['id'] == item_id:
                                    return item
                    else:
                        for item in items:
                            if item['id'] == item_id:
                                return item
            elif category_name == 'crafted':
                for keyword, items in category_data.items():
                    for item in items:
                        if item['id'] == item_id:
                            return item
            elif isinstance(category_data, list):
                for item in category_data:
                    if isinstance(item, dict) and item.get('id') == item_id:
                        return item
            elif isinstance(category_data, dict):
                # Chests or other dict categories
                for key, val in category_data.items():
                    if isinstance(val, dict) and val.get('contents'):
                        for item in val['contents']:
                            if item['id'] == item_id:
                                return item
        
        return None
    
    def get_categories(self) -> Dict:
        """Get all categories with item counts"""
        counts = {}
        
        # Collectibles (now a dict of subcategories)
        collectibles_count = 0
        for subcat_data in self.categories['collectibles'].values():
            if isinstance(subcat_data, dict):
                collectibles_count += sum(len(items) for items in subcat_data.values())
            elif isinstance(subcat_data, list):
                collectibles_count += len(subcat_data)
        counts['collectibles'] = collectibles_count
        
        # Consumables (count all items across skills)
        consumables_count = sum(len(items) for items in self.categories['consumables'].values())
        counts['consumables'] = consumables_count
        
        # Materials
        counts['materials'] = len(self.categories['materials'])
        
        # Loot (count all subcategories)
        loot_count = 0
        for subcategory, items in self.categories['loot'].items():
            if isinstance(items, dict):
                loot_count += sum(len(keyword_items) for keyword_items in items.values())
            else:
                loot_count += len(items)
        counts['loot'] = loot_count
        
        # Crafted (count all items across keywords)
        crafted_count = sum(len(items) for items in self.categories['crafted'].values())
        counts['crafted'] = crafted_count
        
        # Pets
        counts['pets'] = len(self.categories['pets'])
        
        return counts

    
    def _get_all_equipment(self) -> List[Dict]:
        """Get ALL equipment items (for catalog API)"""
        items = []
        seen_uuids = set()
        
        for attr_name in dir(Item):
            if attr_name.startswith('_'):
                continue
            
            # Skip methods (lowercase)
            if not attr_name.isupper():
                continue
            
            item = getattr(Item, attr_name)
            
            # Duck typing: check if it has the attributes we need
            if not hasattr(item, 'name') or not hasattr(item, 'uuid'):
                continue
            
            # Skip aliases (same UUID already seen)
            if item.uuid in seen_uuids:
                continue
            seen_uuids.add(item.uuid)
            
            item_dict = self._item_to_dict(item)
            if item_dict:  # Only add if conversion succeeded
                items.append(item_dict)
        
        return self._sort_items(items)
