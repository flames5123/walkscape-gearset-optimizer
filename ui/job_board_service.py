#!/usr/bin/env python3
"""
Job-board read model for the main-site Job Board page.

Turns the raw `job_board_jobs` rows (stored by ui/job_board_scraper.py) into the
shape the front-end page needs: each job enriched with its board name, location,
faction(s) + icons, and tier; goals and rewards parsed with a derived item slug;
plus the facet lists that drive the filter dropdowns (factions, locations,
tiers, rewards).

Item *names and icons* are intentionally NOT resolved here — the front-end
already has the full item catalog + icon index (loadCatalogEntries /
window.prettyName), so we pass a derived `slug` and let the page render the
name/icon. Goal items use the `item-<slug>-<uuid>` id form (slug derivable);
reward "chest" items are bare UUIDs (slug null) and are labelled client-side.

Faction / location / tier enrichment DOES live here because it needs the
server-side game data (util/autogenerated/factions.py) and a small curated
board map.
"""

import json
import re
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, List, Optional

from util.autogenerated.factions import FACTIONS

# In-process memo of the weekly page payload (see build_jobboard_data). Keyed on
# the scraper's last-success meta so a new week's scrape busts it automatically.
_JB_CACHE: Dict[str, Any] = {"key": None, "data": None}


# ── Chest-drop resolution ─────────────────────────────────────────────────────
# Some goal items (e.g. Gold pan, Mining helmet) are NOT farmed directly and are
# NOT craftable — they only drop from a CHEST. For those the Job Board "Steps for
# you" is steps-per-chest (from the chests report) × the expected chests to get
# one of the item. Build, once, item-slug -> [(chest display name, expected
# chests per item)] from the static Container loot tables. The chest name here
# matches the `chests` report's chest_name so the frontend can divide.
_ITEM_TO_CHESTS: Optional[Dict[str, List[Dict[str, Any]]]] = None
_ACTIVITY_DROP_ITEMS: Optional[set] = None


def _norm_name(s: str) -> str:
    try:
        from util.stats_report.normalize import normalize_item_id
        return normalize_item_id(s or "")
    except Exception:
        return str(s or "").strip().lower().replace(" ", "_")


def _activity_drop_items() -> set:
    """Normalized names of every item obtainable DIRECTLY from an activity
    (non-chest drops). Used to EXCLUDE activity-farmable items from the chest
    calculation — they're reached far faster via their activity, so only
    chest-EXCLUSIVE items should be costed through a chest."""
    global _ACTIVITY_DROP_ITEMS
    if _ACTIVITY_DROP_ITEMS is not None:
        return _ACTIVITY_DROP_ITEMS
    s: set = set()
    try:
        from util.autogenerated.activities import ACTIVITIES_BY_SKILL
        for acts in ACTIVITIES_BY_SKILL.values():
            for a in acts:
                drops = list(getattr(a, "drop_table", None) or []) + \
                        list(getattr(a, "secondary_drop_table", None) or [])
                for d in drops:
                    is_dict = isinstance(d, dict)
                    ref = (d.get("item_ref") if is_dict else getattr(d, "item_ref", None)) or ""
                    nm = (d.get("item_name") if is_dict else getattr(d, "item_name", None)) or ""
                    if not nm:
                        continue
                    if str(ref).startswith("Container.") or "chest" in str(nm).lower():
                        continue   # the chest itself, not a direct item source
                    s.add(_norm_name(nm))
    except Exception:
        pass
    _ACTIVITY_DROP_ITEMS = s
    return s


def _chest_sources_index() -> Dict[str, List[Dict[str, Any]]]:
    global _ITEM_TO_CHESTS
    if _ITEM_TO_CHESTS is not None:
        return _ITEM_TO_CHESTS
    idx: Dict[str, List[Dict[str, Any]]] = {}
    try:
        from util.autogenerated.containers import Container, ContainerInfo
        for attr in dir(Container):
            if attr.startswith("_"):
                continue
            ci = getattr(Container, attr)
            if not isinstance(ci, ContainerInfo):
                continue
            for drop in ci.get_all_drops():
                exp = ci.get_expected_chests_per_item(drop.item_name)
                if not exp or exp <= 0:
                    continue
                key = _norm_name(drop.item_name)
                lst = idx.setdefault(key, [])
                # keep the cheapest (fewest expected chests) per chest name
                prev = next((e for e in lst if e["chest"] == ci.name), None)
                if prev is None:
                    lst.append({"chest": ci.name, "expected_chests": round(exp, 4)})
                elif exp < prev["expected_chests"]:
                    prev["expected_chests"] = round(exp, 4)
    except Exception:
        pass
    # Keep ONLY chest-EXCLUSIVE items: drop any item that a regular activity
    # also produces (Sea shell, Raw squid, Basic hide… are farmed far faster).
    act = _activity_drop_items()
    idx = {k: v for k, v in idx.items() if k not in act}
    _ITEM_TO_CHESTS = idx
    return idx

# ── Board → location + curated faction(s) ─────────────────────────────────────
# Keyed by the tools-API board slug (ui/job_board_scraper.resolve_board). Faction
# slugs match the reward target_id slug (and the sprite-icon file name). The
# authoritative faction set per job is unioned with what the job's rewards show,
# so a new faction appears even if this map is stale.
BOARD_META: Dict[str, Dict[str, Any]] = {
    "azurazera_job_board":          {"location": "Azurazera",           "factions": ["jarvonia"]},
    "blackspell_harbour_job_board": {"location": "Blackspell Harbour",  "factions": ["erdwise"]},
    "everhaven_combined_job_board": {"location": "Everhaven",           "factions": ["trellin", "erdwise"]},
    "granfiddich_job_board":        {"location": "Granfiddich",         "factions": ["trellin"]},
    "halfling_campgrounds_job_board": {"location": "Halfling Campgrounds", "factions": ["halfling_rebels"]},
    "herberts_job_board":           {"location": "Disenchanted Forest", "factions": ["tutorial_area"]},
    "kallaheim_job_board":          {"location": "Kallaheim",           "factions": ["jarvonia"]},
    "vastalume_job_board":          {"location": "Vastalume",           "factions": ["syrenthia"]},
}

# Reward/board faction slug -> factions.py key (where they differ).
_FACTION_KEY_ALIAS = {"tutorial_area": "herberts_guiding_grounds"}

# Tier: difficulty_id -> (rank, label). Herbert's uses a "herberts-" prefix.
_TIER_RANK = {"easy": 1, "mediocre": 2, "hard": 3, "extreme": 4}


def _faction_sprite(slug: str) -> str:
    """URL for a faction's 20px sprite icon."""
    return f"/assets/icons/text/sprite_20_icons/faction_{slug}.svg"


def faction_entry(slug: str) -> Dict[str, str]:
    """{slug, name, icon} for a reward/board faction slug."""
    key = _FACTION_KEY_ALIAS.get(slug, slug)
    name = (FACTIONS.get(key) or {}).get("name") or slug.replace("_", " ").title()
    return {"slug": slug, "name": name, "icon": _faction_sprite(slug)}


def _tier_of(difficulty_id: str) -> Dict[str, Any]:
    """{id, key, label, rank} from a jobdifficulty-* id."""
    raw = (difficulty_id or "").replace("jobdifficulty-", "")
    key = raw.replace("herberts-", "")
    rank = _TIER_RANK.get(key, 99)
    return {"id": difficulty_id, "key": key, "label": key.title() or "Unknown", "rank": rank}


_ITEM_ID_RE = re.compile(r"^item-(.+)-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.I)


def item_slug(item_id: str) -> Optional[str]:
    """Derive the catalog slug from an `item-<slug>-<uuid>` id; None for a bare
    UUID (reward chests), which the front-end labels from the catalog later."""
    if not item_id:
        return None
    m = _ITEM_ID_RE.match(item_id)
    return m.group(1) if m else None


def _item_ref(it: Optional[Dict[str, Any]], item_map: Dict[str, Dict[str, Any]] = None) -> Optional[Dict[str, Any]]:
    if not it:
        return None
    item_id = it.get("id")
    resolved = (item_map or {}).get(item_id) or {}
    slug = resolved.get("slug") or item_slug(item_id)
    # Chest-drop items (Gold pan, Mining helmet, …) get their source chest(s) +
    # expected chests per item so the Job Board can compute steps-per-item as
    # steps-per-chest × expected_chests when the item has no direct activity.
    chest_sources = _chest_sources_index().get(_norm_name(slug or resolved.get("name") or "")) or []
    return {
        "id": item_id,
        "slug": slug,
        "name": resolved.get("name"),
        "type": resolved.get("type"),
        "keywords": resolved.get("keywords") or [],
        "is_chest": bool(resolved.get("is_chest")),
        "quality": it.get("quality"),
        "tag": it.get("tag"),
        "chest_sources": chest_sources,
    }


def _board_faction_slugs(board_slug: Optional[str], rewards: List[Dict[str, Any]]) -> List[str]:
    """Union of the curated faction slugs for the board and any faction seen in
    the job's reputation rewards (order-stable, curated first)."""
    out: List[str] = []
    for s in (BOARD_META.get(board_slug or "", {}).get("factions") or []):
        if s not in out:
            out.append(s)
    for r in rewards:
        if r.get("kind") == "faction_reputation" and r.get("target_id"):
            m = re.match(r"^faction-(.+)-[0-9a-f]{8}-", r["target_id"], re.I)
            if m and m.group(1) not in out:
                out.append(m.group(1))
    return out


def enrich_job(row: Dict[str, Any], item_map: Dict[str, Dict[str, Any]] = None) -> Dict[str, Any]:
    """Enrich one job_board_jobs row into the page's job shape."""
    goals = json.loads(row.get("goals_json") or "[]")
    rewards = json.loads(row.get("rewards_json") or "[]")
    board_slug = row.get("board_slug")
    meta = BOARD_META.get(board_slug or "", {})
    fac_slugs = _board_faction_slugs(board_slug, rewards)
    tier = _tier_of(row.get("difficulty_id") or "")

    out_goals = []
    for g in goals:
        alts = []
        for a in (g.get("alternatives") or []):
            ref = _item_ref(a.get("item"), item_map)
            if ref is not None:
                ref["quantity"] = a.get("quantity")
                alts.append(ref)
        out_goals.append({
            "item": _item_ref(g.get("item"), item_map),
            "quantity": g.get("quantity"),
            # Higher qualities of the same item may be handed in instead, each
            # with its own (usually smaller) quantity.
            "alternatives": alts,
        })

    out_rewards = []
    for r in rewards:
        kind = r.get("kind")
        entry = {"kind": kind, "amount": r.get("amount"), "target_id": r.get("target_id"),
                 "item": _item_ref(r.get("item"), item_map), "faction": None, "skill": None}
        if kind == "faction_reputation" and r.get("target_id"):
            m = re.match(r"^faction-(.+)-[0-9a-f]{8}-", r["target_id"], re.I)
            if m:
                entry["faction"] = faction_entry(m.group(1))
        elif kind == "skill_experience" and r.get("target_id"):
            m = re.match(r"^skill-(.+?)-[0-9a-f]{8}-", r["target_id"], re.I)
            entry["skill"] = (m.group(1) if m else r["target_id"])
        out_rewards.append(entry)

    return {
        "id": row.get("id"),
        "week_index": row.get("week_index"),
        "board_id": row.get("board_id"),
        "board_slug": board_slug,
        "board_name": row.get("board_name") or row.get("board_id"),
        "location": meta.get("location") or row.get("board_name") or "Unknown",
        "factions": [faction_entry(s) for s in fac_slugs],
        "tier": tier,
        "slot": row.get("slot"),
        "bonus": bool(row.get("bonus")),
        "required_level": row.get("required_level"),
        "expires_at": row.get("expires_at"),
        "goals": out_goals,
        "rewards": out_rewards,
    }


def _facets(jobs: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Distinct values for the filter dropdowns."""
    factions: Dict[str, Dict[str, str]] = {}
    locations: Dict[str, Dict[str, Any]] = {}
    tiers: Dict[str, Dict[str, Any]] = {}
    rewards: Dict[str, Dict[str, Any]] = {}
    for j in jobs:
        for f in j["factions"]:
            factions[f["slug"]] = f
        locations.setdefault(j["board_id"], {
            "board_id": j["board_id"], "board_name": j["board_name"],
            "location": j["location"], "factions": j["factions"],
        })
        tiers[j["tier"]["key"]] = {"key": j["tier"]["key"], "label": j["tier"]["label"], "rank": j["tier"]["rank"]}
        for r in j["rewards"]:
            if r["kind"] == "faction_reputation" and r.get("faction"):
                k = f"rep:{r['faction']['slug']}"
                rewards[k] = {"key": k, "kind": "reputation", "label": r["faction"]["name"], "icon": r["faction"]["icon"], "slug": r["faction"]["slug"]}
            elif r["kind"] == "item" and r.get("item"):
                it = r["item"]
                k = f"item:{it.get('slug') or it.get('id')}"
                rewards[k] = {"key": k, "kind": "chest" if it.get("is_chest") else "item",
                              "label": it.get("name"), "icon": None,
                              "slug": it.get("slug"), "id": it.get("id"),
                              "is_chest": bool(it.get("is_chest"))}
            elif r["kind"] == "coins":
                rewards["coins"] = {"key": "coins", "kind": "coins", "label": "Coins", "icon": None, "slug": None}
            elif r["kind"] == "skill_experience":
                k = f"xp:{r.get('skill')}"
                rewards[k] = {"key": k, "kind": "skill", "label": f"{str(r.get('skill') or '').title()} XP", "icon": None, "slug": r.get("skill")}
    return {
        "factions": sorted(factions.values(), key=lambda f: f["name"]),
        "locations": sorted(locations.values(), key=lambda l: l["location"]),
        "tiers": sorted(tiers.values(), key=lambda t: t["rank"]),
        "rewards": sorted(rewards.values(), key=lambda r: (r["kind"], str(r.get("label") or r.get("slug") or ""))),
    }


def build_jobboard_data(db) -> Dict[str, Any]:
    """Full page payload for the running (latest-stored) week: week meta,
    enriched jobs, and filter facets.

    The payload is IDENTICAL for every user (it carries no per-session data —
    owned-item hand-in flags live in /api/jobboard/handin and "steps for you" /
    status are computed client-side). So memoize it in-process and reuse it for
    all callers, rebuilding only when the scraper records a new successful week
    (last_success_week / last_success_at change). This removes the per-page-load
    enrich+facet rebuild that previously ran once per visitor."""
    cache_key = "{}|{}".format(
        db.job_board_get_meta("last_success_week"),
        db.job_board_get_meta("last_success_at"),
    )
    if _JB_CACHE.get("key") == cache_key and _JB_CACHE.get("data") is not None:
        return _JB_CACHE["data"]
    rows = db.job_board_jobs_for_latest_week()
    item_map = db.job_board_item_map()
    jobs = [enrich_job(r, item_map) for r in rows]
    # Stable order: board, then slot.
    jobs.sort(key=lambda j: (j["location"], j["slot"] if j["slot"] is not None else 0))
    week_index = jobs[0]["week_index"] if jobs else db.job_board_get_meta("last_success_week")
    wi = int(week_index) if week_index is not None else None
    starts_at, ends_at = _week_bounds(wi)
    data = {
        "week_index": wi,
        "starts_at": starts_at,
        "ends_at": ends_at,
        "last_success_at": db.job_board_get_meta("last_success_at"),
        "job_count": len(jobs),
        "jobs": jobs,
        "facets": _facets(jobs),
    }
    _JB_CACHE["key"] = cache_key
    _JB_CACHE["data"] = data
    return data


# Week 0 began 2024-01-01 00:00 UTC (a Monday); each week is Mon 00:00 -> Mon 00:00.
_WEEK0 = datetime(2024, 1, 1, tzinfo=timezone.utc)


def _week_bounds(wi: Optional[int]):
    """(starts_at, ends_at) ISO strings for a week index, or (None, None)."""
    if wi is None:
        return None, None
    s = _WEEK0 + timedelta(days=7 * int(wi))
    e = s + timedelta(days=7)
    fmt = "%Y-%m-%dT%H:%M:%S.000Z"
    return s.strftime(fmt), e.strftime(fmt)
