character3 = Character(json.dumps(export_both))

# Clear stats cache to avoid using cached values from previous tests
_STATS_CACHE.clear()

stats3 = screwdriver.get_stats_for_skill('crafting', character=character3)

print(f"\nScrewdriver stats for Crafting (Level 50+, both completions):")
