#!/usr/bin/env python3
"""
Test activity completion requirements implementation.
"""

# Test without circular import by importing directly
import sys
sys.path.insert(0, 'util/autogenerated')

print("Testing activity completion requirements...\n")

# Test 1: Check that requirements are parsed correctly
print("=" * 80)
print("TEST 1: Verify requirements are in generated file")
print("=" * 80)

with open('util/autogenerated/equipment.py', 'r') as f:
    content = f.read()
    
    # Check for activity_completion in requirements
    if "'type': 'activity_completion'" in content:
        print("✓ Activity completion requirements found in equipment.py")
        
        # Count occurrences
        count = content.count("'type': 'activity_completion'")
        print(f"✓ Found {count} activity completion requirements")
    else:
        print("✗ No activity completion requirements found!")

# Test 2: Check specific items
print("\n" + "=" * 80)
print("TEST 2: Verify specific items have correct requirements")
print("=" * 80)

test_cases = [
    ("Hydrilium diving helm", "underwater_swimming", 25),
    ("Hydrilium diving leggings", "underwater_swimming", 25),
    ("Hydrilium diving torso", "underwater_swimming", 25),
    ("Hydrilium log splitter", "firewood_making", 200),
    ("Log splitter", "firewood_making", 200),
    ("Oak skis", "skate_skiing", 50),
    ("Pine skis", "classic_skiing", 50),
    ("Bert's super-skis", "classic_skiing", 50),  # Has 2 requirements
]

for item_name, activity, completions in test_cases:
    # Search for the item and its requirements
    pattern = f'name="{item_name}"'
    if pattern in content:
        # Find the requirements line for this item
        item_start = content.find(pattern)
        item_section = content[item_start:item_start + 2000]
        
        if f"'activity': '{activity}'" in item_section and f"'completions': {completions}" in item_section:
            print(f"✓ {item_name}: {activity} [{completions}x]")
        else:
            print(f"✗ {item_name}: Missing or incorrect requirement")
    else:
        print(f"✗ {item_name}: Item not found")

# Test 3: Check CraftedItem class has requirements parameter
print("\n" + "=" * 80)
print("TEST 3: Verify CraftedItem class supports requirements")
print("=" * 80)

if "class CraftedItem:" in content:
    # Find the __init__ method
    class_start = content.find("class CraftedItem:")
    class_section = content[class_start:class_start + 1000]
    
    if "requirements: list = None" in class_section:
        print("✓ CraftedItem.__init__ has requirements parameter")
    else:
        print("✗ CraftedItem.__init__ missing requirements parameter")
    
    if "self.requirements = requirements or []" in class_section:
        print("✓ CraftedItem stores requirements")
    else:
        print("✗ CraftedItem doesn't store requirements")
    
    # Check quality properties pass requirements
    if "requirements=self.requirements" in content:
        print("✓ Quality properties pass requirements to ItemInstance")
    else:
        print("✗ Quality properties don't pass requirements")
else:
    print("✗ CraftedItem class not found")

# Test 4: Check stats_mixin has activity_completion handling
print("\n" + "=" * 80)
print("TEST 4: Verify stats_mixin handles activity_completion")
print("=" * 80)

with open('util/stats_mixin.py', 'r') as f:
    mixin_content = f.read()
    
    if "req_type == 'activity_completion'" in mixin_content:
        print("✓ stats_mixin checks for activity_completion requirement type")
    else:
        print("✗ stats_mixin missing activity_completion check")
    
    if "COMPLETIONS" in mixin_content:
        print("✓ stats_mixin builds config variable name")
    else:
        print("✗ stats_mixin doesn't build config variable name")

print("\n" + "=" * 80)
print("SUMMARY")
